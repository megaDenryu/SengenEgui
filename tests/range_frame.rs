//! 範囲枠付き画像が、掴んだ部分と開始点からの累積の移動量をドラッグの段階ごとに発することを確かめる。

mod common;

use sengen_egui::{
    スタイル, ノード, 割合, 割合で表した矩形, 割合の差, 画素, 画素の組, 範囲枠の掴んだ部分,
    範囲枠の操作, 範囲枠付き画像, 縦横の割合の差,
};

const 赤い枠線: スタイル = スタイル {
    枠線色: Some(egui::Color32::RED),
    枠線太さ: Some(画素(1.0)),
    ..スタイル::無指定
};

/// 幅100・高さ50のテクスチャを、幅200・高さ100で描き、中央の半分の大きさの枠を重ねた木を組む。
fn 範囲枠の木(テクスチャ: &egui::TextureHandle) -> ノード<範囲枠の操作> {
    let 四分の一 = 割合::範囲へ丸めて生成する(0.25);
    let 四分の三 = 割合::範囲へ丸めて生成する(0.75);
    let 枠 = 割合で表した矩形::生成する(四分の一, 四分の一, 四分の三, 四分の三);
    let Ok(枠) = 枠 else {
        panic!("中央の枠は正しい矩形である");
    };
    範囲枠付き画像(テクスチャ.clone(), 画素の組(200.0, 100.0), 枠, |操作| 操作)
        .装飾(赤い枠線)
        .into()
}

fn テクスチャを登録する(文脈: &egui::Context) -> egui::TextureHandle {
    let 画像 = egui::ColorImage::filled([100, 50], egui::Color32::GRAY);
    文脈.load_texture("範囲枠の下地", 画像, egui::TextureOptions::NEAREST)
}

/// 中央パネルの内余白の分だけ、画像の左上は画面の原点からずれる。最初の配置から読み取る。
fn 画像の左上(文脈: &egui::Context) -> egui::Pos2 {
    let mut 左上 = egui::Pos2::ZERO;
    let _ = 文脈.run(egui::RawInput::default(), |文脈| {
        egui::CentralPanel::default().show(文脈, |ui| 左上 = ui.cursor().min);
    });
    左上
}

fn 移動量(横: f32, 縦: f32) -> 縦横の割合の差 {
    縦横の割合の差::生成する(割合の差::生成する(横), 割合の差::生成する(縦))
}

#[test]
fn 枠の内側をドラッグすると内側を掴んだ操作が開始点からの累積の移動量で出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 原点 = 画像の左上(&文脈);
    let 始点 = 原点 + egui::vec2(100.0, 50.0);
    let 終点 = 始点 + egui::vec2(20.0, 10.0);
    let 集まり = common::左ドラッグする(&文脈, 始点, 終点, &|| 範囲枠の木(&テクスチャ));
    let 掴んだ部分 = 範囲枠の掴んだ部分::内側;
    assert_eq!(
        集まり.first(),
        Some(&範囲枠の操作::掴み始めた { 掴んだ部分 })
    );
    let 期待 = 範囲枠の操作::放した {
        掴んだ部分,
        開始点からの移動量: 移動量(0.1, 0.1),
    };
    assert_eq!(集まり.last(), Some(&期待), "{集まり:?}");
    assert!(
        集まり
            .iter()
            .any(|操作| matches!(操作, 範囲枠の操作::動かしている { .. }))
    );
}

#[test]
fn 右下の隅をドラッグすると右下の隅を掴んだ操作が出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 始点 = 画像の左上(&文脈) + egui::vec2(150.0, 75.0);
    let 終点 = 始点 + egui::vec2(-40.0, 20.0);
    let 集まり = common::左ドラッグする(&文脈, 始点, 終点, &|| 範囲枠の木(&テクスチャ));
    let 期待 = 範囲枠の操作::放した {
        掴んだ部分: 範囲枠の掴んだ部分::右下の隅,
        開始点からの移動量: 移動量(-0.2, 0.2),
    };
    assert_eq!(集まり.last(), Some(&期待), "{集まり:?}");
}

#[test]
fn 枠の外で始めたドラッグは操作を発しない() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 始点 = 画像の左上(&文脈) + egui::vec2(10.0, 10.0);
    let 終点 = 始点 + egui::vec2(30.0, 30.0);
    let 集まり = common::左ドラッグする(&文脈, 始点, 終点, &|| 範囲枠の木(&テクスチャ));
    assert!(集まり.is_empty(), "{集まり:?}");
}

#[test]
fn 写した木でもドラッグの操作が写した応答で出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 始点 = 画像の左上(&文脈) + egui::vec2(100.0, 50.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 木を組む = || 範囲枠の木(&テクスチャ).写す(|操作| format!("{操作:?}"));
    let 集まり = common::左ドラッグする(&文脈, 始点, 終点, &木を組む);
    assert!(
        集まり.last().is_some_and(|文| 文.starts_with("放した")),
        "{集まり:?}"
    );
}
