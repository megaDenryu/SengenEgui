//! 範囲枠付き画像が、掴んだ部分と開始点からの累積の移動量をドラッグの段階ごとに発することを確かめる。

mod common;

use common::range_frame::{テクスチャを登録する, 画像の左上, 範囲枠の木};
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 範囲枠の操作, 縦横の割合の差
};

fn 移動量(横: f32, 縦: f32) -> 縦横の割合の差 {
    縦横の割合の差::生成する(割合の差::生成する(横), 割合の差::生成する(縦))
}

#[test]
fn 枠の内側をドラッグすると内側を掴んだ操作が開始点からの累積の移動量で出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 原点 = 画像の左上(&文脈);
    let 始点 = 原点 + egui::vec2(100.0, 50.0);
    let 終点 = 始点 + egui::vec2(20.0, 10.0);
    let 集まり =
        common::drag::左ドラッグする(&文脈, 始点, 終点, &|| 範囲枠の木(&テクスチャ));
    let 掴んだ部分 = 範囲枠の掴んだ部分::内側;
    assert_eq!(
        集まり.first(),
        Some(&範囲枠の操作::掴み始めた { 掴んだ部分 })
    );
    let 期待 = 範囲枠の操作::放した {
        掴んだ部分,
        開始点からの移動量: 移動量(0.1, 0.1),
    };
    assert_eq!(集まり.last(), Some(&期待), "{集まり:?}");
    assert!(
        集まり
            .iter()
            .any(|操作| matches!(操作, 範囲枠の操作::動かしている { .. }))
    );
}

#[test]
fn 右下の隅をドラッグすると右下の隅を掴んだ操作が出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 始点 = 画像の左上(&文脈) + egui::vec2(150.0, 75.0);
    let 終点 = 始点 + egui::vec2(-40.0, 20.0);
    let 集まり =
        common::drag::左ドラッグする(&文脈, 始点, 終点, &|| 範囲枠の木(&テクスチャ));
    let 期待 = 範囲枠の操作::放した {
        掴んだ部分: 範囲枠の掴んだ部分::右下の隅,
        開始点からの移動量: 移動量(-0.2, 0.2),
    };
    assert_eq!(集まり.last(), Some(&期待), "{集まり:?}");
}

#[test]
fn 写した木でもドラッグの操作が写した応答で出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = テクスチャを登録する(&文脈);
    let 始点 = 画像の左上(&文脈) + egui::vec2(100.0, 50.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 木を組む = || 範囲枠の木(&テクスチャ).写す(|操作| format!("{操作:?}"));
    let 集まり = common::drag::左ドラッグする(&文脈, 始点, 終点, &木を組む);
    assert!(
        集まり.last().is_some_and(|文| 文.starts_with("放した")),
        "{集まり:?}"
    );
}
