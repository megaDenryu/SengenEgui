//! 時間の行の並びが掴んだ塊を鍵で覚えることを確かめる。ドラッグの途中で塊を別の行へ置き直しても同じ塊へ操作が届き、
//! 掴んだ鍵の塊が置かれなくなったら、掴んだ塊が無くなったを1回発してドラッグを終える。

mod common;

use common::time_rows_point::時間の行の並びの上の点;

use std::cell::Cell;

use common::time_rows::{塊, 空の部品, 試験の塊, 試験の応答};
use sengen_egui::{ノード, 時間の塊の操作, 時間の行};

/// 押した後の置き方とは、試験の木が3回目の描画から塊 甲をどう置くかの区別のことである。
#[derive(Clone, Copy)]
enum 押した後の置き方 {
    上の行へ移す,
    置かない,
}

/// 最初の2回（配置を決める回と押す回）は塊 甲を下の行に置き、3回目からは指定の置き方にする木を組む関数を作る。
fn 押した後に置き方を変える木(
    置き方: 押した後の置き方,
) -> impl Fn() -> ノード<試験の応答> {
    let 描いた回数 = Cell::new(0_u32);
    move || {
        let 押した後 = 描いた回数.get() >= 2;
        描いた回数.set(描いた回数.get() + 1);
        let 甲 = 塊(10.0, 20.0);
        let (下の行, 上の行) = match (押した後, 置き方) {
            (false, _) => (時間の行().塊を置く(試験の塊::甲, 甲), 時間の行()),
            (true, 押した後の置き方::上の行へ移す) => {
                (時間の行(), 時間の行().塊を置く(試験の塊::甲, 甲))
            }
            (true, 押した後の置き方::置かない) => (時間の行(), 時間の行()),
        };
        空の部品().行を置く(下の行).行を置く(上の行).into()
    }
}

#[test]
fn ドラッグの途中で塊を別の行へ置き直しても掴んだ塊へ操作が届く() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 2.0);
    let 始点 = 点.行の中(0.0, 20.0);
    let 終点 = 点.行の中(1.0, 20.0);
    let 木を組む = 押した後に置き方を変える木(押した後の置き方::上の行へ移す);
    let 発した応答の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert!(
        common::time_rows::最後に放した移動量が近い(
            &発した応答の一覧,
            試験の塊::甲,
            0.0,
            1
        ),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn ドラッグの途中で掴んだ塊が置かれなくなると掴んだ塊が無くなったを1回発して終える() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 2.0);
    let 始点 = 点.行の中(0.0, 20.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 木を組む = 押した後に置き方を変える木(押した後の置き方::置かない);
    let 発した応答の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    let 無くなった = 試験の応答::塊(試験の塊::甲, 時間の塊の操作::掴んだ塊が無くなった);
    assert_eq!(
        発した応答の一覧.last(),
        Some(&無くなった),
        "{発した応答の一覧:?}"
    );
    assert_eq!(
        発した応答の一覧
            .iter()
            .filter(|応答| **応答 == 無くなった)
            .count(),
        1,
        "{発した応答の一覧:?}"
    );
}
