//! 倍精度の小数（f64）から論理画素と割合を作る口が、単精度へ丸めてから単位の約束を守ることを確かめる。

use sengen_egui::{割合, 割合の範囲外, 論理画素};

#[test]
fn 倍精度の小数から作った論理画素は単精度の最も近い値になる() {
    assert_eq!(
        論理画素::倍精度の小数から生成する(12.5).eguiへ渡す値(),
        12.5
    );
    assert_eq!(
        論理画素::倍精度の小数から生成する(0.1).eguiへ渡す値(),
        0.1_f32
    );
}

#[test]
fn 倍精度の小数から作る割合は範囲外なら理由を返す() {
    assert_eq!(
        割合::倍精度の小数から生成する(0.25).map(割合::eguiへ渡す値),
        Ok(0.25)
    );
    assert_eq!(
        割合::倍精度の小数から生成する(-0.5),
        Err(割合の範囲外::負である(-0.5))
    );
    assert_eq!(
        割合::倍精度の小数から生成する(1.5),
        Err(割合の範囲外::一を超える(1.5))
    );
    assert_eq!(
        割合::倍精度の小数から生成する(f64::NAN),
        Err(割合の範囲外::数でない)
    );
}

#[test]
fn 倍精度の小数から範囲へ丸めて作る割合は0と1の間に収まる() {
    assert_eq!(割合::倍精度の小数から範囲へ丸めて生成する(2.0), 割合::全部);
    assert_eq!(割合::倍精度の小数から範囲へ丸めて生成する(-1.0), 割合::ゼロ);
    assert_eq!(
        割合::倍精度の小数から範囲へ丸めて生成する(f64::NAN),
        割合::ゼロ
    );
    assert_eq!(
        割合::倍精度の小数から範囲へ丸めて生成する(0.5).eguiへ渡す値(),
        0.5
    );
}
