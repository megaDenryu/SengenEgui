//! 重ねる容器の「マウスを乗せている間だけ上に置く」子が、マウスが下地の上にある間だけ描かれ押せることを確かめる。

mod common;

use common::image::横長のテクスチャを登録する;
use common::output::{入力を指定して描画する, 文字を描いたか};
use common::overlay::{下地の左上, 押せる下地};
use sengen_egui::{ノード, ボタン, 重ねる, 重ねる位置};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    下地を押した,
    戻るを押した,
}

fn マウスを動かして描画する(
    eguiの本体: &egui::Context,
    位置: egui::Pos2,
    木を組む: &dyn Fn() -> ノード<応答>,
) -> egui::FullOutput {
    let 入力 = egui::RawInput {
        events: vec![egui::Event::PointerMoved(位置)],
        ..Default::default()
    };
    入力を指定して描画する(eguiの本体, 入力, 木を組む).1
}

#[test]
fn マウスが下地の外にある間は描かずマウスを乗せると描かれて押せる() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&eguiの本体);
    let 木を組む = || {
        重ねる("重ね", 押せる下地(&テクスチャ, 応答::下地を押した))
            .マウスを乗せている間だけ上に置く(
                重ねる位置::左上,
                ボタン("戻る", 応答::戻るを押した),
            )
            .into()
    };
    let 外 = egui::pos2(600.0, 600.0);
    let _ = マウスを動かして描画する(&eguiの本体, 外, &木を組む);
    let 外にある間 = マウスを動かして描画する(&eguiの本体, 外, &木を組む);
    assert!(!文字を描いたか(&外にある間, "戻る"));
    let ボタンの上 = 下地の左上 + egui::vec2(16.0, 16.0);
    let _ = マウスを動かして描画する(&eguiの本体, ボタンの上, &木を組む);
    let 乗せている間 = マウスを動かして描画する(&eguiの本体, ボタンの上, &木を組む);
    assert!(文字を描いたか(&乗せている間, "戻る"));
    let 押下 = common::左クリックする(&eguiの本体, ボタンの上, &木を組む);
    assert_eq!(押下, vec![応答::戻るを押した]);
}

#[test]
fn マウスを乗せる前に押した位置は下地が押される() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&eguiの本体);
    let 木を組む = || {
        重ねる("重ね", 押せる下地(&テクスチャ, 応答::下地を押した))
            .マウスを乗せている間だけ上に置く(
                重ねる位置::左上,
                ボタン("戻る", 応答::戻るを押した),
            )
            .into()
    };
    let 押下 =
        common::左クリックする(&eguiの本体, 下地の左上 + egui::vec2(16.0, 16.0), &木を組む);
    assert_eq!(押下, vec![応答::下地を押した]);
}
