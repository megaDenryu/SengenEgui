//! 一定時間で消える通知の並びが、続けて出た通知を置き換えずに並べて描き、通知ごとに表示の時間を数えて
//! 過ぎたものから消すことを確かめる。

mod common;

use std::time::Duration;

use common::output::{文字を描いたか, 時刻を指定して描画する};
use sengen_egui::{
    ノード, 一定時間で消える通知の並び, 並べる通知, 通知の回
};

fn 並びの木(通知: Vec<並べる通知>) -> impl Fn() -> ノード<()> {
    move || {
        一定時間で消える通知の並び("通知", 通知.clone())
            .表示する長さ(Duration::from_secs(2))
            .into()
    }
}

#[test]
fn 続けて出た通知を置き換えずに並べ_通知ごとに表示の時間を数える() {
    let eguiの本体 = egui::Context::default();
    let 最初 = 通知の回::最初();
    let 一つ目 = 並べる通知::作成する(最初, "設定を読めない");
    let _ = 時刻を指定して描画する(&eguiの本体, 10.0, &並びの木(vec![一つ目.clone()]));
    let 二つ = vec![
        一つ目,
        並べる通知::作成する(最初.次(), "動画を読み込みました"),
    ];
    let 並べた回 = 時刻を指定して描画する(&eguiの本体, 11.0, &並びの木(二つ.clone()));
    assert!(文字を描いたか(&並べた回, "設定を読めない"));
    assert!(文字を描いたか(&並べた回, "動画を読み込みました"));
    let 一つ目が過ぎた回 = 時刻を指定して描画する(&eguiの本体, 12.5, &並びの木(二つ));
    assert!(!文字を描いたか(&一つ目が過ぎた回, "設定を読めない"));
    assert!(文字を描いたか(
        &一つ目が過ぎた回,
        "動画を読み込みました"
    ));
}

#[test]
fn 渡されなくなった通知の回の記憶は捨て_同じ回を渡し直すと表示の時間を始めから数える() {
    let eguiの本体 = egui::Context::default();
    let 最初 = 通知の回::最初();
    let 一つ目 = 並べる通知::作成する(最初, "設定を読めない");
    let _ = 時刻を指定して描画する(&eguiの本体, 10.0, &並びの木(vec![一つ目.clone()]));
    let _ = 時刻を指定して描画する(&eguiの本体, 10.5, &並びの木(Vec::new()));
    let 渡し直した回 =
        時刻を指定して描画する(&eguiの本体, 13.0, &並びの木(vec![一つ目]));
    assert!(
        文字を描いたか(&渡し直した回, "設定を読めない"),
        "並びから外れた回の時刻は覚えていない"
    );
}
