//! 押せる領域が、子の範囲のうち中の部品の無い場所を押すと応答を発し、中のボタンを押したときは発しないことを確かめる。

mod common;

use sengen_egui::{ノード, ボタン, 付け足せる, 子, 文字表示, 画素, 縦積み};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    札を選んだ,
    札の中のボタンを押した,
}

fn 札() -> ノード<応答> {
    縦積み(子![
        文字表示("札の見出し"),
        ボタン("削除", 応答::札の中のボタンを押した),
    ])
    .最小幅(画素(200.0))
    .押されたら発する(応答::札を選んだ)
}

#[test]
fn 札の中の部品の無い場所を押すと札の応答が出る() {
    let eguiの本体 = egui::Context::default();
    let 集まり = common::左クリックする(&eguiの本体, egui::pos2(150.0, 14.0), &札);
    assert_eq!(集まり, vec![応答::札を選んだ]);
}

#[test]
fn 札の中のボタンを押すとボタンの応答だけが出る() {
    let eguiの本体 = egui::Context::default();
    let 集まり = common::左クリックする(&eguiの本体, egui::pos2(24.0, 36.0), &札);
    assert_eq!(集まり, vec![応答::札の中のボタンを押した]);
}
