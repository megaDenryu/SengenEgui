//! 区間の帯が、掴んだだけでは値を変えず、全体の範囲の外にある値をそれより外へ動かさないことを確かめる。
//! 範囲の外の値のつまみは帯の端に外を指す三角で描き、端で掴める。

mod common;

use common::range_band::{帯の上の点, 帯の木, 掴み始めた, 放した, 近い};
use sengen_egui::{ノード, 区間の帯の掴んだもの, 区間の帯の操作};

use 区間の帯の掴んだもの::{区間の内側, 開始のつまみ};

fn 点() -> 帯の上の点 {
    帯の上の点::読み取る(&egui::Context::default())
}

fn ドラッグする(
    始点: egui::Pos2,
    横の移動量: f32,
    木を組む: &dyn Fn() -> ノード<区間の帯の操作>,
) -> Vec<区間の帯の操作> {
    let 文脈 = egui::Context::default();
    common::drag::左ドラッグする(&文脈, 始点, 始点 + egui::vec2(横の移動量, 0.0), 木を組む)
}

fn 押して放す(
    点: egui::Pos2,
    木を組む: &dyn Fn() -> ノード<区間の帯の操作>,
) -> Vec<区間の帯の操作> {
    common::左クリックする(&egui::Context::default(), 点, 木を組む)
}

#[test]
fn 範囲の中のつまみを動かさずに放すと今の値をそのまま発する() {
    let 集まり = 押して放す(点().帯の段(20.0) + egui::vec2(3.0, 0.0), &|| {
        帯の木(20.0, 60.0, None)
    });
    assert_eq!(
        集まり,
        vec![掴み始めた(開始のつまみ, 20.0), 放した(開始のつまみ, 20.0)]
    );
}

#[test]
fn 範囲の外の開始は掴んで動かさずに放しても書き換わらない() {
    let 集まり = 押して放す(点().帯の段(0.0), &|| 帯の木(-10.0, 60.0, None));
    assert_eq!(
        集まり,
        vec![掴み始めた(開始のつまみ, -10.0), 放した(開始のつまみ, -10.0)]
    );
}

#[test]
fn 範囲の外の開始は内側へ動かした分だけ戻りそれより外へは動かない() {
    let 木 = || 帯の木(-10.0, 60.0, None);
    let 集まり = ドラッグする(点().帯の段(0.0), 30.0, &木);
    assert!(近い(集まり.last(), 放した(開始のつまみ, 5.0)), "{集まり:?}");
    let 集まり = ドラッグする(点().帯の段(0.0), -30.0, &木);
    assert!(
        近い(集まり.last(), 放した(開始のつまみ, -10.0)),
        "{集まり:?}"
    );
}

#[test]
fn 範囲より長い区間は内側を押しただけでは動かず全体を覆ったまま動かせる() {
    let 木 = || 帯の木(-20.0, 120.0, None);
    let 集まり = 押して放す(点().帯の段(50.0), &木);
    assert_eq!(
        集まり,
        vec![掴み始めた(区間の内側, -20.0), 放した(区間の内側, -20.0)]
    );
    let 集まり = ドラッグする(点().帯の段(50.0), 10.0, &木);
    assert!(近い(集まり.last(), 放した(区間の内側, -15.0)), "{集まり:?}");
    let 集まり = ドラッグする(点().帯の段(50.0), 100.0, &木);
    assert!(近い(集まり.last(), 放した(区間の内側, 0.0)), "{集まり:?}");
}

/// 描いた図形のうち、塗った多角形（三角）の数。範囲の中のつまみは矩形で描くため数えない。
fn 三角の数(木を組む: &dyn Fn() -> ノード<区間の帯の操作>) -> usize {
    let (_, 出力) = common::output::入力を指定して描画する(
        &egui::Context::default(),
        egui::RawInput::default(),
        木を組む,
    );
    出力
        .shapes
        .iter()
        .filter(|図形| matches!(&図形.shape, egui::Shape::Path(経路) if 経路.points.len() == 3))
        .count()
}

#[test]
fn 範囲の外のつまみは端に外を指す三角で描き範囲の中のつまみは三角で描かない() {
    assert_eq!(三角の数(&|| 帯の木(20.0, 60.0, None)), 0);
    assert_eq!(三角の数(&|| 帯の木(-10.0, 60.0, None)), 1);
    assert_eq!(三角の数(&|| 帯の木(-10.0, 120.0, None)), 2);
}
