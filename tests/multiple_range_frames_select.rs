//! 複数の範囲枠が、選んでいない枠を押したときに、その枠の応答として選んだを掴み始めたより先に発することを確かめる。
//! 枠の内側が重なった場所では手前の枠を選ぶ。

mod common;

use common::multiple_range_frames::{
    二つの枠の木, 基準の矩形の中の位置, 試験で選んでいる枠, 試験の枠,
};
use sengen_egui::{
    範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

#[test]
fn 動かさずに押して放すと選んだと掴み始めたと移動量の無い放したが出る() {
    let eguiの本体 = egui::Context::default();
    let 位置 = 基準の矩形の中の位置(&eguiの本体, 0.8, 0.8);
    let 発した操作の一覧 = common::左クリックする(&eguiの本体, 位置, &|| {
        二つの枠の木(試験で選んでいる枠::奥)
    });
    assert_eq!(
        発した操作の一覧.first(),
        Some(&(試験の枠::手前, 複数の範囲枠の操作::選んだ)),
        "{発した操作の一覧:?}"
    );
    let 期待 = 複数の範囲枠の操作::放した {
        掴んだ部分: 範囲枠の掴んだ部分::内側,
        開始点からの移動量: 縦横の割合の差::ゼロ,
        縦横比の扱い: 縦横比の扱い::保たない,
    };
    assert_eq!(
        発した操作の一覧.last(),
        Some(&(試験の枠::手前, 期待)),
        "{発した操作の一覧:?}"
    );
}

#[test]
fn 枠の内側が重なった場所を押すと手前の枠を選んで掴む() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.5, 0.5);
    let 終点 = 始点 + egui::vec2(10.0, 0.0);
    let 発した操作の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &|| {
        二つの枠の木(試験で選んでいる枠::奥)
    });
    assert_eq!(
        発した操作の一覧.get(..2),
        Some(
            &[
                (試験の枠::手前, 複数の範囲枠の操作::選んだ),
                (
                    試験の枠::手前,
                    複数の範囲枠の操作::掴み始めた {
                        掴んだ部分: 範囲枠の掴んだ部分::内側
                    }
                ),
            ][..]
        ),
        "{発した操作の一覧:?}"
    );
}
