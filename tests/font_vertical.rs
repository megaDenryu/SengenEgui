//! 日本語フォントの字形の縦の補正が、日本語の字形の縦の中心を英字の字形の縦の中心へ揃えることを数値で確かめる。
//! 測るのは、egui が並べた字形の描画の矩形の縦の中心である（`common::glyph` 参照）。目視では確かめない。
//!
//! 前提: 標準の候補のうち、補正量を測ったもの（Windows の3つ）で、この計算機に入っているものだけを測る。
//! 1つも無い計算機では、測定を実行しなかったことを標準エラー出力へ書く（黙って成功にしない）。
//! 利用する側が自分のフォントの補正量を探す道具は `tests/font_correction_search.rs` にある。

mod common;

use common::font_measure::{最大の差, 測れる標準の候補};
use common::glyph::{文字の図形一覧, 縦の中心の集まり};
use sengen_egui::{
    ボタン, 子, 字形の縦の補正, 日本語フォントの候補, 横並び
};

/// 補正した後に残ってよい差の上限（論理画素）。egui は字形の位置を画素へ丸めるため、1画素未満の差は補正では消えない。
const 残ってよい差: f32 = 1.25;

#[test]
fn 標準の候補は補正すると日本語の縦の中心が英字の縦の中心へ揃う() {
    for 候補 in 測れる標準の候補("標準の候補は補正すると揃う") {
        let 差 = 最大の差(候補.置き場所(), 候補.縦の補正());
        assert!(
            差 <= 残ってよい差,
            "{} の差が {差} 論理画素ある",
            候補.置き場所().display()
        );
    }
}

#[test]
fn 補正を持つ標準の候補は補正しないと差が大きくなる() {
    for 候補 in 測れる標準の候補("補正しないと差が大きくなる") {
        if 候補.縦の補正() == 字形の縦の補正::無し {
            continue;
        }
        let 補正した差 = 最大の差(候補.置き場所(), 候補.縦の補正());
        let 補正しない差 = 最大の差(候補.置き場所(), 字形の縦の補正::無し);
        assert!(
            補正しない差 > 補正した差,
            "{} は補正しなくても差が {補正しない差} で、補正した差 {補正した差} より大きくない",
            候補.置き場所().display()
        );
    }
}

#[test]
fn 英字のボタンと日本語のボタンを横に並べると文字の縦の中心が揃う() {
    let Some(候補) = 測れる標準の候補("ボタンを横に並べると揃う")
        .into_iter()
        .next()
    else {
        return;
    };
    let eguiの本体 = egui::Context::default();
    let 候補 = 日本語フォントの候補::補正付きの一覧から作る([候補]);
    assert!(候補.最初に読めたものを設定する(&eguiの本体).is_ok());
    let 木を組む = || {
        横並び(子![
            ボタン("JSON", ()),
            ボタン("読込", ()),
            ボタン("保存", ())
        ])
        .into()
    };
    let _ = common::output::入力を指定して描画する(
        &eguiの本体,
        egui::RawInput::default(),
        &木を組む,
    );
    let (_, 出力) = common::output::入力を指定して描画する(
        &eguiの本体,
        egui::RawInput::default(),
        &木を組む,
    );
    let mut 集まり = 縦の中心の集まり::default();
    for 文字 in 文字の図形一覧(&出力) {
        集まり.足す(文字.pos, &文字.galley);
    }
    let 差 = 集まり.平均する().日本語の英字からの差();
    assert!(
        差.abs() <= 残ってよい差,
        "ボタンの中の日本語が英字から {差} 論理画素ずれている"
    );
}

#[test]
fn 標準の候補がどれも無い計算機では試した置き場所を候補の順に全部報告する() {
    let 標準 = 日本語フォントの候補::標準で入っている候補();
    if 標準.一覧().iter().any(|候補| 候補.置き場所().is_file()) {
        eprintln!(
            "標準の候補がどれも無いときの報告: この計算機には標準の候補があるため、確かめなかった（tests/font.rs が同じ報告を偽の置き場所で確かめる）"
        );
        return;
    }
    let Err(失敗) = 標準.最初に読めたものを設定する(&egui::Context::default())
    else {
        panic!("標準の候補がどれも無いのに設定できた");
    };
    let 試した: Vec<_> = 失敗
        .試した結果一覧()
        .iter()
        .map(|結果| 結果.置き場所().to_path_buf())
        .collect();
    let 候補の順: Vec<_> = 標準
        .一覧()
        .iter()
        .map(|候補| 候補.置き場所().to_path_buf())
        .collect();
    assert_eq!(試した, 候補の順);
}
