//! 日本語フォントの字形の縦の補正が、日本語の字形の縦の中心を英字の字形の縦の中心へ揃えることを数値で確かめる。
//! 測るのは、egui が並べた字形の描画の矩形の縦の中心である（`common::glyph` 参照）。目視では確かめない。
//!
//! 前提: 標準の候補のうち、この計算機に入っているフォントだけを測る。1つも入っていない計算機では、
//! 測れなかったことを失敗として報告する（黙って通さない）。

mod common;

use common::font_measure::{入っている標準の候補, 最大の差};
use common::glyph::{文字の図形一覧, 縦の中心の集まり};
use sengen_egui::{
    ボタン, 子, 字形の縦の補正, 日本語フォントの候補, 横並び
};

/// 補正した後に残ってよい差の上限（論理画素）。egui は字形の位置を画素へ丸めるため、1画素未満の差は補正では消えない。
const 残ってよい差: f32 = 1.25;

#[test]
fn 標準の候補は補正すると日本語の縦の中心が英字の縦の中心へ揃う() {
    for 候補 in 入っている標準の候補() {
        let 差 = 最大の差(候補.置き場所(), 候補.縦の補正());
        assert!(
            差 <= 残ってよい差,
            "{} の差が {差} 論理画素ある",
            候補.置き場所().display()
        );
    }
}

#[test]
fn 補正を持つ標準の候補は補正しないと差が大きくなる() {
    for 候補 in 入っている標準の候補() {
        if 候補.縦の補正() == 字形の縦の補正::無し {
            continue;
        }
        let 補正した差 = 最大の差(候補.置き場所(), 候補.縦の補正());
        let 補正しない差 = 最大の差(候補.置き場所(), 字形の縦の補正::無し);
        assert!(
            補正しない差 > 補正した差,
            "{} は補正しなくても差が {補正しない差} で、補正した差 {補正した差} より大きくない",
            候補.置き場所().display()
        );
    }
}

#[test]
fn 英字のボタンと日本語のボタンを横に並べると文字の縦の中心が揃う() {
    let eguiの本体 = egui::Context::default();
    assert!(
        日本語フォントの候補::標準で入っている候補()
            .最初に読めたものを設定する(&eguiの本体)
            .is_ok()
    );
    let 木を組む = || {
        横並び(子![
            ボタン("JSON", ()),
            ボタン("読込", ()),
            ボタン("保存", ())
        ])
        .into()
    };
    let _ = common::output::入力を指定して描画する(
        &eguiの本体,
        egui::RawInput::default(),
        &木を組む,
    );
    let (_, 出力) = common::output::入力を指定して描画する(
        &eguiの本体,
        egui::RawInput::default(),
        &木を組む,
    );
    let mut 集まり = 縦の中心の集まり::default();
    for 文字 in 文字の図形一覧(&出力) {
        集まり.足す(文字.pos, &文字.galley);
    }
    let 差 = 集まり.平均する().日本語の英字からの差();
    assert!(
        差.abs() <= 残ってよい差,
        "ボタンの中の日本語が英字から {差} 論理画素ずれている"
    );
}
