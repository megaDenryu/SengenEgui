//! 時間の塊の作り方を確かめる。時間の塊は、長さが正で始まりと長さが有限なときだけ作れる。

mod common;

use common::time_rows::{値, 塊};
use sengen_egui::{帯の値の差, 時間の塊, 時間の塊の不正};

#[test]
fn 長さが正でない時間の塊は作れない() {
    let 差 = 帯の値の差::倍精度の小数から生成する;
    assert_eq!(
        時間の塊::生成する(値(1.0), 差(0.0)),
        Err(時間の塊の不正::長さが正でない)
    );
    assert_eq!(
        時間の塊::生成する(値(1.0), 差(-2.0)),
        Err(時間の塊の不正::長さが正でない)
    );
}

#[test]
fn 始まりか長さが有限でない時間の塊は作れない() {
    let 差 = 帯の値の差::倍精度の小数から生成する;
    assert_eq!(
        時間の塊::生成する(値(f64::NAN), 差(1.0)),
        Err(時間の塊の不正::有限でない)
    );
    assert_eq!(
        時間の塊::生成する(値(0.0), 差(f64::INFINITY)),
        Err(時間の塊の不正::有限でない)
    );
}

#[test]
fn 時間の塊の終わりは始まりに長さを足した値である() {
    assert_eq!(塊(10.0, 20.0).終わり(), 値(30.0));
}
