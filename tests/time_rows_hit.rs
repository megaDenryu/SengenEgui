//! 時間の行の並びの押した所の判定を確かめる。同じ行で重なった塊は、選んでいる塊を先に、選んでいない塊どうしでは
//! 後に置いた塊を掴む。塊の無い所（空の行を含む）と、位置の線を動かせないときの時間の軸は、何も無い所を押したことになる。

mod common;

use common::time_rows_point::時間の行の並びの上の点;

use common::time_rows::{
    塊, 空の部品, 置く, 見本の木, 見本の部品, 試験の塊, 試験の応答
};
use sengen_egui::{ノード, 時間の塊の操作, 時間の行};

/// 1つの行に、塊 丁（10〜40）と、後に置いた塊 戊（20〜50）を重ねて置いた木。20〜40 で重なる。
fn 重なった塊の木(選んでいる: Option<試験の塊>) -> ノード<試験の応答> {
    let 行 = 置く(時間の行(), 選んでいる, 試験の塊::丁, 塊(10.0, 30.0));
    空の部品()
        .行を置く(置く(行, 選んでいる, 試験の塊::戊, 塊(20.0, 30.0)))
        .into()
}

fn 掴み始めた塊(発した応答の一覧: &[試験の応答]) -> Option<試験の塊> {
    発した応答の一覧.iter().find_map(|応答| match 応答 {
        試験の応答::塊(鍵, 時間の塊の操作::掴み始めた { .. }) => Some(*鍵),
        _ => None,
    })
}

#[test]
fn 選んでいない塊どうしが重なった所では後に置いた塊を掴む() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 1.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(0.0, 30.0), &|| {
            重なった塊の木(None)
        });
    assert_eq!(
        掴み始めた塊(&発した応答の一覧),
        Some(試験の塊::戊),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 重なった所では選んでいる奥の塊を先に掴む() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 1.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(0.0, 30.0), &|| {
            重なった塊の木(Some(試験の塊::丁))
        });
    assert_eq!(
        掴み始めた塊(&発した応答の一覧),
        Some(試験の塊::丁),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 空の行を押すと何も無い所を1回だけ発する() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(2.0, 50.0), &|| {
            見本の木(None)
        });
    assert_eq!(発した応答の一覧, vec![試験の応答::何も無い所]);
}

#[test]
fn 塊の無い所を押すと何も無い所を発し塊を押すと発さない() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 塊の外 = common::左クリックする(&eguiの本体, 点.行の中(0.0, 60.0), &|| {
        見本の木(None)
    });
    let 塊の上 = common::左クリックする(&eguiの本体, 点.行の中(0.0, 20.0), &|| {
        見本の木(None)
    });
    assert_eq!(塊の外, vec![試験の応答::何も無い所]);
    assert!(!塊の上.contains(&試験の応答::何も無い所), "{塊の上:?}");
}

#[test]
fn 位置の線を動かせないときは時間の軸を押すと何も無い所を発する() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 = common::左クリックする(&eguiの本体, 点.時間の軸(30.0), &|| {
        見本の部品(None, false).into()
    });
    assert_eq!(発した応答の一覧, vec![試験の応答::何も無い所]);
}
