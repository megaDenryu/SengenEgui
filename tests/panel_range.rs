//! パネルの幅と高さの範囲が、最初の寸法と縁のドラッグで変えた寸法の両方を範囲へ収め、
//! 最大が最小より小さいときは最小を優先し、効かない位置に書いた幅または高さの指定がもう一方の寸法を変えないことを確かめる。
//! egui の縁のパネルは中身の大きさまで縮むため、中身には使える幅いっぱいに伸びる区切り線を置く。

mod common;

use common::drag::左ドラッグする;
use common::image::描画した矩形;
use sengen_egui::{ノード, パネル, パネルの位置, 区切り線, 子, 画素};

fn 左のパネル(既定: f32, 最小: f32, 最大: f32) -> ノード<()> {
    パネル("範囲", パネルの位置::左, 子![区切り線()])
        .既定の幅(画素(既定))
        .幅の範囲(画素(最小), 画素(最大))
        .大きさを変えられる(true)
        .into()
}

#[test]
fn 最初の幅は幅の範囲へ収まる() {
    let 狭すぎる = 描画した矩形(&egui::Context::default(), 左のパネル(100.0, 200.0, 300.0));
    assert_eq!(狭すぎる.width(), 200.0);
    let 広すぎる = 描画した矩形(&egui::Context::default(), 左のパネル(400.0, 200.0, 300.0));
    assert_eq!(広すぎる.width(), 300.0);
}

#[test]
fn 最大が最小より小さいときは最小を優先する() {
    let 矩形 = 描画した矩形(&egui::Context::default(), 左のパネル(100.0, 250.0, 150.0));
    assert_eq!(矩形.width(), 250.0);
}

#[test]
fn 縁のドラッグで変えた幅は最大で止まる() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 左のパネル(200.0, 200.0, 300.0);
    let 始めの矩形 = 描画した矩形(&文脈, 木を組む());
    let 縁 = egui::pos2(始めの矩形.right(), 始めの矩形.center().y);
    let _ = 左ドラッグする(&文脈, 縁, 縁 + egui::vec2(400.0, 0.0), &木を組む);
    assert_eq!(描画した矩形(&文脈, 木を組む()).width(), 300.0);
}

#[test]
fn 上のパネルの最初の高さは高さの範囲へ収まる() {
    let 木: ノード<()> = パネル("範囲", パネルの位置::上, 子![区切り線()])
        .既定の高さ(画素(10.0))
        .高さの範囲(画素(60.0), 画素(90.0))
        .into();
    assert_eq!(描画した矩形(&egui::Context::default(), 木).height(), 60.0);
}

fn 上のパネルの高さ(木: ノード<()>) -> f32 {
    描画した矩形(&egui::Context::default(), 木).height()
}

#[test]
fn 上のパネルに書いた幅の指定は高さを変えない() {
    let 上のパネル =
        || パネル("範囲", パネルの位置::上, 子![区切り線()]).既定の高さ(画素(10.0));
    let 幅の指定が無い = 上のパネルの高さ(上のパネル().into());
    let 幅の範囲を書いた =
        上のパネルの高さ(上のパネル().幅の範囲(画素(60.0), 画素(90.0)).into());
    let 既定の幅を書いた = 上のパネルの高さ(上のパネル().既定の幅(画素(200.0)).into());
    assert_eq!(幅の範囲を書いた, 幅の指定が無い);
    assert_eq!(既定の幅を書いた, 幅の指定が無い);
}

#[test]
fn 左のパネルに書いた高さの指定は幅を変えない() {
    let 高さを書いた: ノード<()> = パネル("範囲", パネルの位置::左, 子![区切り線()])
        .既定の幅(画素(200.0))
        .高さの範囲(画素(60.0), 画素(90.0))
        .既定の高さ(画素(400.0))
        .into();
    assert_eq!(
        描画した矩形(&egui::Context::default(), 高さを書いた).width(),
        200.0
    );
}
