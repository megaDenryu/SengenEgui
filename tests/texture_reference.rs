//! 登録したテクスチャの参照を、所有した値だけを持ち込める閉包（使える大きさから組む）へ持ち込み、
//! その中で画像と範囲枠付き画像の両方に使えることを確かめる。

mod common;

use common::image::描画した矩形;
use sengen_egui::{
    ノード, 使える大きさから組む, 割合で表した矩形, 子, 差し替えられるテクスチャ, 拡大縮小の仕方,
    画像, 画素の並び, 画素の組, 画素数の寸法, 範囲枠付き画像, 範囲枠付き画像の周りの余白, 縦積み,
};

fn 灰色のテクスチャを登録する(
    eguiの本体: &egui::Context,
) -> 差し替えられるテクスチャ {
    let 寸法 = 画素数の寸法::生成する(64, 32);
    let バイト列 = [128, 128, 128, 255].repeat(64 * 32);
    match 画素の並び::赤緑青と不透明度のバイト列から作る(寸法, &バイト列)
    {
        Ok(画素) => 差し替えられるテクスチャ::登録して作る(
            eguiの本体,
            "灰色",
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        ),
        Err(不正) => panic!("試験の画素の並びが不正である: {不正}"),
    }
}

#[test]
fn 参照を閉包へ所有させて画像と範囲枠付き画像を描ける() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ = 灰色のテクスチャを登録する(&eguiの本体);
    let 参照 = テクスチャ.参照を複製する();
    let 木: ノード<()> = 使える大きさから組む(move |_| {
        縦積み(子![
            画像(&参照).表示寸法(画素の組(64.0, 32.0)),
            範囲枠付き画像(&参照, 画素の組(128.0, 64.0), 割合で表した矩形::全体, |_| ()),
        ])
        .into()
    })
    .into();
    let 余白 = 範囲枠付き画像の周りの余白.eguiへ渡す値() * 2.0;
    let 間隔 = eguiの本体.style().spacing.item_spacing.y;
    assert_eq!(
        描画した矩形(&eguiの本体, 木).size(),
        egui::vec2(128.0 + 余白, 32.0 + 間隔 + 64.0 + 余白)
    );
}
