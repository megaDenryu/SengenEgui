//! 区間の帯のドラッグの間に、利用する側が全体の範囲を変えても、移動量を掴み始めた回の目盛りで値の差へ直すことを確かめる。
//! 区間の帯の値は掴み始めの値に押した位置からの移動量を足して求めるため、毎フレームの目盛りで直すと、範囲が変わったときに
//! 同じ移動量が違う差を表してしまう。

mod common;

use std::cell::Cell;

use common::range_band::{
    全体の終わりを指定した帯の木, 放した, 横へドラッグする, 点, 近い
};
use sengen_egui::{ノード, 区間の帯の掴んだもの, 区間の帯の操作};

/// 最初の2回（配置を決める回と押す回）は全体の範囲 0〜100、3回目からは 0〜200 で、区間 20〜60 の帯を組む関数を作る。
fn 押した後に全体の範囲を伸ばす木() -> impl Fn() -> ノード<区間の帯の操作> {
    let 描いた回数 = Cell::new(0_u32);
    move || {
        let 終わり = if 描いた回数.get() < 2 {
            100.0
        } else {
            200.0
        };
        描いた回数.set(描いた回数.get() + 1);
        全体の終わりを指定した帯の木(終わり, 20.0, 60.0, None)
    }
}

#[test]
fn ドラッグの間に全体の範囲が伸びても区間の内側は掴み始めた回の目盛りで動く() {
    let 木を組む = 押した後に全体の範囲を伸ばす木();
    let 集まり = 横へドラッグする(点().帯の領域(40.0), 20.0, &木を組む);
    let 掴んだもの = 区間の帯の掴んだもの::区間の内側;
    assert!(近い(集まり.last(), 放した(掴んだもの, 30.0)), "{集まり:?}");
}
