//! 位置を渡していない区間の帯で、つまみにも区間の内側にも当たらない所を押すと `区間の外` を掴んだと発し、
//! 値が押した位置の値で始まり、動かすとポインタの横の位置の値を運ぶことを確かめる。
//! 位置を渡している帯で同じ所を押したときは、従来どおり位置の印を押した位置へ移して掴む。

mod common;

use common::range_band::{帯の上の点, 帯の木, 掴み始めた, 放した, 近い};
use sengen_egui::{区間の帯の掴んだもの, 区間の帯の操作};

use 区間の帯の掴んだもの::{位置の印, 区間の外};

fn 点() -> 帯の上の点 {
    帯の上の点::読み取る(&egui::Context::default())
}

#[test]
fn 位置の無い帯で区間の外を押して放すと押した位置の値で区間の外を発する() {
    let 集まり = common::左クリックする(&egui::Context::default(), 点().帯の段(90.0), &|| {
        帯の木(20.0, 60.0, None)
    });
    assert_eq!(集まり.len(), 2, "{集まり:?}");
    assert!(
        近い(集まり.first(), 掴み始めた(区間の外, 90.0)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(区間の外, 90.0)), "{集まり:?}");
}

#[test]
fn 位置の無い帯で区間の外を掴んで動かすとポインタの位置の値を運ぶ() {
    let 始点 = 点().帯の段(5.0);
    let 集まり = common::drag::左ドラッグする(
        &egui::Context::default(),
        始点,
        始点 + egui::vec2(20.0, 0.0),
        &|| 帯の木(20.0, 60.0, None),
    );
    assert!(
        近い(集まり.first(), 掴み始めた(区間の外, 5.0)),
        "{集まり:?}"
    );
    assert!(
        集まり.iter().any(|操作| matches!(
            操作,
            区間の帯の操作::動かしている {
                掴んだもの: 区間の外,
                ..
            }
        )),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(区間の外, 15.0)), "{集まり:?}");
}

#[test]
fn 位置のある帯で区間の外を押すと従来どおり位置の印を押した位置へ移す() {
    let 集まり = common::左クリックする(&egui::Context::default(), 点().帯の段(90.0), &|| {
        帯の木(20.0, 60.0, Some(10.0))
    });
    assert!(
        近い(集まり.first(), 掴み始めた(位置の印, 90.0)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(位置の印, 90.0)), "{集まり:?}");
}
