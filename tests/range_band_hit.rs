//! 区間の帯の当たりの優先の順を確かめる。位置の印（上の段）> 開始・終了のつまみ > 区間の内側 > 区間の外（位置の印を移す）の順で、
//! 開始と終了のつまみが重なったときは近い方、同じ距離なら押した位置が開始より左のとき開始を掴む。

mod common;

use common::range_band::{帯の上の点, 帯の木};
use sengen_egui::{ノード, 区間の帯の掴んだもの, 区間の帯の操作};

/// 点を押して放し、最初に発した操作の掴んだものを返す。何も発しなければ None である。
fn 押して掴んだもの(
    点: egui::Pos2,
    木を組む: &dyn Fn() -> ノード<区間の帯の操作>,
) -> Option<区間の帯の掴んだもの> {
    let 文脈 = egui::Context::default();
    let 集まり = common::左クリックする(&文脈, 点, 木を組む);
    集まり.first().map(|操作| match 操作 {
        区間の帯の操作::掴み始めた {
            掴んだもの, ..
        }
        | 区間の帯の操作::動かしている {
            掴んだもの, ..
        }
        | 区間の帯の操作::放した {
            掴んだもの, ..
        } => *掴んだもの,
    })
}

fn 点() -> 帯の上の点 {
    帯の上の点::読み取る(&egui::Context::default())
}

use 区間の帯の掴んだもの::{
    位置の印, 区間の内側, 終了のつまみ, 開始のつまみ
};

#[test]
fn 位置の印が開始のつまみに重なると上の段では位置の印を帯の段では開始のつまみを掴む() {
    let 木 = || 帯の木(20.0, 60.0, Some(20.0));
    assert_eq!(押して掴んだもの(点().上の段(20.0), &木), Some(位置の印));
    assert_eq!(押して掴んだもの(点().帯の段(20.0), &木), Some(開始のつまみ));
}

#[test]
fn つまみの当たりは描く幅より広く区間の内側より優先する() {
    let 木 = || 帯の木(20.0, 60.0, Some(80.0));
    let つまみの内側寄り = 点().帯の段(20.0) + egui::vec2(6.0, 0.0);
    assert_eq!(押して掴んだもの(つまみの内側寄り, &木), Some(開始のつまみ));
    let 区間の中ほど = 点().帯の段(40.0);
    assert_eq!(押して掴んだもの(区間の中ほど, &木), Some(区間の内側));
}

#[test]
fn 開始と終了が重なると近い方を掴み同じ距離なら左は開始で右は終了() {
    let 木 = || 帯の木(50.0, 50.0, None);
    let 中心 = 点().帯の段(50.0);
    assert_eq!(
        押して掴んだもの(中心 + egui::vec2(-1.0, 0.0), &木),
        Some(開始のつまみ)
    );
    assert_eq!(
        押して掴んだもの(中心 + egui::vec2(1.0, 0.0), &木),
        Some(終了のつまみ)
    );
    let 開始が少し左 = || 帯の木(49.0, 51.0, None);
    assert_eq!(
        押して掴んだもの(点().帯の段(49.5), &開始が少し左),
        Some(開始のつまみ)
    );
}

#[test]
fn 区間の外と上の段の印の無い所を押すと位置の印を掴む() {
    let 木 = || 帯の木(20.0, 60.0, Some(80.0));
    assert_eq!(押して掴んだもの(点().帯の段(5.0), &木), Some(位置の印));
    assert_eq!(押して掴んだもの(点().上の段(40.0), &木), Some(位置の印));
}

#[test]
fn 位置を渡さなければ区間の外を押しても何も発しない() {
    let 木 = || 帯の木(20.0, 60.0, None);
    assert_eq!(押して掴んだもの(点().帯の段(90.0), &木), None);
}

#[test]
fn 開始が終了を超えているときは区間の内側が無く間を押すと位置の印を掴む() {
    let 木 = || 帯の木(60.0, 20.0, Some(80.0));
    assert_eq!(押して掴んだもの(点().帯の段(40.0), &木), Some(位置の印));
}
