//! 押せる画像が押されると応答を発し、引き伸ばした画像では表示寸法の全体が押せる範囲になることを確かめる。

mod common;

use common::image::{描画した矩形, 横の範囲, 横長のテクスチャを登録する};
use sengen_egui::{ノード, 子, 画像, 画素の組, 縦積み};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    画像を押した,
}

#[test]
fn 押せる画像を押すと応答が出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&文脈);
    let 木を組む = || {
        縦積み(子![
            画像(テクスチャ.clone())
                .表示寸法(画素の組(64.0, 32.0))
                .押されたら発する(応答::画像を押した)
        ])
        .into()
    };
    let 集まり = common::左クリックする(&文脈, egui::pos2(30.0, 20.0), &木を組む);
    assert_eq!(集まり, vec![応答::画像を押した]);
}

#[test]
fn 押せる画像は写しても押すと写した応答が出る() {
    let 文脈 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&文脈);
    let 木を組む = || {
        ノード::from(画像(テクスチャ.clone()).押されたら発する(応答::画像を押した))
            .写す(|応答| format!("{応答:?}"))
    };
    let 集まり = common::左クリックする(&文脈, egui::pos2(30.0, 20.0), &木を組む);
    assert_eq!(集まり, vec!["画像を押した".to_string()]);
}

#[test]
fn 表示寸法へ引き伸ばした画像は表示寸法ちょうどに描き押せる範囲も全体になる() {
    let 文脈 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&文脈);
    let 木を組む = || {
        画像(テクスチャ.clone())
            .描く部分(横の範囲(0.25, 0.5))
            .表示寸法へ引き伸ばす(画素の組(200.0, 60.0))
            .押されたら発する(応答::画像を押した)
            .into()
    };
    assert_eq!(
        描画した矩形(&文脈, 木を組む()).size(),
        egui::vec2(200.0, 60.0)
    );
    let 左上 = 描画した矩形(&文脈, 木を組む()).min;
    let 右下の近く = 左上 + egui::vec2(195.0, 55.0);
    let 集まり = common::左クリックする(&文脈, 右下の近く, &木を組む);
    assert_eq!(集まり, vec![応答::画像を押した]);
}
