//! 公開APIだけでノード木の構築とスタイル合成を確かめる。
//! 描画そのものは egui の文脈が要るため対象外とする。

use sengen_egui::{スタイル, ボタン, 子, 文字列源, 文章, 条件, 縦積み};

#[test]
fn スタイルは上書き側を優先して重なる() {
    let 基本 = スタイル {
        文字サイズ: Some(12.0),
        太字: Some(true),
        ..スタイル::無指定
    };
    let 合成 = 基本.重ねる(スタイル {
        文字サイズ: Some(16.0),
        ..スタイル::無指定
    });
    assert_eq!(合成.文字サイズ, Some(16.0));
    assert_eq!(合成.太字, Some(true));
}

#[test]
fn 動的な文字列源は毎回最新値を取りに行く() {
    use std::{cell::Cell, rc::Rc};
    let 値 = Rc::new(Cell::new(1));
    let 参照 = Rc::clone(&値);
    let 源 = 文字列源::動的(Box::new(move || 参照.get().to_string()));
    assert_eq!(源.現在値(), "1");
    値.set(2);
    assert_eq!(源.現在値(), "2");
}

#[test]
fn ノード木を構築できる() {
    let _根 = 縦積み().子(子![
        文章("見出し"),
        ボタン("実行").押されたら(|| {}),
        条件(|| true, 文章("展開中")),
    ]);
}
