//! 公開APIだけで、木の構築・スタイル合成・描画と応答収集・応答の写像を確かめる。

mod common;

use sengen_egui::{
    スタイル, ノード, ボタン, 子, 文字表示, 条件付き表示, 画素, 縦積み, 表示の部品
};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    加算,
}

#[test]
fn スタイルは上書き側を優先して重なる() {
    let 基本 = スタイル {
        文字サイズ: Some(画素(12.0)),
        太字: Some(true),
        ..スタイル::無指定
    };
    let 合成 = 基本.重ねる(スタイル {
        文字サイズ: Some(画素(16.0)),
        ..スタイル::無指定
    });
    assert_eq!(合成.文字サイズ, Some(画素(16.0)));
    assert_eq!(合成.太字, Some(true));
}

#[test]
fn 条件は不成立なら無しになる() {
    let 節: ノード<応答> = 条件付き表示(false, || 文字表示("出ない"));
    assert!(matches!(節, ノード::無し));
    let 節: ノード<応答> = 条件付き表示(true, || 文字表示("出る"));
    assert!(matches!(節, ノード::表示(表示の部品::文字表示(_))));
}

#[test]
fn 描画できて操作が無ければ応答は空になる() {
    let 文脈 = egui::Context::default();
    let 木を組む = || {
        縦積み(子![
            文字表示("見出し"),
            ボタン("実行", 応答::加算),
            条件付き表示(true, || 文字表示("展開中")),
        ])
        .into()
    };
    assert!(common::描画する(&文脈, vec![], &木を組む).is_empty());
}

#[test]
fn クリックを合成するとボタンの応答が写された値で集まる() {
    let 文脈 = egui::Context::default();
    let 木を組む = || {
        let 木: ノード<u8> = 縦積み(子![ボタン("押す", 1u8).最小幅(画素(300.0))]).into();
        木.写す(|番号| 番号 + 10)
    };
    let 集まり = common::左クリックする(&文脈, egui::pos2(30.0, 18.0), &木を組む);
    assert_eq!(集まり, vec![11]);
}
