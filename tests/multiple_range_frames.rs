//! 複数の範囲枠が、掴んだ部分と開始点からの累積の移動量をドラッグの段階ごとに、掴んだ枠の応答として発することを確かめる。

mod common;

use common::multiple_range_frames::{
    二つの枠の木, 基準の矩形の中の位置, 置いた枠, 選んでいる枠
};
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

fn 移動量(横: f32, 縦: f32) -> 縦横の割合の差 {
    縦横の割合の差::生成する(割合の差::生成する(横), 割合の差::生成する(縦))
}

#[test]
fn 選んでいない枠の内側をドラッグすると選んだに続いて内側を掴んだ操作がその枠の応答で出る() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.2, 0.2);
    let 終点 = 始点 + egui::vec2(20.0, 10.0);
    let 集まり = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &|| {
        二つの枠の木(選んでいる枠::無し)
    });
    let 掴んだ部分 = 範囲枠の掴んだ部分::内側;
    assert_eq!(
        集まり.get(..2),
        Some(
            &[
                (置いた枠::奥, 複数の範囲枠の操作::選んだ),
                (置いた枠::奥, 複数の範囲枠の操作::掴み始めた { 掴んだ部分 }),
            ][..]
        ),
        "{集まり:?}"
    );
    let 期待 = 複数の範囲枠の操作::放した {
        掴んだ部分,
        開始点からの移動量: 移動量(0.1, 0.1),
        縦横比: 縦横比の扱い::保たない,
    };
    assert_eq!(集まり.last(), Some(&(置いた枠::奥, 期待)), "{集まり:?}");
    assert!(
        集まり.iter().any(|(枠, 操作)| *枠 == 置いた枠::奥
            && matches!(操作, 複数の範囲枠の操作::動かしている { .. }))
    );
    assert!(
        集まり.iter().all(|(枠, _)| *枠 == 置いた枠::奥),
        "{集まり:?}"
    );
}

#[test]
fn 選んでいる枠の右下の隅をドラッグすると選んだを発さずに右下の隅を掴んだ操作が出る() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.9, 0.9);
    let 終点 = 始点 + egui::vec2(-40.0, -20.0);
    let 集まり = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &|| {
        二つの枠の木(選んでいる枠::手前)
    });
    let 掴んだ部分 = 範囲枠の掴んだ部分::右下の隅;
    assert_eq!(
        集まり.first(),
        Some(&(
            置いた枠::手前,
            複数の範囲枠の操作::掴み始めた { 掴んだ部分 }
        ))
    );
    let 期待 = 複数の範囲枠の操作::放した {
        掴んだ部分,
        開始点からの移動量: 移動量(-0.2, -0.2),
        縦横比: 縦横比の扱い::保たない,
    };
    assert_eq!(集まり.last(), Some(&(置いた枠::手前, 期待)), "{集まり:?}");
}

#[test]
fn 写した木でも枠ごとの操作が写した応答で出る() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.8, 0.8);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 木を組む =
        || 二つの枠の木(選んでいる枠::無し).写す(|(枠, 操作)| format!("{枠:?} {操作:?}"));
    let 集まり = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert_eq!(集まり.first().map(String::as_str), Some("手前 選んだ"));
    assert!(
        集まり
            .last()
            .is_some_and(|文| 文.starts_with("手前 放した")),
        "{集まり:?}"
    );
}
