//! 単位付きの数値（論理画素・割合）が、生成の口の約束どおりに振る舞うことを確かめる。

use sengen_egui::{
    余白の画素, 余白画素, 割合, 割合の範囲外, 拡大率, 拡大率の範囲外, 整数画素の範囲外, 画素,
    画素の組, 角丸の画素, 論理画素,
};

#[test]
fn 論理画素は加減と倍率の掛け算ができる() {
    let 和 = 画素(8.0) + 画素(4.0);
    assert_eq!(和, 画素(12.0));
    assert_eq!(和 - 画素(2.0), 画素(10.0));
    assert_eq!(画素(3.0) * 2.0, 画素(6.0));
    assert_eq!(画素(3.0).大きい方(画素(5.0)), 画素(5.0));
    assert_eq!(論理画素::ゼロ.eguiへ渡す値(), 0.0);
}

#[test]
fn 縦横の論理画素はeguiのベクトルと位置へ変換できる() {
    let 組 = 画素の組(8.0, 4.0);
    assert_eq!(組.eguiへ渡す値(), egui::vec2(8.0, 4.0));
    assert_eq!(組.eguiの位置へ渡す値(), egui::pos2(8.0, 4.0));
}

#[test]
fn 割合の生成は範囲外を理由付きで断る() {
    assert_eq!(割合::生成する(0.5).map(|値| 値.eguiへ渡す値()), Ok(0.5));
    assert_eq!(割合::生成する(-0.1), Err(割合の範囲外::負である(-0.1)));
    assert_eq!(割合::生成する(1.5), Err(割合の範囲外::一を超える(1.5)));
    assert_eq!(割合::生成する(f32::NAN), Err(割合の範囲外::数でない));
}

#[test]
fn 割合の丸める生成は範囲へ収める() {
    assert_eq!(割合::範囲へ丸めて生成する(-3.0), 割合::ゼロ);
    assert_eq!(割合::範囲へ丸めて生成する(7.0), 割合::全部);
    assert_eq!(割合::範囲へ丸めて生成する(f32::NAN), 割合::ゼロ);
    assert_eq!(割合::範囲へ丸めて生成する(0.25).eguiへ渡す値(), 0.25);
}

#[test]
fn 整数の画素は実行時の範囲外を理由付きで断る() {
    assert_eq!(
        余白の画素::生成を試みる(8).map(|値| 値.eguiへ渡す値()),
        Ok(8)
    );
    assert_eq!(
        余白の画素::生成を試みる(-1),
        Err(整数画素の範囲外::負である(-1))
    );
    assert!(matches!(
        余白の画素::生成を試みる(200),
        Err(整数画素の範囲外::上限を超える { 上限: 127, .. })
    ));
    assert_eq!(
        角丸の画素::生成を試みる(255).map(|値| 値.eguiへ渡す値()),
        Ok(255)
    );
    assert!(matches!(
        角丸の画素::生成を試みる(256),
        Err(整数画素の範囲外::上限を超える { 上限: 255, .. })
    ));
    const 定数: 余白の画素 = 余白画素(12);
    assert_eq!(定数.eguiへ渡す値(), 12);
}

#[test]
fn 拡大率は正の有限な値だけを受け付ける() {
    assert_eq!(拡大率::生成する(1.5).map(|値| 値.eguiへ渡す値()), Ok(1.5));
    assert_eq!(拡大率::生成する(0.0), Err(拡大率の範囲外::正でない(0.0)));
    assert_eq!(
        拡大率::生成する(f32::INFINITY),
        Err(拡大率の範囲外::有限でない)
    );
    assert_eq!(拡大率::範囲外なら等倍にして生成する(-2.0), 拡大率::等倍);
}
