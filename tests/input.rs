//! 入力の部品が描画でき、合成した入力で応答を発行し、`写す` で応答が変換されることを確かめる。

mod common;

use sengen_egui::{
    スライダー, チェックボックス, ノード, ボタン, ラジオボタン, リンク, 一行テキスト入力, 子,
    数値入力, 画素, 縦積み, 色選択, 複数行テキスト入力, 選択ボタン, 選択欄, 選択肢,
};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    押した,
    切り替えた(bool),
    文字を変えた(String),
    数を変えた(i32),
    選んだ(&'static str),
    色を変えた(egui::Color32),
}

fn 全部の入力部品() -> ノード<応答> {
    縦積み(子![
        ボタン("押す", 応答::押した).小さい().枠なし(),
        チェックボックス("有効", true, 応答::切り替えた),
        一行テキスト入力("値", 応答::文字を変えた)
            .伏せ字()
            .案内文("案内"),
        複数行テキスト入力("複数行", 応答::文字を変えた)
            .行数(3)
            .等幅(),
        数値入力(3, 0..=10, 応答::数を変えた)
            .刻み(1)
            .前置き("x")
            .後置き("個"),
        スライダー(3, 0..=10, 応答::数を変えた)
            .文字を添える("量")
            .幅(画素(120.0)),
        ラジオボタン("甲", true, 応答::選んだ("甲")),
        選択ボタン("乙", false, 応答::選んだ("乙")),
        選択欄(
            "欄",
            "甲",
            vec![
                選択肢("甲", 応答::選んだ("甲")),
                選択肢("乙", 応答::選んだ("乙"))
            ]
        ),
        色選択(egui::Color32::RED, 応答::色を変えた),
        リンク("辿る", 応答::押した),
    ])
    .into()
}

#[test]
fn 全部の入力部品が描画できて操作が無ければ応答は空になる() {
    let 文脈 = egui::Context::default();
    assert!(common::描画する(&文脈, vec![], &全部の入力部品).is_empty());
}

#[test]
fn 写した木でも描画できる() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 全部の入力部品().写す(|応答| format!("{応答:?}"));
    assert!(common::描画する(&文脈, vec![], &木を組む).is_empty());
}

#[test]
fn スライダーの軌道を押すと新しい値の応答が出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 縦積み(子![スライダー(0, 0..=100, 応答::数を変えた)]).into();
    let 集まり = common::左クリックする(&文脈, egui::pos2(58.0, 18.0), &木を組む);
    assert!(
        集まり
            .iter()
            .any(|応答| matches!(応答, 応答::数を変えた(値) if *値 > 0)),
        "{集まり:?}"
    );
}

#[test]
fn 選択欄を開いて項目を押すとその選択肢の応答が出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || {
        縦積み(子![選択欄(
            "欄",
            "甲",
            vec![
                選択肢("甲", 応答::選んだ("甲")),
                選択肢("乙", 応答::選んだ("乙"))
            ]
        )])
        .into()
    };
    let 開いた = common::左クリックする(&文脈, egui::pos2(30.0, 18.0), &木を組む);
    assert!(開いた.is_empty(), "{開いた:?}");
    let 選んだ = common::左クリックする(&文脈, egui::pos2(30.0, 62.0), &木を組む);
    assert_eq!(選んだ, vec![応答::選んだ("乙")]);
}

#[test]
fn 選択ボタンを押すと応答が出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 縦積み(子![選択ボタン("乙", false, 応答::選んだ("乙"))]).into();
    let 集まり = common::左クリックする(&文脈, egui::pos2(20.0, 18.0), &木を組む);
    assert_eq!(集まり, vec![応答::選んだ("乙")]);
}
