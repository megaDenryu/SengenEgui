//! 割合で表した矩形が、4つの端からも左上と大きさからも、基準の矩形の外へ出ない組だけを受け取ることを確かめる。

use sengen_egui::{割合, 割合で表した矩形, 割合で表した矩形の不正};

/// 試験に書く 0〜1 の定数から割合を作る。範囲外を黙って丸めず、範囲外なら試験の書き誤りとして止める。
fn 割合にする(値: f32) -> 割合 {
    match 割合::生成する(値) {
        Ok(割合) => 割合,
        Err(範囲外) => panic!("試験の割合が範囲外である（到達したらバグ）: {範囲外}"),
    }
}

#[test]
fn 割合で表した矩形は左端が右端より右なら作れない() {
    let 左端 = 割合にする(0.8);
    let 右端 = 割合にする(0.2);
    let 結果 = 割合で表した矩形::生成する(左端, 割合::ゼロ, 右端, 割合::全部);
    assert_eq!(結果, Err(割合で表した矩形の不正::左端が右端より右にある));
}

#[test]
fn 割合で表した矩形は左上と大きさから作ると右端と下端が左上に大きさを足した位置になる() {
    let 結果 = 割合で表した矩形::左上と大きさから生成する(
        割合にする(0.25),
        割合にする(0.5),
        割合にする(0.5),
        割合にする(0.25),
    );
    let 期待 = 割合で表した矩形::生成する(
        割合にする(0.25),
        割合にする(0.5),
        割合にする(0.75),
        割合にする(0.75),
    );
    assert_eq!(結果, 期待);
    let 全体 = 割合で表した矩形::左上と大きさから生成する(
        割合::ゼロ,
        割合::ゼロ,
        割合::全部,
        割合::全部,
    );
    assert_eq!(全体, Ok(割合で表した矩形::全体));
}

#[test]
fn 割合で表した矩形は左上と大きさから作るとき基準の矩形の外へ出るなら作れない() {
    let 右へ出る = 割合で表した矩形::左上と大きさから生成する(
        割合にする(0.75),
        割合::ゼロ,
        割合にする(0.5),
        割合にする(0.5),
    );
    assert_eq!(
        右へ出る,
        Err(割合で表した矩形の不正::右端が基準の矩形の外にある)
    );
    let 下へ出る = 割合で表した矩形::左上と大きさから生成する(
        割合::ゼロ,
        割合にする(0.75),
        割合にする(0.5),
        割合にする(0.5),
    );
    assert_eq!(
        下へ出る,
        Err(割合で表した矩形の不正::下端が基準の矩形の外にある)
    );
}

#[test]
fn 割合で表した矩形は左上と大きさの和が単精度の丸めで1になる組を受け取り1を明らかに超える組を拒む()
{
    let 丸めで1になる = 割合で表した矩形::左上と大きさから生成する(
        割合にする(0.6),
        割合にする(0.55),
        割合にする(0.4),
        割合にする(0.45),
    );
    assert_eq!(丸めで1になる.map(割合で表した矩形::右端), Ok(割合::全部));
    let 明らかに超える = 割合で表した矩形::左上と大きさから生成する(
        割合にする(0.6),
        割合::ゼロ,
        割合にする(0.41),
        割合にする(0.5),
    );
    assert_eq!(
        明らかに超える,
        Err(割合で表した矩形の不正::右端が基準の矩形の外にある)
    );
}
