//! 時間の行の並びの位置の線を確かめる。時間の軸を押すと押した位置の値で掴み始め、ドラッグすると値が変わったときだけ
//! 動かしているを発し、放すと最後の値で放したを発する。全体の範囲の外までドラッグした値は全体の端に収める。

mod common;

use common::time_rows_point::時間の行の並びの上の点;

use common::time_rows::{見本の木, 試験の応答};
use sengen_egui::{位置の線の操作, 帯の値};

fn 位置の線の操作だけ(
    発した応答の一覧: Vec<試験の応答>
) -> Vec<位置の線の操作> {
    発した応答の一覧
        .into_iter()
        .filter_map(|応答| match 応答 {
            試験の応答::位置の線(操作) => Some(操作),
            _ => None,
        })
        .collect()
}

fn 値が近い(実際: 帯の値, 期待: f64) -> bool {
    (実際.倍精度の小数にする() - 期待).abs() < 1e-6
}

#[test]
fn 時間の軸を押すと押した位置の値で掴み始めて放す() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 操作一覧 = 位置の線の操作だけ(common::左クリックする(
        &eguiの本体,
        点.時間の軸(30.0),
        &|| 見本の木(None),
    ));
    assert!(
        matches!(
            操作一覧.as_slice(),
            [位置の線の操作::掴み始めた { 値: 始め }, 位置の線の操作::放した { 値: 終わり }]
                if 値が近い(*始め, 30.0) && 値が近い(*終わり, 30.0)
        ),
        "{操作一覧:?}"
    );
}

#[test]
fn 時間の軸をドラッグすると位置の線の値を動かして放した値で終える() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 操作一覧 = 位置の線の操作だけ(common::drag::左ドラッグする(
        &eguiの本体,
        点.時間の軸(30.0),
        点.時間の軸(70.0),
        &|| 見本の木(None),
    ));
    assert!(
        操作一覧.iter().any(|操作| matches!(
            操作,
            位置の線の操作::動かしている { 値 } if 値が近い(*値, 50.0)
        )),
        "{操作一覧:?}"
    );
    assert!(
        matches!(操作一覧.last(), Some(位置の線の操作::放した { 値 }) if 値が近い(*値, 70.0)),
        "{操作一覧:?}"
    );
}

#[test]
fn 全体の範囲の外までドラッグした位置の線の値は全体の端に収める() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 操作一覧 = 位置の線の操作だけ(common::drag::左ドラッグする(
        &eguiの本体,
        点.時間の軸(90.0),
        点.時間の軸(140.0),
        &|| 見本の木(None),
    ));
    assert!(
        matches!(操作一覧.last(), Some(位置の線の操作::放した { 値 }) if 値が近い(*値, 100.0)),
        "{操作一覧:?}"
    );
}
