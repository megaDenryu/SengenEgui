//! 重ねる容器が、重ねた子を下地より優先して押させ、覆いが下地への押下を止め、
//! 重ねた子を指定の位置へ寄せることを確かめる。

mod common;

use common::image::横長のテクスチャを登録する;
use sengen_egui::{
    スタイル, スライダー, ノード, ボタン, 大きさを決めた領域, 無し, 画像, 画素, 画素の組, 重ねる,
    重ねる位置,
};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    下地を押した,
    重ねたボタンを押した,
    下地の値を変えた(f32),
}

const 覆い: スタイル = スタイル {
    背景色: Some(egui::Color32::from_black_alpha(160)),
    ..スタイル::無指定
};

const 下地の寸法: (f32, f32) = (256.0, 128.0);

fn 下地(テクスチャ: &egui::TextureHandle) -> ノード<応答> {
    画像(テクスチャ.clone())
        .表示寸法(画素の組(下地の寸法.0, 下地の寸法.1))
        .押されたら発する(応答::下地を押した)
        .into()
}

/// 中央パネルの内余白の分だけずれた、下地の左上の位置。
/// 各試験は押す前に1回描画する。重ねる子は初めて描く回に大きさだけを測り、押せるのは次の回からである。
const 下地の左上: egui::Pos2 = egui::pos2(8.0, 8.0);

#[test]
fn 右下へ重ねたボタンは下地より優先して押され下地の他の場所は下地が押される() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&eguiの本体);
    let 木を組む = || {
        重ねる("重ね", 下地(&テクスチャ))
            .上に置く(重ねる位置::右下, ボタン("次へ", 応答::重ねたボタンを押した))
            .into()
    };
    let _ = common::描画する(&eguiの本体, vec![], &木を組む);
    let 右下の近く = 下地の左上 + egui::vec2(下地の寸法.0 - 16.0, 下地の寸法.1 - 16.0);
    let ボタンの押下 = common::左クリックする(&eguiの本体, 右下の近く, &木を組む);
    assert_eq!(ボタンの押下, vec![応答::重ねたボタンを押した]);
    let 左上の近く = 下地の左上 + egui::vec2(16.0, 16.0);
    let 下地の押下 = common::左クリックする(&eguiの本体, 左上の近く, &木を組む);
    assert_eq!(下地の押下, vec![応答::下地を押した]);
}

#[test]
fn 覆っている間は下地を押せず中央に重ねたボタンは押せる() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ = 横長のテクスチャを登録する(&eguiの本体);
    let 木を組む = || {
        重ねる("重ね", 下地(&テクスチャ))
            .覆って中央に置く(覆い, ボタン("次へ", 応答::重ねたボタンを押した))
            .into()
    };
    let _ = common::描画する(&eguiの本体, vec![], &木を組む);
    let 左上の近く = 下地の左上 + egui::vec2(16.0, 16.0);
    assert!(common::左クリックする(&eguiの本体, 左上の近く, &木を組む).is_empty());
    let 中央 = 下地の左上 + egui::vec2(下地の寸法.0 / 2.0, 下地の寸法.1 / 2.0);
    let 中央の押下 = common::左クリックする(&eguiの本体, 中央, &木を組む);
    assert_eq!(中央の押下, vec![応答::重ねたボタンを押した]);
}

#[test]
fn 覆っている間は下地のスライダーをドラッグできない() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = || {
        重ねる(
            "重ね",
            スライダー(0.5_f32, 0.0..=1.0, 応答::下地の値を変えた).幅(画素(200.0)),
        )
        .覆って中央に置く(覆い, 無し())
        .into()
    };
    let _ = common::描画する(&eguiの本体, vec![], &木を組む);
    let 集まり = common::drag::左ドラッグする(
        &eguiの本体,
        egui::pos2(20.0, 18.0),
        egui::pos2(180.0, 18.0),
        &木を組む,
    );
    assert!(集まり.is_empty(), "{集まり:?}");
}

#[test]
fn 中央へ重ねた幅いっぱいの子は次の回に範囲の幅で左端から描かれる() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = || {
        重ねる("重ね", 大きさを決めた領域(画素の組(300.0, 100.0), vec![]))
            .端からの間隔(画素(0.0))
            .上に置く(
                重ねる位置::中央,
                スライダー(0.5_f32, 0.0..=1.0, 応答::下地の値を変えた)
                    .幅いっぱい()
                    .数値を隠す(),
            )
            .into()
    };
    let _ = common::描画する(&eguiの本体, vec![], &木を組む);
    let 集まり =
        common::左クリックする(&eguiの本体, 下地の左上 + egui::vec2(4.0, 50.0), &木を組む);
    assert_eq!(
        集まり.first(),
        Some(&応答::下地の値を変えた(0.0)),
        "範囲の左端を押せば帯の左端の値になる"
    );
}
