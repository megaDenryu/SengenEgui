//! 重ねる容器の「ポインタが止まると隠して上に置く」子について、ポインタが動いたと数える条件と、下地の外へ出た回の扱いを確かめる。
//! 同じ位置への移動の知らせと、3論理画素未満の移動では出さず、最後に動いたと数えた位置から3論理画素以上離れたら出す。
//! ポインタが下地の外へ出たら（ウィンドウの外へ出た知らせを含む）、時間を待たずに隠す。

mod common;

use common::output::文字を描いたか;
use common::overlay_idle::{
    ポインタの移動, 下地の真ん中, 描く, 操作の欄を置いた木, 測りを済ませる,
};

/// 子の大きさを測り、ポインタを下地の真ん中に止めたまま子が隠れるまで時間を進めた egui の本体を返す。
fn 止めて隠れるまで待つ(
    木を組む: &dyn Fn() -> sengen_egui::ノード<()>
) -> egui::Context {
    let eguiの本体 = egui::Context::default();
    測りを済ませる(&eguiの本体, 木を組む);
    let 隠れた回 = 描く(&eguiの本体, 3.0, vec![], 木を組む);
    assert!(!文字を描いたか(&隠れた回, "操作の欄"));
    eguiの本体
}

#[test]
fn 同じ位置への移動の知らせでは出さずカーソルも隠したまま() {
    let 木を組む = 操作の欄を置いた木(false);
    let eguiの本体 = 止めて隠れるまで待つ(&木を組む);
    let 知らせた回 = 描く(&eguiの本体, 3.1, ポインタの移動(下地の真ん中), &木を組む);
    assert!(!文字を描いたか(&知らせた回, "操作の欄"));
    assert_eq!(
        知らせた回.platform_output.cursor_icon,
        egui::CursorIcon::None
    );
}

#[test]
fn 数えた位置から3論理画素未満の移動では出さず_積み重なって3論理画素以上離れたら出す() {
    let 木を組む = 操作の欄を置いた木(false);
    let eguiの本体 = 止めて隠れるまで待つ(&木を組む);
    let 少し = 下地の真ん中 + egui::vec2(2.0, 0.0);
    let 少し動かした回 = 描く(&eguiの本体, 3.1, ポインタの移動(少し), &木を組む);
    assert!(!文字を描いたか(&少し動かした回, "操作の欄"));
    let さらに = 下地の真ん中 + egui::vec2(3.0, 0.0);
    let さらに動かした回 = 描く(&eguiの本体, 3.2, ポインタの移動(さらに), &木を組む);
    assert!(文字を描いたか(&さらに動かした回, "操作の欄"));
}

#[test]
fn ウィンドウの外へ出た知らせですぐ隠し_戻ってきたら出す() {
    let 木を組む = 操作の欄を置いた木(false);
    let eguiの本体 = egui::Context::default();
    測りを済ませる(&eguiの本体, &木を組む);
    let _ = 描く(
        &eguiの本体,
        0.1,
        ポインタの移動(下地の真ん中 + egui::vec2(10.0, 0.0)),
        &木を組む,
    );
    let 出た回 = 描く(&eguiの本体, 0.2, vec![egui::Event::PointerGone], &木を組む);
    assert!(!文字を描いたか(&出た回, "操作の欄"));
    let 戻った回 = 描く(&eguiの本体, 0.3, ポインタの移動(下地の真ん中), &木を組む);
    assert!(文字を描いたか(&戻った回, "操作の欄"));
}

#[test]
fn 下地の外へ動かすとすぐ隠し_下地の外で動かしても出さない() {
    let 木を組む = 操作の欄を置いた木(false);
    let eguiの本体 = egui::Context::default();
    測りを済ませる(&eguiの本体, &木を組む);
    let 下地の外 = egui::pos2(500.0, 500.0);
    let 出た回 = 描く(&eguiの本体, 0.1, ポインタの移動(下地の外), &木を組む);
    assert!(!文字を描いたか(&出た回, "操作の欄"));
    let 外で動かした回 = 描く(
        &eguiの本体,
        0.2,
        ポインタの移動(下地の外 + egui::vec2(40.0, 0.0)),
        &木を組む,
    );
    assert!(!文字を描いたか(&外で動かした回, "操作の欄"));
}
