//! 時間の行の並びの塊の操作を確かめる。選んでいない塊を押すと選んだを発してから掴み始め、選んでいる塊を押しても選んだを
//! 発さない。横へのドラッグは時間の差を、別の行へのドラッグは行の差を、開始点からの累積の移動量で発する。

mod common;

use common::time_rows_point::{時間の行の並びの上の点, 行の高さ};

use common::time_rows::{
    最後に放した移動量が近い, 見本の木, 試験の塊, 試験の応答
};
use sengen_egui::{時間の塊の操作, 時間の行の番号};

#[test]
fn 選んでいない塊を押すと選んだを発してから掴み始めたを行の番号で発する() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(1.0, 50.0), &|| {
            見本の木(None)
        });
    let 掴み始めた = 発した応答の一覧.iter().find_map(|応答| match 応答 {
        試験の応答::塊(試験の塊::乙, 時間の塊の操作::掴み始めた { 行 }) => {
            Some(*行)
        }
        _ => None,
    });
    assert_eq!(
        発した応答の一覧.first(),
        Some(&試験の応答::塊(試験の塊::乙, 時間の塊の操作::選んだ)),
        "{発した応答の一覧:?}"
    );
    assert_eq!(
        掴み始めた.map(時間の行の番号::置いた順の番号),
        Some(1),
        "{発した応答の一覧:?}"
    );
    assert!(
        最後に放した移動量が近い(&発した応答の一覧, 試験の塊::乙, 0.0, 0),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 選んでいる塊を押しても選んだを発さない() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(1.0, 50.0), &|| {
            見本の木(Some(試験の塊::乙))
        });
    assert!(
        !発した応答の一覧.contains(&試験の応答::塊(試験の塊::乙, 時間の塊の操作::選んだ)),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 塊を横へドラッグすると時間の差を発する() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 始点 = 点.行の中(1.0, 45.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 発した応答の一覧 =
        common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &|| 見本の木(None));
    assert!(
        最後に放した移動量が近い(&発した応答の一覧, 試験の塊::乙, 10.0, 0),
        "{発した応答の一覧:?}"
    );
}

