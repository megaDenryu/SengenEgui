//! 時間の行の並びの塊のドラッグが、ドラッグの間に全体の範囲や行の数が変わっても、掴み始めた回の規則で移動量を発することを確かめる。
//! 利用する側は最後の塊を右へ動かすと全体の範囲を伸ばし、空の行を足し引きするため、その回の配置で数え直すと移動量が膨らみ、ずれる。

mod common;

use std::cell::Cell;

use common::time_rows::{
    塊, 最後に放した移動量が近い, 空の部品, 終わりを指定した空の部品, 試験の塊, 試験の応答,
};
use common::time_rows_point::{時間の行の並びの上の点, 行の高さ};
use sengen_egui::{ノード, 時間の行};

/// 最初の2回（配置を決める回と押す回）と、3回目からとで、組み方を変える木を作る関数を作る。
fn 押した後に組み方を変える木(
    押す前: fn() -> ノード<試験の応答>,
    押した後: fn() -> ノード<試験の応答>,
) -> impl Fn() -> ノード<試験の応答> {
    let 描いた回数 = Cell::new(0_u32);
    move || {
        let 押した後か = 描いた回数.get() >= 2;
        描いた回数.set(描いた回数.get() + 1);
        if 押した後か {
            押した後()
        } else {
            押す前()
        }
    }
}

/// 全体の範囲を指定して、塊 甲（10〜30）だけを置いた1つの行の木を組む。
fn 全体を指定した一つの行の木(終わり: f64) -> ノード<試験の応答> {
    終わりを指定した空の部品(終わり)
        .行を置く(時間の行().塊を置く(試験の塊::甲, 塊(10.0, 20.0)))
        .into()
}

/// 塊 甲（10〜30）を置いた行の上に、空の行を指定の数だけ積んだ木を組む。
fn 空の行を積んだ木(空の行の数: usize) -> ノード<試験の応答> {
    let 部品 = 空の部品().行を置く(時間の行().塊を置く(試験の塊::甲, 塊(10.0, 20.0)));
    (0..空の行の数)
        .fold(部品, |部品, _| 部品.行を置く(時間の行()))
        .into()
}

#[test]
fn ドラッグの間に全体の範囲が伸びても時間の差は掴み始めた回の目盛りで求める() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 1.0);
    let 始点 = 点.行の中(0.0, 20.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 木を組む = 押した後に組み方を変える木(
        || 全体を指定した一つの行の木(100.0),
        || 全体を指定した一つの行の木(200.0),
    );
    let 発した応答の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert!(
        最後に放した移動量が近い(&発した応答の一覧, 試験の塊::甲, 10.0, 0),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn ドラッグの間に行の数が増えても行の差は押した位置からの縦の移動量で数える() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 2.0);
    let 始点 = 点.行の中(0.0, 20.0);
    let 終点 = 始点 + egui::vec2(0.0, -行の高さ);
    let 木を組む =
        押した後に組み方を変える木(|| 空の行を積んだ木(1), || 空の行を積んだ木(3));
    let 発した応答の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert!(
        最後に放した移動量が近い(&発した応答の一覧, 試験の塊::甲, 0.0, 1),
        "{発した応答の一覧:?}"
    );
}
