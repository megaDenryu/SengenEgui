//! 割合の矩形へ置く容器が、子を容器の矩形に対する割合どおりの位置と大きさへ最初の回から描き、
//! 後に置いた子を上に重ねて先に押させることを確かめる。

mod common;

use common::ratio_place::{
    塗りつぶす子, 容器の左上, 左上と大きさの矩形, 押せる子, 色で塗った矩形
};
use sengen_egui::{スタイル, ノード, 割合の矩形へ置く, 画素の組, 色};

const 容器の地の色: 色 = 色::from_rgb(0, 160, 0);
const 甲の色: 色 = 色::from_rgb(200, 0, 0);
const 乙の色: 色 = 色::from_rgb(0, 0, 200);

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    甲を押した,
    乙を押した,
}

#[test]
fn 子は最初の回から容器の矩形に対する割合どおりの位置と大きさに描かれる() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = || -> ノード<()> {
        let 地 = スタイル {
            背景色: Some(容器の地の色),
            ..スタイル::無指定
        };
        割合の矩形へ置く(画素の組(400.0, 200.0))
            .装飾(地)
            .子を置く(
                左上と大きさの矩形(0.25, 0.5, 0.5, 0.25),
                塗りつぶす子(甲の色),
            )
            .子を置く(
                左上と大きさの矩形(0.0, 0.0, 0.25, 0.5),
                塗りつぶす子(乙の色),
            )
            .into()
    };
    let (_, 出力) = common::output::入力を指定して描画する(
        &eguiの本体,
        egui::RawInput::default(),
        &木を組む,
    );
    let 容器 = egui::Rect::from_min_size(容器の左上, egui::vec2(400.0, 200.0));
    assert_eq!(色で塗った矩形(&出力, 容器の地の色), vec![容器]);
    let 甲 = egui::Rect::from_min_size(
        容器の左上 + egui::vec2(100.0, 100.0),
        egui::vec2(200.0, 50.0),
    );
    assert_eq!(色で塗った矩形(&出力, 甲の色), vec![甲]);
    let 乙 = egui::Rect::from_min_size(容器の左上, egui::vec2(100.0, 100.0));
    assert_eq!(色で塗った矩形(&出力, 乙の色), vec![乙]);
}

#[test]
fn 重なった場所では後に置いた子が押され重ならない場所はそれぞれの子が押される() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = || -> ノード<応答> {
        割合の矩形へ置く(画素の組(400.0, 200.0))
            .子を置く(
                左上と大きさの矩形(0.0, 0.0, 0.5, 1.0),
                押せる子(応答::甲を押した),
            )
            .子を置く(
                左上と大きさの矩形(0.25, 0.0, 0.5, 1.0),
                押せる子(応答::乙を押した),
            )
            .into()
    };
    let 押す = |横: f32| {
        common::左クリックする(&eguiの本体, 容器の左上 + egui::vec2(横, 100.0), &木を組む)
    };
    assert_eq!(押す(50.0), vec![応答::甲を押した]);
    assert_eq!(押す(150.0), vec![応答::乙を押した]);
    assert_eq!(押す(250.0), vec![応答::乙を押した]);
    assert!(押す(350.0).is_empty());
}

#[test]
fn 応答を写した容器の子は写した応答を発する() {
    #[derive(Clone, PartialEq, Debug)]
    enum 外側の応答 {
        内側(応答),
    }
    let eguiの本体 = egui::Context::default();
    let 木を組む = || -> ノード<外側の応答> {
        let 内側の木: ノード<応答> = 割合の矩形へ置く(画素の組(400.0, 200.0))
            .子を置く(
                左上と大きさの矩形(0.5, 0.5, 0.5, 0.5),
                押せる子(応答::甲を押した),
            )
            .into();
        内側の木.写す(外側の応答::内側)
    };
    let 集まり = common::左クリックする(
        &eguiの本体,
        容器の左上 + egui::vec2(300.0, 150.0),
        &木を組む,
    );
    assert_eq!(集まり, vec![外側の応答::内側(応答::甲を押した)]);
}
