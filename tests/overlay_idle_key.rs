//! 重ねる容器の「ポインタが止まると隠して上に置く」子が、`キーを押している間は出す` で指定したキーを押している間は出て、
//! 放してから指定の時間で隠れることを確かめる。指定しないキーでは出さない。キーの押下の出来事を先に描いた
//! キー操作の部品が消費していても効くことを、木の先頭にキー操作を置いて確かめる。

mod common;

use common::output::文字を描いたか;
use common::overlay_idle::{描く, 測りを済ませる, 隠すまでの時間};
use sengen_egui::{
    キー, キーの組, キー操作, ノード, ボタン, ポインタが止まると隠す指定, 大きさを決めた領域, 子,
    画素の組, 縦積み, 重ねる, 重ねる位置,
};

fn 左右のキーで出す木() -> ノード<()> {
    let 指定 = ポインタが止まると隠す指定::作成する(隠すまでの時間)
        .キーを押している間は出す(&[キー::ArrowLeft, キー::ArrowRight]);
    縦積み(子![
        キー操作(キーの組::単独(キー::ArrowLeft), ()),
        重ねる("重ね", 大きさを決めた領域(画素の組(300.0, 200.0), vec![]))
            .ポインタが止まると隠して上に置く(
                重ねる位置::下,
                指定,
                ボタン("操作の欄", ())
            ),
    ])
    .into()
}

fn キーの出来事(キー: egui::Key, 押した: bool) -> egui::Event {
    egui::Event::Key {
        key: キー,
        physical_key: None,
        pressed: 押した,
        repeat: false,
        modifiers: egui::Modifiers::NONE,
    }
}

#[test]
fn 指定したキーを押している間は出し_放してから指定の時間で隠す() {
    let eguiの本体 = egui::Context::default();
    測りを済ませる(&eguiの本体, &左右のキーで出す木);
    let 隠れた回 = 描く(&eguiの本体, 3.0, vec![], &左右のキーで出す木);
    assert!(!文字を描いたか(&隠れた回, "操作の欄"));
    let 押した回 = 描く(
        &eguiの本体,
        3.1,
        vec![キーの出来事(キー::ArrowLeft, true)],
        &左右のキーで出す木,
    );
    assert!(文字を描いたか(&押した回, "操作の欄"));
    let 押している回 = 描く(&eguiの本体, 8.0, vec![], &左右のキーで出す木);
    assert!(文字を描いたか(&押している回, "操作の欄"));
    let _ = 描く(
        &eguiの本体,
        8.1,
        vec![キーの出来事(キー::ArrowLeft, false)],
        &左右のキーで出す木,
    );
    let 放して過ぎた回 = 描く(&eguiの本体, 10.5, vec![], &左右のキーで出す木);
    assert!(!文字を描いたか(&放して過ぎた回, "操作の欄"));
}

#[test]
fn 指定しないキーでは出さない() {
    let eguiの本体 = egui::Context::default();
    測りを済ませる(&eguiの本体, &左右のキーで出す木);
    let _ = 描く(&eguiの本体, 3.0, vec![], &左右のキーで出す木);
    let 押した回 = 描く(
        &eguiの本体,
        3.1,
        vec![キーの出来事(キー::Enter, true)],
        &左右のキーで出す木,
    );
    assert!(!文字を描いたか(&押した回, "操作の欄"));
}
