//! 区間の帯を外側の押せる領域（付け足しの `.押されたら発する`）の中に置いたとき、帯の上の押下が外側へ届かず、
//! 帯の外の部品の無い所を押したときだけ外側の応答が出ることを確かめる。帯はドラッグだけを受けるが、egui は一番上の部品が
//! ドラッグだけを受けるとき、その下の押すことを受ける部品へ押下を渡さない。

mod common;

use common::range_band::{帯の上の点, 帯の木};
use sengen_egui::{
    スタイル, ノード, 付け足せる, 余白画素, 子, 文字表示, 縦積み
};

const 外側の応答: &str = "外側を押した";

/// 札の装飾。利用する側の札と同じく、地の色と内余白を持つ枠で包む。
const 札の装飾: スタイル = スタイル {
    背景色: Some(egui::Color32::DARK_GRAY),
    内余白: Some(余白画素(10)),
    ..スタイル::無指定
};

/// 札の内余白の分だけ、帯の上の点をずらす量。
const 内余白の分: egui::Vec2 = egui::vec2(10.0, 10.0);

fn 位置のある札() -> ノード<String> {
    札(Some(80.0))
}

fn 位置の無い札() -> ノード<String> {
    札(None)
}

fn 札(位置: Option<f64>) -> ノード<String> {
    縦積み(子![
        帯の木(20.0, 60.0, 位置).写す(|操作| format!("{操作:?}")),
        文字表示("札の見出し"),
    ])
    .装飾(札の装飾)
    .押されたら発する(外側の応答.to_string())
}

fn 点() -> 帯の上の点 {
    帯の上の点::読み取る(&egui::Context::default())
}

#[test]
fn 帯の上を動かさずに押して放しても外側の押せる領域は応答を発しない() {
    let 押す点の一覧 = [
        点().帯の段(90.0),
        点().帯の段(20.0),
        点().帯の段(40.0),
        点().上の段(80.0),
    ];
    let 札の一覧: [fn() -> ノード<String>; 2] = [位置のある札, 位置の無い札];
    for (札を組む, 押す点) in 札の一覧
        .into_iter()
        .flat_map(|札を組む| 押す点の一覧.map(|押す点| (札を組む, 押す点)))
    {
        let 押す点 = 押す点 + 内余白の分;
        let 集まり = common::左クリックする(&egui::Context::default(), 押す点, &札を組む);
        assert!(
            !集まり.iter().any(|応答| 応答 == 外側の応答),
            "{押す点:?} で {集まり:?}"
        );
        assert!(
            集まり.last().is_some_and(|応答| 応答.starts_with("放した")),
            "{押す点:?} で {集まり:?}"
        );
    }
}

#[test]
fn 帯の外の部品の無い所を押すと外側の押せる領域が応答を発する() {
    let 帯の下 = 点().帯の段(80.0) + 内余白の分 + egui::vec2(0.0, 25.0);
    let 集まり = common::左クリックする(&egui::Context::default(), 帯の下, &位置のある札);
    assert_eq!(集まり, vec![外側の応答.to_string()]);
}
