//! 時間の行の並びの試験の共通部。全体の範囲 0〜100 を幅200論理画素の行の並びへ写した木を組む（1 の値が2論理画素に当たる）。
//! 値と行の番号から画面の点を求める手順は `time_rows_point` に置く。見本の木は3つの行を下から積む。番号0の行（いちばん下）に塊 甲（10〜30）、番号1の行に
//! 塊 乙（40〜60）と塊 丙（70〜80）を置き、番号2の行（いちばん上）は空にする。

use sengen_egui::{
    ノード, 位置の線の操作, 帯の値, 帯の値の差, 帯の全体の範囲, 時間の塊, 時間の塊の操作, 時間の行,
    時間の行の並び, 時間の行の並び型, 時間の行型, 画素,
};

/// 試験の塊とは、見本の木に置いた塊の区別のことであり、部品へ渡す塊の鍵である。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 試験の塊 {
    甲,
    乙,
    丙,
    丁,
    戊,
}

/// 試験の応答とは、見本の木が発する、塊の操作と位置の線の操作と、何も無い所を押したことの区別のことである。
#[derive(Clone, Debug, PartialEq)]
pub enum 試験の応答 {
    塊(試験の塊, 時間の塊の操作),
    位置の線(位置の線の操作),
    何も無い所,
}

pub fn 値(数: f64) -> 帯の値 {
    帯の値::倍精度の小数から生成する(数)
}

pub fn 塊(始まり: f64, 長さ: f64) -> 時間の塊 {
    match 時間の塊::生成する(値(始まり), 帯の値の差::倍精度の小数から生成する(長さ))
    {
        Ok(塊) => 塊,
        Err(不正) => panic!("試験の塊が不正である（到達したらバグ）: {不正}"),
    }
}

/// 塊を、選んでいる塊なら選んでいる塊として置く。
pub fn 置く(
    行: 時間の行型<試験の塊>,
    選んでいる: Option<試験の塊>,
    鍵: 試験の塊,
    置く塊: 時間の塊,
) -> 時間の行型<試験の塊> {
    if 選んでいる == Some(鍵) {
        行.選んでいる塊を置く(鍵, 置く塊)
    } else {
        行.塊を置く(鍵, 置く塊)
    }
}

/// 全体の範囲 0〜100・幅216論理画素（行の並びは200論理画素）で、何も無い所を知らせる部品を、行を置かずに組む。
pub fn 空の部品() -> 時間の行の並び型<試験の応答, 試験の塊> {
    let Ok(全体) = 帯の全体の範囲::生成する(値(0.0), 値(100.0)) else {
        panic!("0〜100 は正しい全体の範囲である");
    };
    時間の行の並び(全体, 試験の応答::塊)
        .幅(画素(216.0))
        .何も無い所を押したら発する(試験の応答::何も無い所)
}

/// 見本の3つの行を置いた部品を組む。位置の線は50に置き、動かせるかを選べる。
pub fn 見本の部品(
    選んでいる: Option<試験の塊>,
    位置の線を動かせる: bool,
) -> 時間の行の並び型<試験の応答, 試験の塊> {
    let 部品 = 空の部品()
        .行を置く(置く(時間の行(), 選んでいる, 試験の塊::甲, 塊(10.0, 20.0)))
        .行を置く(置く(
            置く(時間の行(), 選んでいる, 試験の塊::乙, 塊(40.0, 20.0)),
            選んでいる,
            試験の塊::丙,
            塊(70.0, 10.0),
        ))
        .行を置く(時間の行())
        .位置の線を置く(値(50.0));
    if 位置の線を動かせる {
        部品.位置の線を動かしたら発する(試験の応答::位置の線)
    } else {
        部品
    }
}

/// 位置の線を動かせる見本の木を組む。
pub fn 見本の木(選んでいる: Option<試験の塊>) -> ノード<試験の応答> {
    見本の部品(選んでいる, true).into()
}

/// 時間の差が期待に百万分の一未満で近く、行の差が等しいか。egui は位置を単精度の小数で持つため、時間は丸めの誤差を含む。
pub fn 移動量が近い(
    実際: sengen_egui::時間の塊の移動量, 時間: f64, 行: i32
) -> bool {
    (実際.時間.倍精度の小数にする() - 時間).abs() < 1e-6 && 実際.行.上へ動かした行の数() == 行
}

/// 最後に発した応答が、指定の塊の放したで、移動量が期待に近いか。
pub fn 最後に放した移動量が近い(
    発した応答の一覧: &[試験の応答],
    鍵: 試験の塊,
    時間: f64,
    行: i32,
) -> bool {
    matches!(
        発した応答の一覧.last(),
        Some(試験の応答::塊(放した鍵, 時間の塊の操作::放した { 開始点からの移動量 }))
            if *放した鍵 == 鍵 && 移動量が近い(*開始点からの移動量, 時間, 行)
    )
}
