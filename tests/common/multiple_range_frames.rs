//! 複数の範囲枠の試験の共通部。奥と手前の2つの枠を重ねて置いた見本の木の組み立てと、基準の矩形の左上の画面上の位置の読み取り。
//! 基準の矩形は幅200・高さ100で、奥の枠は割合で (0.1, 0.1)〜(0.6, 0.6)、手前の枠は (0.4, 0.4)〜(0.9, 0.9) を占める。
//! 2つの枠は (0.4, 0.4)〜(0.6, 0.6) で重なる。

use sengen_egui::{
    ノード, 割合, 割合で表した矩形, 大きさを決めた領域, 画素の組, 複数の範囲枠,
    複数の範囲枠の周りの余白, 複数の範囲枠の操作,
};

/// 置いた枠とは、見本の木に置いた2つの枠のどちらかの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 置いた枠 {
    奥,
    手前,
}

/// 見本の木が発する応答。どの枠の操作かと、その操作の組である。
pub type 枠の操作 = (置いた枠, 複数の範囲枠の操作);

/// 見本の木で選んでいる枠の区別。
#[derive(Clone, Copy)]
pub enum 選んでいる枠 {
    無し,
    奥,
    手前,
}

fn 矩形(左端: f32, 上端: f32, 右端: f32, 下端: f32) -> 割合で表した矩形 {
    let 割合にする = |値: f32| match 割合::生成する(値) {
        Ok(割合) => 割合,
        Err(範囲外) => panic!("試験の割合が範囲外である（到達したらバグ）: {範囲外}"),
    };
    match 割合で表した矩形::生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(右端),
        割合にする(下端),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => panic!("試験の矩形が不正である（到達したらバグ）: {不正}"),
    }
}

/// 奥と手前の2つの枠を置いた木を組む。縦横比を保つ指定は付けない。
pub fn 二つの枠の木(選んでいる: 選んでいる枠) -> ノード<枠の操作> {
    二つの枠の部品(選んでいる).into()
}

/// 奥と手前の2つの枠を置き、Shift を押している間は縦横比を保たないと指定した木を組む。
pub fn 縦横比を保つ二つの枠の木(
    選んでいる: 選んでいる枠
) -> ノード<枠の操作> {
    二つの枠の部品(選んでいる)
        .縦横比を保つ(egui::Modifiers::SHIFT)
        .into()
}

fn 二つの枠の部品(
    選んでいる: 選んでいる枠,
) -> sengen_egui::複数の範囲枠型<枠の操作> {
    let 寸法 = 画素の組(200.0, 100.0);
    let 部品 = 複数の範囲枠(寸法, 大きさを決めた領域(寸法, vec![]));
    let 奥の矩形 = 矩形(0.1, 0.1, 0.6, 0.6);
    let 手前の矩形 = 矩形(0.4, 0.4, 0.9, 0.9);
    let 奥の操作 = |操作| (置いた枠::奥, 操作);
    let 手前の操作 = |操作| (置いた枠::手前, 操作);
    match 選んでいる {
        選んでいる枠::無し => 部品
            .枠を置く(奥の矩形, 奥の操作)
            .枠を置く(手前の矩形, 手前の操作),
        選んでいる枠::奥 => 部品
            .選んだ枠を置く(奥の矩形, 奥の操作)
            .枠を置く(手前の矩形, 手前の操作),
        選んでいる枠::手前 => 部品
            .枠を置く(奥の矩形, 奥の操作)
            .選んだ枠を置く(手前の矩形, 手前の操作),
    }
}

/// 基準の矩形の中の割合の位置の、画面上の位置。中央パネルの内余白は最初の配置から読み取り、部品が基準の矩形の
/// 周りに確保する余白を足す。
pub fn 基準の矩形の中の位置(
    eguiの本体: &egui::Context, 横: f32, 縦: f32
) -> egui::Pos2 {
    let mut 左上 = egui::Pos2::ZERO;
    let _ = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
        egui::CentralPanel::default().show(eguiの本体, |ui| 左上 = ui.cursor().min);
    });
    左上 + egui::Vec2::splat(複数の範囲枠の周りの余白.eguiへ渡す値())
        + egui::vec2(200.0 * 横, 100.0 * 縦)
}
