//! 重ねる容器の「ポインタが止まると隠して上に置く」試験の共通部。下地の下の辺に「操作の欄」を1つ置いた木と、
//! 時刻と出来事を指定した1フレームの描画と、子の大きさを測る最初の回。

use std::time::Duration;

use sengen_egui::{
    ノード, ボタン, ポインタが止まると隠す指定, 大きさを決めた領域, 画素の組, 重ねる, 重ねる位置,
};

use super::output::入力を指定して描画する;

/// 試験の指定で渡す、ポインタが止まってから子を隠すまでの時間。
pub const 隠すまでの時間: Duration = Duration::from_secs(2);

/// 中央パネルの内余白の分だけずれた、300×200の下地の中の、子と重ならない位置。
pub const 下地の真ん中: egui::Pos2 = egui::pos2(158.0, 58.0);

/// 下地の下の辺の中央に寄せた「操作の欄」の真ん中。
pub const 操作の欄の真ん中: egui::Pos2 = egui::pos2(158.0, 188.0);

/// 下地の下の辺に「操作の欄」をポインタが止まると隠して置く木。隠している間はカーソルも隠す。
pub fn 操作の欄を置いた木(
    出したままにするか: bool
) -> impl Fn() -> ノード<()> {
    move || {
        let 指定 = ポインタが止まると隠す指定::作成する(隠すまでの時間)
            .出したままにする(出したままにするか)
            .隠している間はカーソルも隠す();
        重ねる("重ね", 大きさを決めた領域(画素の組(300.0, 200.0), vec![]))
            .ポインタが止まると隠して上に置く(
                重ねる位置::下,
                指定,
                ボタン("操作の欄", ()),
            )
            .into()
    }
}

/// 時刻（起動からの秒）と出来事を指定して1フレーム描画し、egui の出力を返す。
pub fn 描く(
    eguiの本体: &egui::Context,
    秒: f64,
    出来事一覧: Vec<egui::Event>,
    木を組む: &dyn Fn() -> ノード<()>,
) -> egui::FullOutput {
    let 入力 = egui::RawInput {
        time: Some(秒),
        events: 出来事一覧,
        ..Default::default()
    };
    入力を指定して描画する(eguiの本体, 入力, 木を組む).1
}

/// ポインタを位置へ動かす出来事の一覧。
pub fn ポインタの移動(位置: egui::Pos2) -> Vec<egui::Event> {
    vec![egui::Event::PointerMoved(位置)]
}

/// 子の大きさを測る最初の回を、時刻0で下地の上へポインタを動かして済ませる。
pub fn 測りを済ませる(
    eguiの本体: &egui::Context, 木を組む: &dyn Fn() -> ノード<()>
) {
    let _ = 描く(eguiの本体, 0.0, ポインタの移動(下地の真ん中), 木を組む);
}
