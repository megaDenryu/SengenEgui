//! 時間の行の並びの試験の、値と行の番号から画面の点を求める手順。部品の中の定数と同じ寸法で、全体の範囲 0〜100 を
//! 幅200論理画素の行の並びへ写した部品（`time_rows` の見本の木）の上の点を求める。

/// 部品が確保した矩形の左右に空ける余白と、時間の軸の段の高さと、行の高さ。部品の中の定数と同じ値である。
const 左右の余白: f32 = 8.0;
const 軸の段の高さ: f32 = 14.0;
pub const 行の高さ: f32 = 24.0;
const 一の値の幅: f32 = 2.0;

/// 時間の行の並びの上の点とは、部品の左上の画面の位置と行の数から、値と行の番号の組を画面の点へ写すもののことである。
pub struct 時間の行の並びの上の点 {
    左上: egui::Pos2,
    行の数: f32,
}

impl 時間の行の並びの上の点 {
    /// 中央パネルの内余白を最初の配置から読み取る。
    pub fn 読み取る(eguiの本体: &egui::Context, 行の数: f32) -> Self {
        let mut 左上 = egui::Pos2::ZERO;
        let _ = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
            egui::CentralPanel::default().show(eguiの本体, |ui| 左上 = ui.cursor().min);
        });
        Self { 左上, 行の数 }
    }

    fn 横(&self, 値: f32) -> f32 {
        self.左上.x + 左右の余白 + 値 * 一の値の幅
    }

    /// 番号の行（0がいちばん下）の縦の中央で、値の横の位置の点。
    pub fn 行の中(&self, 行の番号: f32, 値: f32) -> egui::Pos2 {
        let 上からの行 = self.行の数 - 1.0 - 行の番号;
        let 縦 = self.左上.y + 軸の段の高さ + 上からの行 * 行の高さ + 行の高さ / 2.0;
        egui::pos2(self.横(値), 縦)
    }

    /// 時間の軸の段の縦の中央で、値の横の位置の点。
    pub fn 時間の軸(&self, 値: f32) -> egui::Pos2 {
        egui::pos2(self.横(値), self.左上.y + 軸の段の高さ / 2.0)
    }
}
