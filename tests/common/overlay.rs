//! 重ねる容器の試験の共通部。押せる下地の画像と、その位置と、覆いのスタイル。

use sengen_egui::{スタイル, ノード, 画像, 画素の組};

/// 覆いのスタイル。半透明の黒で塗る。
pub const 覆い: スタイル = スタイル {
    背景色: Some(egui::Color32::from_black_alpha(160)),
    ..スタイル::無指定
};

/// 下地の画像の幅と高さ。
pub const 下地の寸法: (f32, f32) = (256.0, 128.0);

/// 中央パネルの内余白の分だけずれた、下地の左上の位置。
/// 各試験は押す前に1回描画する。重ねる子は識別子ごとに最初に描く1回だけ大きさを測り、押せるのは次の回からである。
pub const 下地の左上: egui::Pos2 = egui::pos2(8.0, 8.0);

/// 押されたら応答を発する下地の画像。
pub fn 押せる下地<M>(テクスチャ: &egui::TextureHandle, 応答: M) -> ノード<M> {
    画像(テクスチャ.clone())
        .表示寸法(画素の組(下地の寸法.0, 下地の寸法.1))
        .押されたら発する(応答)
        .into()
}
