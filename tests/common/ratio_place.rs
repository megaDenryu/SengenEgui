//! 割合の矩形へ置く容器の試験の共通部。左上と大きさで書く矩形と、置かれた矩形いっぱいを塗る子・押せる子と、
//! 出力から指定の色で塗った矩形を読み取る手順。

use sengen_egui::{
    スタイル, ノード, 付け足せる, 使える大きさから組む, 割合, 割合で表した矩形, 大きさを決めた領域,
    色,
};

/// 中央パネルの内余白の分だけずれた、容器の左上の位置。
pub const 容器の左上: egui::Pos2 = egui::pos2(8.0, 8.0);

/// 左上の位置と大きさの割合から、試験に使う割合で表した矩形を作る。
pub fn 左上と大きさから矩形を作る(
    左端: f32,
    上端: f32,
    幅: f32,
    高さ: f32,
) -> 割合で表した矩形 {
    let 割合にする = |値: f32| match 割合::生成する(値) {
        Ok(割合) => 割合,
        Err(範囲外) => panic!("試験の割合が範囲外である（到達したらバグ）: {範囲外}"),
    };
    match 割合で表した矩形::左上と大きさから生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(幅),
        割合にする(高さ),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => panic!("試験の矩形が不正である（到達したらバグ）: {不正}"),
    }
}

/// 使える大きさいっぱいを色で塗る子。子が受け取った矩形の位置と大きさを、塗った矩形として出力から読めるようにする。
pub fn 塗りつぶす子を作る<M: 'static>(塗る色: 色) -> ノード<M> {
    使える大きさから組む(move |大きさ| {
        let 装飾 = スタイル {
            背景色: Some(塗る色),
            ..スタイル::無指定
        };
        大きさを決めた領域(大きさ, vec![]).装飾(装飾).into()
    })
    .into()
}

/// 使える大きさいっぱいの、押されたら応答を発する子。
pub fn 押せる子を作る<M: Clone + 'static>(応答: M) -> ノード<M> {
    使える大きさから組む(move |大きさ| {
        大きさを決めた領域(大きさ, vec![]).押されたら発する(応答.clone())
    })
    .into()
}

fn 図形から塗った矩形を集める(
    図形: &egui::Shape,
    塗る色: 色,
    集まり: &mut Vec<egui::Rect>,
) {
    match 図形 {
        egui::Shape::Rect(矩形の図形) if 矩形の図形.fill == 塗る色 => {
            集まり.push(矩形の図形.rect)
        }
        egui::Shape::Vec(図形一覧) => {
            for 中 in 図形一覧 {
                図形から塗った矩形を集める(中, 塗る色, 集まり);
            }
        }
        _ => {}
    }
}

/// 出力の図形のうち、指定の色で塗った矩形を描いた順に返す。
pub fn 指定の色で塗った矩形を集める(
    出力: &egui::FullOutput,
    塗る色: 色,
) -> Vec<egui::Rect> {
    let mut 集まり = Vec::new();
    for 切り抜いた図形 in &出力.shapes {
        図形から塗った矩形を集める(&切り抜いた図形.shape, 塗る色, &mut 集まり);
    }
    集まり
}
