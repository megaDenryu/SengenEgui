//! 区間の帯の試験の共通部。全体の範囲 0〜100 を帯の段の幅200論理画素に写した木を組み、値と段から画面の点を求める。
//! 1 の値が2論理画素に当たる。

use sengen_egui::{
    ノード, 区間の帯, 区間の帯の掴んだもの, 区間の帯の操作, 帯の値, 帯の全体の範囲, 画素,
};

/// 部品が確保した矩形の左右に空ける余白と、上の段の高さと、帯の段の高さ。部品の中の定数と同じ値である。
const 左右の余白: f32 = 8.0;
const 頭の段の高さ: f32 = 10.0;
const 帯の段の高さ: f32 = 18.0;
const 一の値の幅: f32 = 2.0;

pub fn 値(値: f64) -> 帯の値 {
    帯の値::倍精度の小数から生成する(値)
}

/// 開始・終了・位置を渡し、全体の範囲 0〜100・幅216論理画素（帯の段は200論理画素）の帯を組む。
pub fn 帯の木(
    開始: f64, 終了: f64, 位置: Option<f64>
) -> ノード<区間の帯の操作> {
    let Ok(全体) = 帯の全体の範囲::生成する(値(0.0), 値(100.0)) else {
        panic!("0〜100 は正しい全体の範囲である");
    };
    let 帯 = 区間の帯(全体, 値(開始), 値(終了), |操作| 操作).幅(画素(216.0));
    match 位置 {
        Some(位置) => 帯.位置(値(位置)).into(),
        None => 帯.into(),
    }
}

/// 帯の上の点とは、部品の左上の画面の位置から、値と段の組を画面の点へ写すもののことである。
pub struct 帯の上の点 {
    左上: egui::Pos2,
}

impl 帯の上の点 {
    /// 中央パネルの内余白を最初の配置から読み取る。
    pub fn 読み取る(文脈: &egui::Context) -> Self {
        let mut 左上 = egui::Pos2::ZERO;
        let _ = 文脈.run(egui::RawInput::default(), |文脈| {
            egui::CentralPanel::default().show(文脈, |ui| 左上 = ui.cursor().min);
        });
        Self { 左上 }
    }

    fn 横(&self, 値: f32) -> f32 {
        self.左上.x + 左右の余白 + 値 * 一の値の幅
    }

    /// 帯の段の縦の中央で、値の横の位置の点。
    pub fn 帯の段(&self, 値: f32) -> egui::Pos2 {
        egui::pos2(self.横(値), self.左上.y + 頭の段の高さ + 帯の段の高さ / 2.0)
    }

    /// 上の段の縦の中央で、値の横の位置の点。
    pub fn 上の段(&self, 値: f32) -> egui::Pos2 {
        egui::pos2(self.横(値), self.左上.y + 頭の段の高さ / 2.0)
    }
}

/// 掴み始めた操作を作る。
pub fn 掴み始めた(
    掴んだもの: 区間の帯の掴んだもの, 数: f64
) -> 区間の帯の操作 {
    区間の帯の操作::掴み始めた {
        掴んだもの,
        値: 値(数),
    }
}

/// 放した操作を作る。
pub fn 放した(
    掴んだもの: 区間の帯の掴んだもの, 数: f64
) -> 区間の帯の操作 {
    区間の帯の操作::放した {
        掴んだもの,
        値: 値(数),
    }
}

/// 段階と掴んだものが同じで、値の差が百万分の一未満か。egui は位置を単精度の小数で持つため、値は丸めの誤差を含む。
pub fn 近い(実際: Option<&区間の帯の操作>, 期待: 区間の帯の操作) -> bool {
    let 分ける = |操作: 区間の帯の操作| match 操作 {
        区間の帯の操作::掴み始めた {
            掴んだもの, 値
        } => (0, 掴んだもの, 値),
        区間の帯の操作::動かしている {
            掴んだもの, 値
        } => (1, 掴んだもの, 値),
        区間の帯の操作::放した {
            掴んだもの, 値
        } => (2, 掴んだもの, 値),
    };
    let Some(実際) = 実際 else { return false };
    let ((段階, もの, 値), (期待の段階, 期待のもの, 期待の値)) = (分ける(*実際), 分ける(期待));
    段階 == 期待の段階 && もの == 期待のもの && (値 - 期待の値).倍精度の小数にする().abs() < 1e-6
}
