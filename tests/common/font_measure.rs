//! 日本語フォントの縦の位置の測定の条件。字の大きさ・族・表示倍率の全部の組で、英字と日本語の字形の縦の中心の差を測り、
//! 絶対値の最大を求める。補正量を測ったフォントの一覧と、利用する側のフォントの補正量を探す道具もここに置く。

use super::glyph::{一行に並べる, 縦の中心の集まり};
use sengen_egui::{
    フォントの置き場所と補正, 字形の縦の補正, 日本語フォントの候補
};

const 並べる文字列: &str = "JSON読込保存編集";
const 字の大きさ一覧: [f32; 8] = [10.0, 12.0, 13.0, 14.0, 16.0, 20.0, 24.0, 32.0];
const 表示倍率一覧: [f32; 2] = [1.0, 1.5];

/// 補正量を測った標準の候補の置き場所（`src/font/correction.rs` の測り方で測った Windows の3つ）。
/// Linux の Noto Sans CJK と macOS のヒラギノ角ゴシックは測っておらず、補正の試験の対象にしない。
const 測った置き場所一覧: [&str; 3] = [
    "C:/Windows/Fonts/YuGothM.ttc",
    "C:/Windows/Fonts/meiryo.ttc",
    "C:/Windows/Fonts/msgothic.ttc",
];

/// 標準の候補のうち、補正量を測ったもので、この計算機にファイルがあるもの。無ければ、測らなかったことを
/// 標準エラー出力へ書いて空の一覧を返す（黙って成功にしない）。
pub fn 測れる標準の候補(
    試験の名前: &str
) -> Vec<フォントの置き場所と補正> {
    let 一覧: Vec<_> = 日本語フォントの候補::標準で入っている候補()
        .一覧()
        .iter()
        .filter(|候補| {
            測った置き場所一覧
                .iter()
                .any(|置き場所| 候補.置き場所() == std::path::Path::new(置き場所))
        })
        .filter(|候補| 候補.置き場所().is_file())
        .cloned()
        .collect();
    if 一覧.is_empty() {
        eprintln!(
            "{試験の名前}: 補正量を測った標準の候補のフォントがこの計算機に無いため、測定を実行しなかった"
        );
    }
    一覧
}

/// 1つのフォントを縦の補正を付けて足し、全部の字の大きさ・族・表示倍率で測った差のうち、絶対値の最大を返す。
pub fn 最大の差(置き場所: &std::path::Path, 縦の補正: 字形の縦の補正) -> f32 {
    let mut 最大 = 0.0_f32;
    for 表示倍率 in 表示倍率一覧 {
        let eguiの本体 = egui::Context::default();
        eguiの本体.set_pixels_per_point(表示倍率);
        let 候補 = 日本語フォントの候補::補正付きの一覧から作る([
            フォントの置き場所と補正::生成する(置き場所, 縦の補正),
        ]);
        assert!(候補.最初に読めたものを設定する(&eguiの本体).is_ok());
        let _ = eguiの本体.run(egui::RawInput::default(), |_| {});
        for 族 in [egui::FontFamily::Proportional, egui::FontFamily::Monospace] {
            for 大きさ in 字の大きさ一覧 {
                let 並べた = 一行に並べる(
                    &eguiの本体,
                    並べる文字列,
                    egui::FontId::new(大きさ, 族.clone()),
                );
                let mut 集まり = 縦の中心の集まり::default();
                集まり.足す(egui::Pos2::ZERO, &並べた);
                最大 = 最大.max(集まり.平均する().日本語の英字からの差().abs());
            }
        }
    }
    最大
}

/// 補正の比を -0.10 から 0.40 まで 0.01 刻みで試し、最大の差が最も小さい比とその差を返す。
/// 利用する側が自分のフォントの補正量を決めるときに使う（`tests/font_vertical.rs` の測る道具）。
pub fn 補正量を探す(置き場所: &std::path::Path) -> (字形の縦の補正, f32) {
    let mut 最良 = (字形の縦の補正::無し, f32::INFINITY);
    for 百倍 in -10_i8..=40 {
        let 補正 = 字形の縦の補正::字の大きさに対する比から作る(
            f32::from(百倍) / 100.0,
        );
        let 差 = 最大の差(置き場所, 補正);
        if 差 < 最良.1 {
            最良 = (補正, 差);
        }
    }
    最良
}
