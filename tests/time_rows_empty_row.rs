//! 時間の行の並びの何も無い所を押したときの知らせを確かめる。行の上の何も無い所（塊の無い行を含む）を押すと、押した行の
//! 番号で行の何も無い所を知らせ、全体の何も無い所の知らせはその前に発する。時間の軸を押しても行の知らせは発さない。
//! 幅の狭い塊は、描いた幅より広い最小の幅（6論理画素）で当たる。

mod common;

use common::time_rows::{塊, 空の部品, 見本の部品, 試験の塊, 試験の応答};
use common::time_rows_point::時間の行の並びの上の点;
use sengen_egui::{ノード, 時間の塊の操作, 時間の行, 時間の行の番号};

fn 行を知らせる見本の木() -> ノード<試験の応答> {
    見本の部品(None, false)
        .行の何も無い所を押したら発する(試験の応答::行の何も無い所)
        .into()
}

fn 行の番号(番号: usize) -> 時間の行の番号 {
    時間の行の番号::置いた順の番号から生成する(番号)
}

#[test]
fn 空の行を押すとその行の番号で知らせる() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(2.0, 50.0), &行を知らせる見本の木);
    assert_eq!(
        発した応答の一覧,
        vec![
            試験の応答::何も無い所,
            試験の応答::行の何も無い所(行の番号(2))
        ]
    );
}

#[test]
fn 塊のある行の塊の外を押すとその行の番号で知らせる() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.行の中(0.0, 60.0), &行を知らせる見本の木);
    assert!(
        発した応答の一覧.contains(&試験の応答::行の何も無い所(行の番号(0))),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 時間の軸を押しても行の何も無い所は知らせない() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 3.0);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 点.時間の軸(30.0), &行を知らせる見本の木);
    assert_eq!(発した応答の一覧, vec![試験の応答::何も無い所]);
}

/// 1つの行の50〜50.5に、描くと1論理画素の幅になる短い塊 甲を置いた木。塊の中心は横の値50.25にある。
fn 短い塊の木() -> ノード<試験の応答> {
    空の部品()
        .行を置く(時間の行().塊を置く(試験の塊::甲, 塊(50.0, 0.5)))
        .into()
}

#[test]
fn 幅の狭い塊も中心から最小の幅の半分の内側を押せば掴む() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 1.0);
    let 中心から右へ2論理画素半 = 点.行の中(0.0, 51.5);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 中心から右へ2論理画素半, &短い塊の木);
    assert!(
        発した応答の一覧.contains(&試験の応答::塊(試験の塊::甲, 時間の塊の操作::選んだ)),
        "{発した応答の一覧:?}"
    );
}

#[test]
fn 幅の狭い塊は中心から最小の幅の半分より外を押しても掴まない() {
    let eguiの本体 = egui::Context::default();
    let 点 = 時間の行の並びの上の点::読み取る(&eguiの本体, 1.0);
    let 中心から右へ4論理画素半 = 点.行の中(0.0, 52.5);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 中心から右へ4論理画素半, &短い塊の木);
    assert_eq!(発した応答の一覧, vec![試験の応答::何も無い所]);
}
