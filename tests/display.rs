//! 表示の部品が描画でき、文字の飾りのスタイルが受け付けられることを確かめる。

mod common;

use sengen_egui::{
    スタイル, ノード, 割合, 外部リンク, 子, 文字表示, 画像, 画素, 縦積み, 読み込み中表示, 進捗バー,
};

const 飾り: スタイル = スタイル {
    斜体: Some(true),
    下線: Some(true),
    取り消し線: Some(true),
    弱い: Some(true),
    ..スタイル::無指定
};

fn 全部の表示部品() -> ノード<()> {
    縦積み(子![
        文字表示("選べる").選択できる().装飾(飾り),
        文字表示("切り詰め").折り返さない(),
        進捗バー(割合::範囲へ丸めて生成する(0.4))
            .文字を添える("進行")
            .割合を表示する()
            .幅(画素(120.0)),
        読み込み中表示().大きさ(画素(24.0)),
        外部リンク("公式", "https://example.com/"),
        画像("file://存在しない.png").最大幅(画素(64.0)),
    ])
    .into()
}

#[test]
fn 全部の表示部品が描画できて応答は空になる() {
    let 文脈 = egui::Context::default();
    assert!(common::描画する(&文脈, vec![], &全部の表示部品).is_empty());
}

#[test]
fn 表示の部品は写しても表示のままである() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 全部の表示部品().写す(|()| 1u8);
    assert!(common::描画する(&文脈, vec![], &木を組む).is_empty());
}
