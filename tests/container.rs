//! 容器の部品が描画でき、`写す` で応答が変換され、タブ列と閉じる操作が応答を出すことを確かめる。

mod common;

use sengen_egui::{
    ウィンドウ, タブ列, ノード, パネル, パネルの位置, ボタン, メニュー, メニューバー, モーダル,
    両方向スクロール, 仮想縦スクロール, 子, 折り畳み見出し, 折り返す横並び, 文字表示, 格子,
    横スクロール, 横並び, 画素, 画素の組, 縦スクロール, 縦積み,
};

#[derive(Clone, PartialEq, Debug)]
enum 応答 {
    押した,
    タブを選んだ(usize),
    閉じた,
}

fn 全部の容器() -> ノード<応答> {
    縦積み(子![
        メニューバー(子![メニュー(
            "ファイル",
            子![ボタン("保存", 応答::押した)]
        )]),
        パネル("左", パネルの位置::左, 子![文字表示("左")])
            .既定の幅(画素(80.0))
            .大きさを変えられる(true),
        パネル("上", パネルの位置::上, 子![文字表示("上")]).既定の高さ(画素(20.0)),
        パネル("中央", パネルの位置::中央, 子![文字表示("中央")]),
        横並び(子![文字表示("右寄せ")])
            .右寄せ()
            .有効(false)
            .幅(画素(200.0)),
        折り返す横並び(子![文字表示("折り返し")]).最小幅(画素(40.0)),
        縦スクロール("縦", 子![文字表示("縦")]).最大高さ(画素(50.0)),
        横スクロール("横", 子![文字表示("横")]).最大幅(画素(50.0)),
        両方向スクロール("両", 子![文字表示("両")]),
        仮想縦スクロール("仮想", 画素(16.0), 100, |番号| 文字表示(
            番号.to_string()
        )
        .into()),
        折り畳み見出し("見出し", 子![文字表示("中身")]).既定で開く(),
        格子("格子", 2, 子![文字表示("a"), 文字表示("b")])
            .縞模様()
            .列の間隔(画素(4.0))
            .行の間隔(画素(2.0)),
        ウィンドウ("窓", true, 子![文字表示("窓")])
            .閉じたら(応答::閉じた)
            .大きさを変えられる(false)
            .折り畳める(false)
            .既定の大きさ(画素の組(100.0, 80.0))
            .既定の位置(画素の組(300.0, 300.0)),
        モーダル("覆い", false, 子![文字表示("覆い")]).閉じたら(応答::閉じた),
    ])
    .into()
}

#[test]
fn 全部の容器が描画できて操作が無ければ応答は空になる() {
    let 文脈 = egui::Context::default();
    assert!(common::描画する(&文脈, vec![], &全部の容器).is_empty());
    let 木を組む = || 全部の容器().写す(|応答| format!("{応答:?}"));
    assert!(common::描画する(&文脈, vec![], &木を組む).is_empty());
}

#[test]
fn タブ列で別の見出しを押すと番号の応答が出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || {
        縦積み(子![タブ列(
            vec!["甲".to_string(), "乙".to_string()],
            0,
            応答::タブを選んだ
        )])
        .into()
    };
    let 集まり = common::左クリックする(&文脈, egui::pos2(50.0, 18.0), &木を組む);
    assert_eq!(集まり, vec![応答::タブを選んだ(1)]);
}

#[test]
/// 覆いの当たり判定は前フレームの配置で決まるため、1フレーム描いてから押す。
fn モーダルの外側を押すと閉じたらの応答が出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || {
        縦積み(子![
            モーダル("覆い", true, 子![文字表示("覆い")]).閉じたら(応答::閉じた)
        ])
        .into()
    };
    assert!(common::描画する(&文脈, vec![], &木を組む).is_empty());
    let 集まり = common::左クリックする(&文脈, egui::pos2(5.0, 5.0), &木を組む);
    assert_eq!(集まり, vec![応答::閉じた]);
}
