//! 複数の範囲枠が、押したフレームの中で、選んだ・掴み始めた・移動量の無い動かしているをこの順に発することを確かめる。
//! 利用する側は、選んだで選びを変え、掴み始めたで枠を覚え、同じフレームの動かしているから計算を始められる。

mod common;

use common::multiple_range_frames::{
    二つの枠の木, 基準の矩形の中の位置, 試験で選んでいる枠, 試験の枠,
};
use sengen_egui::{
    範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

#[test]
fn 押したフレームで選んだと掴み始めたに続けて移動量の無い動かしているを発する() {
    let eguiの本体 = egui::Context::default();
    let 位置 = 基準の矩形の中の位置(&eguiの本体, 0.2, 0.2);
    let 木を組む = || 二つの枠の木(試験で選んでいる枠::無し);
    let _ = common::描画する(&eguiの本体, vec![], &木を組む);
    let 押す = vec![
        egui::Event::PointerMoved(位置),
        common::ボタンの出来事(位置, egui::PointerButton::Primary, true),
    ];
    let 押したフレームの操作 = common::描画する(&eguiの本体, 押す, &木を組む);
    let 内側を掴んだ = 範囲枠の掴んだ部分::内側;
    let 期待 = vec![
        (試験の枠::奥, 複数の範囲枠の操作::選んだ),
        (
            試験の枠::奥,
            複数の範囲枠の操作::掴み始めた {
                掴んだ部分: 内側を掴んだ,
            },
        ),
        (
            試験の枠::奥,
            複数の範囲枠の操作::動かしている {
                掴んだ部分: 内側を掴んだ,
                開始点からの移動量: 縦横の割合の差::ゼロ,
                縦横比の扱い: 縦横比の扱い::保たない,
            },
        ),
    ];
    assert_eq!(押したフレームの操作, 期待);
}
