//! 一定時間で消える通知が、表示する長さの間だけ文を描き、消える時刻に描き直しを予約し、
//! 回を進めると表示の時間を始めから数え直すことを確かめる。

mod common;

use std::time::Duration;

use common::output::{
    描き直しまでの時間, 文字を描いたか, 時刻を指定して描画する
};
use sengen_egui::{ノード, 一定時間で消える通知, 通知の回};

fn 通知の木(回: 通知の回) -> impl Fn() -> ノード<()> {
    move || {
        一定時間で消える通知("通知", 回, "保存した")
            .表示する長さ(Duration::from_secs(2))
            .into()
    }
}

#[test]
fn 表示する長さの間は文を描き消える時刻に描き直しを予約する() {
    let eguiの本体 = egui::Context::default();
    let 木 = 通知の木(通知の回::最初());
    let 出した回 = 時刻を指定して描画する(&eguiの本体, 10.0, &木);
    assert_eq!(
        描き直しまでの時間(&出した回),
        Duration::ZERO,
        "egui は重ねる領域を初めて出す回に大きさだけを測って描き直す"
    );
    let 次の描画 = 時刻を指定して描画する(&eguiの本体, 10.1, &木);
    assert!(文字を描いたか(&次の描画, "保存した"));
    let 途中 = 時刻を指定して描画する(&eguiの本体, 11.5, &木);
    assert!(文字を描いたか(&途中, "保存した"));
    assert!(描き直しまでの時間(&途中) <= Duration::from_millis(500));
}

#[test]
fn 表示する長さを過ぎると文を描かない() {
    let eguiの本体 = egui::Context::default();
    let 木 = 通知の木(通知の回::最初());
    let _ = 時刻を指定して描画する(&eguiの本体, 10.0, &木);
    let 過ぎた回 = 時刻を指定して描画する(&eguiの本体, 12.5, &木);
    assert!(!文字を描いたか(&過ぎた回, "保存した"));
}

#[test]
fn 回を進めると同じ文でも表示の時間を始めから数え直す() {
    let eguiの本体 = egui::Context::default();
    let 最初 = 通知の回::最初();
    let _ = 時刻を指定して描画する(&eguiの本体, 10.0, &通知の木(最初));
    let _ = 時刻を指定して描画する(&eguiの本体, 12.5, &通知の木(最初));
    let 次の回 = 時刻を指定して描画する(&eguiの本体, 12.5, &通知の木(最初.次()));
    assert!(文字を描いたか(&次の回, "保存した"));
}
