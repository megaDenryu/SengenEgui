//! 区間の帯が、掴んだものとその値をドラッグの段階ごとに発することを確かめる。
//! 値は掴み始めの値に動かした分を足したものであり、つまみの中心から離れた所を掴んでも押した位置へ飛ばない。

mod common;

use common::range_band::{値, 帯の上の点, 帯の木, 掴み始めた, 放した, 近い};
use sengen_egui::{区間の帯の掴んだもの, 区間の帯の操作};

fn ドラッグする(
    始点: egui::Pos2,
    横の移動量: f32,
    木: fn() -> sengen_egui::ノード<区間の帯の操作>,
) -> Vec<区間の帯の操作> {
    let 文脈 = egui::Context::default();
    let 終点 = 始点 + egui::vec2(横の移動量, 0.0);
    common::drag::左ドラッグする(&文脈, 始点, 終点, &木)
}

fn 点() -> 帯の上の点 {
    帯の上の点::読み取る(&egui::Context::default())
}

fn 区間と位置() -> sengen_egui::ノード<区間の帯の操作> {
    帯の木(20.0, 60.0, Some(80.0))
}

#[test]
fn 開始のつまみを中心から離れた所で掴んで動かすと動かした分だけ開始が変わる() {
    let 集まり = ドラッグする(点().帯の段(20.0) + egui::vec2(3.0, 0.0), 20.0, 区間と位置);
    let 掴んだもの = 区間の帯の掴んだもの::開始のつまみ;
    assert!(
        近い(集まり.first(), 掴み始めた(掴んだもの, 20.0)),
        "{集まり:?}"
    );
    let 途中 = 区間の帯の操作::動かしている {
        掴んだもの,
        値: 値(25.0),
    };
    assert!(
        集まり.iter().any(|操作| 近い(Some(操作), 途中)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(掴んだもの, 30.0)), "{集まり:?}");
}

#[test]
fn 終了のつまみを動かすと終了が変わり全体の範囲の外へは出ない() {
    let 掴んだもの = 区間の帯の掴んだもの::終了のつまみ;
    let 集まり = ドラッグする(点().帯の段(60.0), -10.0, 区間と位置);
    assert!(近い(集まり.last(), 放した(掴んだもの, 55.0)), "{集まり:?}");
    let 集まり = ドラッグする(点().帯の段(60.0), 200.0, 区間と位置);
    assert!(近い(集まり.last(), 放した(掴んだもの, 100.0)), "{集まり:?}");
}

#[test]
fn 区間の内側を動かすと新しい開始を発し区間の全体が全体の範囲に収まるよう止まる() {
    let 掴んだもの = 区間の帯の掴んだもの::区間の内側;
    let 集まり = ドラッグする(点().帯の段(40.0), 30.0, 区間と位置);
    assert!(
        近い(集まり.first(), 掴み始めた(掴んだもの, 20.0)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(掴んだもの, 35.0)), "{集まり:?}");
    let 集まり = ドラッグする(点().帯の段(40.0), 200.0, 区間と位置);
    assert!(近い(集まり.last(), 放した(掴んだもの, 60.0)), "{集まり:?}");
}

#[test]
fn 位置の印の頭を掴んで動かすと位置が変わる() {
    let 掴んだもの = 区間の帯の掴んだもの::位置の印;
    let 集まり = ドラッグする(点().上の段(80.0) + egui::vec2(2.0, 0.0), -20.0, 区間と位置);
    assert!(
        近い(集まり.first(), 掴み始めた(掴んだもの, 80.0)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(掴んだもの, 70.0)), "{集まり:?}");
}

#[test]
fn 帯の区間の外を押すと位置の印をそこへ移して掴み放すと同じ値を発する() {
    let 文脈 = egui::Context::default();
    let 集まり = common::左クリックする(&文脈, 点().帯の段(90.0), &区間と位置);
    let 掴んだもの = 区間の帯の掴んだもの::位置の印;
    assert_eq!(集まり.len(), 2, "{集まり:?}");
    assert!(
        近い(集まり.first(), 掴み始めた(掴んだもの, 90.0)),
        "{集まり:?}"
    );
    assert!(近い(集まり.last(), 放した(掴んだもの, 90.0)), "{集まり:?}");
}

#[test]
fn 主ボタン以外のドラッグには反応しない() {
    let 文脈 = egui::Context::default();
    let 始点 = 点().帯の段(20.0);
    let 終点 = 始点 + egui::vec2(20.0, 0.0);
    let 右ボタン = egui::PointerButton::Secondary;
    let 集まり = common::drag::ドラッグする(&文脈, 始点, 終点, 右ボタン, &区間と位置);
    assert!(集まり.is_empty(), "{集まり:?}");
}

#[test]
fn 写した木でも操作が写した応答で出る() {
    let 文脈 = egui::Context::default();
    let 木を組む = || 区間と位置().写す(|操作| format!("{操作:?}"));
    let 集まり = common::左クリックする(&文脈, 点().帯の段(90.0), &木を組む);
    assert!(
        集まり.last().is_some_and(|文| 文.starts_with("放した")),
        "{集まり:?}"
    );
}
