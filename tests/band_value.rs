//! 帯の値と帯の全体の範囲が、生成の口の約束どおりに振る舞うことを確かめる。

use sengen_egui::{帯の値, 帯の全体の範囲, 帯の全体の範囲の不正};

fn 値(数: f64) -> 帯の値 {
    帯の値::倍精度の小数から生成する(数)
}

#[test]
fn 帯の全体の範囲は始めが終わり以上か有限でない値を受け取らない() {
    assert_eq!(
        帯の全体の範囲::生成する(値(5.0), 値(5.0)),
        Err(帯の全体の範囲の不正::始めが終わり以上)
    );
    assert_eq!(
        帯の全体の範囲::生成する(値(0.0), 値(f64::NAN)),
        Err(帯の全体の範囲の不正::有限でない)
    );
    let Ok(全体) = 帯の全体の範囲::生成する(値(1.0), 値(3.0)) else {
        panic!("1〜3 は正しい全体の範囲である");
    };
    assert_eq!((全体.始め(), 全体.終わり()), (値(1.0), 値(3.0)));
}

#[test]
fn 帯の値の差は引き算で作り足し算で戻る() {
    let 差 = 値(7.5) - 値(2.5);
    assert_eq!(差.倍精度の小数にする(), 5.0);
    assert_eq!(値(1.0) + 差, 値(6.0));
}
