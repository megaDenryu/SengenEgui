//! 複数の範囲枠の縦横比を保つ指定が、指定した修飾キーを押している間だけ保たないと発することを確かめる。

mod common;

use common::multiple_range_frames::{
    基準の矩形の中の位置, 枠の操作, 縦横比を保つ二つの枠の木, 選んでいる枠,
};
use sengen_egui::{縦横比の扱い, 複数の範囲枠の操作};

fn 放した操作の縦横比(集まり: &[枠の操作]) -> Option<縦横比の扱い> {
    match 集まり.last() {
        Some((_, 複数の範囲枠の操作::放した { 縦横比, .. })) => Some(*縦横比),
        _ => None,
    }
}

#[test]
fn 縦横比を保つ指定では修飾キーを押していなければ保つと発し_指定の修飾キーを押していれば保たないと発する()
 {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.9, 0.9);
    let 終点 = 始点 + egui::vec2(-40.0, -10.0);
    let 木を組む = || 縦横比を保つ二つの枠の木(選んでいる枠::手前);
    let 押していない = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert_eq!(
        放した操作の縦横比(&押していない),
        Some(縦横比の扱い::保つ),
        "{押していない:?}"
    );
    let 押している = common::drag::修飾キーを押して左ドラッグする(
        &eguiの本体,
        始点,
        終点,
        egui::Modifiers::SHIFT,
        &木を組む,
    );
    assert_eq!(
        放した操作の縦横比(&押している),
        Some(縦横比の扱い::保たない),
        "{押している:?}"
    );
}
