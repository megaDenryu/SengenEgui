//! 差し替えられるテクスチャが、画素の並びの長さを確かめて登録でき、差し替えで寸法が変わり、
//! 画像と範囲枠付き画像へそのまま渡せることを確かめる。

mod common;

use common::image::描画した矩形;
use sengen_egui::{
    ノード, 割合で表した矩形, 差し替えられるテクスチャ, 拡大縮小の仕方, 画像, 画素の並び,
    画素の並びの不正, 画素の組, 画素数の寸法, 範囲枠付き画像, 範囲枠付き画像の周りの余白,
};

fn 灰色のバイト列(寸法: 画素数の寸法) -> Vec<u8> {
    let 個数 = usize::try_from(寸法.幅() * 寸法.高さ()).unwrap_or(0);
    [128, 128, 128, 255].repeat(個数)
}

fn 灰色のテクスチャを登録する(
    eguiの本体: &egui::Context,
    寸法: 画素数の寸法,
) -> 差し替えられるテクスチャ {
    let バイト列 = 灰色のバイト列(寸法);
    match 画素の並び::赤緑青と不透明度のバイト列から作る(寸法, &バイト列)
    {
        Ok(画素) => 差し替えられるテクスチャ::登録して作る(
            eguiの本体,
            "灰色",
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        ),
        Err(不正) => panic!("試験の画素の並びが不正である: {不正}"),
    }
}

#[test]
fn バイト数が寸法と合わない画素の並びは理由を返す() {
    let 寸法 = 画素数の寸法::生成する(4, 2);
    let 結果 = 画素の並び::赤緑青と不透明度のバイト列から作る(寸法, &[0; 31]);
    assert_eq!(
        結果.err(),
        Some(画素の並びの不正::バイト数が合わない {
            寸法,
            要るバイト数: 32,
            渡したバイト数: 31,
        })
    );
}

#[test]
fn 幅か高さが0の画素の並びは理由を返す() {
    let 寸法 = 画素数の寸法::生成する(0, 2);
    let 結果 = 画素の並び::赤緑青と不透明度のバイト列から作る(寸法, &[]);
    assert_eq!(結果.err(), Some(画素の並びの不正::寸法が空である(寸法)));
}

#[test]
fn 差し替えると寸法が新しい画素の並びの寸法になり画像は新しい縦横比で描かれる() {
    let eguiの本体 = egui::Context::default();
    let mut テクスチャ =
        灰色のテクスチャを登録する(&eguiの本体, 画素数の寸法::生成する(64, 32));
    let 新しい寸法 = 画素数の寸法::生成する(16, 16);
    let バイト列 = 灰色のバイト列(新しい寸法);
    match 画素の並び::赤緑青と不透明度のバイト列から作る(
        新しい寸法,
        &バイト列,
    ) {
        Ok(画素) => テクスチャ.差し替える(画素),
        Err(不正) => panic!("試験の画素の並びが不正である: {不正}"),
    }
    assert_eq!(テクスチャ.寸法(), 新しい寸法);
    let 木: ノード<()> = 画像(&テクスチャ).表示寸法(画素の組(100.0, 50.0)).into();
    assert_eq!(描画した矩形(&eguiの本体, 木).size(), egui::vec2(50.0, 50.0));
}

#[test]
fn 範囲枠付き画像へ差し替えられるテクスチャをそのまま渡せる() {
    let eguiの本体 = egui::Context::default();
    let テクスチャ =
        灰色のテクスチャを登録する(&eguiの本体, 画素数の寸法::生成する(64, 32));
    let 木: ノード<()> = 範囲枠付き画像(
        &テクスチャ,
        画素の組(128.0, 64.0),
        割合で表した矩形::全体,
        |_| (),
    )
    .into();
    let 余白 = 範囲枠付き画像の周りの余白.eguiへ渡す値() * 2.0;
    assert_eq!(
        描画した矩形(&eguiの本体, 木).size(),
        egui::vec2(128.0 + 余白, 64.0 + 余白)
    );
}
