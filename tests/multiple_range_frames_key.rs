//! 複数の範囲枠が掴んだ枠を鍵で覚えることを確かめる。ドラッグの途中で置く順が変わっても同じ枠へ操作が届き、
//! 掴んだ鍵の枠が置かれなくなったら、掴んだ枠が無くなったを1回発してドラッグを終える。

mod common;

use std::cell::Cell;

use common::multiple_range_frames::{
    二つの枠の部品, 基準の矩形の中の位置, 枠の操作, 試験で選んでいる枠, 試験の並べ方, 試験の枠,
};
use sengen_egui::{ノード, 複数の範囲枠の操作};

/// 最初の2回（配置を決める回と押す回）は奥から手前の順に置き、3回目からは指定の並べ方で置く木を組む関数を作る。
fn 押した後に並べ方を変える木(
    押した後の並べ方: 試験の並べ方,
) -> impl Fn() -> ノード<枠の操作> {
    let 描いた回数 = Cell::new(0_u32);
    move || {
        let 並べ方 = if 描いた回数.get() < 2 {
            試験の並べ方::奥から手前の順
        } else {
            押した後の並べ方
        };
        描いた回数.set(描いた回数.get() + 1);
        二つの枠の部品(試験で選んでいる枠::無し, 並べ方, |鍵, 操作| (鍵, 操作)).into()
    }
}

#[test]
fn ドラッグの途中で置く順が変わっても掴んだ枠へ操作が届く() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.2, 0.2);
    let 終点 = 始点 + egui::vec2(20.0, 10.0);
    let 木を組む = 押した後に並べ方を変える木(試験の並べ方::手前の枠を先に置く);
    let 発した操作の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    assert!(
        matches!(
            発した操作の一覧.last(),
            Some((試験の枠::奥, 複数の範囲枠の操作::放した { .. }))
        ),
        "{発した操作の一覧:?}"
    );
    assert!(
        発した操作の一覧.iter().all(|(枠, _)| *枠 == 試験の枠::奥),
        "{発した操作の一覧:?}"
    );
}

#[test]
fn ドラッグの途中で掴んだ枠が置かれなくなると掴んだ枠が無くなったを1回発して終える() {
    let eguiの本体 = egui::Context::default();
    let 始点 = 基準の矩形の中の位置(&eguiの本体, 0.8, 0.8);
    let 終点 = 始点 + egui::vec2(-20.0, -10.0);
    let 木を組む = 押した後に並べ方を変える木(試験の並べ方::奥の枠だけ);
    let 発した操作の一覧 = common::drag::左ドラッグする(&eguiの本体, 始点, 終点, &木を組む);
    let 無くなった = (試験の枠::手前, 複数の範囲枠の操作::掴んだ枠が無くなった);
    assert_eq!(
        発した操作の一覧.last(),
        Some(&無くなった),
        "{発した操作の一覧:?}"
    );
    assert_eq!(
        発した操作の一覧
            .iter()
            .filter(|操作| **操作 == 無くなった)
            .count(),
        1,
        "{発した操作の一覧:?}"
    );
}
