//! 重ねる容器の「ポインタが止まると隠して上に置く」子が、子の上にポインタがある間と、
//! 子の上で押し始めたボタンを押し続けている間は、止まって指定の時間が経っても隠れないことを確かめる。

mod common;

use common::output::文字を描いたか;
use common::overlay_idle::{
    ポインタの移動, 下地の真ん中, 描く, 操作の欄の真ん中, 操作の欄を置いた木, 測りを済ませる,
};

#[test]
fn 子の上にポインタがある間は止まっていても隠さない() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = 操作の欄を置いた木(false);
    測りを済ませる(&eguiの本体, &木を組む);
    let _ = 描く(
        &eguiの本体,
        0.1,
        ポインタの移動(操作の欄の真ん中),
        &木を組む,
    );
    let 過ぎた回 = 描く(&eguiの本体, 5.0, vec![], &木を組む);
    assert!(文字を描いたか(&過ぎた回, "操作の欄"));
}

#[test]
fn 子の上で押し始めたボタンを押し続けている間は子の外へ動かしても隠さない() {
    let eguiの本体 = egui::Context::default();
    let 木を組む = 操作の欄を置いた木(false);
    測りを済ませる(&eguiの本体, &木を組む);
    let _ = 描く(
        &eguiの本体,
        0.1,
        ポインタの移動(操作の欄の真ん中),
        &木を組む,
    );
    let 押す = common::ボタンの出来事(操作の欄の真ん中, egui::PointerButton::Primary, true);
    let _ = 描く(&eguiの本体, 0.2, vec![押す], &木を組む);
    let _ = 描く(&eguiの本体, 0.3, ポインタの移動(下地の真ん中), &木を組む);
    let 押し続けている回 = 描く(&eguiの本体, 5.0, vec![], &木を組む);
    assert!(文字を描いたか(&押し続けている回, "操作の欄"));
    let 放す = common::ボタンの出来事(下地の真ん中, egui::PointerButton::Primary, false);
    let _ = 描く(&eguiの本体, 5.1, vec![放す], &木を組む);
    let 放して過ぎた回 = 描く(&eguiの本体, 7.5, vec![], &木を組む);
    assert!(!文字を描いたか(&放して過ぎた回, "操作の欄"));
}
