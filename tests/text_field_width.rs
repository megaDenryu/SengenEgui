//! 一行テキスト入力の幅の指定を確かめる。幅いっぱいは使える幅の全部を占め、最小幅は使える幅や指定の幅より狭くさせない。
//! 幅と最小幅は枠の内側の幅であり、描いた矩形は枠の内側の余白(左右4論理画素ずつ)の分だけ広い。

mod common;

use common::image::描画した矩形;
use sengen_egui::{ノード, 一行テキスト入力, 画素};

/// 枠の内側の余白の左右の合計。
const 余白の横の合計: f32 = 8.0;

fn 使える幅() -> f32 {
    let eguiの本体 = egui::Context::default();
    let mut 幅 = 0.0;
    let _ = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
        egui::CentralPanel::default().show(eguiの本体, |ui| 幅 = ui.available_width());
    });
    幅
}

fn 入力欄(値: &str) -> sengen_egui::一行テキスト入力型<()> {
    一行テキスト入力(値, |_| ())
}

fn 描いた幅(木: ノード<()>) -> f32 {
    描画した矩形(&egui::Context::default(), 木).width()
}

#[test]
fn 幅いっぱいにした入力欄は使える幅の全部を占める() {
    assert_eq!(描いた幅(入力欄("名前").幅いっぱい().into()), 使える幅());
}

#[test]
fn 最小幅は指定の幅より狭くさせない() {
    let 幅 = 描いた幅(入力欄("名前").幅(画素(10.0)).最小幅(画素(50.0)).into());
    assert_eq!(幅, 50.0 + 余白の横の合計);
}

#[test]
fn 最小幅は使える幅より広ければ使える幅からはみ出す() {
    let 下限 = 使える幅() + 100.0;
    let 幅 = 描いた幅(入力欄("名前").幅いっぱい().最小幅(画素(下限)).into());
    assert_eq!(幅, 下限 + 余白の横の合計);
}

#[test]
fn 幅を指定した入力欄は枠の内側がその幅になる() {
    assert_eq!(
        描いた幅(入力欄("名前").幅(画素(120.0)).into()),
        120.0 + 余白の横の合計
    );
}
