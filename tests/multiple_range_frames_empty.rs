//! 複数の範囲枠の何も無い所を押したら発する口が、どの枠にもつまみにも当たらない所を押したときだけ、指定の応答を1回発することを確かめる。

mod common;

use common::multiple_range_frames::{
    二つの枠の部品, 基準の矩形の中の位置, 試験で選んでいる枠, 試験の並べ方, 試験の枠,
};
use sengen_egui::{ノード, 複数の範囲枠の操作};

/// 押した結果とは、試験の木が発する、枠の操作と、何も無い所を押したことの区別のことである。
#[derive(Clone, Debug, PartialEq)]
enum 押した結果 {
    枠の操作(試験の枠, 複数の範囲枠の操作),
    何も無い所を押した,
}

fn 何も無い所を知らせる木() -> ノード<押した結果> {
    二つの枠の部品(
        試験で選んでいる枠::無し,
        試験の並べ方::奥から手前の順,
        押した結果::枠の操作,
    )
    .何も無い所を押したら発する(押した結果::何も無い所を押した)
    .into()
}

#[test]
fn どの枠にも当たらない所を押すと指定の応答を1回発する() {
    let eguiの本体 = egui::Context::default();
    let 位置 = 基準の矩形の中の位置(&eguiの本体, 0.95, 0.05);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 位置, &何も無い所を知らせる木);
    assert_eq!(発した応答の一覧, vec![押した結果::何も無い所を押した]);
}

#[test]
fn 枠を押したときは何も無い所の応答を発さない() {
    let eguiの本体 = egui::Context::default();
    let 位置 = 基準の矩形の中の位置(&eguiの本体, 0.2, 0.2);
    let 発した応答の一覧 =
        common::左クリックする(&eguiの本体, 位置, &何も無い所を知らせる木);
    assert!(
        !発した応答の一覧.contains(&押した結果::何も無い所を押した),
        "{発した応答の一覧:?}"
    );
    assert!(
        発した応答の一覧.contains(&押した結果::枠の操作(
            試験の枠::奥,
            複数の範囲枠の操作::選んだ
        )),
        "{発した応答の一覧:?}"
    );
}
