//! 再生のキーの見本。再生を切り替えるキーを、「キーを変える」を押した後に押したキーへ変える。
//! 次に押されたキーの組の受け取りを、待っている間だけ木へ置く形の見本である。Escape を押すと変えずに待つのをやめる。

use sengen_egui::{
    キー, キーの組, キー操作, ノード, ボタン, 子, 文字表示, 横並び, 次に押されたキーの組を受け取る,
};

use crate::player_page::包む;
use crate::sample_player::再生画面の応答;
use crate::state::応答;
use crate::styles;

/// 再生のキーの操作とは、再生のキーを変える画面の操作の語彙のことである。
#[derive(Clone, Debug)]
pub enum 再生のキーの操作 {
    待ち始めた,
    受け取った(キーの組),
}

/// 見本の再生のキーとは、再生を切り替えるキーの組と、次に押されたキーを待っているかの組のことである。
pub struct 見本の再生のキー {
    組: キーの組,
    待っているか: bool,
}

impl 見本の再生のキー {
    pub fn 新規() -> Self {
        Self {
            組: キーの組::単独(キー::Space),
            待っているか: false,
        }
    }

    pub fn 適用する(&mut self, 操作: 再生のキーの操作) {
        match 操作 {
            再生のキーの操作::待ち始めた => self.待っているか = true,
            再生のキーの操作::受け取った(組) => {
                if 組 != キーの組::単独(キー::Escape) {
                    self.組 = 組;
                }
                self.待っているか = false;
            }
        }
    }

    /// 待っている間は次に押されたキーを受け取り、待っていない間は再生を切り替えるキー操作を置く。
    pub fn 見張り(&self) -> ノード<応答> {
        if self.待っているか {
            次に押されたキーの組を受け取る(
                |組| 操作を包む(再生のキーの操作::受け取った(組)),
            )
            .into()
        } else {
            キー操作(self.組, 包む(再生画面の応答::再生を切り替えた)).into()
        }
    }

    /// 今のキーの表記と、キーを変えるボタンの行。
    pub fn 行(&self) -> ノード<応答> {
        let 文 = if self.待っているか {
            "変えるキーを押してください(Escape でやめる)".to_string()
        } else {
            format!("{} で再生を切り替える", self.組.表記())
        };
        横並び(子![
            文字表示(文).装飾(styles::補足),
            ボタン("キーを変える", 操作を包む(再生のキーの操作::待ち始めた)).小さい(),
        ])
        .into()
    }
}

fn 操作を包む(操作: 再生のキーの操作) -> 応答 {
    包む(再生画面の応答::再生のキーを操作した(操作))
}
