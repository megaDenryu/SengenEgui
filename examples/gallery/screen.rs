//! 画面の骨格。メニューバー・タブ列・ページの出し分け・記録の欄・窓と覆い・キー操作を組む。
//! 各ページの中身は族ごとのファイルが持つ。

use sengen_egui::{
    ウィンドウ, キー, キーの組, キー操作, タブ列, ノード, パネル, パネルの位置, ボタン, メニュー,
    メニューバー, モーダル, 仮想縦スクロール, 修飾キー, 子, 文字表示, 条件付き表示, 横並び, 画素,
    縦積み,
};

use crate::state::{応答, 状態};
use crate::styles;
use crate::{attach_page, container_page, display_page, input_page, player_page};

const タブの見出し一覧: [&str; 5] = ["表示", "入力", "容器", "付け足し", "再生画面"];

pub fn 画面(状態: &状態) -> ノード<応答> {
    縦積み(子![
        キー操作(
            キーの組::生成する(修飾キー::COMMAND, キー::W),
            応答::窓を開閉した(true)
        ),
        メニューバー(子![
            メニュー(
                "窓",
                子![
                    ボタン("見本の窓を開く (Ctrl+W)", 応答::窓を開閉した(true)),
                    ボタン("覆いを開く", 応答::覆いを開閉した(true)),
                    メニュー(
                        "入れ子",
                        子![ボタン("入れ子の項目", 応答::押した("入れ子"))]
                    ),
                ]
            ),
            メニュー("記録", 子![ボタン("消す", 応答::記録を消した)]),
        ]),
        パネル("記録", パネルの位置::下, 子![記録の欄(状態)])
            .既定の高さ(画素(140.0))
            .大きさを変えられる(true),
        パネル("本体", パネルの位置::中央, 子![本体(状態)]),
        ウィンドウ(
            "見本の窓",
            状態.窓が開いている,
            子![文字表示("閉じるボタンで応答が出る")]
        )
        .閉じたら(応答::窓を開閉した(false))
        .既定の大きさ(sengen_egui::画素の組(240.0, 120.0)),
        モーダル(
            "覆い",
            状態.覆いが開いている,
            子![
                文字表示("外側を押すか Escape で閉じる"),
                ボタン("閉じる", 応答::覆いを開閉した(false)),
            ]
        )
        .閉じたら(応答::覆いを開閉した(false)),
    ])
    .into()
}

fn 本体(状態: &状態) -> ノード<応答> {
    let 番号 = 状態.選択中のタブ;
    縦積み(子![
        タブ列(
            タブの見出し一覧
                .iter()
                .map(|見出し| (*見出し).to_string())
                .collect(),
            番号,
            応答::タブを選んだ
        ),
        条件付き表示(番号 == 0, || display_page::ページ(状態)),
        条件付き表示(番号 == 1, || input_page::ページ(状態)),
        条件付き表示(番号 == 2, || container_page::ページ(状態)),
        条件付き表示(番号 == 3, || attach_page::ページ(状態)),
        条件付き表示(番号 == 4, || player_page::ページ(状態)),
    ])
    .into()
}

fn 記録の欄(状態: &状態) -> ノード<応答> {
    let 行一覧: Vec<String> = 状態.記録.iter().rev().take(200).cloned().collect();
    let 行数 = 行一覧.len();
    縦積み(子![
        横並び(子![
            文字表示("発行した応答").装飾(styles::見出し),
            文字表示(format!("最後に押したもの: {}", 状態.最後に押したもの)),
            ボタン("消す", 応答::記録を消した).小さい(),
            文字表示(見えている行の表示(状態)),
        ]),
        仮想縦スクロール("記録", 画素(18.0), 行数, move |行番号| {
            文字表示(行一覧[行番号].clone()).折り返さない().into()
        })
        .見えている行を発する(応答::記録の見えている行),
    ])
    .into()
}

/// 記録の欄で前のフレームに見えていた行の番号。見えている行を応答として受け取る口の見本である。
fn 見えている行の表示(状態: &状態) -> String {
    状態.記録の見えている行.map_or_else(
        || "見えている行: なし".to_string(),
        |範囲| format!("見えている行: {} から {}", 範囲.最初(), 範囲.最後()),
    )
}
