//! 見本の行の並び。見本の時間の行の並びが置いた塊と行の数を持ち、塊を動かし、空の行を足し引きする。
//! 利用する側が持つ規則の一例として、移した先の行でほかの塊と重なるときは塊を動かさず、消せるのは塊の無い行だけにする。

use sengen_egui::{時間の塊の移動量, 時間の行の差, 時間の行の番号};

use crate::sample_time_block::見本の置いた塊;

/// 見本の行の並びとは、置いた塊と行の数の組のことである。
pub struct 見本の行の並び {
    塊一覧: Vec<見本の置いた塊>,
    行の数: usize,
}

impl 見本の行の並び {
    pub fn 塊と行の数から作る(
        塊一覧: Vec<見本の置いた塊>, 行の数: usize
    ) -> Self {
        Self {
            塊一覧, 行の数
        }
    }

    pub fn 行の数(&self) -> usize {
        self.行の数
    }

    pub fn 置いた塊を巡る(&self) -> impl Iterator<Item = 見本の置いた塊> + '_ {
        self.塊一覧.iter().copied()
    }

    /// 掴み始めの塊を移動量だけ動かした位置へ置き直す。移した先の行でほかの塊と重なるなら動かさない。
    pub fn 塊を動かす(
        &mut self, 始め: 見本の置いた塊, 移動量: 時間の塊の移動量
    ) {
        let 動かした塊 = 始め.移動量だけ動かした塊(移動量, self.行の数);
        let 重なる = self
            .置いた塊を巡る()
            .any(|置いた| 置いた.鍵 != 始め.鍵 && 置いた.重なるか(動かした塊));
        if let Some(置いた) = self.塊一覧.iter_mut().find(|置いた| 置いた.鍵 == 始め.鍵)
            && !重なる
        {
            *置いた = 動かした塊;
        }
    }

    /// 行の番号の行に塊が1つも無いか。
    pub fn 空の行か(&self, 行: 時間の行の番号) -> bool {
        行.置いた順の番号() < self.行の数 && self.置いた塊を巡る().all(|置いた| 置いた.行 != 行)
    }

    /// 一番上に空の行を足す。
    pub fn 一番上に空の行を足す(&mut self) {
        self.行の数 += 1;
    }

    /// 空の行を消し、それより上の行の塊を1つ下の行へ移す。空でない行は消さない。
    pub fn 空の行を消す(&mut self, 行: 時間の行の番号) {
        if !self.空の行か(行) {
            return;
        }
        let 一つ下へ = 時間の行の差::上へ動かした行の数から生成する(-1);
        for 置いた in self.塊一覧.iter_mut().filter(|置いた| 置いた.行 > 行) {
            置いた.行 = 置いた.行.差だけ動かした番号(一つ下へ).unwrap_or(置いた.行);
        }
        self.行の数 -= 1;
    }
}
