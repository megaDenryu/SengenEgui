//! 入力の族のページ。値は状態のこのフレームの値を渡し、変更は応答として発行する。

use sengen_egui::{
    スライダー, チェックボックス, ノード, ボタン, ラジオボタン, リンク, 一行テキスト入力, 区切り線,
    子, 数値入力, 文字表示, 格子, 横並び, 画素, 縦積み, 色選択, 複数行テキスト入力, 選択ボタン,
    選択欄, 選択肢,
};

use crate::state::{応答, 状態};
use crate::styles;

const 選べるもの一覧: [&str; 3] = ["甲", "乙", "丙"];

pub fn ページ(状態: &状態) -> ノード<応答> {
    縦積み(子![
        文字表示("ボタン").装飾(styles::見出し),
        横並び(子![
            ボタン("普通", 応答::押した("普通")),
            ボタン("小さい", 応答::押した("小さい")).小さい(),
            ボタン("枠なし", 応答::押した("枠なし")).枠なし(),
            ボタン("最小幅", 応答::押した("最小幅")).最小幅(画素(120.0)),
            ボタン("無効", 応答::押した("無効")).有効(false),
            リンク("リンク", 応答::押した("リンク")),
        ]),
        区切り線(),
        文字表示("文字の入力").装飾(styles::見出し),
        格子(
            "文字の入力",
            2,
            子![
                文字表示("毎キー発行"),
                一行テキスト入力(状態.一行.clone(), 応答::一行を変えた).幅(画素(240.0)),
                文字表示("確定時のみ発行"),
                一行テキスト入力(状態.一行.clone(), 応答::一行を変えた)
                    .確定時のみ発行("確定時")
                    .案内文("Enter か焦点が外れたときに発行")
                    .幅(画素(240.0)),
                文字表示("伏せ字"),
                一行テキスト入力(状態.合言葉.clone(), 応答::合言葉を変えた)
                    .伏せ字()
                    .案内文("合言葉")
                    .幅(画素(240.0)),
                文字表示("複数行・等幅"),
                複数行テキスト入力(状態.複数行.clone(), 応答::複数行を変えた)
                    .行数(3)
                    .等幅()
                    .幅(画素(240.0)),
            ]
        ),
        区切り線(),
        文字表示("数の入力").装飾(styles::見出し),
        横並び(子![
            数値入力(状態.数, 0..=100, 応答::数を変えた)
                .刻み(1)
                .前置き("数: ")
                .後置き(" 個"),
            スライダー(状態.数, 0..=100, 応答::数を変えた).文字を添える("同じ数"),
            スライダー(状態.小数, 0.0..=1.0, 応答::小数を変えた)
                .文字を添える("小数（0.05 刻み）")
                .刻み(0.05)
                .幅(画素(200.0)),
        ]),
        区切り線(),
        文字表示("選ぶ").装飾(styles::見出し),
        横並び(
            選べるもの一覧
                .iter()
                .map(
                    |名前| ラジオボタン(*名前, 状態.選んだもの == *名前, 応答::選んだ(名前)).into()
                )
                .collect()
        ),
        横並び(
            選べるもの一覧
                .iter()
                .map(|名前| 選択ボタン(*名前, 状態.選んだもの == *名前, 応答::選んだ(名前)).into())
                .collect()
        ),
        選択欄(
            "選択欄",
            状態.選んだもの,
            選べるもの一覧
                .iter()
                .map(|名前| 選択肢(*名前, 応答::選んだ(名前)))
                .collect()
        )
        .幅(画素(160.0)),
        横並び(子![
            チェックボックス("まとめて有効", 状態.有効, 応答::有効を切り替えた),
            色選択(状態.色, 応答::色を変えた),
            文字表示("色選択"),
        ]),
    ])
    .装飾(styles::カード)
    .into()
}
