//! 表示の族のページ。文字表示・進捗バー・読み込み中表示・外部リンク・画像・余白・区切り線。
//! 画像を材料にする入力の部品（押せる画像・範囲枠付き画像）も、画像の節にまとめて置く。

use sengen_egui::{
    ノード, 余白, 割合, 区切り線, 外部リンク, 子, 文字表示, 格子, 横並び, 画像, 画素, 画素の組,
    範囲枠付き画像, 縦積み, 読み込み中表示, 進捗バー,
};

use crate::state::{応答, 状態};
use crate::styles;

pub fn ページ(状態: &状態) -> ノード<応答> {
    縦積み(子![
        文字表示("文字表示").装飾(styles::見出し),
        格子(
            "文字の見本",
            2,
            子![
                文字表示("既定"),
                文字表示("そのままの文字"),
                文字表示("斜体と下線"),
                文字表示("装飾を付けた文字").装飾(styles::斜体と下線),
                文字表示("取り消し線と弱い"),
                文字表示("目立たせない文字").装飾(styles::取り消し線と弱い),
                文字表示("選択できる"),
                文字表示("ドラッグで選んでコピーできる").選択できる(),
                文字表示("折り返さない"),
                文字表示("幅が足りなければ末尾を省略記号で切り詰める長い長い長い文字列")
                    .折り返さない(),
            ]
        )
        .縞模様(),
        区切り線(),
        文字表示("進捗バーと読み込み中表示").装飾(styles::見出し),
        進捗バー(割合::範囲へ丸めて生成する(状態.小数))
            .文字を添える("スライダーの小数に連動")
            .幅(画素(240.0)),
        進捗バー(割合::範囲へ丸めて生成する(状態.小数)).割合を表示する(),
        読み込み中表示().大きさ(画素(24.0)),
        余白(画素(8.0)),
        文字表示("リンクと画像").装飾(styles::見出し),
        外部リンク(
            "egui の公式リポジトリをブラウザで開く",
            "https://github.com/emilk/egui"
        ),
        横並び(子![
            画像(状態.画像.clone()).最大幅(画素(96.0)),
            画像(状態.画像.clone()).表示寸法(画素の組(160.0, 64.0)),
            画像(状態.画像.clone())
                .表示寸法(画素の組(64.0, 64.0))
                .押されたら発する(応答::押した("画像")),
        ]),
        文字表示(
            "左から: 最大幅の指定・表示寸法の指定（縦横比を保って枠へ収める）・押せる画像。             画素から作ったテクスチャ。URI から出すには読み込み器を導入する"
        )
        .装飾(styles::補足),
        範囲枠付き画像(
            状態.画像.clone(),
            画素の組(256.0, 160.0),
            状態.範囲枠.部品へ渡す枠(),
            応答::範囲枠を操作した
        ),
        文字表示(
            "範囲枠付き画像: 枠の内側のドラッグで移動、4隅のつまみで大きさの変更。             画像の内側へ収める規則と最小の大きさは見本帳の側（sample_frame.rs）が持つ"
        )
        .装飾(styles::補足),
    ])
    .装飾(styles::カード)
    .into()
}
