//! 容器の族のページのうち、割合の矩形へ置く節。16:9 の容器の中へ、色を塗った3つの子を容器に対する割合の矩形で重ねて置き、
//! 後に置いた子ほど上に重なって、重なった場所では先に押されることを見せる。

use sengen_egui::{
    スタイル, ノード, 付け足せる, 使える大きさから組む, 割合, 割合で表した矩形, 割合の矩形へ置く,
    大きさを決めた領域, 子, 文字表示, 画素の組, 縦積み, 色,
};

use crate::state::応答;
use crate::styles;

const 容器の地: スタイル = スタイル {
    背景色: Some(色::from_rgb(8, 10, 14)),
    ..スタイル::無指定
};

pub fn 割合の矩形へ置く節() -> ノード<応答> {
    縦積み(子![
        文字表示("割合の矩形へ置く（後に置いた子ほど上。押すと最後に押したものが変わる）")
            .装飾(styles::見出し),
        割合の矩形へ置く(画素の組(384.0, 216.0))
            .装飾(容器の地)
            .子を置く(
                左上と大きさから矩形を作る(0.05, 0.1, 0.5, 0.5),
                塗った子を作る("奥（左上 5%・10%、大きさ 50%）", 色::from_rgb(150, 60, 60))
            )
            .子を置く(
                左上と大きさから矩形を作る(0.3, 0.3, 0.5, 0.5),
                塗った子を作る("中（左上 30%・30%）", 色::from_rgb(60, 130, 70))
            )
            .子を置く(
                左上と大きさから矩形を作る(0.6, 0.55, 0.4, 0.45),
                塗った子を作る("手前（右下の隅まで）", 色::from_rgb(60, 90, 160))
            ),
    ])
    .into()
}

/// 見本の割合は容器の内側に収まる定数なので、生成の失敗は到達したらバグである。
fn 左上と大きさから矩形を作る(
    左端: f32,
    上端: f32,
    幅: f32,
    高さ: f32,
) -> 割合で表した矩形 {
    let 割合にする = |値: f32| match 割合::生成する(値) {
        Ok(割合) => 割合,
        Err(範囲外) => panic!("見本の割合が範囲外である（到達したらバグ）: {範囲外}"),
    };
    match 割合で表した矩形::左上と大きさから生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(幅),
        割合にする(高さ),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => panic!("見本の矩形が容器の外へ出ている（到達したらバグ）: {不正}"),
    }
}

/// 置かれた矩形いっぱいを色で塗り、名前を書いた、押せる子を作る。
fn 塗った子を作る(名前: &'static str, 塗る色: 色) -> ノード<応答> {
    使える大きさから組む(move |大きさ| {
        let 地 = スタイル {
            背景色: Some(塗る色),
            ..スタイル::無指定
        };
        大きさを決めた領域(大きさ, 子![文字表示(名前)])
            .装飾(地)
            .押されたら発する(応答::押した(名前))
    })
    .into()
}
