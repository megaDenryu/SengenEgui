//! 容器の族のページのうち、パネルの節。縁のパネルを先に、中央のパネルを最後に置く順序と、
//! 縁のドラッグで変えられる幅の範囲と、装飾で変える地の色と余白を見せる。

use sengen_egui::{ノード, パネル, パネルの位置, 子, 文字表示, 画素, 縦積み};

use crate::state::応答;
use crate::styles;

pub fn パネルの節() -> ノード<応答> {
    縦積み(子![
        文字表示("パネル（縁を先に、中央を最後に置く）").装飾(styles::見出し),
        縦積み(子![
            パネル("見本の左", パネルの位置::左, 子![文字表示("左")])
                .既定の幅(画素(80.0))
                .幅の範囲(画素(60.0), 画素(160.0))
                .大きさを変えられる(true),
            パネル("見本の右", パネルの位置::右, 子![文字表示("右")]).既定の幅(画素(80.0)),
            パネル(
                "見本の上",
                パネルの位置::上,
                子![文字表示("上（装飾で地の色と余白を変える）")]
            )
            .装飾(styles::上のパネル),
            パネル(
                "見本の中央",
                パネルの位置::中央,
                子![文字表示(
                    "中央。左の縁はドラッグで幅を60から160論理画素の間で変えられる"
                )]
            ),
        ])
        .装飾(styles::カード),
    ])
    .into()
}
