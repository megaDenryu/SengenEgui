//! 入力の族のページのうち、複数の範囲枠の節。16:9 の下地の上に、色を塗った3つの区画を枠と同じ割合の矩形で置き、
//! その上に3つの枠を重ねる。押した枠を選び、内側のドラッグで動かし、選んでいる枠の4隅のつまみで大きさを変える。
//! 選んでいる枠を先に掴み、選んでいない枠の内側が重なった場所では手前の枠を選ぶ。何も無い所を押すと選びを外す。

use sengen_egui::{
    スタイル, ノード, 使える大きさから組む, 修飾キー, 割合の矩形へ置く, 大きさを決めた領域, 子,
    文字表示, 画素の組, 縦積み, 色, 複数の範囲枠,
};

use crate::sample_range_frames::{
    見本の枠の鍵, 見本の複数の範囲枠, 見本の複数の範囲枠の応答
};
use crate::state::応答;
use crate::styles;

const 下地の背景: スタイル = スタイル {
    背景色: Some(色::from_rgb(8, 10, 14)),
    ..スタイル::無指定
};

/// 枠の鍵ごとの区画の色。
fn 区画の色(鍵: 見本の枠の鍵) -> 色 {
    match 鍵 {
        見本の枠の鍵::赤 => 色::from_rgb(150, 60, 60),
        見本の枠の鍵::緑 => 色::from_rgb(60, 130, 70),
        見本の枠の鍵::青 => 色::from_rgb(60, 90, 160),
    }
}

pub fn 複数の範囲枠の節(見本: &見本の複数の範囲枠) -> ノード<応答> {
    let 寸法 = 画素の組(384.0, 216.0);
    let 下地 = 見本.置く枠を巡る().fold(
        割合の矩形へ置く(寸法).装飾(下地の背景),
        |容器, (鍵, 枠)| 容器.子を置く(枠.部品へ渡す枠(), 塗った区画を作る(区画の色(鍵))),
    );
    let 部品 = 複数の範囲枠(寸法, 下地, |鍵, 操作| {
        応答::複数の範囲枠(見本の複数の範囲枠の応答::枠を操作した(
            鍵, 操作,
        ))
    })
    .縦横比を保つ(修飾キー::SHIFT)
    .何も無い所を押したら発する(応答::複数の範囲枠(
        見本の複数の範囲枠の応答::何も無い所を押した,
    ));
    let 部品 = 見本.置く枠を巡る().fold(部品, |部品, (鍵, 枠)| {
        if 見本.選んでいる枠() == Some(鍵) {
            部品.選んでいる枠を置く(鍵, 枠.部品へ渡す枠())
        } else {
            部品.枠を置く(鍵, 枠.部品へ渡す枠())
        }
    });
    縦積み(子![
        文字表示("複数の範囲枠（押して選ぶ・内側で移動・選んだ枠の4隅で大きさ。選んだ枠を先に掴み、ほかは手前を掴む。何も無い所を押すと選びを外す）")
            .装飾(styles::見出し),
        部品,
        文字表示(format!(
            "最後に発した縦横比の扱い: {}（Shift を押している間は保たない。保った大きさの計算は利用する側が行うため、この見本では使わない）",
            見本.最後の縦横比の扱いの表示()
        )),
    ])
    .into()
}

/// 置かれた矩形いっぱいを色で塗った区画を作る。
fn 塗った区画を作る(塗る色: 色) -> ノード<応答> {
    使える大きさから組む(move |大きさ| {
        let 地 = スタイル {
            背景色: Some(塗る色),
            ..スタイル::無指定
        };
        大きさを決めた領域(大きさ, vec![]).装飾(地).into()
    })
    .into()
}
