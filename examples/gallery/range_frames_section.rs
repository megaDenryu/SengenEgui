//! 入力の族のページのうち、複数の範囲枠の節。16:9 の下地の上に、色を塗った3つの区画を枠と同じ割合の矩形で置き、
//! その上に3つの枠を重ねる。押した枠を選び、内側のドラッグで動かし、選んでいる枠の4隅のつまみで大きさを変える。
//! 内側が重なった場所では手前の枠を選ぶ。

use sengen_egui::{
    スタイル, ノード, 使える大きさから組む, 修飾キー, 割合の矩形へ置く, 大きさを決めた領域, 子,
    文字表示, 画素の組, 縦積み, 色, 複数の範囲枠,
};

use crate::sample_range_frames::見本の複数の範囲枠;
use crate::state::応答;
use crate::styles;

const 下地の背景: スタイル = スタイル {
    背景色: Some(色::from_rgb(8, 10, 14)),
    ..スタイル::無指定
};

const 区画の色一覧: [色; 3] = [
    色::from_rgb(150, 60, 60),
    色::from_rgb(60, 130, 70),
    色::from_rgb(60, 90, 160),
];

pub fn 複数の範囲枠の節(見本: &見本の複数の範囲枠) -> ノード<応答> {
    let 寸法 = 画素の組(384.0, 216.0);
    let 枠一覧 = 見本.部品へ渡す枠一覧();
    let 下地 = 枠一覧.iter().zip(区画の色一覧).fold(
        割合の矩形へ置く(寸法).装飾(下地の背景),
        |容器, ((矩形, _), 塗る色)| 容器.子を置く(*矩形, 塗った区画を作る(塗る色)),
    );
    let 部品 = 枠一覧.iter().enumerate().fold(
        複数の範囲枠(寸法, 下地).縦横比を保つ(修飾キー::SHIFT),
        |部品, (番号, (矩形, 選んでいる))| {
            let 操作から応答を作る =
                move |操作| 応答::複数の範囲枠を操作した(番号, 操作);
            if *選んでいる {
                部品.選んでいる枠を置く(*矩形, 操作から応答を作る)
            } else {
                部品.枠を置く(*矩形, 操作から応答を作る)
            }
        },
    );
    縦積み(子![
        文字表示("複数の範囲枠（押して選ぶ・内側で移動・選んだ枠の4隅で大きさ。重なった所は手前を選ぶ）")
            .装飾(styles::見出し),
        部品,
        文字表示(format!(
            "最後に発した縦横比の扱い: {}（Shift を押している間は保たない。保った大きさの計算は利用する側が行うため、この見本では使わない）",
            見本.最後の縦横比の扱いの表示()
        )),
    ])
    .into()
}

/// 置かれた矩形いっぱいを色で塗った区画を作る。
fn 塗った区画を作る(塗る色: 色) -> ノード<応答> {
    使える大きさから組む(move |大きさ| {
        let 地 = スタイル {
            背景色: Some(塗る色),
            ..スタイル::無指定
        };
        大きさを決めた領域(大きさ, vec![]).装飾(地).into()
    })
    .into()
}
