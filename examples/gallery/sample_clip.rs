//! 見本の区間。区間の帯の操作を受けて区間を更新する、利用する側の状態の見本である。
//! 部品は掴んだものとその値だけを発するため、開始が終了を超えない規則と最小の長さは、部品でなくこの利用する側が持つ。
//! 区間を動かしている間と位置の印を動かしている間は、再生位置をその値へ移す（ドラッグの間の軽い処理の見本）。

use sengen_egui::{区間の帯の掴んだもの, 区間の帯の操作, 帯の値};

/// 区間の最小の長さ（秒）。
const 最小の長さ: f64 = 0.5;

/// 見本の区間とは、再生する映像のうち切り出す部分の開始と終了（秒）の組のことである。
pub struct 見本の区間 {
    開始: f64,
    終了: f64,
}

impl 見本の区間 {
    pub fn 新規() -> Self {
        Self {
            開始: 2.0,
            終了: 5.0,
        }
    }

    pub fn 開始(&self) -> 帯の値 {
        帯の値::倍精度の小数から生成する(self.開始)
    }

    pub fn 終了(&self) -> 帯の値 {
        帯の値::倍精度の小数から生成する(self.終了)
    }

    /// 操作を区間へ適用し、再生位置を移す先（秒）があれば返す。区間の内側を動かしたときは新しい開始へ、
    /// 位置の印を動かしたときはその値へ移す。つまみを動かしたときは再生位置を変えない。
    pub fn 操作を適用する(&mut self, 操作: 区間の帯の操作) -> Option<f64> {
        let (掴んだもの, 値) = match 操作 {
            区間の帯の操作::掴み始めた {
                掴んだもの, 値
            }
            | 区間の帯の操作::動かしている {
                掴んだもの, 値
            }
            | 区間の帯の操作::放した {
                掴んだもの, 値
            } => (掴んだもの, 値.倍精度の小数にする()),
        };
        match 掴んだもの {
            区間の帯の掴んだもの::開始のつまみ => {
                self.開始 = 値.min(self.終了 - 最小の長さ);
                None
            }
            区間の帯の掴んだもの::終了のつまみ => {
                self.終了 = 値.max(self.開始 + 最小の長さ);
                None
            }
            区間の帯の掴んだもの::区間の内側 => {
                let 長さ = self.終了 - self.開始;
                self.開始 = 値;
                self.終了 = 値 + 長さ;
                Some(値)
            }
            区間の帯の掴んだもの::位置の印 => Some(値),
        }
    }
}
