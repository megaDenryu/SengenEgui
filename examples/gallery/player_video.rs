//! 再生画面のページの映像の欄。使える幅から16:9の欄の大きさを計算し、欄の中央へ4:3の映像を描き、欄の上へ文字とボタンを重ねる。
//! 停止している間は映像を半透明の黒で覆い、真ん中に再生のボタンを置く。マウスを乗せている間だけ右上に案内を出す。
//! 映像のテクスチャは、閉包へ所有させるため参照を複製して持ち込む。

use sengen_egui::{
    ノード, ボタン, 使える大きさから組む, 大きさを決めた領域, 文字表示, 画像, 縦横の論理画素,
    論理画素, 重ねる, 重ねる位置,
};

use crate::player_page::包む;
use crate::sample_player::{再生画面の応答 as 再生, 見本の再生};
use crate::state::応答;
use crate::styles;

/// 欄の幅の上限。見本帳の窓が広くても、映像の欄が画面を占めすぎないようにする。
const 欄の幅の上限: f64 = 560.0;

pub fn 映像の欄(再生の状態: &見本の再生) -> ノード<応答> {
    let 映像 = 再生の状態.映像.参照を複製する();
    let 再生中 = 再生の状態.再生中;
    使える大きさから組む(move |大きさ| {
        let 欄の幅 = 論理画素::倍精度の小数から生成する(
            大きさ.横.倍精度の小数にする().min(欄の幅の上限),
        );
        let 欄の高さ = 欄の幅 * (9.0 / 16.0);
        let 映像 = 画像(&映像)
            .表示寸法へ引き伸ばす(縦横の論理画素::生成する(
                欄の高さ * (4.0 / 3.0),
                欄の高さ,
            ))
            .押されたら発する(包む(再生::再生を切り替えた));
        let 欄 = 大きさを決めた領域(
            縦横の論理画素::生成する(欄の幅, 欄の高さ),
            vec![映像.into()],
        )
        .中央寄せ()
        .装飾(styles::映像の欄);
        let 重ね = 重ねる("見本の映像の欄", 欄)
            .上に置く(
                重ねる位置::左上,
                文字表示("見本の映像").装飾(styles::映像の上の文字),
            )
            .マウスを乗せている間だけ上に置く(
                重ねる位置::右上,
                文字表示("マウスを乗せている間だけ出る").装飾(styles::映像の上の文字),
            )
            .上に置く(
                重ねる位置::右下,
                ボタン(
                    "通知を出す",
                    包む(再生::通知を出した("映像の上のボタンを押した")),
                ),
            );
        if 再生中 {
            重ね.into()
        } else {
            重ね
                .覆って中央に置く(
                    styles::停止中の覆い,
                    ボタン("再生する", 包む(再生::再生を切り替えた)),
                )
                .into()
        }
    })
    .into()
}
