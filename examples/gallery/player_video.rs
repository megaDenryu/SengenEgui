//! 再生画面のページの映像の欄。使える幅から16:9の大きさを計算して映像を描き、映像の上へ文字とボタンを重ねる。
//! 停止している間は映像を半透明の黒で覆い、真ん中に再生のボタンを置く。

use eframe::egui;
use sengen_egui::{
    ノード, ボタン, 使える大きさから組む, 文字表示, 画像, 画像の出所, 画素の組, 重ねる, 重ねる位置,
};

use crate::player_page::包む;
use crate::sample_player::{再生画面の応答 as 再生, 見本の再生};
use crate::state::応答;
use crate::styles;

/// 映像の幅の上限。見本帳の窓が広くても、映像が画面を占めすぎないようにする。
const 映像の幅の上限: f32 = 480.0;

pub fn 映像の欄(再生の状態: &見本の再生) -> ノード<応答> {
    let 映像 = 画像の出所::from(&再生の状態.映像);
    let 再生中 = 再生の状態.再生中;
    使える大きさから組む(move |大きさ| {
        let 幅 = 大きさ.横.eguiへ渡す値().min(映像の幅の上限);
        let 下地 = 画像(映像.clone())
            .表示寸法へ引き伸ばす(画素の組(幅, 幅 * 9.0 / 16.0))
            .押されたら発する(包む(再生::再生を切り替えた));
        let 重ね = 重ねる(下地)
            .上に置く(
                重ねる位置::左上,
                文字表示("見本の映像").装飾(styles::映像の上の文字),
            )
            .上に置く(
                重ねる位置::右下,
                ボタン(
                    "通知を出す",
                    包む(再生::通知を出した("映像の上のボタンを押した")),
                ),
            );
        if 再生中 {
            重ね.into()
        } else {
            重ね
                .覆って中央に置く(
                    egui::Color32::from_black_alpha(140),
                    ボタン("再生する", 包む(再生::再生を切り替えた)),
                )
                .into()
        }
    })
    .into()
}
