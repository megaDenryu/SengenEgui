//! 容器の族のページ。横並びの寄せ・折り返し・スクロール・折り畳み・格子・パネル・有効の切り替え。

use sengen_egui::{
    ノード, ボタン, 両方向スクロール, 区切り線, 子, 折り畳み見出し, 折り返す横並び, 文字表示, 格子,
    横スクロール, 横並び, 画素, 縦スクロール, 縦積み,
};

use crate::state::{応答, 状態};
use crate::{panel_section, styles};

pub fn ページ(状態: &状態) -> ノード<応答> {
    縦積み(子![
        文字表示("横並びの寄せと有効の切り替え").装飾(styles::見出し),
        横並び(子![
            ボタン("左詰め", 応答::押した("左詰め")),
            文字表示("既定の寄せ")
        ])
        .有効(状態.有効),
        横並び(子![
            ボタン("右詰め", 応答::押した("右詰め")),
            文字表示("右寄せ")
        ])
        .右寄せ()
        .有効(状態.有効),
        横並び(子![
            ボタン("中央", 応答::押した("中央")),
            文字表示("中央寄せ")
        ])
        .中央寄せ()
        .幅(画素(400.0))
        .有効(状態.有効),
        区切り線(),
        文字表示("折り返す横並び").装飾(styles::見出し),
        折り返す横並び(
            (1..=24)
                .map(|番号| ボタン(format!("項目 {番号}"), 応答::押した("折り返し")).into())
                .collect()
        )
        .最小幅(画素(200.0)),
        区切り線(),
        文字表示("スクロール（縦・横・両方向）").装飾(styles::見出し),
        横並び(子![
            縦スクロール("縦", 行の一覧(30))
                .最大高さ(画素(100.0))
                .最大幅(画素(160.0)),
            横スクロール("横", 子![横並び(行の一覧(30))]).最大幅(画素(240.0)),
            両方向スクロール("両", 子![格子("両の格子", 12, 行の一覧(144))])
                .最大幅(画素(240.0))
                .最大高さ(画素(100.0)),
        ]),
        区切り線(),
        文字表示("折り畳み見出しと格子").装飾(styles::見出し),
        折り畳み見出し("開閉できる見出し", 子![格子の見本()]).既定で開く(),
        区切り線(),
        panel_section::パネルの節(),
    ])
    .装飾(styles::カード)
    .into()
}

fn 行の一覧(件数: usize) -> Vec<ノード<応答>> {
    (1..=件数)
        .map(|番号| 文字表示(format!("行 {番号}")).into())
        .collect()
}

fn 格子の見本() -> ノード<応答> {
    格子(
        "格子の見本",
        3,
        子![
            文字表示("名前").装飾(styles::見出し),
            文字表示("値").装飾(styles::見出し),
            文字表示("操作").装飾(styles::見出し),
            文字表示("甲"),
            文字表示("1"),
            ボタン("押す", 応答::押した("格子の甲")).小さい(),
            文字表示("乙"),
            文字表示("2"),
            ボタン("押す", 応答::押した("格子の乙")).小さい(),
        ],
    )
    .縞模様()
    .列の間隔(画素(24.0))
    .行の間隔(画素(6.0))
    .into()
}
