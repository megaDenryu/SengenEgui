//! 再生画面のページ。差し替えられるテクスチャ・使える大きさから組む・重ねる・再生位置の帯・押せる領域・
//! 一定時間で消える通知・描き直しの予約・落とされたファイルの受け取りを、動画の再生画面の形で組み合わせる。

use sengen_egui::{
    キー, キーの組, キー操作, スライダー, ノード, ボタン, 一定時間で消える通知, 付け足せる, 子,
    描き直しを予約する, 数値入力, 文字表示, 条件付き表示, 横並び, 無し, 画素, 縦積み,
    落とされたファイルを受け取る,
};

use crate::player_video;
use crate::sample_player::{
    一コマの時間, 再生の長さ, 再生画面の応答 as 再生, 見本の再生
};
use crate::state::{応答, 状態};
use crate::styles;

pub fn 包む(応答: 再生) -> 応答 {
    応答::再生画面(応答)
}

pub fn ページ(状態: &状態) -> ノード<応答> {
    let 再生の状態 = &状態.再生;
    縦積み(子![
        落とされたファイルを受け取る(|パス| 包む(再生::ファイルを受け取った(パス))),
        キー操作(キーの組::単独(キー::Space), 包む(再生::再生を切り替えた)),
        条件付き表示(再生の状態.再生中, || 描き直しを予約する(
            一コマの時間
        )),
        文字表示("映像（使える幅から16:9の大きさを計算し、映像の上へボタンを重ねる）")
            .装飾(styles::見出し),
        player_video::映像の欄(再生の状態),
        再生の操作(再生の状態),
        文字表示("札（札の全体を押すと選び、中のボタンは札を選ばずに通知を出す）")
            .装飾(styles::見出し),
        横並び(
            (0..3)
                .map(|番号| 札(番号, 再生の状態.選んだ札 == 番号))
                .collect()
        ),
        文字表示(format!(
            "窓へ落としたファイル: {}",
            再生の状態.受け取ったファイル.join("、")
        )),
        match 再生の状態.通知 {
            Some((回, 文)) => 一定時間で消える通知("見本の通知", 回, 文).into(),
            None => 無し(),
        },
    ])
    .装飾(styles::カード)
    .into()
}

/// 再生と停止のボタン・秒の数値入力・再生位置の帯。帯はドラッグの間も位置を動かし、放したときに位置を決める。
fn 再生の操作(再生の状態: &見本の再生) -> ノード<応答> {
    let 秒 = 再生の状態.位置.as_secs_f32();
    let 長さ = 再生の長さ.as_secs_f32();
    縦積み(子![
        横並び(子![
            ボタン(
                if 再生の状態.再生中 {
                    "停止"
                } else {
                    "再生"
                },
                包む(再生::再生を切り替えた)
            ),
            数値入力(秒, 0.0..=長さ, |秒| 包む(再生::位置を決めた(秒)))
                .刻み(0.05)
                .小数点以下の桁数(2)
                .後置き(" 秒"),
            文字表示("Space でも再生を切り替える").装飾(styles::補足),
        ]),
        スライダー(秒, 0.0..=長さ, |秒| 包む(再生::位置を動かしている(秒)))
            .幅いっぱい()
            .数値を隠す()
            .操作を終えたら発する(|秒| 包む(再生::位置を決めた(秒))),
    ])
    .into()
}

fn 札(番号: usize, 選ばれている: bool) -> ノード<応答> {
    縦積み(子![
        文字表示(format!("札 {}", 番号 + 1)),
        ボタン("通知", 包む(再生::通知を出した("札の中のボタンを押した"))).小さい(),
    ])
    .最小幅(画素(120.0))
    .装飾(if 選ばれている {
        styles::選ばれた札
    } else {
        styles::札
    })
    .押されたら発する(包む(再生::札を選んだ(番号)))
}
