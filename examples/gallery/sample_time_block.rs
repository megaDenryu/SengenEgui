//! 見本の置いた塊。見本の時間の行の並びに置く1つの塊を、置いた行と、検証済みの時間の塊で持ち、部品が発した移動量だけ
//! 動かした塊を求める。行は今ある行の中へ、始まりは全体の範囲へ収める。時間の塊は作るときに長さが正で有限であることを
//! 確かめてあるため、見本の置いた塊は検証を通った値からしか作れない。

use std::num::NonZeroU32;

use sengen_egui::{
    帯の値, 帯の値の差, 時間の塊, 時間の塊の不正, 時間の塊の移動量, 時間の行の番号
};

/// 見本の全体の始まりと終わり。
pub const 見本の全体の始まり: 帯の値 = 帯の値::倍精度の小数から生成する(0.0);
pub const 見本の全体の終わり: 帯の値 = 帯の値::倍精度の小数から生成する(30.0);

/// 見本の塊の鍵とは、見本の3つの塊を見分ける値のことであり、部品へ渡す鍵である。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 見本の塊の鍵 {
    赤,
    緑,
    青,
}

/// 見本の置いた塊とは、見本の塊の鍵と、置いた行と、時間の塊の組のことである。
#[derive(Clone, Copy)]
pub struct 見本の置いた塊 {
    pub 鍵: 見本の塊の鍵,
    pub 行: 時間の行の番号,
    pub 塊: 時間の塊,
}

impl 見本の置いた塊 {
    /// 見本が最初に置く3つの塊。赤を下の行に、緑と青を上の行に置き、赤は3回、緑は4回の繰り返しの区切りを付ける。
    /// 見本の値が時間の塊として不正なら理由を返す。
    pub fn 最初の並びを作る() -> Result<Vec<Self>, 時間の塊の不正> {
        let 塊 = |始まり, 長さ| {
            時間の塊::生成する(
                帯の値::倍精度の小数から生成する(始まり),
                帯の値の差::倍精度の小数から生成する(長さ),
            )
        };
        let 置く = |鍵, 行, 塊| Self {
            鍵,
            行: 時間の行の番号::置いた順の番号から生成する(行),
            塊,
        };
        let 三回 = NonZeroU32::MIN.saturating_add(2);
        let 四回 = NonZeroU32::MIN.saturating_add(3);
        Ok(vec![
            置く(見本の塊の鍵::赤, 0, 塊(2.0, 6.0)?.等しい長さに分ける(三回)),
            置く(見本の塊の鍵::緑, 1, 塊(5.0, 8.0)?.等しい長さに分ける(四回)),
            置く(見本の塊の鍵::青, 1, 塊(16.0, 4.0)?),
        ])
    }

    /// 移動量だけ動かした塊。行は0から行の数より1少ない番号までへ、始まりは全体の範囲に塊が収まる時刻までへ収める。
    /// 始まりが有限でなくなって時間の塊を作れないときは、動かさない。
    pub fn 移動量だけ動かした塊(
        self, 移動量: 時間の塊の移動量, 行の数: usize
    ) -> Self {
        let 一番上 = 時間の行の番号::置いた順の番号から生成する(
            行の数.saturating_sub(1),
        );
        let 行 = self.行.差だけ動かした番号(移動量.行).map_or(
            時間の行の番号::置いた順の番号から生成する(0),
            |行| 行.min(一番上),
        );
        let 最後の始まり = 見本の全体の終わり + self.塊.長さ() * -1.0;
        let 動かした始まり = self.塊.始まり() + 移動量.時間;
        let 始まり = if 動かした始まり < 見本の全体の始まり {
            見本の全体の始まり
        } else if 動かした始まり > 最後の始まり {
            最後の始まり
        } else {
            動かした始まり
        };
        match self.塊.始まりを移した塊(始まり) {
            Ok(塊) => Self { 行, 塊, ..self },
            Err(_) => self,
        }
    }

    /// 同じ行にあって、占める時間が重なるか。
    pub fn 重なるか(self, 相手: Self) -> bool {
        self.行 == 相手.行
            && self.塊.始まり() < 相手.塊.終わり()
            && 相手.塊.始まり() < self.塊.終わり()
    }
}
