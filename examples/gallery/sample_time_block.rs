//! 見本の置いた塊。見本の時間の行の並びに置く1つの塊を、利用する側の値（行・始まり・長さ・中を分ける数）で持ち、
//! 部品へ渡す時間の塊を作り、部品が発した移動量だけ動かした塊を求める。行は今ある行の中へ、始まりは全体の範囲へ収める。

use std::num::NonZeroU32;

use sengen_egui::{
    帯の値, 帯の値の差, 時間の塊, 時間の塊の移動量, 時間の行の番号
};

/// 見本の全体の長さ（秒）。
pub const 見本の全体の秒: f64 = 30.0;

/// 見本の塊の鍵とは、見本の3つの塊を見分ける値のことであり、部品へ渡す鍵である。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 見本の塊の鍵 {
    赤,
    緑,
    青,
}

/// 見本の置いた塊とは、見本の塊の鍵と、置いた行と、始まりと長さと、中を分ける数の組のことである。
#[derive(Clone, Copy)]
pub struct 見本の置いた塊 {
    pub 鍵: 見本の塊の鍵,
    pub 行: 時間の行の番号,
    始まり: 帯の値,
    長さ: 帯の値の差,
    分ける数: NonZeroU32,
}

impl 見本の置いた塊 {
    /// 行の番号と、始まりと長さの秒と、中を分ける数から作る。分ける数が0なら1とする。
    pub fn 秒から作る(
        鍵: 見本の塊の鍵,
        行: usize,
        始まり: f64,
        長さ: f64,
        分ける数: u32,
    ) -> Self {
        Self {
            鍵,
            行: 時間の行の番号::置いた順の番号から生成する(行),
            始まり: 帯の値::倍精度の小数から生成する(始まり),
            長さ: 帯の値の差::倍精度の小数から生成する(長さ),
            分ける数: NonZeroU32::new(分ける数).unwrap_or(NonZeroU32::MIN),
        }
    }

    /// 部品へ渡す時間の塊。長さは見本の中で正に保つため、作れないのは到達したらバグである。
    pub fn 部品へ渡す塊(self) -> 時間の塊 {
        match 時間の塊::生成する(self.始まり, self.長さ) {
            Ok(塊) => 塊.等しい長さに分ける(self.分ける数),
            Err(不正) => panic!("見本の塊が不正である（到達したらバグ）: {不正}"),
        }
    }

    /// 移動量だけ動かした塊。行は0から行の数より1少ない番号までへ、始まりは0秒から全体の終わりに収まる時刻までへ収める。
    pub fn 移動量だけ動かした塊(
        self, 移動量: 時間の塊の移動量, 行の数: usize
    ) -> Self {
        let 一番上 = 時間の行の番号::置いた順の番号から生成する(
            行の数.saturating_sub(1),
        );
        let 行 = self.行.差だけ動かした番号(移動量.行).map_or(
            時間の行の番号::置いた順の番号から生成する(0),
            |行| 行.min(一番上),
        );
        let 最後の始まり = 見本の全体の秒 - self.長さ.倍精度の小数にする();
        let 始まりの秒 = (self.始まり + 移動量.時間)
            .倍精度の小数にする()
            .clamp(0.0, 最後の始まり);
        Self {
            行,
            始まり: 帯の値::倍精度の小数から生成する(始まりの秒),
            ..self
        }
    }

    /// 同じ行にあって、占める時間が重なるか。
    pub fn 重なるか(self, 相手: Self) -> bool {
        self.行 == 相手.行
            && self.始まり < 相手.始まり + 相手.長さ
            && 相手.始まり < self.始まり + self.長さ
    }
}
