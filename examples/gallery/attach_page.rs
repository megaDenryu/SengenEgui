//! 付け足しの族のページ。説明・右クリックメニュー・ドラッグ元と落とし先。キー操作は画面の骨格にある。

use sengen_egui::{
    ドラッグ元, ノード, ボタン, 付け足せる, 区切り線, 子, 文字表示, 横並び, 画素, 縦積み, 落とし先,
};

use crate::state::{応答, 状態};
use crate::styles;

const 運べるもの一覧: [&str; 3] = ["林檎", "蜜柑", "葡萄"];

pub fn ページ(状態: &状態) -> ノード<応答> {
    縦積み(子![
        文字表示("説明（ポインタを乗せる）").装飾(styles::見出し),
        横並び(子![
            ボタン("説明付きのボタン", 応答::押した("説明付き")).説明("押すと応答が記録へ出る"),
            文字表示("説明付きの文字").説明("文字にも付けられる"),
        ]),
        区切り線(),
        文字表示("右クリックメニュー").装飾(styles::見出し),
        横並び(子![
            ボタン(
                "左クリックも効くボタン",
                応答::押した("右クリックメニュー付き")
            )
            .右クリックメニュー(子![
                ボタン("メニューの項目1", 応答::押した("項目1")),
                ボタン("メニューの項目2", 応答::押した("項目2")),
            ]),
            縦積み(子![文字表示(
                "容器にも付けられる。この枠の中を右クリック"
            )])
            .装飾(styles::カード)
            .右クリックメニュー(子![ボタン("容器の項目", 応答::押した("容器の項目"))]),
        ]),
        区切り線(),
        文字表示("ドラッグ元と落とし先").装飾(styles::見出し),
        横並び(
            運べるもの一覧
                .iter()
                .map(|名前| ドラッグ元(
                    format!("元の{名前}"),
                    (*名前).to_string(),
                    ボタン(*名前, 応答::押した("ドラッグ元"))
                ))
                .collect()
        ),
        落とし先(
            縦積み(子![
                文字表示("ここへ落とす").装飾(styles::補足),
                文字表示(format!("受け取った: {}", 状態.受け取った一覧.join("、"))),
            ])
            .最小幅(画素(320.0)),
            応答::受け取った
        ),
        文字表示("Ctrl+W で見本の窓が開く（キー操作）").装飾(styles::補足),
    ])
    .装飾(styles::カード)
    .into()
}
