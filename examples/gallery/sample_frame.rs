//! 見本の枠。範囲枠付き画像の利用する側のドメインの見本であり、掴んだ部分と移動量から
//! 新しい枠を計算する。画像の内側へ収める規則と最小の大きさの規則はここが持つ。

use sengen_egui::{割合, 割合で表した矩形, 範囲枠の掴んだ部分};

/// 枠の幅と高さの下限。画像の幅と高さを1とした長さである。
const 最小の辺: f32 = 0.1;

/// 見本の枠とは、画像の幅と高さを1とした左端・上端・右端・下端の組のことである。
#[derive(Clone, Copy, Debug)]
pub struct 見本の枠 {
    左端: f32,
    上端: f32,
    右端: f32,
    下端: f32,
}

impl 見本の枠 {
    /// 見本帳を開いたときの枠。画像の中央の6割を囲む。
    pub const 最初の枠: 見本の枠 = 見本の枠 {
        左端: 0.2,
        上端: 0.2,
        右端: 0.8,
        下端: 0.8,
    };

    /// 部品へ渡す枠。規則で左端が右端を超えないため、生成は常に成功する。
    pub fn 部品へ渡す枠(self) -> 割合で表した矩形 {
        let 割合にする = 割合::範囲へ丸めて生成する;
        割合で表した矩形::生成する(
            割合にする(self.左端),
            割合にする(self.上端),
            割合にする(self.右端),
            割合にする(self.下端),
        )
        .unwrap_or(割合で表した矩形::全体)
    }

    /// 掴んだ部分を横と縦へ動かした枠。内側は大きさを保って画像の内側に収め、
    /// 隅は向かいの辺との間に最小の辺を残して画像の内側に収める。
    pub fn 動かした枠(self, 部分: 範囲枠の掴んだ部分, 横: f32, 縦: f32) -> Self {
        let 動かした左端 = (self.左端 + 横).clamp(0.0, self.右端 - 最小の辺);
        let 動かした右端 = (self.右端 + 横).clamp(self.左端 + 最小の辺, 1.0);
        let 動かした上端 = (self.上端 + 縦).clamp(0.0, self.下端 - 最小の辺);
        let 動かした下端 = (self.下端 + 縦).clamp(self.上端 + 最小の辺, 1.0);
        match 部分 {
            範囲枠の掴んだ部分::内側 => {
                self.大きさを保って動かした枠(横, 縦)
            }
            範囲枠の掴んだ部分::左上の隅 => Self {
                左端: 動かした左端,
                上端: 動かした上端,
                ..self
            },
            範囲枠の掴んだ部分::右上の隅 => Self {
                右端: 動かした右端,
                上端: 動かした上端,
                ..self
            },
            範囲枠の掴んだ部分::左下の隅 => Self {
                左端: 動かした左端,
                下端: 動かした下端,
                ..self
            },
            範囲枠の掴んだ部分::右下の隅 => Self {
                右端: 動かした右端,
                下端: 動かした下端,
                ..self
            },
        }
    }

    fn 大きさを保って動かした枠(self, 横: f32, 縦: f32) -> Self {
        let 横の量 = 横.clamp(-self.左端, 1.0 - self.右端);
        let 縦の量 = 縦.clamp(-self.上端, 1.0 - self.下端);
        Self {
            左端: self.左端 + 横の量,
            上端: self.上端 + 縦の量,
            右端: self.右端 + 横の量,
            下端: self.下端 + 縦の量,
        }
    }
}
