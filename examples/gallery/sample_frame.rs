//! 見本の枠。範囲枠付き画像の利用する側のドメインの見本であり、掴んだ部分と移動量から
//! 新しい枠を計算する。画像の内側へ収める規則と最小の大きさの規則はここが持つ。

use sengen_egui::{
    割合, 割合で表した矩形, 割合の差, 範囲枠の掴んだ部分, 縦横の割合の差
};

/// 枠の幅と高さの下限。画像の幅と高さを1とした長さである。
const 最小の辺: 割合の差 = 割合の差::生成する(0.1);

/// 見本の枠とは、画像の幅と高さを1とした左端・上端・右端・下端の組のことである。
/// 左端と右端、上端と下端の間は、常に最小の辺以上に保つ。
#[derive(Clone, Copy, Debug)]
pub struct 見本の枠 {
    左端: 割合,
    上端: 割合,
    右端: 割合,
    下端: 割合,
}

impl 見本の枠 {
    /// 見本帳を開いたときの枠。画像の中央の6割を囲む。
    pub const 最初の枠: 見本の枠 = 見本の枠 {
        左端: 割合::範囲へ丸めて生成する(0.2),
        上端: 割合::範囲へ丸めて生成する(0.2),
        右端: 割合::範囲へ丸めて生成する(0.8),
        下端: 割合::範囲へ丸めて生成する(0.8),
    };

    /// 部品へ渡す枠。規則で左端が右端を、上端が下端を超えないため、生成の失敗は到達したらバグである。
    pub fn 部品へ渡す枠(self) -> 割合で表した矩形 {
        match 割合で表した矩形::生成する(self.左端, self.上端, self.右端, self.下端)
        {
            Ok(枠) => 枠,
            Err(不正) => panic!("見本の枠の規則が破れている（到達したらバグ）: {不正}"),
        }
    }

    /// 掴んだ部分を移動量だけ動かした枠。内側は大きさを保って画像の内側に収め、
    /// 隅は向かいの辺との間に最小の辺を残して画像の内側に収める。
    pub fn 動かした枠(
        self, 部分: 範囲枠の掴んだ部分, 移動量: 縦横の割合の差
    ) -> Self {
        let (横, 縦) = (移動量.横, 移動量.縦);
        let 動かした左端 = self.左端.差を足して範囲へ丸める(横).下限と上限の間へ収める(
            割合::ゼロ,
            self.右端.差を足して範囲へ丸める(-最小の辺),
        );
        let 動かした右端 = self.右端.差を足して範囲へ丸める(横).下限と上限の間へ収める(
            self.左端.差を足して範囲へ丸める(最小の辺),
            割合::全部,
        );
        let 動かした上端 = self.上端.差を足して範囲へ丸める(縦).下限と上限の間へ収める(
            割合::ゼロ,
            self.下端.差を足して範囲へ丸める(-最小の辺),
        );
        let 動かした下端 = self.下端.差を足して範囲へ丸める(縦).下限と上限の間へ収める(
            self.上端.差を足して範囲へ丸める(最小の辺),
            割合::全部,
        );
        match 部分 {
            範囲枠の掴んだ部分::内側 => {
                self.大きさを保って動かした枠(移動量)
            }
            範囲枠の掴んだ部分::左上の隅 => Self {
                左端: 動かした左端,
                上端: 動かした上端,
                ..self
            },
            範囲枠の掴んだ部分::右上の隅 => Self {
                右端: 動かした右端,
                上端: 動かした上端,
                ..self
            },
            範囲枠の掴んだ部分::左下の隅 => Self {
                左端: 動かした左端,
                下端: 動かした下端,
                ..self
            },
            範囲枠の掴んだ部分::右下の隅 => Self {
                右端: 動かした右端,
                下端: 動かした下端,
                ..self
            },
        }
    }

    fn 大きさを保って動かした枠(self, 移動量: 縦横の割合の差) -> Self {
        let 横の量 = 移動量
            .横
            .下限と上限の間へ収める(割合::ゼロ - self.左端, 割合::全部 - self.右端);
        let 縦の量 = 移動量
            .縦
            .下限と上限の間へ収める(割合::ゼロ - self.上端, 割合::全部 - self.下端);
        Self {
            左端: self.左端.差を足して範囲へ丸める(横の量),
            上端: self.上端.差を足して範囲へ丸める(縦の量),
            右端: self.右端.差を足して範囲へ丸める(横の量),
            下端: self.下端.差を足して範囲へ丸める(縦の量),
        }
    }
}
