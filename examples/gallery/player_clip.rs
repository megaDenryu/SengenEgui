//! 再生画面の区間の欄。映像の全体の長さを1本の帯にし、切り出す区間と再生位置を重ねて見せる。
//! 区間の内側を動かすと、再生位置の印が区間の開始へ移る（見本の区間が再生位置を移す先を返すため）。

use sengen_egui::{
    ノード, 区間の帯, 子, 帯の値, 帯の全体の範囲, 文字表示, 縦積み
};

use crate::player_page::包む;
use crate::sample_player::{再生の長さ, 再生画面の応答 as 再生, 見本の再生};
use crate::state::応答;
use crate::styles;

pub fn 区間の欄(再生の状態: &見本の再生) -> ノード<応答> {
    let 秒 = 帯の値::倍精度の小数から生成する;
    let 区間 = &再生の状態.区間;
    let 帯: ノード<応答> =
        match 帯の全体の範囲::生成する(秒(0.0), 秒(再生の長さ.as_secs_f64())) {
            Ok(全体) => 区間の帯(全体, 区間.開始(), 区間.終了(), |操作| {
                包む(再生::区間の帯を操作した(操作))
            })
            .位置(秒(再生の状態.位置.as_secs_f64()))
            .into(),
            Err(不正) => 文字表示(format!("区間の帯の全体の範囲が不正: {不正}")).into(),
        };
    縦積み(子![
        文字表示(format!(
            "区間の帯（区間 {:.2}〜{:.2} 秒。端のつまみ・区間の内側・位置の印の頭を動かす。区間の外を押すと位置が移る）",
            区間.開始().倍精度の小数にする(),
            区間.終了().倍精度の小数にする(),
        ))
        .装飾(styles::補足),
        帯,
    ])
    .into()
}
