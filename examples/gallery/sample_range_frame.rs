//! 見本の範囲枠。範囲枠付き画像の操作を受けて、現在の枠を更新する利用する側の状態の見本である。
//! 部品は掴んだ部分と開始点からの累積の移動量だけを発するため、掴み始めの枠を覚えておき、
//! 累積の移動量から毎回計算する。

use sengen_egui::{
    割合で表した矩形, 範囲枠の掴んだ部分, 範囲枠の操作, 縦横の割合の差
};

use crate::sample_frame::見本の枠;

/// 見本の範囲枠とは、現在の枠と、掴んでいる間だけ覚える掴み始めの枠の組のことである。
pub struct 見本の範囲枠 {
    現在: 見本の枠,
    掴み始めの枠: Option<見本の枠>,
}

impl 見本の範囲枠 {
    pub fn 新規() -> Self {
        Self {
            現在: 見本の枠::最初の枠,
            掴み始めの枠: None,
        }
    }

    pub fn 操作を適用する(&mut self, 操作: 範囲枠の操作) {
        match 操作 {
            範囲枠の操作::掴み始めた { .. } => self.掴み始めの枠 = Some(self.現在),
            範囲枠の操作::動かしている {
                掴んだ部分,
                開始点からの移動量,
            } => {
                self.動かす(掴んだ部分, 開始点からの移動量);
            }
            範囲枠の操作::放した {
                掴んだ部分,
                開始点からの移動量,
            } => {
                self.動かす(掴んだ部分, 開始点からの移動量);
                self.掴み始めの枠 = None;
            }
        }
    }

    pub fn 部品へ渡す枠(&self) -> 割合で表した矩形 {
        self.現在.部品へ渡す枠()
    }

    fn 動かす(&mut self, 部分: 範囲枠の掴んだ部分, 移動量: 縦横の割合の差) {
        if let Some(始め) = self.掴み始めの枠 {
            self.現在 = 始め.動かした枠(部分, 移動量);
        }
    }
}
