//! 見本の画素。読み込み器なしで画像を出すため、画素のバイト列を計算で作る。

use sengen_egui::{画素の並び, 画素の並びの不正, 画素数の寸法};

/// 見本の画像の一辺の画素の個数。
const 一辺: u32 = 64;
const 寸法: 画素数の寸法 = 画素数の寸法::生成する(一辺, 一辺);

/// 見本の画素のバイト列とは、横に赤、縦に緑が増える模様を右下へ巡回させた画像の中身のことである。
/// ずらす量を変えて作り直し、テクスチャを差し替えれば、動く映像の見本になる。
pub struct 見本の画素のバイト列(Vec<u8>);

impl 見本の画素のバイト列 {
    pub fn ずらして作る(ずらす量: u32) -> Self {
        let バイト列 = (0..一辺 * 一辺)
            .flat_map(|番号| {
                let 横 = (番号 % 一辺 + ずらす量) % 一辺;
                let 縦 = (番号 / 一辺 + ずらす量) % 一辺;
                let 赤 = u8::try_from(横 * 4).unwrap_or(u8::MAX);
                let 緑 = u8::try_from(縦 * 4).unwrap_or(u8::MAX);
                [赤, 緑, 160, 255]
            })
            .collect();
        Self(バイト列)
    }

    /// テクスチャへ渡す画素の並び。作り方から長さは常に寸法と一致するが、一致の検査は画素の並びに任せる。
    pub fn 画素の並び(&self) -> Result<画素の並び<'_>, 画素の並びの不正> {
        画素の並び::赤緑青と不透明度のバイト列から作る(寸法, &self.0)
    }
}
