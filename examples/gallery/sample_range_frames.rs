//! 見本の複数の範囲枠。複数の範囲枠の操作を受けて、枠ごとの現在の枠と、選んでいる枠を更新する利用する側の状態の見本である。
//! 部品は選んだことと、掴んだ部分と開始点からの累積の移動量だけを発するため、掴み始めの枠を覚えておき、
//! 累積の移動量から毎回計算する（新しい枠の計算は sample_frame.rs の `見本の枠` が持つ）。何も無い所を押したら選びを外す。
//! 縦横比の扱いは、部品が発した値を見せるだけで、枠の計算には使わない。保った大きさの計算は利用する側の規則だからである。

use sengen_egui::{割合, 縦横比の扱い, 複数の範囲枠の操作};

use crate::sample_frame::見本の枠;

/// 見本の枠の鍵とは、見本の3つの枠を見分ける値のことであり、部品へ渡す鍵である。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 見本の枠の鍵 {
    赤,
    緑,
    青,
}

/// 見本の複数の範囲枠の応答とは、見本の複数の範囲枠の節が発する出来事の区別のことである。
#[derive(Clone, Debug)]
pub enum 見本の複数の範囲枠の応答 {
    枠を操作した(見本の枠の鍵, 複数の範囲枠の操作),
    何も無い所を押した,
}

/// 見本の複数の範囲枠とは、置いた順の鍵と枠と、選んでいる枠の鍵と、掴んでいる間だけ覚える掴み始めの枠と、
/// 最後に発した縦横比の扱いの組のことである。
pub struct 見本の複数の範囲枠 {
    枠一覧: Vec<(見本の枠の鍵, 見本の枠)>,
    選んでいる枠: Option<見本の枠の鍵>,
    掴み始めの枠: Option<見本の枠>,
    最後の縦横比の扱い: Option<縦横比の扱い>,
}

const fn 割合にする(値: f32) -> 割合 {
    割合::範囲へ丸めて生成する(値)
}

impl 見本の複数の範囲枠 {
    pub fn 新規() -> Self {
        let 枠 = |左端, 上端, 右端, 下端| {
            見本の枠::四つの端の割合から作る(
                割合にする(左端),
                割合にする(上端),
                割合にする(右端),
                割合にする(下端),
            )
        };
        Self {
            枠一覧: vec![
                (見本の枠の鍵::赤, 枠(0.05, 0.1, 0.5, 0.6)),
                (見本の枠の鍵::緑, 枠(0.3, 0.3, 0.8, 0.8)),
                (見本の枠の鍵::青, 枠(0.6, 0.55, 0.95, 0.95)),
            ],
            選んでいる枠: Some(見本の枠の鍵::赤),
            掴み始めの枠: None,
            最後の縦横比の扱い: None,
        }
    }

    pub fn 適用する(&mut self, 応答: 見本の複数の範囲枠の応答) {
        let (鍵, 操作) = match 応答 {
            見本の複数の範囲枠の応答::枠を操作した(鍵, 操作) => (鍵, 操作),
            見本の複数の範囲枠の応答::何も無い所を押した => {
                self.選んでいる枠 = None;
                return;
            }
        };
        let 今の枠 = self
            .枠一覧
            .iter_mut()
            .find(|(置いた鍵, _)| *置いた鍵 == 鍵)
            .map(|(_, 枠)| 枠);
        match 操作 {
            複数の範囲枠の操作::選んだ => self.選んでいる枠 = Some(鍵),
            複数の範囲枠の操作::掴み始めた { .. } => {
                self.掴み始めの枠 = 今の枠.map(|枠| *枠)
            }
            複数の範囲枠の操作::動かしている {
                掴んだ部分,
                開始点からの移動量,
                縦横比の扱い,
            }
            | 複数の範囲枠の操作::放した {
                掴んだ部分,
                開始点からの移動量,
                縦横比の扱い,
            } => {
                self.最後の縦横比の扱い = Some(縦横比の扱い);
                if let (Some(始め), Some(枠)) = (self.掴み始めの枠, 今の枠) {
                    *枠 = 始め.動かした枠(掴んだ部分, 開始点からの移動量);
                }
                if matches!(操作, 複数の範囲枠の操作::放した { .. }) {
                    self.掴み始めの枠 = None;
                }
            }
            複数の範囲枠の操作::掴んだ枠が無くなった => self.掴み始めの枠 = None,
        }
    }

    /// 置いた順の鍵と枠。
    pub fn 置く枠を巡る(
        &self,
    ) -> impl Iterator<Item = (見本の枠の鍵, 見本の枠)> + '_ {
        self.枠一覧.iter().copied()
    }

    /// 選んでいる枠の鍵。何も無い所を押した後は選んでいる枠が無い。
    pub fn 選んでいる枠(&self) -> Option<見本の枠の鍵> {
        self.選んでいる枠
    }

    pub fn 最後の縦横比の扱いの表示(&self) -> &'static str {
        match self.最後の縦横比の扱い {
            None => "まだドラッグしていない",
            Some(縦横比の扱い::保つ) => "保つ",
            Some(縦横比の扱い::保たない) => "保たない（Shift を押している）",
        }
    }
}
