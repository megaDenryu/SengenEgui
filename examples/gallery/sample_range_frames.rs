//! 見本の複数の範囲枠。複数の範囲枠の操作を受けて、枠ごとの現在の枠と、選んでいる枠を更新する利用する側の状態の見本である。
//! 部品は選んだことと、掴んだ部分と開始点からの累積の移動量だけを発するため、掴み始めの枠を覚えておき、
//! 累積の移動量から毎回計算する（新しい枠の計算は sample_frame.rs の `見本の枠` が持つ）。
//! 縦横比の扱いは、部品が発した値を見せるだけで、枠の計算には使わない。保った大きさの計算は利用する側の規則だからである。

use sengen_egui::{割合で表した矩形, 縦横比の扱い, 複数の範囲枠の操作};

use crate::sample_frame::見本の枠;

/// 見本の複数の範囲枠とは、置いた順の枠と、選んでいる枠の番号と、掴んでいる間だけ覚える掴み始めの枠と、
/// 最後に発した縦横比の扱いの組のことである。
pub struct 見本の複数の範囲枠 {
    枠一覧: Vec<見本の枠>,
    選んでいる枠の番号: Option<usize>,
    掴み始めの枠: Option<見本の枠>,
    最後の縦横比の扱い: Option<縦横比の扱い>,
}

impl 見本の複数の範囲枠 {
    pub fn 新規() -> Self {
        Self {
            枠一覧: vec![
                見本の枠::四つの端の割合から作る(0.05, 0.1, 0.5, 0.6),
                見本の枠::四つの端の割合から作る(0.3, 0.3, 0.8, 0.8),
                見本の枠::四つの端の割合から作る(0.6, 0.55, 0.95, 0.95),
            ],
            選んでいる枠の番号: Some(0),
            掴み始めの枠: None,
            最後の縦横比の扱い: None,
        }
    }

    pub fn 操作を適用する(&mut self, 番号: usize, 操作: 複数の範囲枠の操作) {
        match 操作 {
            複数の範囲枠の操作::選んだ => self.選んでいる枠の番号 = Some(番号),
            複数の範囲枠の操作::掴み始めた { .. } => {
                self.掴み始めの枠 = self.枠一覧.get(番号).copied();
            }
            複数の範囲枠の操作::動かしている {
                掴んだ部分,
                開始点からの移動量,
                縦横比の扱い,
            } => {
                self.最後の縦横比の扱い = Some(縦横比の扱い);
                if let (Some(始め), Some(枠)) = (self.掴み始めの枠, self.枠一覧.get_mut(番号))
                {
                    *枠 = 始め.動かした枠(掴んだ部分, 開始点からの移動量);
                }
            }
            複数の範囲枠の操作::放した {
                掴んだ部分,
                開始点からの移動量,
                縦横比の扱い,
            } => {
                self.最後の縦横比の扱い = Some(縦横比の扱い);
                if let (Some(始め), Some(枠)) = (self.掴み始めの枠, self.枠一覧.get_mut(番号))
                {
                    *枠 = 始め.動かした枠(掴んだ部分, 開始点からの移動量);
                }
                self.掴み始めの枠 = None;
            }
        }
    }

    /// 置いた順の、部品へ渡す枠と、選んでいるかの組。
    pub fn 部品へ渡す枠一覧(&self) -> Vec<(割合で表した矩形, bool)> {
        self.枠一覧
            .iter()
            .enumerate()
            .map(|(番号, 枠)| (枠.部品へ渡す枠(), self.選んでいる枠の番号 == Some(番号)))
            .collect()
    }

    pub fn 最後の縦横比の扱いの表示(&self) -> &'static str {
        match self.最後の縦横比の扱い {
            None => "まだドラッグしていない",
            Some(縦横比の扱い::保つ) => "保つ",
            Some(縦横比の扱い::保たない) => "保たない（Shift を押している）",
        }
    }
}
