//! 再生画面のページのうち、時間の行の並びの節。0〜30秒の時間の軸の下に3つの行（いちばん上は空の行）を積み、
//! 塊を置く。塊を押して選び、横へドラッグして時刻を、上下へドラッグして行を変え、時間の軸を押してドラッグして位置の線を動かす。
//! 何も無い所を押すと選びを外す。

use sengen_egui::{
    ノード, 子, 帯の値, 帯の全体の範囲, 文字表示, 時間の行, 時間の行の並び, 縦積み
};

use crate::sample_time_block::見本の全体の秒;
use crate::sample_time_rows::{
    見本の時間の行の並び, 見本の時間の行の並びの応答 as 時間の行の並びの応答,
};
use crate::state::応答;
use crate::styles;

fn 包む(応答: 時間の行の並びの応答) -> 応答 {
    応答::時間の行の並び(応答)
}

pub fn 時間の行の並びの節(見本: &見本の時間の行の並び) -> ノード<応答> {
    let 全体 = 帯の全体の範囲::生成する(
        帯の値::倍精度の小数から生成する(0.0),
        帯の値::倍精度の小数から生成する(見本の全体の秒),
    );
    let 部品 = match 全体 {
        Ok(全体) => 部品を組む(見本, 全体),
        Err(不正) => 文字表示(format!("時間の行の並びの全体の範囲が不正: {不正}")).into(),
    };
    縦積み(子![
        文字表示("時間の行の並び（塊を押して選ぶ・横へずらす・上下の行へ移す。上の時間の軸を押して位置の線を動かす。何も無い所を押すと選びを外す）")
            .装飾(styles::見出し),
        部品,
        文字表示(format!(
            "位置: {:.2} 秒（移した先の行で重なるときは動かさない。ぶつかった所で止める規則は利用する側が持つ）",
            見本.位置.倍精度の小数にする()
        )),
    ])
    .into()
}

fn 部品を組む(
    見本: &見本の時間の行の並び, 全体: 帯の全体の範囲
) -> ノード<応答> {
    let 行一覧 = (0..見本.行の数).map(|行の番号| {
        見本
            .置いた塊を巡る()
            .filter(move |置いた| 置いた.行.置いた順の番号() == 行の番号)
            .fold(時間の行(), |行, 置いた| {
                if 見本.選んでいる塊 == Some(置いた.鍵) {
                    行.選んでいる塊を置く(置いた.鍵, 置いた.部品へ渡す塊())
                } else {
                    行.塊を置く(置いた.鍵, 置いた.部品へ渡す塊())
                }
            })
    });
    行一覧
        .fold(
            時間の行の並び(全体, |鍵, 操作| {
                包む(時間の行の並びの応答::塊を操作した(鍵, 操作))
            }),
            |部品, 行| 部品.行を置く(行),
        )
        .位置の線を置く(見本.位置)
        .位置の線を動かしたら発する(
            |操作| {
                包む(時間の行の並びの応答::位置の線を操作した(
                    操作,
                ))
            },
        )
        .何も無い所を押したら発する(包む(時間の行の並びの応答::何も無い所を押した))
        .into()
}
