//! 見本の時間の行の並び。時間の行の並びの操作を受けて、塊ごとの行と始まりと、選んでいる塊と、選んでいる空の行と、
//! 位置の線の値を更新する利用する側の状態の見本である。部品は開始点からの累積の移動量（時間の差と行の差）だけを発するため、
//! 掴み始めの塊を覚えておき、移動量から毎回計算する（計算は sample_time_block.rs の `見本の置いた塊` が持つ）。
//! 行の何も無い所を押したら、その行が空なら選び、「選んだ空の行を消す」で消せるようにする。

use sengen_egui::{
    位置の線の操作, 帯の値, 時間の塊の不正, 時間の塊の操作, 時間の行の番号
};

use crate::sample_row_list::見本の行の並び;
use crate::sample_time_block::{見本の塊の鍵, 見本の置いた塊};

/// 見本の時間の行の並びの応答とは、見本の時間の行の並びの節が発する出来事の区別のことである。
#[derive(Clone, Debug)]
pub enum 見本の時間の行の並びの応答 {
    塊を操作した(見本の塊の鍵, 時間の塊の操作),
    位置の線を操作した(位置の線の操作),
    何も無い所を押した,
    行の何も無い所を押した(時間の行の番号),
    一番上に空の行を足した,
    選んだ空の行を消した,
}

/// 見本の時間の行の並びとは、行の並びと、選んでいる塊と、選んでいる空の行と、掴んでいる間だけ覚える掴み始めの塊と、
/// 位置の線の値の組のことである。
pub struct 見本の時間の行の並び {
    pub 行の並び: 見本の行の並び,
    pub 選んでいる塊: Option<見本の塊の鍵>,
    pub 選んでいる空の行: Option<時間の行の番号>,
    掴み始め: Option<見本の置いた塊>,
    pub 位置の線の値: 帯の値,
}

impl 見本の時間の行の並び {
    /// 3つの行に3つの塊を置いた見本を作る。見本の塊の値が時間の塊として不正なら理由を返す。
    pub fn 新規() -> Result<Self, 時間の塊の不正> {
        Ok(Self {
            行の並び: 見本の行の並び::塊と行の数から作る(
                見本の置いた塊::最初の並びを作る()?,
                3,
            ),
            選んでいる塊: Some(見本の塊の鍵::緑),
            選んでいる空の行: None,
            掴み始め: None,
            位置の線の値: 帯の値::倍精度の小数から生成する(9.0),
        })
    }

    pub fn 適用する(&mut self, 応答: 見本の時間の行の並びの応答) {
        match 応答 {
            見本の時間の行の並びの応答::塊を操作した(鍵, 操作) => {
                self.塊の操作を適用する(鍵, 操作)
            }
            見本の時間の行の並びの応答::位置の線を操作した(
                位置の線の操作::掴み始めた { 値 }
                | 位置の線の操作::動かしている { 値 }
                | 位置の線の操作::放した { 値 },
            ) => self.位置の線の値 = 値,
            見本の時間の行の並びの応答::何も無い所を押した => {
                self.選んでいる塊 = None
            }
            見本の時間の行の並びの応答::行の何も無い所を押した(行) => {
                self.選んでいる空の行 = self.行の並び.空の行か(行).then_some(行);
            }
            見本の時間の行の並びの応答::一番上に空の行を足した => {
                self.行の並び.一番上に空の行を足す()
            }
            見本の時間の行の並びの応答::選んだ空の行を消した => {
                if let Some(行) = self.選んでいる空の行.take() {
                    self.行の並び.空の行を消す(行);
                }
            }
        }
    }

    fn 塊の操作を適用する(
        &mut self, 鍵: 見本の塊の鍵, 操作: 時間の塊の操作
    ) {
        match 操作 {
            時間の塊の操作::選んだ => self.選んでいる塊 = Some(鍵),
            時間の塊の操作::掴み始めた { .. } => {
                let 掴んだ塊 = self
                    .行の並び
                    .置いた塊を巡る()
                    .find(|置いた| 置いた.鍵 == 鍵);
                self.掴み始め = 掴んだ塊;
            }
            時間の塊の操作::動かしている {
                開始点からの移動量
            } => {
                if let Some(始め) = self.掴み始め {
                    self.行の並び.塊を動かす(始め, 開始点からの移動量);
                }
            }
            時間の塊の操作::放した {
                開始点からの移動量
            } => {
                if let Some(始め) = self.掴み始め.take() {
                    self.行の並び.塊を動かす(始め, 開始点からの移動量);
                }
            }
            時間の塊の操作::掴んだ塊が無くなった => self.掴み始め = None,
        }
    }
}
