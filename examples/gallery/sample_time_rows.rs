//! 見本の時間の行の並び。時間の行の並びの操作を受けて、塊ごとの行と始まりと、選んでいる塊と、位置の線の値を更新する
//! 利用する側の状態の見本である。部品は開始点からの累積の移動量（時間の差と行の差）だけを発するため、掴み始めの塊を
//! 覚えておき、移動量から毎回計算する（計算は sample_time_block.rs の `見本の置いた塊` が持つ）。移した先の行で
//! ほかの塊と重なるときは動かさない（ぶつかった所で止める規則は、利用する側が持つ規則の一例として省いた）。

use sengen_egui::{
    位置の線の操作, 帯の値, 時間の塊の不正, 時間の塊の操作, 時間の塊の移動量
};

use crate::sample_time_block::{見本の塊の鍵, 見本の置いた塊};

/// 見本の時間の行の並びの応答とは、見本の時間の行の並びの節が発する出来事の区別のことである。
#[derive(Clone, Debug)]
pub enum 見本の時間の行の並びの応答 {
    塊を操作した(見本の塊の鍵, 時間の塊の操作),
    位置の線を操作した(位置の線の操作),
    何も無い所を押した,
}

/// 見本の時間の行の並びとは、置いた塊と、行の数と、選んでいる塊と、掴んでいる間だけ覚える掴み始めの塊と、位置の線の値の組のことである。
pub struct 見本の時間の行の並び {
    塊一覧: Vec<見本の置いた塊>,
    pub 行の数: usize,
    pub 選んでいる塊: Option<見本の塊の鍵>,
    掴み始め: Option<見本の置いた塊>,
    pub 位置の線の値: 帯の値,
}

impl 見本の時間の行の並び {
    /// 3つの塊を置いた見本を作る。見本の塊の値が時間の塊として不正なら理由を返す。
    pub fn 新規() -> Result<Self, 時間の塊の不正> {
        Ok(Self {
            塊一覧: 見本の置いた塊::最初の並びを作る()?,
            行の数: 3,
            選んでいる塊: Some(見本の塊の鍵::緑),
            掴み始め: None,
            位置の線の値: 帯の値::倍精度の小数から生成する(9.0),
        })
    }

    pub fn 置いた塊を巡る(&self) -> impl Iterator<Item = 見本の置いた塊> + '_ {
        self.塊一覧.iter().copied()
    }

    pub fn 適用する(&mut self, 応答: 見本の時間の行の並びの応答) {
        match 応答 {
            見本の時間の行の並びの応答::塊を操作した(鍵, 操作) => {
                self.塊の操作を適用する(鍵, 操作)
            }
            見本の時間の行の並びの応答::位置の線を操作した(
                位置の線の操作::掴み始めた { 値 }
                | 位置の線の操作::動かしている { 値 }
                | 位置の線の操作::放した { 値 },
            ) => self.位置の線の値 = 値,
            見本の時間の行の並びの応答::何も無い所を押した => {
                self.選んでいる塊 = None
            }
        }
    }

    fn 塊の操作を適用する(
        &mut self, 鍵: 見本の塊の鍵, 操作: 時間の塊の操作
    ) {
        match 操作 {
            時間の塊の操作::選んだ => self.選んでいる塊 = Some(鍵),
            時間の塊の操作::掴み始めた { .. } => {
                let 掴んだ塊 = self.置いた塊を巡る().find(|置いた| 置いた.鍵 == 鍵);
                self.掴み始め = 掴んだ塊;
            }
            時間の塊の操作::動かしている {
                開始点からの移動量
            } => self.動かす(開始点からの移動量),
            時間の塊の操作::放した {
                開始点からの移動量
            } => {
                self.動かす(開始点からの移動量);
                self.掴み始め = None;
            }
            時間の塊の操作::掴んだ塊が無くなった => self.掴み始め = None,
        }
    }

    /// 掴み始めの塊を移動量だけ動かした位置へ置き直す。移した先の行でほかの塊と重なるなら動かさない。
    fn 動かす(&mut self, 移動量: 時間の塊の移動量) {
        let Some(始め) = self.掴み始め else {
            return;
        };
        let 動かした塊 = 始め.移動量だけ動かした塊(移動量, self.行の数);
        let 重なる = self
            .置いた塊を巡る()
            .any(|置いた| 置いた.鍵 != 始め.鍵 && 置いた.重なるか(動かした塊));
        if let Some(置いた) = self.塊一覧.iter_mut().find(|置いた| 置いた.鍵 == 始め.鍵)
            && !重なる
        {
            *置いた = 動かした塊;
        }
    }
}
