//! 帯の全体の範囲。区間の帯の左端と右端が表す値の組であり、値を画面の割合へ写し、動かした値を収める規則を持つ。
//!
//! 収める規則: 動かした値は、全体の範囲と動かす前の値を合わせた範囲へ収める。範囲の外にあった値は、それより外へは
//! 動かないが、範囲の内側へは戻れる。掴んだだけ（動かしていない）なら値は変わらない。範囲の外の値を利用する側が
//! 持つこと（拡大の帯で、区間が見えている範囲からはみ出すこと等）を部品が黙って書き換えないためである。

use crate::measure::{割合, 帯の値, 帯の値の差};

/// 帯の全体の範囲とは、区間の帯の左端と右端が表す値の組のことである。始めは終わりより小さく、どちらも有限である。
///
/// 区間の帯は、範囲の外の値を帯の端に外を指す三角で描き、端で掴めるようにする。掴んだ値を動かしたときは、全体の範囲と
/// 動かす前の値を合わせた範囲へ収める（範囲の外の値はそれより外へ動かず、内側へは戻れる）。区間の内側を動かすときは、
/// 区間が全体より短ければ全体の内側に、長ければ全体を覆ったままになる範囲へ、動かす前の開始も含めて収める。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct 帯の全体の範囲 {
    始め: 帯の値,
    終わり: 帯の値,
}

/// 帯の全体の範囲の不正とは、帯の全体の範囲として受け取れない値の組の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 帯の全体の範囲の不正 {
    /// 始めか終わりが無限大か NaN である。
    有限でない,
    /// 始めが終わり以上である。長さ0の範囲は帯の上で値を区別できないため受け取らない。
    始めが終わり以上,
}

/// 範囲との位置関係とは、値が全体の範囲の内側にあるか、どちら側の外にあるかの区別のことである。NaN は始めより前とみなす。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum 範囲との位置関係 {
    内側,
    始めより前,
    終わりより後,
}

impl 帯の全体の範囲 {
    /// 始めと終わりから作る。どちらかが有限でないか、始めが終わり以上なら理由を返す。
    pub fn 生成する(
        始め: 帯の値,
        終わり: 帯の値,
    ) -> Result<Self, 帯の全体の範囲の不正> {
        let (始めの数, 終わりの数) = (始め.倍精度の小数にする(), 終わり.倍精度の小数にする());
        if !始めの数.is_finite() || !終わりの数.is_finite() {
            return Err(帯の全体の範囲の不正::有限でない);
        }
        if 始め >= 終わり {
            return Err(帯の全体の範囲の不正::始めが終わり以上);
        }
        Ok(Self { 始め, 終わり })
    }

    /// 始めの値。
    pub const fn 始め(self) -> 帯の値 {
        self.始め
    }

    /// 終わりの値。
    pub const fn 終わり(self) -> 帯の値 {
        self.終わり
    }

    /// 値が全体のどこにあるかの割合。範囲の外の値は端へ、NaN は始めへ寄せる。
    pub(crate) fn 割合へ写す(self, 値: 帯の値) -> 割合 {
        let 比 = (値 - self.始め).倍精度の小数にする() / self.長さ().倍精度の小数にする();
        割合::倍精度の小数から範囲へ丸めて生成する(比)
    }

    /// 始めから終わりまでの長さ。
    pub(crate) fn 長さ(self) -> 帯の値の差 {
        self.終わり - self.始め
    }

    pub(crate) fn 位置関係(self, 値: 帯の値) -> 範囲との位置関係 {
        if 値 > self.終わり {
            範囲との位置関係::終わりより後
        } else if 値 >= self.始め {
            範囲との位置関係::内側
        } else {
            範囲との位置関係::始めより前
        }
    }

    /// 値を始めと終わりの間へ収める。NaN は始めにする。
    pub(crate) fn 内側へ収める(self, 値: 帯の値) -> 帯の値 {
        値.間へ収める(self.始め, self.終わり)
    }

    /// 動かした値を、全体の範囲と動かす前の値を合わせた範囲へ収める。
    pub(crate) fn 動かす前より外へ出さずに収める(
        self,
        動かした値: 帯の値,
        動かす前: 帯の値,
    ) -> 帯の値 {
        動かした値.間へ収める(self.始め.小さい方(動かす前), self.終わり.大きい方(動かす前))
    }

    /// 長さを保って動かした区間の開始を収める。区間が全体より短ければ区間が全体の内側に、長ければ区間が全体を
    /// 覆ったままになる開始の範囲を求め、その範囲と動かす前の開始を合わせた範囲へ収める。
    pub(crate) fn 区間を動かす前より外へ出さずに開始を収める(
        self,
        動かした開始: 帯の値,
        動かす前の開始: 帯の値,
        長さ: 帯の値の差,
    ) -> 帯の値 {
        let 終わりに揃えた開始 = self.終わり + 長さ * -1.0;
        let 下限 = self
            .始め
            .小さい方(終わりに揃えた開始)
            .小さい方(動かす前の開始);
        let 上限 = self
            .始め
            .大きい方(終わりに揃えた開始)
            .大きい方(動かす前の開始);
        動かした開始.間へ収める(下限, 上限)
    }
}

impl std::fmt::Display for 帯の全体の範囲の不正 {
    fn fmt(&self, 出力: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::有限でない => write!(出力, "帯の全体の範囲の始めか終わりが有限でない"),
            Self::始めが終わり以上 => {
                write!(出力, "帯の全体の範囲の始めが終わり以上である")
            }
        }
    }
}

impl std::error::Error for 帯の全体の範囲の不正 {}
