//! 割合で表した矩形の不正。端の組や左上と大きさの組が、割合で表した矩形として受け取れない理由を区別する。

/// 割合で表した矩形の不正とは、矩形として受け取れない端の組、または左上と大きさの組の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 割合で表した矩形の不正 {
    /// 左端が右端より右にある。
    左端が右端より右にある,
    /// 上端が下端より下にある。
    上端が下端より下にある,
    /// 左端に幅を足した右端が、基準の矩形の右の辺（1）を超える。
    右端が基準の矩形の外にある,
    /// 上端に高さを足した下端が、基準の矩形の下の辺（1）を超える。
    下端が基準の矩形の外にある,
}

impl std::fmt::Display for 割合で表した矩形の不正 {
    fn fmt(&self, 出力: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::左端が右端より右にある => write!(出力, "矩形の左端が右端より右にある"),
            Self::上端が下端より下にある => write!(出力, "矩形の上端が下端より下にある"),
            Self::右端が基準の矩形の外にある => {
                write!(出力, "矩形の右端が基準の矩形の右の辺を超える")
            }
            Self::下端が基準の矩形の外にある => {
                write!(出力, "矩形の下端が基準の矩形の下の辺を超える")
            }
        }
    }
}

impl std::error::Error for 割合で表した矩形の不正 {}
