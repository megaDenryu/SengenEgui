//! 縦横の論理画素。幅と高さ、または横と縦の間隔のように、2方向の寸法を1組で持つ値である。

use crate::measure::論理画素;

/// 縦横の論理画素とは、横方向と縦方向の論理画素の組のことである。
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct 縦横の論理画素 {
    /// 横方向（幅・横の間隔・左からの位置）の長さ。
    pub 横: 論理画素,
    /// 縦方向（高さ・縦の間隔・上からの位置）の長さ。
    pub 縦: 論理画素,
}

impl 縦横の論理画素 {
    /// 横と縦の論理画素から組を作る。
    pub const fn 生成する(横: 論理画素, 縦: 論理画素) -> Self {
        Self { 横, 縦 }
    }

    /// egui の2次元ベクトルから組を作る。egui から受け取る境界でだけ使う。
    pub(crate) const fn eguiの大きさから作る(大きさ: egui::Vec2) -> Self {
        Self::生成する(論理画素::生成する(大きさ.x), 論理画素::生成する(大きさ.y))
    }

    /// egui の2次元ベクトルへ変換する。この口以外で生の値へ戻さない。
    pub const fn eguiへ渡す値(self) -> egui::Vec2 {
        egui::vec2(self.横.eguiへ渡す値(), self.縦.eguiへ渡す値())
    }

    /// egui の位置（画面左上を原点とする点）へ変換する。既定の位置の指定に使う。
    pub const fn eguiの位置へ渡す値(self) -> egui::Pos2 {
        egui::pos2(self.横.eguiへ渡す値(), self.縦.eguiへ渡す値())
    }
}

/// 縦横の論理画素を短く書くための生成の口。`画素の組(8.0, 4.0)` のように使う。
pub const fn 画素の組(横: f32, 縦: f32) -> 縦横の論理画素 {
    縦横の論理画素::生成する(論理画素::生成する(横), 論理画素::生成する(縦))
}
