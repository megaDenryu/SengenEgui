//! 帯の全体の範囲が値を割合へ写すとき、有限でない値を端へ寄せることを確かめる。+∞ は終わり（右端）、-∞ と NaN は始め（左端）。

use super::帯の全体の範囲;
use crate::measure::{割合, 帯の値};

fn 零から百() -> 帯の全体の範囲 {
    match 帯の全体の範囲::生成する(
        帯の値::倍精度の小数から生成する(0.0),
        帯の値::倍精度の小数から生成する(100.0),
    ) {
        Ok(全体) => 全体,
        Err(不正) => panic!("0〜100 は正しい全体の範囲である（到達したらバグ）: {不正}"),
    }
}

#[test]
fn 正の無限大は終わりへ寄せる() {
    let 値 = 帯の値::倍精度の小数から生成する(f64::INFINITY);
    assert_eq!(零から百().割合へ写す(値), 割合::全部);
}

#[test]
fn 負の無限大とnanは始めへ寄せる() {
    for 数 in [f64::NEG_INFINITY, f64::NAN] {
        assert_eq!(
            零から百().割合へ写す(帯の値::倍精度の小数から生成する(数)),
            割合::ゼロ
        );
    }
}

#[test]
fn 範囲の内側の値は比のとおりの割合になる() {
    let 値 = 帯の値::倍精度の小数から生成する(25.0);
    assert_eq!(零から百().割合へ写す(値), 割合::範囲へ丸めて生成する(0.25));
}
