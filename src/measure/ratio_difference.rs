//! 割合の差。2つの割合の差であり、負の値も1を超える値も取る。0〜1 に限る割合とは別の量である。
//! 範囲枠をドラッグした移動量のように、画像の幅や高さを1とした長さで向きを持つ量を表す。

/// 割合の差とは、幅や高さを1とした長さで測った、向きを持つ量のことである。
#[derive(Clone, Copy, Debug, Default, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 割合の差(f32);

impl 割合の差 {
    /// 差が無いこと（0）。
    pub const ゼロ: 割合の差 = 割合の差(0.0);

    /// 数値から割合の差を作る。負の値も1を超える値も受け取る。
    pub const fn 生成する(値: f32) -> Self {
        Self(値)
    }

    /// 下限と上限の間へ収めた差。下限が上限を超えるときは上限を返す。
    pub fn 下限と上限の間へ収める(self, 下限: Self, 上限: Self) -> Self {
        Self(self.0.max(下限.0).min(上限.0))
    }

    /// 生の値。利用する側が自分のドメインの型へ移す境界でだけ使う。
    pub const fn 生の値(self) -> f32 {
        self.0
    }
}

impl std::ops::Neg for 割合の差 {
    type Output = Self;
    fn neg(self) -> Self {
        Self(-self.0)
    }
}

/// 縦横の割合の差とは、横方向と縦方向の割合の差の組のことである。
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct 縦横の割合の差 {
    /// 横方向の差。右向きが正である。
    pub 横: 割合の差,
    /// 縦方向の差。下向きが正である。
    pub 縦: 割合の差,
}

impl 縦横の割合の差 {
    /// 横と縦の割合の差から組を作る。
    pub const fn 生成する(横: 割合の差, 縦: 割合の差) -> Self {
        Self { 横, 縦 }
    }

    /// 差が無い組。
    pub const ゼロ: 縦横の割合の差 = 縦横の割合の差 {
        横: 割合の差::ゼロ,
        縦: 割合の差::ゼロ,
    };

    /// 画面上の移動量を、画像の幅と高さを1とした割合の差へ直す。
    /// 幅や高さが0以下の方向は差を0とする（面積の無い画像はドラッグされないため）。
    pub(crate) fn 画面の移動量から作る(
        移動量: egui::Vec2,
        画像の大きさ: egui::Vec2,
    ) -> Self {
        let 一方向を直す = |量: f32, 長さ: f32| {
            if 長さ > 0.0 {
                割合の差(量 / 長さ)
            } else {
                割合の差::ゼロ
            }
        };
        Self {
            横: 一方向を直す(移動量.x, 画像の大きさ.x),
            縦: 一方向を直す(移動量.y, 画像の大きさ.y),
        }
    }
}
