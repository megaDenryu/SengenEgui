//! 負でない論理画素。幅のように負になってはならない長さを、作るときに0以上へ揃えて持つ。
//! 部品の確保した矩形が余白より狭いと、余白を除いた内側の幅は計算の上で負になる。その幅を型で0以上に保ち、
//! 幅で割る計算や範囲を組み立てる計算に負の値を持ち込ませない。

use crate::measure::論理画素;

// 負でない論理画素とは、0以上であることを作るときに確かめた論理画素のことである。
#[derive(Clone, Copy, Debug, Default, PartialEq, PartialOrd)]
#[repr(transparent)]
pub(crate) struct 負でない論理画素(論理画素);

impl 負でない論理画素 {
    // 長さから作る。負の長さと NaN は0にする。余白より狭い矩形の内側の幅は、幅の無い範囲として扱うためである。
    pub(crate) fn 負なら0にして生成する(長さ: 論理画素) -> Self {
        Self(論理画素::生成する(長さ.eguiへ渡す値().max(0.0)))
    }

    pub(crate) const fn 論理画素にする(self) -> 論理画素 {
        self.0
    }
}
