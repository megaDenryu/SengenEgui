//! 次元の無い比を最も近い整数へ丸めるとき、ちょうど半分を0から遠い方へ丸めることを確かめる。

use super::次元の無い比;

fn 比(割られる量: f64, 基準: f64) -> 次元の無い比 {
    match 次元の無い比::二つの量から求める(割られる量, 基準) {
        Some(比) => 比,
        None => panic!("試験の比が決まらない（到達したらバグ）"),
    }
}

#[test]
fn ちょうど半分は0から遠い方へ丸める() {
    assert_eq!(比(12.0, 24.0).最も近い整数へ丸める(), 1);
    assert_eq!(比(-12.0, 24.0).最も近い整数へ丸める(), -1);
}

#[test]
fn 半分より小さい端数は0の方へ丸める() {
    assert_eq!(比(11.0, 24.0).最も近い整数へ丸める(), 0);
    assert_eq!(比(-11.0, 24.0).最も近い整数へ丸める(), 0);
}

#[test]
fn 基準が0なら比は決まらない() {
    assert_eq!(次元の無い比::二つの量から求める(1.0, 0.0), None);
}
