//! 字形の縦の補正。egui は既定のフォント（英字）に無い字形だけを足したフォントで描き、そのとき字形の縦の位置を
//! 足したフォントの寸法（上端から基準線までの高さと行の高さ）から決める。游ゴシックのように上端から基準線までの
//! 高さが既定のフォントより大きいフォントを足すと、日本語の字形だけが英字より上へずれる。
//!
//! 補正量は次の方法で測った。字の大きさ10〜32の8段階と、通常と等幅の2つの族と、表示倍率1と1.5の組の全部について、`JSON読込保存編集` を1行に並べ、
//! egui が並べた各字形の描画の矩形（字形の位置に字形の画像のずれを足した矩形）の縦の中心を求める。英字の中心の平均と
//! 日本語の中心の平均の差を最も小さくする比を、0.01 刻みで探した。egui は字形の位置を画素へ丸めるため、
//! 補正した後も1画素未満の差は残る。測った値と測り方の試験は `tests/font_vertical.rs` に、利用する側が自分のフォントの
//! 補正量を同じ方法で探す道具は `tests/font_correction_search.rs` にある。

/// 字形の縦の補正とは、足した日本語フォントの字形を縦へずらす量を、字の大きさに対する比で表したもののことである。
/// 正の値は下へ、負の値は上へずらす。字の大きさに比例させるのは、ずれがフォントの寸法の比から生じ、字の大きさに比例するためである。
#[derive(Clone, Copy, Debug, PartialEq)]
#[repr(transparent)]
pub struct 字形の縦の補正(f32);

impl 字形の縦の補正 {
    /// ずらさない。
    pub const 無し: Self = Self(0.0);

    /// 字の大きさに対する比から作る。字の大きさ14で 0.25 なら、字形を3.5論理画素（画素へ丸めて4）下げる。
    pub const fn 字の大きさに対する比から作る(比: f32) -> Self {
        Self(比)
    }

    /// 字の大きさに対する比。
    pub const fn 字の大きさに対する比(self) -> f32 {
        self.0
    }

    /// egui のフォントの調整へ変える。egui の `y_offset_factor` は描く位置だけをずらし、行の高さと並べ方を変えない。
    pub(super) fn eguiのフォントの調整へ変える(self) -> egui::FontTweak {
        egui::FontTweak {
            y_offset_factor: self.0,
            ..Default::default()
        }
    }
}
