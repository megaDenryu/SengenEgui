//! 補正付きの置き場所。日本語フォントの候補の1件であり、フォントのファイルの置き場所と、そのフォントの字形の縦の補正を組にする。
//! 補正量はフォントの寸法で決まるため、置き場所と一緒に持つ。

use std::path::{Path, PathBuf};

use super::字形の縦の補正;

/// フォントの置き場所と補正とは、日本語フォントのファイルの置き場所と、そのフォントを足すときの字形の縦の補正の組のことである。
#[derive(Clone, Debug, PartialEq)]
pub struct フォントの置き場所と補正 {
    置き場所: PathBuf,
    縦の補正: 字形の縦の補正,
}

impl フォントの置き場所と補正 {
    /// 置き場所と縦の補正から作る。
    pub fn 生成する(
        置き場所: impl Into<PathBuf>, 縦の補正: 字形の縦の補正
    ) -> Self {
        Self {
            置き場所: 置き場所.into(),
            縦の補正,
        }
    }

    /// フォントのファイルの置き場所。
    pub fn 置き場所(&self) -> &Path {
        &self.置き場所
    }

    /// このフォントを足すときの字形の縦の補正。
    pub fn 縦の補正(&self) -> 字形の縦の補正 {
        self.縦の補正
    }
}
