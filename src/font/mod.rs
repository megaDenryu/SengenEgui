//! 日本語フォントの候補と、egui への設定。egui の既定のフォントは日本語の字形を持たないため、
//! 利用する側は起動の部分（窓を作る閉包の中）で1回、OS に入っているフォントを読み込んで足す。
//! ファイルを読むのは `フォントのバイト列::置き場所から読む` の1箇所だけである。
//! 足したフォントの字形は既定のフォントの字形と縦の位置がずれるため、候補ごとに縦の補正を持つ（`correction` 参照）。

mod bytes;
mod correction;
mod failure;
mod placement;

use std::path::PathBuf;

use bytes::フォントのバイト列;
pub use correction::字形の縦の補正;
pub use failure::{
    フォントを使えなかった理由, 使えなかった置き場所, 日本語フォントが見つからない
};
pub use placement::フォントの置き場所と補正;

/// OS に入っている日本語フォントの置き場所と縦の補正。前から順に試す。
/// Windows の游ゴシック・メイリオ・MS ゴシック、Linux の Noto Sans CJK、macOS のヒラギノ角ゴシックの順である。
/// 補正量は Windows の3つだけを測った（測り方は `correction` の説明）。Linux と macOS のフォントは測っておらず補正しない。
const 標準で入っている置き場所一覧: [(&str, 字形の縦の補正); 6] = [
    (
        "C:/Windows/Fonts/YuGothM.ttc",
        字形の縦の補正::字の大きさに対する比から作る(0.26),
    ),
    (
        "C:/Windows/Fonts/meiryo.ttc",
        字形の縦の補正::字の大きさに対する比から作る(0.04),
    ),
    ("C:/Windows/Fonts/msgothic.ttc", 字形の縦の補正::無し),
    (
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        字形の縦の補正::無し,
    ),
    (
        "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc",
        字形の縦の補正::無し,
    ),
    (
        "/System/Library/Fonts/ヒラギノ角ゴシック W3.ttc",
        字形の縦の補正::無し,
    ),
];

/// 日本語フォントの候補とは、日本語の字形を持つフォントのファイルの置き場所と縦の補正を、試す順に並べた一覧のことである。
pub struct 日本語フォントの候補 {
    一覧: Vec<フォントの置き場所と補正>,
}

impl 日本語フォントの候補 {
    /// Windows・Linux・macOS に標準で入っている日本語フォントを、測った縦の補正とともに候補にする。
    pub fn 標準で入っている候補() -> Self {
        Self::補正付きの一覧から作る(
            標準で入っている置き場所一覧.map(|(置き場所, 補正)| {
                フォントの置き場所と補正::生成する(置き場所, 補正)
            }),
        )
    }

    /// 利用する側が選んだフォントのファイルの置き場所を、試す順に並べて候補にする。縦の補正はしない。
    pub fn 置き場所の一覧から作る(
        置き場所一覧: impl IntoIterator<Item = impl Into<PathBuf>>,
    ) -> Self {
        Self::補正付きの一覧から作る(置き場所一覧.into_iter().map(|置き場所| {
            フォントの置き場所と補正::生成する(置き場所, 字形の縦の補正::無し)
        }))
    }

    /// 利用する側が選んだフォントの置き場所と縦の補正を、試す順に並べて候補にする。補正量を利用する側で決めるときに使う。
    pub fn 補正付きの一覧から作る(
        一覧: impl IntoIterator<Item = フォントの置き場所と補正>,
    ) -> Self {
        Self {
            一覧: 一覧.into_iter().collect(),
        }
    }

    /// 試す順の置き場所と縦の補正の一覧。
    pub fn 一覧(&self) -> &[フォントの置き場所と補正] {
        &self.一覧
    }

    /// 候補を前から順に読み、読めて先頭のバイトがフォントの形式を示す最初のファイルを、その候補の縦の補正を付けて
    /// egui の文字の族（通常と等幅）の最後へ足す。既定のフォントに無い字形だけがこのフォントで描かれる。
    /// 足したフォントは次のフレームから効く。
    /// どれも使えなければ、試した置き場所と理由を持つ失敗を返す。起動を止めるかどうかは利用する側が決める。
    ///
    /// 注意: 同じ egui の本体へ2回目以降に呼ぶと、egui は同じ名前のフォントを足さないため何も変わらずに Ok を返す。
    /// 別のフォントへ差し替える口ではない。
    pub fn 最初に読めたものを設定する(
        &self,
        eguiの本体: &egui::Context,
    ) -> Result<(), 日本語フォントが見つからない> {
        let mut 試した結果一覧 = Vec::new();
        for 候補 in &self.一覧 {
            match フォントのバイト列::置き場所から読む(候補.置き場所()) {
                Ok(フォント) => {
                    フォント.日本語の字形として足す(eguiの本体, 候補.縦の補正());
                    return Ok(());
                }
                Err(理由) => 試した結果一覧.push(使えなかった置き場所 {
                    置き場所: 候補.置き場所().to_path_buf(),
                    理由,
                }),
            }
        }
        Err(日本語フォントが見つからない {
            試した結果一覧
        })
    }
}
