//! 2つの色の見分けやすさの純粋な計算。強調色の地の上に載せる文字の色を、指定された色の中から選ぶときに使う。
//! 見分けやすさには WCAG 2（ウェブの読みやすさの指針）のコントラスト比を使う。コントラスト比とは、明るい方の相対輝度に
//! 0.05 を足した値を、暗い方の相対輝度に 0.05 を足した値で割った比のことであり、1（同じ明るさ）から21（白と黒）までをとる。

use egui::Color32;

/// 2つの色のコントラスト比。不透明度は見ない。
pub(super) fn コントラスト比(甲: Color32, 乙: Color32) -> f32 {
    let (甲の輝度, 乙の輝度) = (相対輝度(甲), 相対輝度(乙));
    (甲の輝度.max(乙の輝度) + 0.05) / (甲の輝度.min(乙の輝度) + 0.05)
}

/// sRGB の色の相対輝度（0 が黒、1 が白）。各成分をガンマを外した線形の値へ戻して、人の目の感度で重み付けして足す。
fn 相対輝度(色: Color32) -> f32 {
    let 線形 = |成分: u8| {
        let 値 = f32::from(成分) / 255.0;
        if 値 <= 0.04045 {
            値 / 12.92
        } else {
            ((値 + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * 線形(色.r()) + 0.7152 * 線形(色.g()) + 0.0722 * 線形(色.b())
}
