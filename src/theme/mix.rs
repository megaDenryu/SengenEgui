//! 2つの色を割合で混ぜる純粋な計算。テーマが指定された色から残りの色を導くときに使う。
//! 成分は、混ぜる2つの成分の間にある整数の中から、計算した実数に最も近いものを選ぶ。
//! 候補を2つの成分の間に限るため、結果が u8 に収まることを計算の形が保証し、変換の失敗が起こらない。

use crate::measure::割合;
use egui::Color32;

/// 甲の色を乙の色の方へ、乙の割合だけ寄せた色を返す。乙の割合が0なら甲、1なら乙になる。
/// 甲と乙を入れ替えて割合を1から引いても同じ色になるため、どちらかを主語にせず対等に受ける。
pub(super) fn 二色を混ぜる(甲: Color32, 乙: Color32, 乙の割合: 割合) -> Color32 {
    let [甲の赤, 甲の緑, 甲の青, 甲の不透明度] = 甲.to_array();
    let [乙の赤, 乙の緑, 乙の青, 乙の不透明度] = 乙.to_array();
    Color32::from_rgba_premultiplied(
        成分を混ぜる(甲の赤, 乙の赤, 乙の割合),
        成分を混ぜる(甲の緑, 乙の緑, 乙の割合),
        成分を混ぜる(甲の青, 乙の青, 乙の割合),
        成分を混ぜる(甲の不透明度, 乙の不透明度, 乙の割合),
    )
}

fn 成分を混ぜる(甲: u8, 乙: u8, 乙の割合: 割合) -> u8 {
    let 目標 = 乙の割合.二つの値の間を取る(f32::from(甲), f32::from(乙));
    let 目標からの距離 = |候補: &u8| (f32::from(*候補) - 目標).abs();
    // 注意: 範囲 小..=大 は空にならないため min_by は必ず値を返す。unwrap_or の甲には到達しない。
    (甲.min(乙)..=甲.max(乙))
        .min_by(|左, 右| 目標からの距離(左).total_cmp(&目標からの距離(右)))
        .unwrap_or(甲)
}
