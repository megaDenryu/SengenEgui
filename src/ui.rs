//! 糖衣ファクトリ。利用側はこの関数群だけでノード木を組み、egui のAPIを直接呼ばない。
//! 口が足りないときはこのライブラリへ足す（利用側に素の egui 呼び出しを書いて回避しない）。

use crate::primitives::{ボタン型, 入力欄型, 切り替え型, 文章型};
use crate::tree::{スクロール型, ノード, 積み型, 積む向き};

/// 文字表示。動的な値は `format!` 等でこのフレームの文字列を作って渡す。
pub fn 文章(内容: impl Into<String>) -> 文章型 {
    文章型::新規(内容.into())
}

/// ボタン。押されたら応答の値を発行する。
pub fn ボタン<M>(表示: impl Into<String>, 応答: M) -> ボタン型<M> {
    ボタン型::新規(表示.into(), 応答)
}

/// チェックボックス。現在値と、新しい値から応答を作る関数を渡す。
pub fn 切り替え<M>(
    表示: impl Into<String>,
    値: bool,
    変更: impl Fn(bool) -> M + 'static,
) -> 切り替え型<M> {
    切り替え型::新規(表示.into(), 値, Box::new(変更))
}

/// 一行テキスト入力。現在値と、新しい値から応答を作る関数を渡す。
pub fn 入力欄<M>(
    値: impl Into<String>,
    変更: impl Fn(String) -> M + 'static,
) -> 入力欄型<M> {
    入力欄型::新規(値.into(), Box::new(変更))
}

pub fn 余白<M>(量: f32) -> ノード<M> {
    ノード::余白(量)
}

pub fn 区切り線<M>() -> ノード<M> {
    ノード::区切り線
}

pub fn 縦積み<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::縦, 子一覧)
}

pub fn 横並び<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::横, 子一覧)
}

pub fn 縦スクロール<M>(
    識別子: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> スクロール型<M> {
    スクロール型::新規(識別子.into(), 子一覧)
}

/// 条件が成立するときだけ組み立てて表示する。不成立なら何も描画しない。
/// 条件はこのフレームの判定値を渡す。
pub fn 条件<M, N: Into<ノード<M>>>(
    成立: bool, 組み立て: impl FnOnce() -> N
) -> ノード<M> {
    if 成立 {
        組み立て().into()
    } else {
        ノード::無し
    }
}

/// 条件で2つの表示を切り替える。成立した側だけを組み立てる。
pub fn 条件二択<M, 真: Into<ノード<M>>, 偽: Into<ノード<M>>>(
    成立: bool,
    真側: impl FnOnce() -> 真,
    偽側: impl FnOnce() -> 偽,
) -> ノード<M> {
    if 成立 {
        真側().into()
    } else {
        偽側().into()
    }
}

/// 何も描画しないノード。`if` 式の「無い側」に使う。
pub fn 無し<M>() -> ノード<M> {
    ノード::無し
}
