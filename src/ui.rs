//! 糖衣ファクトリ。利用側はこの関数群だけでノード木を組み、egui のAPIを直接呼ばない。
//! 口が足りないときはこのライブラリへ足す（利用側に素の egui 呼び出しを書いて回避しない）。

use crate::primitives::{ボタン型, 入力欄型, 切り替え型, 文章型};
use crate::tree::{
    ウィンドウ型, スクロール型, ノード, 仮想列型, 折り畳み型, 格子型, 積み型, 積む向き,
};

/// 文字表示。動的な値は `format!` 等でこのフレームの文字列を作って渡す。
pub fn 文章(内容: impl Into<String>) -> 文章型 {
    文章型::新規(内容.into())
}

/// ボタン。押されたら応答の値を発行する。
pub fn ボタン<M>(表示: impl Into<String>, 応答: M) -> ボタン型<M> {
    ボタン型::新規(表示.into(), 応答)
}

/// チェックボックス。現在値と、新しい値から応答を作る関数を渡す。
pub fn 切り替え<M>(
    表示: impl Into<String>,
    値: bool,
    変更: impl Fn(bool) -> M + 'static,
) -> 切り替え型<M> {
    切り替え型::新規(表示.into(), 値, Box::new(変更))
}

/// 一行テキスト入力。現在値と、新しい値から応答を作る関数を渡す。
pub fn 入力欄<M>(
    値: impl Into<String>,
    変更: impl Fn(String) -> M + 'static,
) -> 入力欄型<M> {
    入力欄型::新規(値.into(), Box::new(変更))
}

pub fn 余白<M>(量: f32) -> ノード<M> {
    ノード::余白(量)
}

pub fn 区切り線<M>() -> ノード<M> {
    ノード::区切り線
}

pub fn 縦積み<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::縦, 子一覧)
}

pub fn 横並び<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::横, 子一覧)
}

pub fn 縦スクロール<M>(
    識別子: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> スクロール型<M> {
    スクロール型::新規(識別子.into(), 子一覧)
}

/// 条件が成立するときだけ組み立てて表示する。不成立なら何も描画しない。
/// 条件はこのフレームの判定値を渡す。
pub fn 条件<M, N: Into<ノード<M>>>(
    成立: bool, 組み立て: impl FnOnce() -> N
) -> ノード<M> {
    if 成立 {
        組み立て().into()
    } else {
        ノード::無し
    }
}

/// 条件で2つの表示を切り替える。成立した側だけを組み立てる。
pub fn 条件二択<M, 真: Into<ノード<M>>, 偽: Into<ノード<M>>>(
    成立: bool,
    真側: impl FnOnce() -> 真,
    偽側: impl FnOnce() -> 偽,
) -> ノード<M> {
    if 成立 {
        真側().into()
    } else {
        偽側().into()
    }
}

/// 何も描画しないノード。`if` 式の「無い側」に使う。
pub fn 無し<M>() -> ノード<M> {
    ノード::無し
}

/// 折り畳み見出し。開閉状態は egui が内部保持する。
pub fn 折り畳み<M>(
    見出し: impl Into<String>, 子一覧: Vec<ノード<M>>
) -> 折り畳み型<M> {
    折り畳み型::新規(見出し.into(), 子一覧)
}

/// 格子。子を左から右へ、列数で折り返して並べる。
pub fn 格子<M>(
    識別子: impl Into<String>, 列数: usize, 子一覧: Vec<ノード<M>>
) -> 格子型<M> {
    格子型::新規(識別子.into(), 列数, 子一覧)
}

/// ドラッグ可能な浮きウィンドウ。開閉はアプリ状態のboolで制御する。
pub fn ウィンドウ<M>(
    表題: impl Into<String>,
    開いている: bool,
    子一覧: Vec<ノード<M>>,
) -> ウィンドウ型<M> {
    ウィンドウ型::新規(表題.into(), 開いている, 子一覧)
}

/// 仮想化された縦のリスト。見えている行だけを行番号から組んで描画する。
/// 行高さは一定である前提を置く。
pub fn 仮想縦スクロール<M>(
    識別子: impl Into<String>,
    行高さ: f32,
    行数: usize,
    行を組む: impl Fn(usize) -> ノード<M> + 'static,
) -> 仮想列型<M> {
    仮想列型::新規(識別子.into(), 行高さ, 行数, Box::new(行を組む))
}
