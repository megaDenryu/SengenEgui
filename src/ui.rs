//! 糖衣ファクトリ。利用側はこの関数群だけでノード木を組み、egui のAPIを直接呼ばない。
//! 口が足りないときはこのライブラリへ足す（利用側に素の egui 呼び出しを書いて回避しない）。

use crate::{
    component::{部品, 部品箱},
    containers::{
        条件ノード, 横並びノード, 縦スクロールノード, 縦積みノード
    },
    node::{ノード, 空ノード, 箱},
    primitives::{
        ボタンノード, 余白ノード, 入力欄ノード, 切り替えノード, 区切り線ノード, 文章ノード,
    },
    source::文字列源,
};

/// 静的な文字表示。値が変わるなら [`文章動`] を使う。
pub fn 文章(内容: impl Into<文字列源>) -> 文章ノード {
    文章ノード::新規(内容.into())
}

/// 動的な文字表示。描画のたびにクロージャで最新値を取りに行く。
pub fn 文章動(取得: impl Fn() -> String + 'static) -> 文章ノード {
    文章ノード::新規(文字列源::動的(Box::new(取得)))
}

/// 表示が固定のボタン。押下時の処理は `.押されたら(処理)` で渡す。
pub fn ボタン(表示: impl Into<文字列源>) -> ボタンノード {
    ボタンノード::新規(表示.into())
}

/// 表示が動的なボタン（例: 稼働状態で「起動」「停止」を切り替える）。
pub fn ボタン動(取得: impl Fn() -> String + 'static) -> ボタンノード {
    ボタンノード::新規(文字列源::動的(Box::new(取得)))
}

/// チェックボックス。読みと書きを別クロージャで渡す。
pub fn 切り替え(
    表示: impl Into<文字列源>,
    読み: impl Fn() -> bool + 'static,
    書き: impl FnMut(bool) + 'static,
) -> 切り替えノード {
    切り替えノード::新規(表示.into(), Box::new(読み), Box::new(書き))
}

/// 一行テキスト入力。読みと書きを別クロージャで渡す。
pub fn 入力欄(
    読み: impl Fn() -> String + 'static,
    書き: impl FnMut(String) + 'static,
) -> 入力欄ノード {
    入力欄ノード::新規(Box::new(読み), Box::new(書き))
}

pub fn 余白(量: f32) -> 余白ノード {
    余白ノード::新規(量)
}

pub fn 区切り線() -> 区切り線ノード {
    区切り線ノード
}

pub fn 縦積み() -> 縦積みノード {
    縦積みノード::新規()
}

pub fn 横並び() -> 横並びノード {
    横並びノード::新規()
}

pub fn 縦スクロール(識別子: impl Into<String>) -> 縦スクロールノード {
    縦スクロールノード::新規(識別子.into())
}

/// 実行中に変わる条件で表示を出し入れする。条件が偽のときは何も描画しない。
pub fn 条件(
    判定: impl Fn() -> bool + 'static, 真側: impl ノード + 'static
) -> 条件ノード {
    条件ノード::新規(Box::new(判定), 箱(真側), None)
}

/// 実行中に変わる条件で2つの表示を切り替える。
pub fn 条件二択(
    判定: impl Fn() -> bool + 'static,
    真側: impl ノード + 'static,
    偽側: impl ノード + 'static,
) -> 条件ノード {
    条件ノード::新規(Box::new(判定), 箱(真側), Some(箱(偽側)))
}

/// 何も描画しないノード。構築時に決まる条件分岐の「無い側」に使う。
pub fn 無し() -> 空ノード {
    空ノード
}

/// 部品をノードとして扱える形に包む。
pub fn 部品化<T: 部品>(本体: T) -> 部品箱<T> {
    部品箱::新規(本体)
}
