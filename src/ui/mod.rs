//! 糖衣ファクトリ。利用側はこの関数群だけでノード木を組み、egui のAPIを直接呼ばない。
//! 口が足りないときはこのライブラリへ足す（利用側に素の egui 呼び出しを書いて回避しない）。
//! 族ごとにファイルを分け、このファイルは構造（余白・区切り線・無し・条件）だけを持つ。

mod attach;
mod container;
mod display;
mod input;
mod invisible;

pub use attach::{ドラッグ元, 落とし先};
pub use container::{
    ウィンドウ, タブ列, パネル, メニュー, メニューバー, モーダル, 両方向スクロール,
    仮想縦スクロール, 折り畳み見出し, 折り返す横並び, 格子, 横スクロール, 横並び, 縦スクロール,
    縦積み,
};
pub use display::{外部リンク, 文字表示, 画像, 読み込み中表示, 進捗バー};
pub use input::{
    スライダー, チェックボックス, ボタン, ラジオボタン, リンク, 一行テキスト入力, 数値入力,
    範囲枠付き画像, 色選択, 複数行テキスト入力, 選択ボタン, 選択欄, 選択肢,
};
pub use invisible::キー操作;

use crate::measure::論理画素;
use crate::tree::ノード;

/// 並びの向きに空ける余白。
pub fn 余白<M>(量: 論理画素) -> ノード<M> {
    ノード::余白(量)
}

/// 並びの向きに直交する区切り線。
pub fn 区切り線<M>() -> ノード<M> {
    ノード::区切り線
}

/// 条件が成立するときだけ組み立てて表示する。不成立なら何も描画しない。
/// 条件はこのフレームの判定値を渡す。
pub fn 条件付き表示<M, N: Into<ノード<M>>>(
    成立: bool,
    組み立てる: impl FnOnce() -> N,
) -> ノード<M> {
    if 成立 {
        組み立てる().into()
    } else {
        ノード::無し
    }
}

/// 条件で2つの表示を切り替える。成立した側だけを組み立てる。
pub fn 条件で出し分ける表示<M, 真: Into<ノード<M>>, 偽: Into<ノード<M>>>(
    成立: bool,
    成立時に組み立てる: impl FnOnce() -> 真,
    不成立時に組み立てる: impl FnOnce() -> 偽,
) -> ノード<M> {
    if 成立 {
        成立時に組み立てる().into()
    } else {
        不成立時に組み立てる().into()
    }
}

/// 何も描画しないノード。`if` 式の「無い側」に使う。
pub fn 無し<M>() -> ノード<M> {
    ノード::無し
}
