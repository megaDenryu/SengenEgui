//! 付け足しの族のうち、ドラッグで運ぶ2つの糖衣ファクトリ。
//! 説明と右クリックメニューは `付け足せる` のメソッドとして部品に直接付ける。

use std::any::Any;

use crate::tree::attach::{ドラッグ元型, 付け足し, 落とし先型};
use crate::tree::ノード;

/// ドラッグ元。子をドラッグで運び出せるようにする。識別子は同一画面内で重複させない。
/// 運ぶ値は落とし先が受け取る値であり、型が一致する落とし先だけが受け取る。
pub fn ドラッグ元<M, 運ぶ値: Clone + Any + Send + Sync>(
    識別子: impl Into<String>,
    運ぶ値: 運ぶ値,
    子: impl Into<ノード<M>>,
) -> ノード<M> {
    付け足し::ドラッグ元(ドラッグ元型::新規(識別子.into(), 運ぶ値, 子.into())).into()
}

/// 落とし先。子を枠で囲み、運ばれた値が枠の上で放されたら値から作った応答を発行する。
pub fn 落とし先<M, 運ぶ値: Clone + Any + Send + Sync>(
    子: impl Into<ノード<M>>,
    落とされた値から応答を作る: impl Fn(運ぶ値) -> M + 'static,
) -> ノード<M> {
    付け足し::落とし先(落とし先型::新規(
        子.into(),
        落とされた値から応答を作る,
    ))
    .into()
}
