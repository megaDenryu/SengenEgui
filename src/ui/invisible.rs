//! 見えない部品の族の糖衣ファクトリ。

use std::path::PathBuf;
use std::time::Duration;

use crate::tree::invisible::{
    キーの組, キー操作型, 描き直しの予約型, 落とされたファイルの受け取り型,
};

/// キー操作。そのフレームにキーの組が押されていたら応答を発行する。何も描画しない。
pub fn キー操作<M>(キーの組: キーの組, 応答: M) -> キー操作型<M> {
    キー操作型::新規(キーの組, 応答)
}

/// 落とされたファイルの受け取り。OS のファイルが窓のどこかへ落とされたら、ファイルごとにパスから作った応答を発行する。
/// 何も描画しない。受け取ったファイルは入力から取り除くため、同じ画面に2つ置くと先に描画した方だけが受け取る。
pub fn 落とされたファイルを受け取る<M>(
    パスから応答を作る: impl Fn(PathBuf) -> M + 'static,
) -> 落とされたファイルの受け取り型<M> {
    落とされたファイルの受け取り型::新規(Box::new(パスから応答を作る))
}

/// 描き直しの予約。待つ時間が経ったらもう一度描画させる。何も描画せず、応答も発しない。
/// 入力が無くても画面を進めたい間（動画の再生中等）だけ `条件付き表示` で木へ置く。
pub fn 描き直しを予約する(待つ時間: Duration) -> 描き直しの予約型 {
    描き直しの予約型::新規(待つ時間)
}
