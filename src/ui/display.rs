//! 表示の族の糖衣ファクトリ。応答を発しない部品を作る。

use crate::measure::割合;
use crate::tree::display::{
    一定時間で消える通知型, 外部リンク型, 文字表示型, 画像の出所, 画像型, 読み込み中表示型,
    通知の回, 進捗バー型,
};

/// 文字表示。動的な値は `format!` 等でこのフレームの文字列を作って渡す。
pub fn 文字表示(内容: impl Into<String>) -> 文字表示型 {
    文字表示型::新規(内容.into())
}

/// 進捗バー。割合はこのフレームの値を渡す。
pub fn 進捗バー(割合: 割合) -> 進捗バー型 {
    進捗バー型::新規(割合)
}

/// 読み込み中表示。処理中であることを回転で示す。
pub fn 読み込み中表示() -> 読み込み中表示型 {
    読み込み中表示型::新規()
}

/// 外部リンク。押されるとブラウザで行き先の URL を開く（egui 自身の動作。応答は発しない）。
pub fn 外部リンク(
    表示文字列: impl Into<String>,
    行き先: impl Into<String>,
) -> 外部リンク型 {
    外部リンク型::新規(表示文字列.into(), 行き先.into())
}

/// 画像。出所は URI の文字列か、`&差し替えられるテクスチャ`（または egui に登録済みのテクスチャの持ち手）を渡す。
/// URI から表示するには利用側が起動時に画像の読み込み器を導入している必要がある（`画像型` 参照）。
pub fn 画像(出所: impl Into<画像の出所>) -> 画像型 {
    画像型::新規(出所.into())
}

/// 一定時間で消える通知。画面の下の中央に他の部品の上へ重ねて文を出し、表示する長さ（既定3秒）が過ぎたら消す。
/// 識別子は同一画面内で重複させない。新しい通知を出すときは、利用する側が回を `通知の回::次` で進める。
/// 通知が無いときは `条件付き表示` で木から外す。egui の重ねる領域の仕様で、初めて出す回は大きさだけを測って見えず、次の回から見える。
pub fn 一定時間で消える通知(
    識別子: impl Into<String>,
    回: 通知の回,
    文: impl Into<String>,
) -> 一定時間で消える通知型 {
    一定時間で消える通知型::新規(識別子.into(), 回, 文.into())
}
