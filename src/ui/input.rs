//! 入力の族の糖衣ファクトリ。操作されると応答を発する部品を作る。
//! 値はこのフレームの値を渡し、変更は新しい値から応答を作る関数で受ける。

use std::ops::RangeInclusive;

use crate::measure::{割合で表した矩形, 縦横の論理画素};
use crate::texture::テクスチャの持ち手;
use crate::tree::input::{
    スライダー型, チェックボックス型, ボタン型, ラジオボタン型, リンク型, 一行テキスト入力型,
    数値入力型, 範囲枠の操作, 範囲枠付き画像型, 色選択型, 複数行テキスト入力型, 選択ボタン型,
    選択欄型, 選択肢,
};

/// ボタン。押されたら応答の値を発行する。
pub fn ボタン<M>(表示文字列: impl Into<String>, 応答: M) -> ボタン型<M> {
    ボタン型::新規(表示文字列.into(), 応答)
}

/// チェックボックス。現在値と、新しい値から応答を作る関数を渡す。
pub fn チェックボックス<M>(
    表示文字列: impl Into<String>,
    値: bool,
    新しい値から応答を作る: impl Fn(bool) -> M + 'static,
) -> チェックボックス型<M> {
    チェックボックス型::新規(表示文字列.into(), 値, Box::new(新しい値から応答を作る))
}

