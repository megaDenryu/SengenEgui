//! 容器の族のうち、領域を扱う3つの糖衣ファクトリ。使える領域の大きさを測る・決めた大きさの領域を占める・
//! 下地の領域の上へ重ねる。どれも子を並べる順でなく、領域の矩形を基準に子を置く。

use crate::measure::縦横の論理画素;
use crate::tree::container::{
    使える大きさから組む型, 大きさを決めた領域型, 重ね型
};
use crate::tree::ノード;

/// 使える大きさから組む。描画する時点で使える幅と高さ（置いた位置から親の領域の右端と下端まで）を測り、
/// その大きさから子の木を組んで描く。映像を使える領域いっぱいに縦横比を保って出すときのように、
/// 子の寸法を使える大きさから計算するときに使う。組む手続きは描画のたびに呼ばれ、捕まえる値は所有させる（'static）。
/// 注意: 横並びの中に置くと、高さは行の高さ（操作部品1つ分）しか得られない。領域いっぱいの高さを使うには、
/// `パネル` で区画を切ってその中に直接置くか、縦積みの最後に置く。
pub fn 使える大きさから組む<M>(
    子を組む: impl Fn(縦横の論理画素) -> ノード<M> + 'static,
) -> 使える大きさから組む型<M> {
    使える大きさから組む型::新規(Box::new(子を組む))
}

/// 大きさを決めた領域。指定の幅と高さをちょうど占め、その中へ子を上から並べる。子が小さくても領域の大きさは変わらない。
/// 映像より大きい欄の全体へ覆いやボタンを重ねるとき、`重ねる` の下地に使う。
pub fn 大きさを決めた領域<M>(
    寸法: 縦横の論理画素,
    子一覧: Vec<ノード<M>>,
) -> 大きさを決めた領域型<M> {
    大きさを決めた領域型::新規(寸法, 子一覧)
}

/// 重ねる。下地の子を描いてから、`.上に置く(位置, 子)` や `.覆って中央に置く(覆い, 子)` で足した子を下地の矩形の上へ重ねる。
/// 重ねた子は下地より優先して押される。識別子は同一画面内で重複させない（重ねる子の大きさの記憶の鍵にする）。
/// 重ねる子は、識別子ごとに最初に出した1回だけ大きさを測るため見えず、押せない。2回目以降は出した回から見えて押せる。
pub fn 重ねる<M>(識別子: impl Into<String>, 下地: impl Into<ノード<M>>) -> 重ね型<M> {
    重ね型::新規(識別子.into(), 下地.into())
}
