//! 容器の族の糖衣ファクトリ。子のノードを並べる部品を作る。

use crate::measure::{縦横の論理画素, 論理画素};
use crate::tree::container::{
    ウィンドウ型, スクロールの向き, スクロール型, タブ列型, パネルの位置, パネル型, メニューバー型,
    メニュー型, モーダル型, 仮想列型, 使える大きさから組む型, 折り畳み見出し型, 格子型, 積み型,
    積む向き, 重ね型,
};
use crate::tree::ノード;

/// 縦積み。子を上から下へ並べる。
pub fn 縦積み<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::縦, 子一覧)
}

/// 横並び。子を左から右へ並べる。幅が足りなくても折り返さない。
pub fn 横並び<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::横, 子一覧)
}

/// 折り返す横並び。子を左から右へ並べ、幅が足りなければ次の行へ折り返す。
pub fn 折り返す横並び<M>(子一覧: Vec<ノード<M>>) -> 積み型<M> {
    積み型::新規(積む向き::折り返す横, 子一覧)
}

/// 縦スクロール。識別子は同一画面内で重複させない。
pub fn 縦スクロール<M>(
    識別子: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> スクロール型<M> {
    スクロール型::新規(識別子.into(), スクロールの向き::縦, 子一覧)
}

/// 横スクロール。識別子は同一画面内で重複させない。
pub fn 横スクロール<M>(
    識別子: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> スクロール型<M> {
    スクロール型::新規(識別子.into(), スクロールの向き::横, 子一覧)
}

/// 両方向スクロール。識別子は同一画面内で重複させない。
pub fn 両方向スクロール<M>(
    識別子: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> スクロール型<M> {
    スクロール型::新規(識別子.into(), スクロールの向き::両方向, 子一覧)
}

/// 仮想化された縦のリスト。見えている行だけを行番号から組んで描画する。行の高さは一定である前提を置く。
pub fn 仮想縦スクロール<M>(
    識別子: impl Into<String>,
    行高さ: 論理画素,
    行数: usize,
    行を組む: impl Fn(usize) -> ノード<M> + 'static,
) -> 仮想列型<M> {
    仮想列型::新規(識別子.into(), 行高さ, 行数, Box::new(行を組む))
}

/// 折り畳み見出し。開閉状態は egui が内部保持する。
pub fn 折り畳み見出し<M>(
    見出し: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> 折り畳み見出し型<M> {
    折り畳み見出し型::新規(見出し.into(), 子一覧)
}

/// 格子。子を左から右へ、列数で折り返して並べる。
pub fn 格子<M>(
    識別子: impl Into<String>, 列数: usize, 子一覧: Vec<ノード<M>>
) -> 格子型<M> {
    格子型::新規(識別子.into(), 列数, 子一覧)
}

/// ドラッグ可能な浮きウィンドウ。開閉はアプリ状態のboolで制御する。
pub fn ウィンドウ<M>(
    表題: impl Into<String>,
    開いている: bool,
    子一覧: Vec<ノード<M>>,
) -> ウィンドウ型<M> {
    ウィンドウ型::新規(表題.into(), 開いている, 子一覧)
}

/// パネル。親の領域の縁または中央の区画。中央は同じ親の中で縁のパネルより後に置く（`パネル型` 参照）。
pub fn パネル<M>(
    識別子: impl Into<String>,
    位置: パネルの位置,
    子一覧: Vec<ノード<M>>,
) -> パネル型<M> {
    パネル型::新規(識別子.into(), 位置, 子一覧)
}

/// タブ列。見出しの一覧と選択中の番号を渡し、別の見出しが押されたら番号から作った応答を発行する。
pub fn タブ列<M>(
    見出し一覧: Vec<String>,
    選択中の番号: usize,
    番号から応答を作る: impl Fn(usize) -> M + 'static,
) -> タブ列型<M> {
    タブ列型::新規(見出し一覧, 選択中の番号, Box::new(番号から応答を作る))
}

/// メニューバー。メニューを横に並べる帯。
pub fn メニューバー<M>(子一覧: Vec<ノード<M>>) -> メニューバー型<M> {
    メニューバー型::新規(子一覧)
}

/// メニュー。押すと子の一覧を吹き出しで開く。メニューの中に置くと入れ子の小メニューになる。
pub fn メニュー<M>(
    表示文字列: impl Into<String>,
    子一覧: Vec<ノード<M>>,
) -> メニュー型<M> {
    メニュー型::新規(表示文字列.into(), 子一覧)
}

/// モーダル。画面を覆って子を置く。開閉はアプリ状態のboolで制御する。
pub fn モーダル<M>(
    識別子: impl Into<String>,
    開いている: bool,
    子一覧: Vec<ノード<M>>,
) -> モーダル型<M> {
    モーダル型::新規(識別子.into(), 開いている, 子一覧)
}

/// 使える大きさから組む。描画する時点で使える幅と高さ（置いた位置から親の領域の右端と下端まで）を測り、
/// その大きさから子の木を組んで描く。映像を使える領域いっぱいに縦横比を保って出すときのように、
/// 子の寸法を使える大きさから計算するときに使う。組む手続きは描画のたびに呼ばれ、捕まえる値は所有させる（'static）。
pub fn 使える大きさから組む<M>(
    子を組む: impl Fn(縦横の論理画素) -> ノード<M> + 'static,
) -> 使える大きさから組む型<M> {
    使える大きさから組む型::新規(Box::new(子を組む))
}

/// 重ねる。下地の子を描いてから、`.上に置く(位置, 子)` や `.覆って中央に置く(色, 子)` で足した子を下地の矩形の上へ重ねる。
/// 重ねた子は下地より優先して押される。
pub fn 重ねる<M>(下地: impl Into<ノード<M>>) -> 重ね型<M> {
    重ね型::新規(下地.into())
}
