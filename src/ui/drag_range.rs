//! 入力の族のうち、ドラッグで範囲や位置を動かす部品の糖衣ファクトリ。どの部品も操作を掴み始め・動かしている・放したの
//! 3段階で発し、新しい範囲や位置の計算（最小の大きさ・基準の内側へ収める・丸め等）は利用する側が行う。

use crate::measure::{
    割合で表した矩形, 帯の値, 帯の全体の範囲, 縦横の論理画素
};
use crate::texture::登録したテクスチャの参照;
use crate::tree::input::{
    区間の帯の操作, 区間の帯型, 時間の塊の操作, 時間の塊の鍵, 時間の行の並び型, 時間の行型,
    範囲枠の操作, 範囲枠付き画像型, 複数の範囲枠の操作, 複数の範囲枠の鍵, 複数の範囲枠型,
};
use crate::tree::ノード;

/// 範囲枠付き画像。テクスチャ（`&差し替えられるテクスチャ` か、所有した値だけを持ち込める閉包の中では `登録したテクスチャの参照`）・表示寸法（縦横比を保って収める枠）・画像に対する割合で表した現在の枠と、
/// 操作から応答を作る関数を渡す。操作は掴み始め・動かしている・放したの3段階で発し、
/// 新しい枠の計算は利用する側が行う（`範囲枠の操作` 参照）。
/// 枠が画像の端にあっても隅のつまみを掴めるよう、画像の周りの上下左右に `範囲枠付き画像の周りの余白`
/// （8論理画素）を確保する。部品が占める大きさは、表示寸法へ縦横比を保って収めた画像の幅と高さに
/// それぞれ16論理画素を足した大きさになる。
pub fn 範囲枠付き画像<M>(
    テクスチャ: impl Into<登録したテクスチャの参照>,
    表示寸法: 縦横の論理画素,
    枠: 割合で表した矩形,
    操作から応答を作る: impl Fn(範囲枠の操作) -> M + 'static,
) -> 範囲枠付き画像型<M> {
    範囲枠付き画像型::新規(
        テクスチャ.into(),
        表示寸法,
        枠,
        Box::new(操作から応答を作る),
    )
}

/// 区間の帯。値の全体の範囲・区間の開始と終了（値の単位）と、操作から応答を作る関数を渡す。位置の印は `.位置()` で足す。
/// 操作は掴み始め・動かしている・放したの3段階で、掴んだものとその値を発する。新しい区間の計算（丸め・最小の長さ・
/// 開始が終了を超えない規則）は利用する側が行う（`区間の帯の操作` 参照）。押した位置からの移動量は、ドラッグの間に
/// 全体の範囲が変わっても、掴み始めたフレームの目盛りで値の差へ直す。幅は既定で使える幅いっぱいになる。
pub fn 区間の帯<M>(
    全体: 帯の全体の範囲,
    開始: 帯の値,
    終了: 帯の値,
    操作から応答を作る: impl Fn(区間の帯の操作) -> M + 'static,
) -> 区間の帯型<M> {
    区間の帯型::新規(全体, 開始, 終了, Box::new(操作から応答を作る))
}

/// 複数の範囲枠。占める寸法（基準の矩形の幅と高さ）と、基準の矩形に描く下地と、枠の鍵と操作から応答を作る関数を渡す。
/// `.枠を置く(鍵, 矩形)` と `.選んでいる枠を置く(鍵, 矩形)` で、基準の矩形の幅と高さを1とした割合で表した枠を置く。
/// 後に置いた枠ほど手前にある。押した枠を選び（選んでいない枠なら `選んだ` を発する）、枠の内側のドラッグで移動を、
/// 選んでいる枠の4隅のつまみのドラッグで大きさの変更を受け付け、範囲枠付き画像と同じく掴み始め・動かしている・放したの
/// 3段階で発する（`複数の範囲枠の操作` 参照）。どの枠の操作かは鍵で渡し、ドラッグの間も鍵で枠を探す。
/// 新しい枠の計算は利用する側が行う。隅のつまみを掴めるよう基準の矩形の周りの上下左右に `複数の範囲枠の周りの余白`
/// （8論理画素）を確保するため、部品が占める大きさは寸法の幅と高さにそれぞれ16論理画素を足した大きさになる。
/// 部品は余白を含む全体で押下を受け取るため、下地の中の部品は押せない。
pub fn 複数の範囲枠<M, 鍵: 複数の範囲枠の鍵>(
    寸法: 縦横の論理画素,
    下地: impl Into<ノード<M>>,
    操作から応答を作る: impl Fn(鍵, 複数の範囲枠の操作) -> M + 'static,
) -> 複数の範囲枠型<M, 鍵> {
    複数の範囲枠型::新規(寸法, 下地.into(), Box::new(操作から応答を作る))
}

/// 時間の行の並び。値の全体の範囲（時間）と、塊の鍵と操作から応答を作る関数を渡す。`.行を置く(時間の行().塊を置く(鍵, 塊))` で
/// 行を置いた順に下から上へ積み、各行に `時間の塊`（始まりと長さ）を並べる。塊の無い行も地を描く。押した塊を選び
/// （選んでいない塊なら `選んだ` を発する）、塊のドラッグを掴み始め・動かしている・放したの3段階で、開始点からの累積の
/// 移動量（時間の差と行の差）で発する（`時間の塊の操作` 参照）。どの塊の操作かは鍵で渡し、ドラッグの間も鍵で塊を探す。
/// 選んでいる塊を先に掴み、同じ行で重なった所では後に置いた塊を掴む。位置の線は `.位置の線を置く()` で描き、
/// `.位置の線を動かしたら発する()` を付けると、上の時間の軸を押してドラッグした値を発する（`位置の線の操作` 参照）。
/// 新しい始まりと行と位置の計算は利用する側が行う。幅は既定で使える幅いっぱいになる。
pub fn 時間の行の並び<M, 鍵: 時間の塊の鍵>(
    全体: 帯の全体の範囲,
    操作から応答を作る: impl Fn(鍵, 時間の塊の操作) -> M + 'static,
) -> 時間の行の並び型<M, 鍵> {
    時間の行の並び型::新規(全体, Box::new(操作から応答を作る))
}

/// 時間の行の並びに置く1つの行。`.塊を置く(鍵, 塊)`・`.選んでいる塊を置く(鍵, 塊)` で塊を並べる。
pub fn 時間の行<鍵>() -> 時間の行型<鍵> {
    時間の行型::新規()
}
