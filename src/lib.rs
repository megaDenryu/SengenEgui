//! 宣言的UIラッパー `sengen_egui`。C#版 SengenImgui・TypeScript版 SengenUI と同じ精神
//! （宣言的な構造記述・構造と装飾の分離・利用側は素の描画APIを呼ばない）を、
//! egui の流儀に合わせた形で実現する。
//!
//! 中核の方針は次の3つである。
//!
//! 1. **ノード木は1フレーム分のUI記述であり、毎フレーム組み直して捨てる。**
//!    ノードは状態を借りてその場の値を直接埋めるため、値の購読・通知もクロージャの
//!    共有参照も要らない。C#版の「永続ノード木」はUnityのGC回避が動機だったが、
//!    GCの無いRustと毎フレームレイアウトする egui ではその動機が消えるため、意図的に捨てた
//! 2. **操作は応答（利用側で定義するメッセージ型 M）として収集する。**
//!    ボタンや入力は応答の値を発行し、描画後にまとめて `&mut 状態` へ適用する。
//!    描画中に状態を書き換えないので、可変借用の衝突が構造的に起きない
//! 3. **装飾（[`スタイル`]）は構造から分離し、名前付き定数として集約する**
//!
//! 寸法は [`論理画素`]、比率は [`割合`]、向きを持つ比率の差は [`割合の差`]、拡大は [`拡大率`]、egui が整数で受ける余白と角丸は
//! [`余白の画素`]・[`角丸の画素`] で受け取り、裸の数値を公開APIへ出さない。
//!
//! ```
//! use sengen_egui::{子, ボタン, 文字表示, 縦積み, ノード};
//!
//! #[derive(Clone)]
//! enum 応答 {
//!     加算,
//! }
//!
//! struct 状態 {
//!     数: i32,
//! }
//!
//! fn 画面(状態: &状態) -> ノード<応答> {
//!     縦積み(子![
//!         文字表示(format!("カウンタ: {}", 状態.数)),
//!         ボタン("+1", 応答::加算),
//!     ])
//!     .into()
//! }
//!
//! // 毎フレーム、eguiの描画閉包の中で:
//! //   for 応答 in 画面(&状態).描画して集める(ui) {
//! //       match 応答 { 応答::加算 => 状態.数 += 1 }
//! //   }
//! # let _ = 画面(&状態 { 数: 0 });
//! ```
