//! 複合UI単位。SengenImgui の Component に相当する。
//! C#版の遅延構築は「コンストラクタから virtual を呼ばない」規律のためだったが、
//! Rust には継承が無くその問題も無い。遅延構築は再構築の予約を可能にするために残す。

use crate::node::{ノード, ノード箱};

/// 部品とは、複数のノードをまとめた再利用可能なUI単位のことである。
/// `組み立てる` は初回描画のときだけ呼ばれ、結果のノード木が保持される。
pub trait 部品 {
    fn 組み立てる(&mut self) -> ノード箱;
}

/// 部品箱とは、部品をノードとして扱うための入れ物のことである。
/// `部品化` で作り、他のコンテナや部品の子としてそのまま渡せる。
pub struct 部品箱<T: 部品> {
    本体: T,
    実体: Option<ノード箱>,
}

impl<T: 部品> 部品箱<T> {
    pub(crate) fn 新規(本体: T) -> Self {
        Self {
            本体, 実体: None
        }
    }

    /// 次の描画で `組み立てる` をやり直す。割り当てを生むため多用しない
    /// （表示の切り替えは条件ノードで表現する）。
    pub fn 再構築を予約する(&mut self) {
        self.実体 = None;
    }
}

impl<T: 部品> ノード for 部品箱<T> {
    fn 描画する(&mut self, ui: &mut egui::Ui) {
        let 実体 = self.実体.get_or_insert_with(|| self.本体.組み立てる());
        実体.描画する(ui);
    }
}
