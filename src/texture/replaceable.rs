//! 差し替えられるテクスチャ。egui へ登録したテクスチャの持ち手を保持し、中身の画素を差し替える。
//!
//! 差し替えは呼んだ回だけ egui へ画素を送る。送るたびに1コマ分の領域を確保して写す（egui が所有した画像を要求するため）。同じ画素を毎フレーム送らないよう、
//! 中身が変わったとき（動画のコマが進んだとき等）だけ利用する側が呼ぶ。
//! 部品へ渡した持ち手と、ここで保持する持ち手は同じテクスチャを指すため、差し替えた中身は次の描画から部品に出る。

use crate::texture::{テクスチャの持ち手, 画素の並び, 画素数の寸法};

/// 拡大縮小の仕方とは、テクスチャを元の画素数と違う大きさで描くときの画素の埋め方の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 拡大縮小の仕方 {
    /// 最も近い画素の色をそのまま使う。ドット絵のように画素の境目をくっきり保つ。
    画素をそのまま使う,
    /// 隣り合う画素の色を混ぜて滑らかにする。写真や動画のコマに向く。
    隣の画素と混ぜる,
}

impl 拡大縮小の仕方 {
    fn eguiへ渡す値(self) -> egui::TextureOptions {
        match self {
            Self::画素をそのまま使う => egui::TextureOptions::NEAREST,
            Self::隣の画素と混ぜる => egui::TextureOptions::LINEAR,
        }
    }
}

/// 差し替えられるテクスチャとは、egui へ登録したテクスチャの持ち手と、今の中身の寸法の組のことである。
/// 利用する側の状態に置いて保持し続ける。捨てると egui 側のテクスチャも解放される。
pub struct 差し替えられるテクスチャ {
    持ち手: egui::TextureHandle,
    寸法: 画素数の寸法,
    仕方: 拡大縮小の仕方,
}

impl 差し替えられるテクスチャ {
    /// 画素の並びを egui へ登録してテクスチャを作る。名前は egui の調査用の表示に出るだけで、重複してもよい。
    /// egui の本体は、eframe の作成の閉包の `egui_ctx` か、`App::update` が受け取るものを渡す。
    pub fn 登録して作る(
        eguiの本体: &egui::Context,
        名前: impl Into<String>,
        画素: 画素の並び<'_>,
        仕方: 拡大縮小の仕方,
    ) -> Self {
        let 持ち手 =
            eguiの本体.load_texture(名前, 画素.eguiの画像へ変換する(), 仕方.eguiへ渡す値());
        Self {
            持ち手,
            寸法: 画素.寸法(),
            仕方,
        }
    }

    /// 中身を新しい画素の並びへ差し替える。寸法は前の中身と違ってよい。
    pub fn 差し替える(&mut self, 画素: 画素の並び<'_>) {
        self.持ち手
            .set(画素.eguiの画像へ変換する(), self.仕方.eguiへ渡す値());
        self.寸法 = 画素.寸法();
    }

    /// 今の中身の寸法。
    pub fn 寸法(&self) -> 画素数の寸法 {
        self.寸法
    }

    /// 同じテクスチャを指す持ち手を複製する。所有した値だけを持ち込める閉包の中で画像を描くときに使う。
    pub fn 持ち手を複製する(&self) -> テクスチャの持ち手 {
        テクスチャの持ち手::from(self.持ち手.clone())
    }
}
