//! 画素の並び。画像の中身を、左上の画素から行ごとに右へ、1画素につき赤・緑・青・不透明度の順で
//! 各1バイトずつ並べたバイト列として受け取る。不透明度を色へ掛けていない（乗算済みでない）値とみなす。
//!
//! 画素の並び自体はバイト列を借りるだけで写さない。利用する側が溜めたコマのバイト列を、そのまま差し替えへ渡せるようにするためである。
//! ただし登録と差し替えのたびに、egui が所有した画像（`egui::ColorImage`）を要求するため、1コマ分の領域を確保して写す。

use crate::texture::画素数の寸法;

/// 画素の並びとは、寸法と、その寸法に長さが一致すると確かめたバイト列の組のことである。
#[derive(Clone, Copy, Debug)]
pub struct 画素の並び<'バイト列> {
    寸法: 画素数の寸法,
    eguiの寸法: [usize; 2],
    バイト列: &'バイト列 [u8],
}

/// 画素の並びの不正とは、寸法とバイト列から画素の並びを作れない理由の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 画素の並びの不正 {
    /// 幅か高さが0である。
    寸法が空である(画素数の寸法),
    /// 寸法から求めたバイト数が、この環境で扱える大きさを超える。
    寸法が大きすぎる(画素数の寸法),
    /// バイト列の長さが、幅×高さ×4 と一致しない。
    バイト数が合わない {
        /// 渡した寸法。
        寸法: 画素数の寸法,
        /// 寸法から求めたバイト数。
        要るバイト数: usize,
        /// 渡したバイト列の長さ。
        渡したバイト数: usize,
    },
}

impl<'バイト列> 画素の並び<'バイト列> {
    /// 寸法と、1画素につき赤・緑・青・不透明度の順で各1バイトのバイト列から画素の並びを作る。
    /// バイト列の長さが幅×高さ×4 と一致しなければ理由を返す。
    pub fn 赤緑青と不透明度のバイト列から作る(
        寸法: 画素数の寸法,
        バイト列: &'バイト列 [u8],
    ) -> Result<Self, 画素の並びの不正> {
        if 寸法.空であるか() {
            return Err(画素の並びの不正::寸法が空である(寸法));
        }
        let (Some(要るバイト数), Some(eguiの寸法)) =
            (寸法.四バイトの画素で並べたバイト数(), 寸法.eguiへ渡す値())
        else {
            return Err(画素の並びの不正::寸法が大きすぎる(寸法));
        };
        if バイト列.len() != 要るバイト数 {
            return Err(画素の並びの不正::バイト数が合わない {
                寸法,
                要るバイト数,
                渡したバイト数: バイト列.len(),
            });
        }
        Ok(Self {
            寸法,
            eguiの寸法,
            バイト列,
        })
    }

    /// 画素の並びの寸法。
    pub fn 寸法(&self) -> 画素数の寸法 {
        self.寸法
    }

    /// egui の画像へ変換する。長さは作るときに確かめてあるため、egui の長さの検査は必ず通る。
    pub(crate) fn eguiの画像へ変換する(&self) -> egui::ColorImage {
        egui::ColorImage::from_rgba_unmultiplied(self.eguiの寸法, self.バイト列)
    }
}

impl std::fmt::Display for 画素の並びの不正 {
    fn fmt(&self, 出力: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::寸法が空である(寸法) => {
                write!(出力, "画素の並びの寸法 {寸法} は幅か高さが0である")
            }
            Self::寸法が大きすぎる(寸法) => {
                write!(
                    出力,
                    "画素の並びの寸法 {寸法} はこの環境で扱えるバイト数を超える"
                )
            }
            Self::バイト数が合わない {
                寸法,
                要るバイト数,
                渡したバイト数,
            } => write!(
                出力,
                "寸法 {寸法} には {要るバイト数} バイトが要るが、{渡したバイト数} バイトを渡した"
            ),
        }
    }
}

impl std::error::Error for 画素の並びの不正 {}
