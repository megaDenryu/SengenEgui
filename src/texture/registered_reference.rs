//! テクスチャの持ち手。egui へ登録済みのテクスチャを指し、複製して部品へ渡せる値である。
//!
//! `差し替えられるテクスチャ` は利用する側の状態が所有するため、借りられない場所（`使える大きさから組む` の閉包のように
//! 所有した値だけを持ち込める場所）へは渡せない。持ち手を複製して閉包へ所有させれば、そこで `画像` と `範囲枠付き画像` の両方に使える。
//! 複製は参照の数を増やすだけで画素は写さない。差し替えた中身は、次の描画から持ち手の先にも出る。

use crate::texture::差し替えられるテクスチャ;
use crate::tree::display::画像の出所;

/// テクスチャの持ち手とは、egui に登録済みのテクスチャを指し、複製して部品へ渡せる値のことである。
#[derive(Clone)]
pub struct テクスチャの持ち手(egui::TextureHandle);

impl テクスチャの持ち手 {
    /// egui の部品へ渡すための持ち手。この口以外で egui の持ち手へ戻さない。
    pub(crate) fn eguiへ渡す値(&self) -> &egui::TextureHandle {
        &self.0
    }
}

impl From<egui::TextureHandle> for テクスチャの持ち手 {
    fn from(値: egui::TextureHandle) -> Self {
        Self(値)
    }
}

/// `範囲枠付き画像(&テクスチャ, …)` の形で渡すための変換。
impl From<&差し替えられるテクスチャ> for テクスチャの持ち手 {
    fn from(値: &差し替えられるテクスチャ) -> Self {
        値.持ち手を複製する()
    }
}

/// `範囲枠付き画像(&持ち手, …)` の形で、持ち手を手放さずに渡すための変換。
impl From<&テクスチャの持ち手> for テクスチャの持ち手 {
    fn from(値: &テクスチャの持ち手) -> Self {
        値.clone()
    }
}

/// `画像(持ち手)` の形で画像の部品へ渡すための変換。
impl From<テクスチャの持ち手> for 画像の出所 {
    fn from(値: テクスチャの持ち手) -> Self {
        Self::テクスチャ(値)
    }
}

/// `画像(&持ち手)` の形で、持ち手を手放さずに画像の部品へ渡すための変換。
impl From<&テクスチャの持ち手> for 画像の出所 {
    fn from(値: &テクスチャの持ち手) -> Self {
        Self::テクスチャ(値.clone())
    }
}

/// `画像(&テクスチャ)` の形で画像の部品へ渡すための変換。
impl From<&差し替えられるテクスチャ> for 画像の出所 {
    fn from(値: &差し替えられるテクスチャ) -> Self {
        Self::テクスチャ(値.持ち手を複製する())
    }
}
