//! 応答型の写像。部品ローカルの応答型を親の応答型へ埋め込むときに使う
//! （Elm系UIの map に相当する）。値は即時に、クロージャは包んで遅延で変換する。

use std::rc::Rc;

use crate::tree::ノード;

impl<M: 'static> ノード<M> {
    /// 応答型を別の型へ写した木を返す。
    pub fn 写す<N: 'static>(self, 変換: impl Fn(M) -> N + 'static) -> ノード<N> {
        self.rcで写す(Rc::new(変換))
    }

    pub(crate) fn rcで写す<N: 'static>(self, 変換: Rc<dyn Fn(M) -> N>) -> ノード<N> {
        match self {
            Self::文章(中身) => ノード::文章(中身),
            Self::ボタン(中身) => ノード::ボタン(中身.写す(&*変換)),
            Self::切り替え(中身) => ノード::切り替え(中身.写す(変換)),
            Self::入力欄(中身) => ノード::入力欄(中身.写す(変換)),
            Self::余白(量) => ノード::余白(量),
            Self::区切り線 => ノード::区切り線,
            Self::積み(中身) => ノード::積み(中身.写す(変換)),
            Self::縦スクロール(中身) => ノード::縦スクロール(中身.写す(変換)),
            Self::仮想列(中身) => ノード::仮想列(中身.写す(変換)),
            Self::折り畳み(中身) => ノード::折り畳み(中身.写す(変換)),
            Self::格子(中身) => ノード::格子(中身.写す(変換)),
            Self::ウィンドウ(中身) => ノード::ウィンドウ(中身.写す(変換)),
            Self::無し => ノード::無し,
        }
    }
}

/// 子ノード列の各要素を写す。各コンテナの `写す` が使う共通部。
pub(crate) fn 子一覧を写す<M: 'static, N: 'static>(
    子一覧: Vec<ノード<M>>,
    変換: &Rc<dyn Fn(M) -> N>,
) -> Vec<ノード<N>> {
    子一覧
        .into_iter()
        .map(|子| 子.rcで写す(Rc::clone(変換)))
        .collect()
}
