//! 応答型の写像。部品ローカルの応答型を親の応答型へ埋め込むときに使う
//! （Elm系UIの map に相当する）。値は即時に、クロージャは包んで遅延で変換する。

use std::rc::Rc;

use crate::tree::ノード;

impl<M: 'static> ノード<M> {
    /// 応答型を別の型へ写した木を返す。
    pub fn 写す<N: 'static>(
        self, 応答を変換する: impl Fn(M) -> N + 'static
    ) -> ノード<N> {
        self.rcで写す(Rc::new(応答を変換する))
    }

    pub(crate) fn rcで写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> ノード<N> {
        match self {
            Self::表示(中身) => ノード::表示(中身),
            Self::入力(中身) => ノード::入力(中身.写す(応答を変換する)),
            Self::容器(中身) => ノード::容器(中身.写す(応答を変換する)),
            Self::付け足し(中身) => {
                ノード::付け足し(Box::new(中身.写す(応答を変換する)))
            }
            Self::見えない(中身) => ノード::見えない(中身.写す(応答を変換する)),
            Self::余白(量) => ノード::余白(量),
            Self::区切り線 => ノード::区切り線,
            Self::無し => ノード::無し,
        }
    }
}

/// 子ノード列の各要素を写す。各容器の `写す` が使う共通部。
pub(crate) fn 子一覧を写す<M: 'static, N: 'static>(
    子一覧: Vec<ノード<M>>,
    応答を変換する: &Rc<dyn Fn(M) -> N>,
) -> Vec<ノード<N>> {
    子一覧
        .into_iter()
        .map(|子| 子.rcで写す(Rc::clone(応答を変換する)))
        .collect()
}
