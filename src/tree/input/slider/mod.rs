//! スライダー。範囲内の数をつまみで変える。数の型は egui の `Numeric` を満たす型で汎用である。
//! ノードへ変換する時点で数の型を閉包へ閉じ込める（`erased` 参照）。
//! 値が変わるたびに発する応答のほかに、操作を終えたとき（ドラッグを放したとき・キーで値を変えたとき・
//! 数値の欄の入力を確定したとき）だけ発する応答を持てる。変更のたびには軽い処理を、終えたときに重い処理を行う利用のためである。
//! 描画と応答の判定は `draw` が、軌道の幅の決め方は `track` が持つ。

mod draw;
mod track;

use std::ops::RangeInclusive;

use crate::measure::論理画素;
use crate::tree::input::erased::型を消した入力型;
use crate::tree::input::入力の部品;
use crate::tree::ノード;
use track::軌道の幅;

type 値から応答を作る手続き<M, 数> = Box<dyn Fn(数) -> M>;

/// スライダー型とは、範囲内の数をつまみで編集する部品の記述のことである。
pub struct スライダー型<M, 数: egui::emath::Numeric> {
    値: 数,
    範囲: RangeInclusive<数>,
    新しい値から応答を作る: 値から応答を作る手続き<M, 数>,
    操作を終えた値から応答を作る: Option<値から応答を作る手続き<M, 数>>,
    添える文字: Option<String>,
    軌道の幅: 軌道の幅,
    数値を表示する: bool,
    刻み指定: Option<数>,
}

impl<M, 数: egui::emath::Numeric> スライダー型<M, 数> {
    pub(crate) fn 新規(
        値: 数,
        範囲: RangeInclusive<数>,
        新しい値から応答を作る: 値から応答を作る手続き<M, 数>,
    ) -> Self {
        Self {
            値,
            範囲,
            新しい値から応答を作る,
            操作を終えた値から応答を作る: None,
            添える文字: None,
            軌道の幅: 軌道の幅::既定,
            数値を表示する: true,
            刻み指定: None,
        }
    }

    /// つまみの右に添える文字を指定する。
    pub fn 文字を添える(mut self, 文字: impl Into<String>) -> Self {
        self.添える文字 = Some(文字.into());
        self
    }

    /// つまみが動く軌道の幅を指定する。`幅いっぱい` とは後に書いた方が効く。
    pub fn 幅(mut self, 幅: 論理画素) -> Self {
        self.軌道の幅 = 軌道の幅::指定(幅);
        self
    }

    /// 軌道を、使える幅から数値の欄と添える文字の分を差し引いた残りの全部へ広げる。再生位置の帯のように横いっぱいに使う。
    pub fn 幅いっぱい(mut self) -> Self {
        self.軌道の幅 = 軌道の幅::使える幅いっぱい;
        self
    }

    /// 値を刻みの倍数に揃える。0.05 刻みの速度や音量に使う。
    pub fn 刻み(mut self, 刻み: 数) -> Self {
        self.刻み指定 = Some(刻み);
        self
    }

    /// 軌道の右の数値の欄を出さない。
    pub fn 数値を隠す(mut self) -> Self {
        self.数値を表示する = false;
        self
    }

    /// 操作を終えたとき（ドラッグを放したとき、またはドラッグ以外の操作で値が変わったとき）に、その時点の値から作った応答を発する。
    /// ドラッグ以外の操作とは、軌道を押す（押してから放すまではドラッグとして扱う）・フォーカスを持つ間の矢印キー・
    /// 数値の欄の入力の確定（Enter かフォーカスが外れたとき）である。この指定があると、数値の欄は打鍵のたびでなく
    /// 確定したときだけ値を変える（値が変わるたびの応答も確定したときに1回だけ出る）。
    /// 値が変わるたびの応答も今までどおり発し、同じ回に両方が出るときは変わった応答が先に並ぶ。
    pub fn 操作を終えたら発する(
        mut self,
        値から応答を作る: impl Fn(数) -> M + 'static,
    ) -> Self {
        self.操作を終えた値から応答を作る = Some(Box::new(値から応答を作る));
        self
    }
}

impl<M: 'static, 数: egui::emath::Numeric> From<スライダー型<M, 数>> for ノード<M> {
    fn from(値: スライダー型<M, 数>) -> Self {
        let 消去済み =
            型を消した入力型::新規(
                Box::new(move |ui| ui.scope(|内側| 値.描画する(内側)).inner),
            );
        Self::入力(入力の部品::スライダー(消去済み))
    }
}
