//! 押せる画像。画像の表示に「押されたら応答を発する」を足した部品である。
//! 表示の族の画像型は応答型 M を持たないため、押されたときの応答を足した時点で
//! 入力の族の型へ移る。見た目と寸法の指定は画像型のものをそのまま使う。

use crate::tree::display::画像型;

/// 押せる画像型とは、押されると応答を発する画像の記述のことである。
pub struct 押せる画像型<M> {
    画像: 画像型,
    応答: M,
}

impl 画像型 {
    /// 画像が押されたら応答を発するようにする。応答型を持つ入力の部品へ移る。
    /// 寸法の指定（`最大幅`・`表示寸法`）はこの口より前に書く。
    pub fn 押されたら発する<M>(self, 応答: M) -> 押せる画像型<M> {
        押せる画像型 {
            画像: self, 応答
        }
    }
}

impl<M> 押せる画像型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。
    pub(crate) fn 写す<N>(self, 応答を変換する: &dyn Fn(M) -> N) -> 押せる画像型<N> {
        押せる画像型 {
            画像: self.画像,
            応答: 応答を変換する(self.応答),
        }
    }
}

impl<M: Clone> 押せる画像型<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 部品 = self.画像.egui部品を組む().sense(egui::Sense::click());
        let 反応 = ui.add(部品);
        if 反応.clicked() {
            発行した応答.push(self.応答.clone());
        }
        反応
    }
}
