//! 時間の行の並びの配置。部品が確保した矩形を、上の時間の軸の領域と、その下の行の並びに分け、行の並びを下から行の数だけ
//! 区切る。行は置いた順に下から上へ積む（番号0の行がいちばん下）。後に置いたものほど手前・上に来る複数の範囲枠の
//! 重なりの順と揃え、利用する側の奥から手前の順の行の並びをそのまま渡せるようにするためである。
//! 値と横の位置を相互に求める規則は、区間の帯と共有する `帯の横の目盛り` が持つ。

use super::block::時間の塊;
use super::row_number::時間の行の番号;
use crate::measure::{帯の全体の範囲, 画素, 論理画素};
use crate::tree::input::band_scale::帯の横の目盛り;

const 時間の軸の領域の高さ: 論理画素 = 画素(14.0); // 位置の印の頭を描き、押すと位置の線を動かす時間の軸の領域の高さ
pub(super) const 行の高さ: 論理画素 = 画素(24.0); // 1つの行の高さ。ドラッグの行の差を数える単位でもある
const 塊の上下の空き: 論理画素 = 画素(3.0); // 塊を行の上下の端から離して描き、隣の行の塊と見分けやすくする

// 時間の行の並びの配置とは、1フレームの時間の軸の領域と行の並びの矩形と、行ごとの矩形（番号の順）と、横の目盛りの組のことである。
pub(super) struct 時間の行の並びの配置 {
    pub(super) 時間の軸の領域: egui::Rect,
    pub(super) 行の並びの矩形: egui::Rect,
    行の矩形一覧: Vec<egui::Rect>,
    pub(super) 目盛り: 帯の横の目盛り,
}

impl 時間の行の並びの配置 {
    // 行の数の行を並べたときの部品の高さ。
    pub(super) fn 部品の高さ(行の数: usize) -> 論理画素 {
        (0..行の数).fold(時間の軸の領域の高さ, |高さ, _| {
            高さ + 行の高さ
        })
    }

    // 確保した矩形の左右に余白を空けた内側に目盛りを刻み、上から時間の軸の領域と行の並びに分け、行の並びを下から行の数だけ区切る。
    pub(super) fn 確保した矩形を分ける(
        確保した矩形: egui::Rect,
        全体: 帯の全体の範囲,
        行の数: usize,
    ) -> Self {
        let 目盛り =
            帯の横の目盛り::確保した矩形の内側に刻む(確保した矩形, 全体);
        let 横 = 目盛り.横の範囲();
        let 境目 = 確保した矩形.top() + 時間の軸の領域の高さ.eguiへ渡す値();
        let 行の並びの矩形 = egui::Rect::from_x_y_ranges(横, 境目..=確保した矩形.bottom());
        let 高さ = 行の高さ.eguiへ渡す値();
        let 行の矩形一覧 = (0..行の数)
            .scan(行の並びの矩形.bottom(), |下端, _| {
                let 上端 = *下端 - 高さ;
                let 行 = egui::Rect::from_x_y_ranges(横, 上端..=*下端);
                *下端 = 上端;
                Some(行)
            })
            .collect();
        Self {
            時間の軸の領域: egui::Rect::from_x_y_ranges(横, 確保した矩形.top()..=境目),
            行の並びの矩形,
            行の矩形一覧,
            目盛り,
        }
    }

    // 番号の行の矩形。並びに無い番号なら None を返す。
    pub(super) fn 行の矩形(&self, 番号: 時間の行の番号) -> Option<egui::Rect> {
        self.行の矩形一覧.get(番号.置いた順の番号()).copied()
    }

    // 番号の順（下から上）の行の矩形。
    pub(super) fn 行の矩形を巡る(&self) -> impl Iterator<Item = egui::Rect> + '_ {
        self.行の矩形一覧.iter().copied()
    }

    // 縦の位置を含む行の番号。行の並びの外なら None を返す。横の位置は問わない（左右の余白も行の上とみなす）。
    pub(super) fn 縦の位置を含む行(
        &self,
        縦の位置: 論理画素,
    ) -> Option<時間の行の番号> {
        self.行の矩形一覧
            .iter()
            .position(|行| 行.y_range().contains(縦の位置.eguiへ渡す値()))
            .map(時間の行の番号::置いた順の番号から生成する)
    }

    // 行の矩形の中に塊を描く矩形。全体の範囲の外にある部分は、全体の端より外の横の位置になる。
    pub(super) fn 塊の矩形(&self, 行の矩形: egui::Rect, 塊: 時間の塊) -> egui::Rect {
        let 横の位置 = |値| {
            self.目盛り
                .値から範囲へ収めずに横の位置を求める(値)
                .eguiへ渡す値()
        };
        egui::Rect::from_x_y_ranges(
            横の位置(塊.始まり())..=横の位置(塊.終わり()),
            行の矩形.y_range(),
        )
        .shrink2(egui::vec2(0.0, 塊の上下の空き.eguiへ渡す値()))
    }
}
