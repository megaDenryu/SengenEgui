//! 時間の行の並びの配置。部品が確保した矩形を、上の時間の軸の段と、その下の行の並びに分け、値と横の位置を相互に写し、
//! 縦の位置から行を求める。行は置いた順に下から上へ積む（番号0の行がいちばん下）。後に置いたものほど手前・上に来る
//! 複数の範囲枠の重なりの順と揃え、利用する側の奥から手前の順の行の並びをそのまま渡せるようにするためである。
//! 軸の段と行の並びは確保した矩形の左右に `左右の余白` を空けた内側であり、その左端を全体の始め、右端を終わりとして写す。

use super::block::時間の塊;
use super::row_number::{時間の行の差, 時間の行の番号};
use crate::measure::{帯の値, 帯の値の差, 帯の全体の範囲, 画素, 論理画素};

/// 位置の線の頭（下向きの三角）を描き、押すと位置の線を動かす時間の軸の段の高さ。
const 軸の段の高さ: 論理画素 = 画素(14.0);
/// 1つの行の高さ。
const 行の高さ: 論理画素 = 画素(24.0);
/// 塊を行の上下の端から離して描く幅。隣の行の塊と見分けやすくする。
const 塊の上下の空き: 論理画素 = 画素(3.0);
/// 確保した矩形の左右の内側に空ける幅。全体の端にある位置の線の頭も見えるようにする。
const 左右の余白: 論理画素 = 画素(8.0);

/// 時間の行の並びの配置とは、1フレームの時間の軸の段と、行ごとの矩形（番号の順）と、全体の範囲の組のことである。
pub(super) struct 時間の行の並びの配置 {
    pub(super) 軸の段: egui::Rect,
    pub(super) 行の並びの矩形: egui::Rect,
    行の矩形一覧: Vec<egui::Rect>,
    pub(super) 全体: 帯の全体の範囲,
}

impl 時間の行の並びの配置 {
    /// 行の数の行を並べたときの部品の高さ。
    pub(super) fn 部品の高さ(行の数: usize) -> f32 {
        (0..行の数).fold(軸の段の高さ.eguiへ渡す値(), |高さ, _| {
            高さ + 行の高さ.eguiへ渡す値()
        })
    }

    /// 確保した矩形の左右に余白を空け、上から軸の段と行の並びに分け、行の並びを下から行の数だけ区切る。
    pub(super) fn 確保した矩形を分ける(
        確保した矩形: egui::Rect,
        全体: 帯の全体の範囲,
        行の数: usize,
    ) -> Self {
        let 矩形 = 確保した矩形.shrink2(egui::vec2(左右の余白.eguiへ渡す値(), 0.0));
        let 境目 = 矩形.top() + 軸の段の高さ.eguiへ渡す値();
        let 行の並びの矩形 = egui::Rect::from_x_y_ranges(矩形.x_range(), 境目..=矩形.bottom());
        let 高さ = 行の高さ.eguiへ渡す値();
        let 行の矩形一覧 = (0..行の数)
            .scan(行の並びの矩形.bottom(), |下端, _| {
                let 上端 = *下端 - 高さ;
                let 行 = egui::Rect::from_x_y_ranges(矩形.x_range(), 上端..=*下端);
                *下端 = 上端;
                Some(行)
            })
            .collect();
        Self {
            軸の段: egui::Rect::from_x_y_ranges(矩形.x_range(), 矩形.top()..=境目),
            行の並びの矩形,
            行の矩形一覧,
            全体,
        }
    }

    /// 番号の行の矩形。並びに無い番号なら None を返す。
    pub(super) fn 行の矩形(&self, 番号: 時間の行の番号) -> Option<egui::Rect> {
        self.行の矩形一覧.get(番号.置いた順の番号()).copied()
    }

    /// 番号の順（下から上）の行の矩形。
    pub(super) fn 行の矩形を巡る(&self) -> impl Iterator<Item = egui::Rect> + '_ {
        self.行の矩形一覧.iter().copied()
    }

    /// 行の矩形の中に塊を描く矩形。全体の範囲の外にある部分は、全体の端より外の横の位置になる。
    pub(super) fn 塊の矩形(&self, 行の矩形: egui::Rect, 塊: 時間の塊) -> egui::Rect {
        let 横 = self.範囲へ収めない横の位置(塊.始まり())
            ..=self.範囲へ収めない横の位置(塊.終わり());
        egui::Rect::from_x_y_ranges(横, 行の矩形.y_range())
            .shrink2(egui::vec2(0.0, 塊の上下の空き.eguiへ渡す値()))
    }

    /// 値を描く横の位置。全体の範囲の外の値は端に描く。
    pub(super) fn 値の横の位置(&self, 値: 帯の値) -> f32 {
        let 割合 = self.全体.割合へ写す(値);
        割合.二つの値の間を取る(self.行の並びの矩形.left(), self.行の並びの矩形.right())
    }

    /// 横の位置が指す値。全体の範囲の外の位置は全体の端の値にする。
    pub(super) fn 横の位置の値(&self, 横の位置: f32) -> 帯の値 {
        let 始めからの差 = self.横の移動量の値の差(横の位置 - self.行の並びの矩形.left());
        self.全体.内側へ収める(self.全体.始め() + 始めからの差)
    }

    /// 横の移動量が表す値の差。
    pub(super) fn 横の移動量の値の差(&self, 移動量: f32) -> 帯の値の差 {
        let 幅 = f64::from(self.行の並びの矩形.width());
        let 比 = if 幅 > 0.0 {
            f64::from(移動量) / 幅
        } else {
            0.0
        };
        self.全体.長さ() * 比
    }

    /// 縦の位置にある行の番号から、開始の行の番号を引いた差。行の並びの外は、行がそこまで続いているとみなして数える。
    pub(super) fn 縦の位置の行の差(
        &self,
        開始の行: 時間の行の番号,
        縦の位置: f32,
    ) -> 時間の行の差 {
        let 下からの行 =
            ((self.行の並びの矩形.bottom() - 縦の位置) / 行の高さ.eguiへ渡す値()).floor();
        let 今の行 = <i32 as egui::emath::Numeric>::from_f64(f64::from(下からの行));
        let 開始 = i32::try_from(開始の行.置いた順の番号()).unwrap_or(i32::MAX);
        時間の行の差::上へ動かした行の数から生成する(
            今の行.saturating_sub(開始),
        )
    }

    /// 値を描く横の位置を、全体の範囲の外の値も端へ収めずに求める。塊と塊の中の境目に使う。
    pub(super) fn 範囲へ収めない横の位置(&self, 値: 帯の値) -> f32 {
        let 左端 = f64::from(self.行の並びの矩形.left());
        let 比 =
            (値 - self.全体.始め()).倍精度の小数にする() / self.全体.長さ().倍精度の小数にする();
        論理画素::倍精度の小数から生成する(
            左端 + 比 * f64::from(self.行の並びの矩形.width()),
        )
        .eguiへ渡す値()
    }
}
