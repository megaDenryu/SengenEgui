//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴んだものと開始点を、放すまでフレームをまたいで保ち、
//! 掴み始めた後のフレームごとに、記憶とそのフレームのドラッグの様子から発する出来事と次の記憶を決める。
//! 塊の記憶の読み方は `hold_block`、位置の線の記憶の読み方は `hold_position` に書き、ここではその結果を出来事と
//! 次の記憶へ包む。

use super::event::読み取った出来事;
use super::hit::画面上の塊の並び;
use super::hold_block::{塊のドラッグの1フレーム, 塊を掴んでいる間の記憶};
use super::hold_position::{
    位置の線のドラッグの1フレーム, 位置の線を掴んでいる間の記憶
};
use super::layout::時間の行の並びの配置;
use super::operation::時間の塊の操作;
use super::時間の塊の鍵;
use crate::tree::input::pointer_drag::{ドラッグの段階, 掴んでいる間に置く記憶};

// 掴んでいる間の記憶とは、ドラッグを始めたときに決まる掴んだものごとの記憶の区別のことである。
#[derive(Clone)]
pub(super) enum 掴んでいる間の記憶<鍵> {
    塊(塊を掴んでいる間の記憶<鍵>),
    位置の線(位置の線を掴んでいる間の記憶),
}

impl<鍵: 時間の塊の鍵> 掴んでいる間に置く記憶 for 掴んでいる間の記憶<鍵> {
    const 記憶の名前: &'static str = "時間の行の並びの掴んでいる間の記憶";
}

// 掴んだ後のフレームを読んだ結果とは、このフレームで発する出来事と、次のフレームへ持ち越す記憶（ドラッグを終えたなら無し）の組のことである。
pub(super) struct 掴んだ後のフレームを読んだ結果<鍵> {
    pub(super) 出来事一覧: Vec<読み取った出来事<鍵>>,
    pub(super) 次の記憶: Option<掴んでいる間の記憶<鍵>>,
}

impl<鍵: 時間の塊の鍵> 掴んでいる間の記憶<鍵> {
    // 掴み始めた後の1フレームを、そのフレームのポインタの座標とドラッグの段階から読む。
    pub(super) fn 掴んだ後のフレームを読む(
        self,
        ポインタの座標: Option<egui::Pos2>,
        段階: ドラッグの段階,
        配置: &時間の行の並びの配置,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 掴んだ後のフレームを読んだ結果<鍵> {
        match self {
            Self::塊(記憶) => Self::塊の操作へ包む(
                記憶.鍵.clone(),
                記憶.掴んだ後のフレームを読む(ポインタの座標, 段階, 塊の並び),
            ),
            Self::位置の線(記憶) => Self::位置の線の操作へ包む(
                記憶.掴んだ後のフレームを読む(ポインタの座標, 段階, 配置.目盛り),
            ),
        }
    }

    fn 塊の操作へ包む(
        鍵: 鍵,
        フレーム: 塊のドラッグの1フレーム<鍵>,
    ) -> 掴んだ後のフレームを読んだ結果<鍵> {
        let (操作, 次の記憶) = match フレーム {
            塊のドラッグの1フレーム::続ける {
                開始点からの移動量,
                次の記憶,
            } => (
                Some(時間の塊の操作::動かしている {
                    開始点からの移動量
                }),
                Some(Self::塊(次の記憶)),
            ),
            塊のドラッグの1フレーム::放した {
                開始点からの移動量
            } => (
                Some(時間の塊の操作::放した {
                    開始点からの移動量
                }),
                None,
            ),
            塊のドラッグの1フレーム::掴んだ塊が無くなった => {
                (Some(時間の塊の操作::掴んだ塊が無くなった), None)
            }
            塊のドラッグの1フレーム::放したと判定できずに終わった => {
                (None, None)
            }
        };
        掴んだ後のフレームを読んだ結果 {
            出来事一覧: 操作
                .map(|操作| 読み取った出来事::塊の操作(鍵, 操作))
                .into_iter()
                .collect(),
            次の記憶,
        }
    }

    fn 位置の線の操作へ包む(
        フレーム: 位置の線のドラッグの1フレーム,
    ) -> 掴んだ後のフレームを読んだ結果<鍵> {
        let (操作, 次の記憶) = match フレーム {
            位置の線のドラッグの1フレーム::続ける {
                動かしている,
                次の記憶,
            } => (動かしている, Some(Self::位置の線(次の記憶))),
            位置の線のドラッグの1フレーム::終える { 放した } => {
                (Some(放した), None)
            }
        };
        掴んだ後のフレームを読んだ結果 {
            出来事一覧: 操作
                .map(読み取った出来事::位置の線の操作)
                .into_iter()
                .collect(),
            次の記憶,
        }
    }
}
