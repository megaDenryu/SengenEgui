//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴んだものと開始点を、放すまでフレームをまたいで保ち、
//! 掴み始めた後のフレームごとに、記憶とそのフレームのドラッグの様子から発する出来事と次の記憶を決める。
//! 塊の掴んだ後のフレームの読み方は `hold_block` に書く。位置の線は、区間の帯の位置の印と共有する `横に動かす値の記憶` で読み、
//! ポインタの横の位置の値（その回の目盛りで求め、全体の範囲へ収める）を運ぶ。

use super::hit::画面上の塊の並び;
use super::hold_block::塊を掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::operation::{位置の線の操作, 時間の塊の操作};
use super::row_number::時間の行の番号;
use super::時間の塊の鍵;
use crate::measure::論理画素;
use crate::tree::input::horizontal_drag::{
    横に動かす値の出来事, 横に動かす値の記憶
};
use crate::tree::input::pointer_drag::ドラッグの段階;

// 読み取った出来事とは、1フレームのドラッグの読み取りが見つけた、塊の操作と位置の線の操作と、何も無い所を押したこと
// （行の上なら押した行の番号を持つ）の区別のことである。
pub(super) enum 読み取った出来事<鍵> {
    塊の操作(鍵, 時間の塊の操作),
    位置の線の操作(位置の線の操作),
    何も無い所を押した { 行: Option<時間の行の番号> },
}

// 掴んでいる間の記憶とは、ドラッグを始めたときに決まる掴んだものごとの記憶の区別のことである。
#[derive(Clone)]
pub(super) enum 掴んでいる間の記憶<鍵> {
    塊(塊を掴んでいる間の記憶<鍵>),
    位置の線(横に動かす値の記憶),
}

// ドラッグの今の様子とは、掴み始めた後の1フレームの、ポインタの座標とドラッグの段階の組のことである。
#[derive(Clone, Copy)]
pub(super) struct ドラッグの今の様子 {
    pub(super) ポインタの座標: Option<egui::Pos2>,
    pub(super) 段階: ドラッグの段階,
}

// 掴んだ後のフレームを読んだ結果とは、このフレームで発する出来事と、次のフレームへ持ち越す記憶（ドラッグを終えたなら無し）の組のことである。
pub(super) struct 掴んだ後のフレームを読んだ結果<鍵> {
    pub(super) 出来事一覧: Vec<読み取った出来事<鍵>>,
    pub(super) 次の記憶: Option<掴んでいる間の記憶<鍵>>,
}

impl<鍵: 時間の塊の鍵> 掴んでいる間の記憶<鍵> {
    // 掴み始めた後の1フレームの掴んだ後のフレームを読む。
    pub(super) fn 掴んだ後のフレームを読む(
        self,
        様子: ドラッグの今の様子,
        配置: &時間の行の並びの配置,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 掴んだ後のフレームを読んだ結果<鍵> {
        match self {
            Self::塊(記憶) => 記憶.掴んだ後のフレームを読む(様子, 塊の並び),
            Self::位置の線(記憶) => {
                let 目盛り = 配置.目盛り;
                let 結果 = 記憶.掴んだ後のフレームを読む(
                    様子.ポインタの座標.map(|座標| 論理画素::生成する(座標.x)),
                    様子.段階,
                    |_, 今の横の位置| 目盛り.横の位置から値を求める(今の横の位置),
                );
                let 操作 = 結果.出来事.map(|出来事| match 出来事 {
                    横に動かす値の出来事::動かしている(値) => {
                        位置の線の操作::動かしている { 値 }
                    }
                    横に動かす値の出来事::放した(値) => {
                        位置の線の操作::放した { 値 }
                    }
                });
                掴んだ後のフレームを読んだ結果 {
                    出来事一覧: 操作
                        .map(読み取った出来事::位置の線の操作)
                        .into_iter()
                        .collect(),
                    次の記憶: 結果.次の記憶.map(Self::位置の線),
                }
            }
        }
    }
}
