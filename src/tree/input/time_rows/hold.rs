//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴んだものと開始点を、放すまでフレームをまたいで保ち、
//! 掴み始めた後のフレームごとに、記憶とそのフレームのドラッグの様子から発する出来事と次の記憶を決める。
//! 掴んだものごとの続きの読み方は、塊は `hold_block`、位置の線は `hold_position` に書く。

use super::hit::画面上の塊の並び;
use super::hold_block::塊を掴んでいる間の記憶;
use super::hold_position::位置の線を掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::operation::{位置の線の操作, 時間の塊の操作};
use super::時間の塊の鍵;

/// 読み取った出来事とは、1フレームのドラッグの読み取りが見つけた、塊の操作と位置の線の操作と、何も無い所を押したことの区別のことである。
pub(super) enum 読み取った出来事<鍵> {
    塊の操作(鍵, 時間の塊の操作),
    位置の線の操作(位置の線の操作),
    何も無い所を押した,
}

/// 掴んでいる間の記憶とは、ドラッグを始めたときに決まる掴んだものごとの記憶の区別のことである。
#[derive(Clone)]
pub(super) enum 掴んでいる間の記憶<鍵> {
    塊(塊を掴んでいる間の記憶<鍵>),
    位置の線(位置の線を掴んでいる間の記憶),
}

/// ドラッグの段階とは、掴み始めた後の1フレームで、egui のドラッグが続いているか、放したか、どちらとも判定できずに
/// 終わったか（ポインタを見失った等）の区別のことである。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum ドラッグの段階 {
    続けている,
    放した,
    放したと判定できずに終わった,
}

/// ドラッグの今の様子とは、掴み始めた後の1フレームの、ポインタの位置とドラッグの段階の組のことである。
#[derive(Clone, Copy)]
pub(super) struct ドラッグの今の様子 {
    pub(super) ポインタの位置: Option<egui::Pos2>,
    pub(super) 段階: ドラッグの段階,
}

/// 続きを読んだ結果とは、このフレームで発する出来事と、次のフレームへ持ち越す記憶（ドラッグを終えたなら無し）の組のことである。
pub(super) struct 続きを読んだ結果<鍵> {
    pub(super) 出来事一覧: Vec<読み取った出来事<鍵>>,
    pub(super) 次の記憶: Option<掴んでいる間の記憶<鍵>>,
}

impl<鍵: 時間の塊の鍵> 掴んでいる間の記憶<鍵> {
    /// 掴み始めた後の1フレームの続きを読む。
    pub(super) fn 続きを読む(
        self,
        様子: ドラッグの今の様子,
        配置: &時間の行の並びの配置,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 続きを読んだ結果<鍵> {
        match self {
            Self::塊(記憶) => 記憶.続きを読む(様子, 配置, 塊の並び),
            Self::位置の線(記憶) => 記憶.続きを読む(様子, 配置),
        }
    }
}
