//! 時間の行の並び。値の全体の範囲（時間）を横の軸にとり、その下に複数の行を置いた順に下から上へ積み、各行に時間の塊
//! （始まりと長さ）を並べる。塊を押して選び、ドラッグで横（時間）と縦（別の行）へ動かす操作と、上の時間の軸を押して
//! ドラッグすることで位置の線を動かす操作を受け付ける。区間の帯（時間の値と全体の範囲の表し方）と、複数の範囲枠
//! （鍵で覚える・選んでいるものを先に掴む・掴んだものが無くなったら知らせる・何も無い所を押したら知らせる）を合わせた部品である。
//!
//! 部品は塊の新しい始まりと行も、選択状態も、位置も状態へ書かない。発するのは、どの塊を選んだか・開始点からの累積の
//! 移動量（時間の差と行の差）・位置の線の値だけであり、ぶつかった所で止める・行の数の範囲へ収める・丸めの規則は
//! 利用する側が持つ。部品は全体で押下とドラッグを受け取る。描画と操作の読み取りの順は `draw` に書く。
//! ノードの列挙は型引数を応答しか持てないため、ノードへ変換する時点で鍵の型をクロージャへ閉じ込める（複数の範囲枠と同じ）。

