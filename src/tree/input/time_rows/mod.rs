/// 時間の行の並び型とは、時間の軸の下に積んだ行に時間の塊を並べ、塊と位置の線をドラッグで動かす部品の記述のことである。
/// 型引数の鍵は、利用する側が塊を見分ける値の型である。
pub struct 時間の行の並び型<M, 鍵> {
    全体: 帯の全体の範囲,
    行一覧: Vec<時間の行型<鍵>>,
    位置の線の値: Option<帯の値>,
    幅: 帯の幅,
    塊の操作から応答を作る: Box<dyn Fn(鍵, 時間の塊の操作) -> M>,
    位置の線の操作から応答を作る: Option<Box<dyn Fn(位置の線の操作) -> M>>,
    何も無い所を押したときの応答: Option<M>,
    行の何も無い所を押したときの応答を作る: Option<Box<dyn Fn(時間の行の番号) -> M>>,
    装飾値: スタイル,
}

impl<M, 鍵: 時間の塊の鍵> 時間の行の並び型<M, 鍵> {
    pub(crate) fn 新規(
        全体: 帯の全体の範囲,
        塊の操作から応答を作る: Box<dyn Fn(鍵, 時間の塊の操作) -> M>,
    ) -> Self {
        Self {
            全体,
            行一覧: Vec::new(),
            位置の線の値: None,
            幅: 帯の幅::使える幅いっぱい,
            塊の操作から応答を作る,
            位置の線の操作から応答を作る: None,
            何も無い所を押したときの応答: None,
            行の何も無い所を押したときの応答を作る: None,
            装飾値: スタイル::無指定,
        }
    }

    /// 行を置く。後に置いた行ほど上に描く（最初に置いた行がいちばん下で、行の番号は0）。塊の無い行も背景を描く。
    pub fn 行を置く(mut self, 行: 時間の行型<鍵>) -> Self {
        self.行一覧.push(行);
        self
    }

    /// 位置の線の値（再生の位置など）を渡す。時間の軸の領域から行の並びの下端まで縦の線を引く。渡さなければ描かない。
    pub fn 位置の線を置く(mut self, 位置の線の値: 帯の値) -> Self {
        self.位置の線の値 = Some(位置の線の値);
        self
    }

    /// 時間の軸の領域を押してドラッグしたら、位置の線の操作から応答を作って発する。指定しなければ時間の軸は押しても
    /// 何も無い所として扱う。位置の線を置いていなくても発する（押した所の値で始まる）。
    pub fn 位置の線を動かしたら発する(
        mut self,
        操作から応答を作る: impl Fn(位置の線の操作) -> M + 'static,
    ) -> Self {
        self.位置の線の操作から応答を作る = Some(Box::new(操作から応答を作る));
        self
    }

    /// 部品の中で、どの塊にも当たらない所（位置の線を動かせないときは時間の軸の領域も）を押したら、この応答を発する。
    /// 行の上を押したときは、`行の何も無い所を押したら発する` の応答より先に発する。
    pub fn 何も無い所を押したら発する(mut self, 応答: M) -> Self {
        self.何も無い所を押したときの応答 = Some(応答);
        self
    }

    /// 行の上で、どの塊にも当たらない所（塊の無い行を含む）を押したら、押した行の番号から応答を作って発する。
    /// `何も無い所を押したら発する` と独立したメソッドであり、両方を指定すると、行の上を押したときは両方の応答をその順に発する。
    /// 時間の軸の領域は行の上ではないため、この応答を発さない。
    pub fn 行の何も無い所を押したら発する(
        mut self,
        行の番号から応答を作る: impl Fn(時間の行の番号) -> M + 'static,
    ) -> Self {
        self.行の何も無い所を押したときの応答を作る = Some(Box::new(行の番号から応答を作る));
        self
    }

    /// 部品の幅を指定する。指定しなければ使える幅いっぱいに広げる。
    pub fn 幅(mut self, 幅: 論理画素) -> Self {
        self.幅 = 帯の幅::指定(幅);
        self
    }

    /// 装飾を適用する。使う項目は背景色（行の背景）・枠線色と枠線太さ（選んでいる塊の枠線）・文字色（位置の線）だけである。
    /// 指定しなければ、行の背景はテーマの窪んだ面の色、選んでいる塊の枠線はテーマの選択の縁の色で2論理画素、
    /// 位置の線はテーマの強い文字の色になる。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }
}
