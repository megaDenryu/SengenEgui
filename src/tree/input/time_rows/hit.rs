//! 画面上の塊の並びと、押した位置が何に当たったかの判定。判定の順は次のとおりである。
//! 1. 時間の軸の段: 位置の線を動かせるなら時間の軸、動かせないなら何も無い所
//! 2. 行の並びの中: 選んでいる塊、それ以外の塊の順に、どちらも後に置いた塊から調べる。どれにも当たらなければ何も無い所
//!
//! 選んでいる塊を先に掴むのは、同じ時間に重なって置かれた塊でも、選んでいる塊を動かせるようにするためである
//! （複数の範囲枠と同じ）。塊の当たりは行の高さの全体で取り、幅が `塊の当たりの最小の幅` より狭い塊は、その幅まで
//! 左右へ広げて当てる。全体に比べてごく短い塊も掴めるようにするためである。

use super::layout::時間の行の並びの配置;
use super::row::{塊の選択状態, 置いた塊};
use super::row_number::時間の行の番号;
use super::時間の塊の鍵;
use crate::measure::{画素, 論理画素};

const 塊の当たりの最小の幅: 論理画素 = 画素(6.0);

/// 画面上の塊とは、置いた塊（鍵と時間の塊と選択状態）と、行の番号と、描く矩形と当たりの矩形の組のことである。
pub(super) struct 画面上の塊<'置いた, 鍵> {
    pub(super) 行: 時間の行の番号,
    pub(super) 描く矩形: egui::Rect,
    pub(super) 置いた塊: &'置いた 置いた塊<鍵>,
    当たりの矩形: egui::Rect,
}

/// 押した所とは、押した位置が時間の行の並びのどこに当たったかの区別のことである。
pub(super) enum 押した所<'置いた, 鍵> {
    塊 {
        鍵: &'置いた 鍵,
        行: 時間の行の番号,
        選択状態: 塊の選択状態,
    },
    時間の軸,
    何も無い所,
}

/// 画面上の塊の並びとは、行の番号の順に、行の中は置いた順に並べた画面上の塊のことである。
pub(super) struct 画面上の塊の並び<'置いた, 鍵> {
    一覧: Vec<画面上の塊<'置いた, 鍵>>,
}

impl<'置いた, 鍵: 時間の塊の鍵> 画面上の塊の並び<'置いた, 鍵> {
    /// 行ごとの置いた塊を、配置の行の矩形へ写して並べる。
    pub(super) fn 行ごとの塊から作る<'行>(
        行一覧: impl Iterator<Item = &'置いた [置いた塊<鍵>]>,
        配置: &'行 時間の行の並びの配置,
    ) -> Self {
        let 一覧 = 行一覧
            .enumerate()
            .flat_map(|(番号, 塊一覧)| {
                let 行 = 時間の行の番号::置いた順の番号から生成する(番号);
                let 行の矩形 = 配置.行の矩形(行);
                塊一覧.iter().filter_map(move |置いた塊| {
                    let 行の矩形 = 行の矩形?;
                    let 描く矩形 = 配置.塊の矩形(行の矩形, 置いた塊.塊);
                    let 当たりの幅 = 描く矩形.width().max(塊の当たりの最小の幅.eguiへ渡す値());
                    let 当たりの横 =
                        egui::Rangef::point(描く矩形.center().x).expand(当たりの幅 / 2.0);
                    Some(画面上の塊 {
                        行,
                        描く矩形,
                        置いた塊,
                        当たりの矩形: egui::Rect::from_x_y_ranges(
                            当たりの横,
                            行の矩形.y_range(),
                        ),
                    })
                })
            })
            .collect();
        Self { 一覧 }
    }

    /// 置いた順の画面上の塊。描くときに使う。
    pub(super) fn 置いた順に巡る(
        &self,
    ) -> impl Iterator<Item = &画面上の塊<'置いた, 鍵>> {
        self.一覧.iter()
    }

    /// 鍵の塊を返す。並びに無い鍵なら None を返す。
    pub(super) fn 鍵の塊(&self, 探す鍵: &鍵) -> Option<&画面上の塊<'置いた, 鍵>> {
        self.一覧.iter().find(|塊| &塊.置いた塊.鍵 == 探す鍵)
    }

    /// 押した位置が何に当たったかを判定する。
    pub(super) fn 押した所を判定する(
        &self,
        配置: &時間の行の並びの配置,
        位置: egui::Pos2,
        位置の線を動かせるか: bool,
    ) -> 押した所<'置いた, 鍵> {
        if 配置.軸の段.contains(位置) {
            return if 位置の線を動かせるか {
                押した所::時間の軸
            } else {
                押した所::何も無い所
            };
        }
        let 当たった塊 = |選択状態| {
            self.一覧
                .iter()
                .rev()
                .find(|塊| 塊.置いた塊.選択状態 == 選択状態 && 塊.当たりの矩形.contains(位置))
        };
        当たった塊(塊の選択状態::選んでいる)
            .or_else(|| 当たった塊(塊の選択状態::選んでいない))
            .map_or(押した所::何も無い所, |塊| 押した所::塊 {
                鍵: &塊.置いた塊.鍵,
                行: 塊.行,
                選択状態: 塊.置いた塊.選択状態,
            })
    }
}
