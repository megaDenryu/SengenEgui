//! 位置の線を掴んでいる間の記憶。区間の帯の位置の印と同じく、ポインタの横の位置の値を全体の範囲へ収めて運び、
//! 値が変わったフレームだけ動かしているを発する。ポインタの位置が分からないフレームは最後に分かった位置を使い、
//! egui がドラッグを終えたら、放したと判定できたフレームでなくても最後に分かった位置の値で放したを発する。

use super::hold::{
    ドラッグの今の様子, ドラッグの段階, 掴んでいる間の記憶, 続きを読んだ結果, 読み取った出来事,
};
use super::layout::時間の行の並びの配置;
use super::operation::位置の線の操作;
use crate::measure::帯の値;

/// 位置の線を掴んでいる間の記憶とは、最後に分かったポインタの横の位置と、最後に発した値の組のことである。
#[derive(Clone, Copy)]
pub(super) struct 位置の線を掴んでいる間の記憶 {
    pub(super) 最後に分かった横の位置: f32,
    pub(super) 最後に発した値: 帯の値,
}

impl 位置の線を掴んでいる間の記憶 {
    pub(super) fn 続きを読む<鍵>(
        self,
        様子: ドラッグの今の様子,
        配置: &時間の行の並びの配置,
    ) -> 続きを読んだ結果<鍵> {
        let 横の位置 = 様子
            .ポインタの位置
            .map_or(self.最後に分かった横の位置, |位置| 位置.x);
        let 値 = 配置.横の位置の値(横の位置);
        if 様子.段階 != ドラッグの段階::続けている {
            let 放した = 位置の線の操作::放した { 値 };
            return 続きを読んだ結果 {
                出来事一覧: vec![読み取った出来事::位置の線の操作(放した)],
                次の記憶: None,
            };
        }
        let 動かしている = (値 != self.最後に発した値)
            .then_some(位置の線の操作::動かしている { 値 })
            .map(読み取った出来事::位置の線の操作);
        続きを読んだ結果 {
            出来事一覧: 動かしている.into_iter().collect(),
            次の記憶: Some(掴んでいる間の記憶::位置の線(Self {
                最後に分かった横の位置: 横の位置,
                最後に発した値: 値,
            })),
        }
    }
}
