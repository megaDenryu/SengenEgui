//! 位置の線を掴んでいる間の記憶。区間の帯の位置の印と共有する `横に動かす値の記憶` で横の位置を運び、掴み始めた後の
//! フレームごとに、ドラッグを続けるか終えるかと、位置の線の操作を決める。操作と次の記憶を出来事へ包むのは親（`hold`）が行う。
//!
//! 位置の線の値は、ポインタの下の値そのものであり、今のフレームの目盛りで求めて全体の範囲へ収める。押した所からの
//! 移動量を使う塊と違い、今の画面で見えている位置と線を一致させることが目的だからである。

use super::operation::位置の線の操作;
use crate::measure::論理画素;
use crate::tree::input::band_scale::帯の横の目盛り;
use crate::tree::input::horizontal_drag::{
    横に動かす値の1フレーム, 横に動かす値の記憶
};
use crate::tree::input::pointer_drag::ドラッグの段階;

// 位置の線を掴んでいる間の記憶とは、位置の線のドラッグで運ぶ横に動かす値の記憶のことである。
#[derive(Clone, Copy)]
pub(super) struct 位置の線を掴んでいる間の記憶(横に動かす値の記憶);

// 位置の線のドラッグの1フレームとは、掴み始めた後の1フレームで、ドラッグを続ける（値が変わったなら動かしているの操作と、
// 次の記憶を持つ）か、放したの操作で終えるかの区別のことである。
pub(super) enum 位置の線のドラッグの1フレーム {
    続ける {
        動かしている: Option<位置の線の操作>,
        次の記憶: 位置の線を掴んでいる間の記憶,
    },
    終える {
        放した: 位置の線の操作,
    },
}

impl 位置の線を掴んでいる間の記憶 {
    // 押した横の位置と、その位置の値から作る。
    pub(super) fn 押した横の位置から作る(
        押した横の位置: 論理画素,
        目盛り: 帯の横の目盛り,
    ) -> (Self, 位置の線の操作) {
        let 値 = 目盛り.横の位置から値を求める(押した横の位置);
        (
            Self(横に動かす値の記憶::押した横の位置から作る(押した横の位置, 値)),
            位置の線の操作::掴み始めた { 値 },
        )
    }

    pub(super) fn 掴んだ後のフレームを読む(
        self,
        ポインタの座標: Option<egui::Pos2>,
        段階: ドラッグの段階,
        今の目盛り: 帯の横の目盛り,
    ) -> 位置の線のドラッグの1フレーム {
        let 覚えた記憶 = self.0.ポインタの横の位置を覚える(
            ポインタの座標.map(|座標| 論理画素::生成する(座標.x)),
        );
        let 値 = 今の目盛り.横の位置から値を求める(覚えた記憶.最後に分かった横の位置());
        match 覚えた記憶.求めた値でこのフレームを決める(値, 段階) {
            横に動かす値の1フレーム::続ける {
                動かした値,
                次の記憶,
            } => 位置の線のドラッグの1フレーム::続ける {
                動かしている: 動かした値
                    .map(|値| 位置の線の操作::動かしている { 値 }),
                次の記憶: Self(次の記憶),
            },
            横に動かす値の1フレーム::終える { 放した値 } => {
                位置の線のドラッグの1フレーム::終える {
                    放した: 位置の線の操作::放した { 値: 放した値 },
                }
            }
        }
    }
}
