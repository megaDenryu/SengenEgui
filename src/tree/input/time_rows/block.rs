//! 時間の塊。時間の行の並びの1つの行に置く、始まりと長さで表した時間の区間であり、描くときに中を等しい長さに分ける
//! 区切りの数を持つ。長さが正で有限であることを作るときに確かめる。長さ0の塊は帯の上で掴めず、負の長さの塊は
//! 終わりが始まりより前になって描けないためである。

use std::num::NonZeroU32;

use crate::measure::{帯の値, 帯の値の差};

/// 時間の塊とは、時間の行に置く区間を、始まりの値と長さ（利用する側の単位）と、中を等しい長さに分ける数で表した値のことである。
/// 分ける数が1なら区切りの線を描かず、2以上なら分けた境目に細い線を描く（繰り返して再生する区間の周回の区切り等）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct 時間の塊 {
    始まり: 帯の値,
    長さ: 帯の値の差,
    分ける数: NonZeroU32,
}

/// 時間の塊の不正とは、時間の塊として受け取れない始まりと長さの組の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 時間の塊の不正 {
    /// 始まりか長さが無限大か NaN である。
    有限でない,
    /// 長さが0以下である。
    長さが正でない,
}

impl 時間の塊 {
    /// 始まりと長さから作る。分ける数は1（区切りの線を描かない）で始める。始まりか長さが有限でないか、長さが0以下なら理由を返す。
    pub fn 生成する(
        始まり: 帯の値, 長さ: 帯の値の差
    ) -> Result<Self, 時間の塊の不正> {
        let (始まりの数, 長さの数) = (始まり.倍精度の小数にする(), 長さ.倍精度の小数にする());
        if !始まりの数.is_finite() || !長さの数.is_finite() {
            return Err(時間の塊の不正::有限でない);
        }
        if 長さの数 <= 0.0 {
            return Err(時間の塊の不正::長さが正でない);
        }
        Ok(Self {
            始まり,
            長さ,
            分ける数: NonZeroU32::MIN,
        })
    }

    /// 塊の中を、指定の数の等しい長さに分けて描く。分けた境目（分ける数より1つ少ない）に細い線を描く。
    pub fn 等しい長さに分ける(mut self, 分ける数: NonZeroU32) -> Self {
        self.分ける数 = 分ける数;
        self
    }

    /// 始まりの値。
    pub const fn 始まり(self) -> 帯の値 {
        self.始まり
    }

    /// 終わりの値。始まりに長さを足したものである。
    pub fn 終わり(self) -> 帯の値 {
        self.始まり + self.長さ
    }

    /// 分けた境目の値を、始まりに近い方から返す。分ける数が1なら何も返さない。
    pub(super) fn 分けた境目を巡る(self) -> impl Iterator<Item = 帯の値> {
        let 分ける数 = f64::from(self.分ける数.get());
        (1..self.分ける数.get())
            .map(move |番号| self.始まり + self.長さ * (f64::from(番号) / 分ける数))
    }
}

impl std::fmt::Display for 時間の塊の不正 {
    fn fmt(&self, 出力: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::有限でない => write!(出力, "時間の塊の始まりか長さが有限でない"),
            Self::長さが正でない => write!(出力, "時間の塊の長さが0以下である"),
        }
    }
}

impl std::error::Error for 時間の塊の不正 {}
