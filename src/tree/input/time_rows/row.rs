//! 時間の行。時間の行の並びに置く1つの行の記述であり、鍵と時間の塊の組を置いた順に持つ。塊を1つも置かない行も
//! 行として描く（利用する側が、塊を取り除いて空になった行を残す使い方のため）。

use super::block::時間の塊;

// 塊の選択状態とは、置いた塊が選んでいる塊かの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum 塊の選択状態 {
    選んでいる,
    選んでいない,
}

// 置いた塊とは、塊を見分ける鍵と、時間の塊と、選択状態の組のことである。
pub(super) struct 置いた塊<鍵> {
    pub(super) 鍵: 鍵,
    pub(super) 塊: 時間の塊,
    pub(super) 選択状態: 塊の選択状態,
}

/// 時間の行型とは、時間の行の並びの1つの行に置く塊の並びの記述のことである。型引数の鍵は、利用する側が塊を見分ける値の型である。
pub struct 時間の行型<鍵> {
    pub(super) 塊一覧: Vec<置いた塊<鍵>>,
}

impl<鍵> 時間の行型<鍵> {
    pub(crate) fn 新規() -> Self {
        Self {
            塊一覧: Vec::new()
        }
    }

    /// 選んでいない塊を、鍵と時間の塊で置く。同じ行の中で塊が重なった場所では、後に置いた塊を先に掴む。
    /// 鍵は同じ時間の行の並びの中で重ねない（重ねると、鍵で探したときに先に置いた塊が見つかる）。
    pub fn 塊を置く(self, 鍵: 鍵, 塊: 時間の塊) -> Self {
        self.塊を選択状態で置く(鍵, 塊, 塊の選択状態::選んでいない)
    }

    /// 選んでいる塊を置く。選んでいる塊は強調の色と太い枠線で描き、選んでいない塊より先に掴まれる。
    /// 選んでいる塊を押しても `選んだ` は発しない。鍵と置く順の扱いは `塊を置く` と同じである。
    pub fn 選んでいる塊を置く(self, 鍵: 鍵, 塊: 時間の塊) -> Self {
        self.塊を選択状態で置く(鍵, 塊, 塊の選択状態::選んでいる)
    }

    fn 塊を選択状態で置く(
        mut self, 鍵: 鍵, 塊: 時間の塊, 選択状態: 塊の選択状態
    ) -> Self {
        self.塊一覧.push(置いた塊 {
            鍵, 塊, 選択状態
        });
        self
    }
}
