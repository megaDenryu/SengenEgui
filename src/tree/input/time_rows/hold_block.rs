//! 塊を掴んでいる間の記憶。掴んだ塊の鍵と行と開始点を保ち、続きのフレームで開始点からの累積の移動量を発する。
//! 塊は鍵で覚えるため、ドラッグの途中で塊を別の行へ置き直しても同じ塊へ操作が届く。掴んだ鍵の塊が置かれなくなったら、
//! 掴んだ塊が無くなったを発してドラッグを終える。ポインタの位置が分からないフレームは、開始点にあるとみなす（複数の範囲枠と同じ）。

use super::hit::画面上の塊の並び;
use super::hold::{
    ドラッグの今の様子, ドラッグの段階, 掴んでいる間の記憶, 続きを読んだ結果, 読み取った出来事,
};
use super::layout::時間の行の並びの配置;
use super::operation::{時間の塊の操作, 時間の塊の移動量};
use super::row_number::時間の行の番号;
use super::時間の塊の鍵;

/// 塊を掴んでいる間の記憶とは、掴んだ塊の鍵と、掴み始めたときの行と、押した位置の組のことである。
#[derive(Clone)]
pub(super) struct 塊を掴んでいる間の記憶<鍵> {
    pub(super) 鍵: 鍵,
    pub(super) 行: 時間の行の番号,
    pub(super) 開始位置: egui::Pos2,
}

impl<鍵: 時間の塊の鍵> 塊を掴んでいる間の記憶<鍵> {
    pub(super) fn 続きを読む(
        self,
        様子: ドラッグの今の様子,
        配置: &時間の行の並びの配置,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 続きを読んだ結果<鍵> {
        let 開始点からの移動量 = self.開始点からの移動量(様子, 配置);
        let (操作, 続けるか) = if 塊の並び.鍵の塊(&self.鍵).is_none() {
            (Some(時間の塊の操作::掴んだ塊が無くなった), false)
        } else {
            match 様子.段階 {
                ドラッグの段階::続けている => (
                    Some(時間の塊の操作::動かしている {
                        開始点からの移動量
                    }),
                    true,
                ),
                ドラッグの段階::放した => (
                    Some(時間の塊の操作::放した {
                        開始点からの移動量
                    }),
                    false,
                ),
                ドラッグの段階::放したと判定できずに終わった => (None, false),
            }
        };
        let 出来事一覧 = 操作
            .map(|操作| 読み取った出来事::塊の操作(self.鍵.clone(), 操作))
            .into_iter()
            .collect();
        続きを読んだ結果 {
            出来事一覧,
            次の記憶: 続けるか.then_some(掴んでいる間の記憶::塊(self)),
        }
    }

    fn 開始点からの移動量(
        &self,
        様子: ドラッグの今の様子,
        配置: &時間の行の並びの配置,
    ) -> 時間の塊の移動量 {
        let 位置 = 様子.ポインタの位置.unwrap_or(self.開始位置);
        時間の塊の移動量 {
            時間: 配置.横の移動量の値の差(位置.x - self.開始位置.x),
            行: 配置.縦の位置の行の差(self.行, 位置.y),
        }
    }
}
