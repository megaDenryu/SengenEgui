//! 塊を掴んでいる間の記憶。掴んだ塊の鍵と押した座標と、掴み始めた回の横の目盛りを保ち、掴み始めた後のフレームごとに、
//! ドラッグを続けるか終えるかと、開始点からの累積の移動量を決める。操作へ包むのは親（`hold`）が行う。
//! 時間の差は掴み始めた回の目盛りで求めるため、ドラッグの間に全体の範囲や部品の幅が変わっても膨らまない。
//! 行の差は押した座標からの縦の移動量を行の高さで割って求めるため、ドラッグの間に行の数が変わってもずれない。
//! 塊は鍵で覚えるため、ドラッグの途中で塊を別の行へ置き直しても同じ塊へ操作が届く。掴んだ鍵の塊が置かれなくなったら、
//! 掴んだ塊が無くなったとしてドラッグを終える。ポインタの座標が分からないフレームは、押した座標にあるとみなす
//! （複数の範囲枠と同じ）。

use super::hit::画面上の塊の並び;
use super::layout::行の高さ;
use super::operation::時間の塊の移動量;
use super::row_number::時間の行の差;
use super::時間の塊の鍵;
use crate::measure::論理画素;
use crate::tree::input::band_scale::帯の横の目盛り;
use crate::tree::input::pointer_drag::ドラッグの段階;

// 塊を掴んでいる間の記憶とは、掴んだ塊の鍵と、押した座標と、掴み始めた回の横の目盛りの組のことである。
#[derive(Clone)]
pub(super) struct 塊を掴んでいる間の記憶<鍵> {
    pub(super) 鍵: 鍵,
    pub(super) 押した座標: egui::Pos2,
    pub(super) 掴み始めた回の目盛り: 帯の横の目盛り,
}

// 塊のドラッグの1フレームとは、掴み始めた後の1フレームで、ドラッグを続ける（移動量と次の記憶を持つ）か、放したか、
// 掴んだ塊が無くなったか、egui が放したと判定できずにドラッグを終えたかの区別のことである。
pub(super) enum 塊のドラッグの1フレーム<鍵> {
    続ける {
        開始点からの移動量: 時間の塊の移動量,
        次の記憶: 塊を掴んでいる間の記憶<鍵>,
    },
    放した {
        開始点からの移動量: 時間の塊の移動量,
    },
    掴んだ塊が無くなった,
    放したと判定できずに終わった,
}

impl<鍵: 時間の塊の鍵> 塊を掴んでいる間の記憶<鍵> {
    pub(super) fn 掴んだ後のフレームを読む(
        self,
        ポインタの座標: Option<egui::Pos2>,
        段階: ドラッグの段階,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 塊のドラッグの1フレーム<鍵> {
        if 塊の並び.鍵の塊(&self.鍵).is_none() {
            return 塊のドラッグの1フレーム::掴んだ塊が無くなった;
        }
        let 開始点からの移動量 = self.開始点からの移動量(ポインタの座標);
        match 段階 {
            ドラッグの段階::続けている => {
                塊のドラッグの1フレーム::続ける {
                    開始点からの移動量,
                    次の記憶: self,
                }
            }
            ドラッグの段階::放した => 塊のドラッグの1フレーム::放した {
                開始点からの移動量,
            },
            ドラッグの段階::放したと判定できずに終わった => {
                塊のドラッグの1フレーム::放したと判定できずに終わった
            }
        }
    }

    fn 開始点からの移動量(
        &self,
        ポインタの座標: Option<egui::Pos2>,
    ) -> 時間の塊の移動量 {
        let 座標 = ポインタの座標.unwrap_or(self.押した座標);
        let 横の移動量 = 論理画素::生成する(座標.x - self.押した座標.x);
        let 上への移動量 = 論理画素::生成する(self.押した座標.y - 座標.y);
        時間の塊の移動量 {
            時間: self
                .掴み始めた回の目盛り
                .横の移動量から値の差を求める(横の移動量),
            行: 時間の行の差::上への移動量から求める(上への移動量, 行の高さ),
        }
    }
}
