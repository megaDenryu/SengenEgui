//! 塊を掴んでいる間の記憶。掴んだ塊の鍵と押した座標と、掴み始めた回の横の目盛りを保ち、掴んだ後のフレームで開始点からの
//! 累積の移動量を発する。時間の差は掴み始めた回の目盛りで求めるため、ドラッグの間に全体の範囲や部品の幅が変わっても
//! 膨らまない。行の差は押した座標からの縦の移動量を行の高さで割って求めるため、ドラッグの間に行の数が変わってもずれない。
//! 塊は鍵で覚えるため、ドラッグの途中で塊を別の行へ置き直しても同じ塊へ操作が届く。掴んだ鍵の塊が置かれなくなったら、
//! 掴んだ塊が無くなったを発してドラッグを終える。ポインタの座標が分からないフレームは、押した座標にあるとみなす
//! （複数の範囲枠と同じ）。egui がドラッグを放したと判定できずに終えたときは、何も発さずにドラッグを終える。

use super::hit::画面上の塊の並び;
use super::hold::{
    ドラッグの今の様子, 掴んだ後のフレームを読んだ結果, 掴んでいる間の記憶, 読み取った出来事,
};
use super::layout::行の高さ;
use super::operation::{時間の塊の操作, 時間の塊の移動量};
use super::row_number::時間の行の差;
use super::時間の塊の鍵;
use crate::measure::論理画素;
use crate::tree::input::band_scale::帯の横の目盛り;
use crate::tree::input::pointer_drag::ドラッグの段階;

// 塊を掴んでいる間の記憶とは、掴んだ塊の鍵と、押した座標と、掴み始めた回の横の目盛りの組のことである。
#[derive(Clone)]
pub(super) struct 塊を掴んでいる間の記憶<鍵> {
    pub(super) 鍵: 鍵,
    pub(super) 押した座標: egui::Pos2,
    pub(super) 掴み始めた回の目盛り: 帯の横の目盛り,
}

impl<鍵: 時間の塊の鍵> 塊を掴んでいる間の記憶<鍵> {
    pub(super) fn 掴んだ後のフレームを読む(
        self,
        様子: ドラッグの今の様子,
        塊の並び: &画面上の塊の並び<'_, 鍵>,
    ) -> 掴んだ後のフレームを読んだ結果<鍵> {
        let 開始点からの移動量 = self.開始点からの移動量(様子);
        let (操作, 続けるか) = if 塊の並び.鍵の塊(&self.鍵).is_none() {
            (Some(時間の塊の操作::掴んだ塊が無くなった), false)
        } else {
            match 様子.段階 {
                ドラッグの段階::続けている => (
                    Some(時間の塊の操作::動かしている {
                        開始点からの移動量
                    }),
                    true,
                ),
                ドラッグの段階::放した => (
                    Some(時間の塊の操作::放した {
                        開始点からの移動量
                    }),
                    false,
                ),
                ドラッグの段階::放したと判定できずに終わった => (None, false),
            }
        };
        let 出来事一覧 = 操作
            .map(|操作| 読み取った出来事::塊の操作(self.鍵.clone(), 操作))
            .into_iter()
            .collect();
        掴んだ後のフレームを読んだ結果 {
            出来事一覧,
            次の記憶: 続けるか.then_some(掴んでいる間の記憶::塊(self)),
        }
    }

    fn 開始点からの移動量(
        &self, 様子: ドラッグの今の様子
    ) -> 時間の塊の移動量 {
        let 座標 = 様子.ポインタの座標.unwrap_or(self.押した座標);
        let 横の移動量 = 論理画素::生成する(座標.x - self.押した座標.x);
        let 上への移動量 = 論理画素::生成する(self.押した座標.y - 座標.y);
        時間の塊の移動量 {
            時間: self
                .掴み始めた回の目盛り
                .横の移動量から値の差を求める(横の移動量),
            行: 時間の行の差::上への移動量から求める(上への移動量, 行の高さ),
        }
    }
}
