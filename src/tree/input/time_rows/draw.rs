//! 時間の行の並びの描画と操作の読み取りの順。場所を確保して軸と行と塊と位置の線を描き、カーソルの形を変え、
//! このフレームの出来事を読み取って応答へ変える。描いてから読み取るため、ドラッグで変わった値は次のフレームの描画に出る
//! （複数の範囲枠と同じ）。部品はドラッグだけを受けるため、egui はポインタを押した時点でドラッグを始める。
//! ノードへの変換（鍵の型をクロージャへ閉じ込める）もここに置く。

use super::drag::時間の行の並びのドラッグの読み取り手;
use super::hit::画面上の塊の並び;
use super::hold::読み取った出来事;
use super::layout::時間の行の並びの配置;
use super::paint::時間の行の並びの描き方;
use super::press::時間の軸を押したときの扱い;
use super::{時間の塊の鍵, 時間の行の並び型};
use crate::tree::input::erased::{型を消した入力型, 描画の結果};
use crate::tree::input::入力の部品;
use crate::tree::ノード;

impl<M: Clone, 鍵: 時間の塊の鍵> 時間の行の並び型<M, 鍵> {
    fn 描画する(&self, ui: &mut egui::Ui) -> 描画の結果<M> {
        let 幅 = self.幅.占める幅(ui);
        let 高さ = 時間の行の並びの配置::部品の高さ(self.行一覧.len()).eguiへ渡す値();
        let (矩形, 反応) = ui.allocate_exact_size(egui::vec2(幅, 高さ), egui::Sense::drag());
        let 配置 = 時間の行の並びの配置::確保した矩形を分ける(
            矩形,
            self.全体,
            self.行一覧.len(),
        );
        let 塊の並び = 画面上の塊の並び::行ごとの塊から作る(
            self.行一覧.iter().map(|行| 行.塊一覧.as_slice()),
            &配置,
        );
        時間の行の並びの描き方::装飾と見た目から作る(
            self.装飾値,
            ui.visuals(),
        )
        .描く(ui.painter(), &配置, &塊の並び, self.位置);
        let 読み取り手 = 時間の行の並びのドラッグの読み取り手 {
            反応: &反応,
            配置: &配置,
            塊の並び: &塊の並び,
            時間の軸を押したときの扱い: match self.位置の線の操作から応答を作る
            {
                Some(_) => 時間の軸を押したときの扱い::位置の線を動かす,
                None => 時間の軸を押したときの扱い::何も無い所とする,
            },
        };
        読み取り手.カーソルを変える(ui);
        let 発行する応答 = 読み取り手
            .出来事を読み取る(ui)
            .into_iter()
            .flat_map(|出来事| self.出来事を応答にする(出来事))
            .collect();
        描画の結果 {
            反応, 発行する応答
        }
    }

    // 出来事から発する応答。応答を作る口を指定していない出来事は何も発さず、行の上の何も無い所は2つの口の応答をその順に発する。
    fn 出来事を応答にする(&self, 出来事: 読み取った出来事<鍵>) -> Vec<M> {
        match 出来事 {
            読み取った出来事::塊の操作(鍵, 操作) => {
                vec![(self.塊の操作から応答を作る)(鍵, 操作)]
            }
            読み取った出来事::位置の線の操作(操作) => self
                .位置の線の操作から応答を作る
                .as_ref()
                .map(|応答を作る| 応答を作る(操作))
                .into_iter()
                .collect(),
            読み取った出来事::何も無い所を押した { 行 } => {
                let 行の応答 = 行.and_then(|行| {
                    self.行の何も無い所を押したときの応答を作る
                        .as_ref()
                        .map(|応答を作る| 応答を作る(行))
                });
                self.何も無い所を押したときの応答
                    .clone()
                    .into_iter()
                    .chain(行の応答)
                    .collect()
            }
        }
    }
}

impl<M: Clone + 'static, 鍵: 時間の塊の鍵> From<時間の行の並び型<M, 鍵>> for ノード<M> {
    fn from(値: 時間の行の並び型<M, 鍵>) -> Self {
        let 消去済み = 型を消した入力型::新規(Box::new(move |ui| 値.描画する(ui)));
        Self::入力(入力の部品::時間の行の並び(消去済み))
    }
}
