//! 掴み始め。押した所から、掴み始めのフレームに発する出来事と、放すまで保つ時間の行の並びを掴んでいる間の記憶を決める。
//! 選んでいない塊なら、選んだを掴み始めたより先に発する。塊の記憶には掴み始めた回の横の目盛りを入れ、ドラッグの間に
//! 全体の範囲や部品の幅が変わっても、移動量を掴み始めた回と同じ規則で時間の差へ直す。時間の軸なら押した座標の値で
//! 位置の線を掴み始める。何も無い所なら、押した行の番号を添えて何も無い所を押したことだけを発し、記憶を作らない。

use super::event::時間の行の並びで読み取った出来事;
use super::hold::時間の行の並びを掴んでいる間の記憶;
use super::hold_block::塊を掴んでいる間の記憶;
use super::hold_position::位置の線を掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::operation::時間の塊の操作;
use super::press::押した所;
use super::row::塊の選択状態;
use super::時間の塊の鍵;
use crate::measure::論理画素;

impl<鍵: 時間の塊の鍵> 押した所<'_, 鍵> {
    // 押した座標で掴み始め、このフレームの出来事と記憶を返す。
    pub(super) fn 掴み始める(
        self,
        押した座標: egui::Pos2,
        配置: &時間の行の並びの配置,
    ) -> (
        Vec<時間の行の並びで読み取った出来事<鍵>>,
        Option<時間の行の並びを掴んでいる間の記憶<鍵>>,
    ) {
        match self {
            押した所::塊 {
                鍵, 行, 選択状態
            } => {
                let 塊の操作 = |操作| {
                    時間の行の並びで読み取った出来事::塊の操作(鍵.clone(), 操作)
                };
                let 選んだ = (選択状態 == 塊の選択状態::選んでいない)
                    .then(|| 塊の操作(時間の塊の操作::選んだ));
                let 出来事一覧 = 選んだ
                    .into_iter()
                    .chain([塊の操作(時間の塊の操作::掴み始めた { 行 })])
                    .collect();
                let 記憶 = 時間の行の並びを掴んでいる間の記憶::塊(
                    塊を掴んでいる間の記憶 {
                        鍵: 鍵.clone(),
                        押した座標,
                        掴み始めた回の目盛り: 配置.目盛り,
                    },
                );
                (出来事一覧, Some(記憶))
            }
            押した所::時間の軸 => {
                let 押した横の位置 = 論理画素::生成する(押した座標.x);
                let (記憶, 掴み始めた) =
                    位置の線を掴んでいる間の記憶::押した横の位置から作る(
                        押した横の位置,
                        配置.目盛り,
                    );
                (
                    vec![
                        時間の行の並びで読み取った出来事::位置の線の操作(
                            掴み始めた,
                        ),
                    ],
                    Some(時間の行の並びを掴んでいる間の記憶::位置の線(記憶)),
                )
            }
            押した所::何も無い所 { 行 } => {
                (
                    vec![時間の行の並びで読み取った出来事::何も無い所を押した { 行 }],
                    None,
                )
            }
        }
    }
}
