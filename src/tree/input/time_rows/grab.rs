//! 掴み始め。押した所から、掴み始めのフレームに発する出来事と、放すまで保つ掴んでいる間の記憶を決める。
//! 選んでいない塊なら、選んだを掴み始めたより先に発する。時間の軸なら押した位置の値で位置の線を掴み始める。
//! 何も無い所なら、何も無い所を押したことだけを発して記憶を作らない。

use super::hit::押した所;
use super::hold::{掴んでいる間の記憶, 読み取った出来事};
use super::hold_block::塊を掴んでいる間の記憶;
use super::hold_position::位置の線を掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::operation::{位置の線の操作, 時間の塊の操作};
use super::row::塊の選択状態;
use super::時間の塊の鍵;

impl<鍵: 時間の塊の鍵> 押した所<'_, 鍵> {
    /// 押した位置で掴み始め、このフレームの出来事と記憶を返す。
    pub(super) fn 掴み始める(
        self,
        位置: egui::Pos2,
        配置: &時間の行の並びの配置,
    ) -> (Vec<読み取った出来事<鍵>>, Option<掴んでいる間の記憶<鍵>>) {
        match self {
            押した所::塊 {
                鍵, 行, 選択状態
            } => {
                let 塊の操作 = |操作| 読み取った出来事::塊の操作(鍵.clone(), 操作);
                let 選んだ = (選択状態 == 塊の選択状態::選んでいない)
                    .then(|| 塊の操作(時間の塊の操作::選んだ));
                let 出来事一覧 = 選んだ
                    .into_iter()
                    .chain([塊の操作(時間の塊の操作::掴み始めた { 行 })])
                    .collect();
                let 記憶 = 掴んでいる間の記憶::塊(塊を掴んでいる間の記憶 {
                    鍵: 鍵.clone(),
                    行,
                    開始位置: 位置,
                });
                (出来事一覧, Some(記憶))
            }
            押した所::時間の軸 => {
                let 値 = 配置.横の位置の値(位置.x);
                let 掴み始めた = 位置の線の操作::掴み始めた { 値 };
                let 記憶 =
                    掴んでいる間の記憶::位置の線(位置の線を掴んでいる間の記憶 {
                        最後に分かった横の位置: 位置.x,
                        最後に発した値: 値,
                    });
                (
                    vec![読み取った出来事::位置の線の操作(掴み始めた)],
                    Some(記憶),
                )
            }
            押した所::何も無い所 => (vec![読み取った出来事::何も無い所を押した], None),
        }
    }
}
