//! 時間の行の並びの操作の語彙。塊を選んだことと塊のドラッグの段階と掴んだ塊が無くなったことを区別する操作と、
//! 時間の軸で位置の線を動かす操作の2つがある。塊の新しい始まりと行は部品の中で計算しない。複数の範囲枠と同じく、
//! 利用する側が掴み始めたときの塊を覚えておき、開始点からの移動量から毎回計算する（ぶつかった所で止める・行の数の
//! 範囲へ収める等の規則は利用する側が持つ）。

use super::row_number::{時間の行の差, 時間の行の番号};
use crate::measure::{帯の値, 帯の値の差};

/// 時間の塊の移動量とは、塊のドラッグを始めた点からの累積の移動を、横の時間の差と縦の行の差で表した値の組のことである。
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct 時間の塊の移動量 {
    /// 横の移動を、掴み始めた回の全体の範囲と幅で直した時間の差。右向きが正で、全体の範囲へは収めていない。
    pub 時間: 帯の値の差,
    /// 押した位置から上への縦の移動を行の高さで割り、最も近い整数へ丸めた行の差。行の数の範囲へは収めていない。
    pub 行: 時間の行の差,
}

/// 時間の塊の操作とは、時間の行の並びの1つの塊について、選ぶこととドラッグの段階ごとに発する出来事の区別のことである。
/// どの塊の操作かは、操作と一緒に「操作から応答を作る関数」へ渡す、塊を置くときに渡した鍵で表す。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 時間の塊の操作 {
    /// 選んでいない塊を押した。同じフレームで、続けて掴み始めたを発する。
    選んだ,
    /// ドラッグを始めた。利用する側はこの時点の塊の始まりと行を覚える。
    掴み始めた {
        /// 掴んだ塊を置いた行の番号。
        行: 時間の行の番号,
    },
    /// ドラッグを続けている。同じフレームで掴み始めたの直後にも発する。
    動かしている {
        /// 開始点からの累積の移動量。
        開始点からの移動量: 時間の塊の移動量,
    },
    /// ドラッグを終えた。動かさずに放したときも、移動量0で発する。
    放した {
        /// 開始点からの累積の移動量。
        開始点からの移動量: 時間の塊の移動量,
    },
    /// ドラッグの途中で、掴んだ鍵の塊が置かれなくなった。部品はこのドラッグを終え、以後このドラッグの操作を発さない。
    /// 利用する側は、掴み始めたときに覚えた塊を捨てる。
    掴んだ塊が無くなった,
}

/// 位置の線の操作とは、時間の軸を押して位置の線を動かすドラッグの段階ごとに発する出来事の区別のことである。
/// 値はポインタの横の位置が指す値を全体の範囲へ収めたものであり、押した所へ線が移る（区間の帯の位置の印と同じ動き方）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 位置の線の操作 {
    /// 時間の軸を押した。値は押した位置の値である。
    掴み始めた {
        /// 押した位置の値。
        値: 帯の値,
    },
    /// 押したまま動かし、値が変わった。値が変わらないフレームでは発しない。
    動かしている {
        /// ポインタの位置の値。
        値: 帯の値,
    },
    /// 放した。値が変わっていなくても必ず発する。
    放した {
        /// 最後の値。
        値: 帯の値,
    },
}
