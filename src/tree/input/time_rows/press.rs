//! 押した所の判定。押した座標が時間の行の並びの何に当たったかを、次の順で決める。
//! 1. 時間の軸の領域: 位置の線を動かせるなら時間の軸、動かせないなら何も無い所
//! 2. 行の並びの中: 座標に当たる塊（選んでいる塊を先に調べる。`hit` に書く）。どれにも当たらなければ、
//!    押した行の番号を添えた何も無い所
//!
//! 何も無い所に行の番号を添えるのは、利用する側が塊の無い行を指して消す等の操作を受け取れるようにするためである。

use super::drag::時間の行の並びのドラッグの読み取り手;
use super::row::塊の選択状態;
use super::row_number::時間の行の番号;
use super::時間の塊の鍵;
use crate::measure::論理画素;

// 時間の軸を押したときの扱いとは、利用する側が位置の線を動かす応答を渡したかで決まる、時間の軸の領域を押したときの区別のことである。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum 時間の軸を押したときの扱い {
    位置の線を動かす,
    何も無い所とする,
}

// 押した所とは、押した座標が時間の行の並びのどこに当たったかの区別のことである。何も無い所は、行の上なら行の番号を持つ。
pub(super) enum 押した所<'置いた, 鍵> {
    塊 {
        鍵: &'置いた 鍵,
        行: 時間の行の番号,
        選択状態: 塊の選択状態,
    },
    時間の軸,
    何も無い所 {
        行: Option<時間の行の番号>,
    },
}

impl<'描画, 鍵: 時間の塊の鍵> 時間の行の並びのドラッグの読み取り手<'描画, 鍵> {
    // 押した座標が何に当たったかを判定する。
    pub(super) fn 押した所を判定する(
        &self,
        押した座標: egui::Pos2,
    ) -> 押した所<'描画, 鍵> {
        if self.配置.時間の軸の領域.contains(押した座標) {
            return match self.時間の軸を押したときの扱い {
                時間の軸を押したときの扱い::位置の線を動かす => {
                    押した所::時間の軸
                }
                時間の軸を押したときの扱い::何も無い所とする => {
                    押した所::何も無い所 { 行: None }
                }
            };
        }
        match self.塊の並び.座標に当たる塊(押した座標) {
            Some(塊) => 押した所::塊 {
                鍵: &塊.置いた塊.鍵,
                行: 塊.行,
                選択状態: 塊.置いた塊.選択状態,
            },
            None => 押した所::何も無い所 {
                行: self.配置.縦の位置を含む行(論理画素::生成する(押した座標.y)),
            },
        }
    }
}
