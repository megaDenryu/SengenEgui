//! 塊を掴んでいる間の記憶の、掴み始めた後のフレームの読み方を、ドラッグの段階ごとに確かめる。egui のドラッグを
//! 放したと判定できずに終わる回は入力の合成で作れないため、部品の外からでなく記憶の `掴んだ後のフレームを読む` メソッドを
//! 直に呼んで確かめる。

use super::block::時間の塊;
use super::event::読み取った出来事;
use super::hit::画面上の塊の並び;
use super::hold::{掴んだ後のフレームを読んだ結果, 掴んでいる間の記憶};
use super::hold_block::塊を掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::operation::時間の塊の操作;
use super::row::時間の行型;
use crate::measure::{帯の値, 帯の値の差, 帯の全体の範囲};
use crate::tree::input::pointer_drag::ドラッグの段階;

const 掴んだ塊の鍵: u8 = 1;

fn 全体() -> 帯の全体の範囲 {
    match 帯の全体の範囲::生成する(
        帯の値::倍精度の小数から生成する(0.0),
        帯の値::倍精度の小数から生成する(100.0),
    ) {
        Ok(全体) => 全体,
        Err(不正) => panic!("0〜100 は正しい全体の範囲である（到達したらバグ）: {不正}"),
    }
}

// 鍵1の塊を1つ置いた行を並べ、押した座標から右へ20論理画素動かした回を、指定の段階で読む。
fn 掴んだ後のフレームを読む(
    段階: ドラッグの段階,
) -> 掴んだ後のフレームを読んだ結果<u8> {
    let 塊 = match 時間の塊::生成する(
        帯の値::倍精度の小数から生成する(10.0),
        帯の値の差::倍精度の小数から生成する(20.0),
    ) {
        Ok(塊) => 塊,
        Err(不正) => panic!("試験の塊が不正である（到達したらバグ）: {不正}"),
    };
    let 行 = 時間の行型::新規().塊を置く(掴んだ塊の鍵, 塊);
    let 確保した矩形 = egui::Rect::from_min_size(egui::Pos2::ZERO, egui::vec2(216.0, 38.0));
    let 配置 =
        時間の行の並びの配置::確保した矩形を分ける(確保した矩形, 全体(), 1);
    let 塊の並び = 画面上の塊の並び::行ごとの塊から作る(
        std::iter::once(行.塊一覧.as_slice()),
        &配置,
    );
    let 押した座標 = egui::pos2(40.0, 26.0);
    let 記憶 = 掴んでいる間の記憶::塊(塊を掴んでいる間の記憶 {
        鍵: 掴んだ塊の鍵,
        押した座標,
        掴み始めた回の目盛り: 配置.目盛り,
    });
    記憶.掴んだ後のフレームを読む(
        Some(押した座標 + egui::vec2(20.0, 0.0)),
        段階,
        &配置,
        &塊の並び,
    )
}

fn 塊の操作一覧(
    結果: &掴んだ後のフレームを読んだ結果<u8>
) -> Vec<時間の塊の操作> {
    結果
        .出来事一覧
        .iter()
        .filter_map(|出来事| match 出来事 {
            読み取った出来事::塊の操作(_, 操作) => Some(*操作),
            _ => None,
        })
        .collect()
}

#[test]
fn 放したと判定できずに終わった回は塊の操作を発さずにドラッグを終える() {
    let 結果 = 掴んだ後のフレームを読む(ドラッグの段階::放したと判定できずに終わった);
    assert!(結果.出来事一覧.is_empty());
    assert!(結果.次の記憶.is_none());
}

#[test]
fn 放した回は放したを発してドラッグを終える() {
    let 結果 = 掴んだ後のフレームを読む(ドラッグの段階::放した);
    assert!(matches!(
        塊の操作一覧(&結果).as_slice(),
        [時間の塊の操作::放した { .. }]
    ));
    assert!(結果.次の記憶.is_none());
}

#[test]
fn 続けている回は動かしているを発して記憶を持ち越す() {
    let 結果 = 掴んだ後のフレームを読む(ドラッグの段階::続けている);
    assert!(matches!(
        塊の操作一覧(&結果).as_slice(),
        [時間の塊の操作::動かしている { .. }]
    ));
    assert!(matches!(結果.次の記憶, Some(掴んでいる間の記憶::塊(_))));
}
