//! 時間の行の並びのドラッグの読み取り。egui の反応から、押した所の判定（掴み始め）と、時間の行の並びを掴んでいる間の記憶で掴んだ後のフレームを読み、
//! そのフレームの出来事を返す。押した所の判定は `hit`、掴み始めの出来事と記憶の決め方は `grab`、カーソルの形の
//! 合わせ方は `cursor` に書く。記憶の置き場とドラッグの段階の読み方は、入力の部品が共有する `pointer_drag` による。

use super::event::時間の行の並びで読み取った出来事;
use super::hit::画面上の塊の並び;
use super::hold::時間の行の並びを掴んでいる間の記憶;
use super::layout::時間の行の並びの配置;
use super::press::時間の軸を押したときの扱い;
use super::時間の塊の鍵;
use crate::tree::input::pointer_drag::{
    ドラッグの段階, 今のポインタの座標, 掴んでいる間の記憶の置き場,
};

// 時間の行の並びのドラッグの読み取り手とは、1フレームの反応と、配置と、画面上の塊の並びと、時間の軸を押したときの扱いの組のことである。
pub(super) struct 時間の行の並びのドラッグの読み取り手<'描画, 鍵> {
    pub(super) 反応: &'描画 egui::Response,
    pub(super) 配置: &'描画 時間の行の並びの配置,
    pub(super) 塊の並び: &'描画 画面上の塊の並び<'描画, 鍵>,
    pub(super) 時間の軸を押したときの扱い: 時間の軸を押したときの扱い,
}

impl<鍵: 時間の塊の鍵> 時間の行の並びのドラッグの読み取り手<'_, 鍵> {
    // このフレームで見つけた出来事を順に返す。押した座標が分からないまま始まったドラッグは無視する。
    pub(super) fn 出来事を読み取る(
        &self,
        ui: &egui::Ui,
    ) -> Vec<時間の行の並びで読み取った出来事<鍵>> {
        let 置き場 = self.記憶の置き場();
        let mut 出来事一覧 = Vec::new();
        if let Some(押した座標) = 置き場.ドラッグを始めた回なら前の記憶を捨てて押した座標を返す(
            ui,
            self.反応,
        ) {
            let (掴み始めの出来事一覧, 記憶) = self
                .押した所を判定する(押した座標)
                .掴み始める(押した座標, self.配置);
            出来事一覧.extend(掴み始めの出来事一覧);
            if let Some(記憶) = 記憶 {
                置き場.置く(ui, 記憶);
            }
        }
        let Some(記憶) = 置き場.読む(ui) else {
            return 出来事一覧;
        };
        let 結果 = 記憶.掴んだ後のフレームを読む(
            今のポインタの座標(ui),
            ドラッグの段階::反応から読む(self.反応),
            self.配置,
            self.塊の並び,
        );
        置き場.次の記憶にする(ui, 結果.次の記憶);
        出来事一覧.extend(結果.出来事一覧);
        出来事一覧
    }

    pub(super) fn 記憶の置き場(
        &self,
    ) -> 掴んでいる間の記憶の置き場<時間の行の並びを掴んでいる間の記憶<鍵>> {
        掴んでいる間の記憶の置き場::反応から作る(self.反応)
    }
}
