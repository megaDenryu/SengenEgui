/// 入力の部品とは、操作されると応答を発する部品の区別のことである。
pub enum 入力の部品<M> {
    /// 押されると応答を発するボタン。
    ボタン(ボタン型<M>),
    /// 真偽を切り替えるチェックボックス。
    チェックボックス(チェックボックス型<M>),
    /// 1行の文字列の入力。
    一行テキスト入力(一行テキスト入力型<M>),
    /// 複数行の文字列の入力。
    複数行テキスト入力(複数行テキスト入力型<M>),
    /// 数のドラッグ入力（数の型は変換時に閉包へ閉じ込める）。
    数値入力(型を消した入力型<M>),
    /// 数のつまみ入力（数の型は変換時に閉包へ閉じ込める）。
    スライダー(型を消した入力型<M>),
    /// 排他的な選択肢の1つ。
    ラジオボタン(ラジオボタン型<M>),
    /// 選ばれている状態を面の色で示すボタン。
    選択ボタン(選択ボタン型<M>),
    /// 一覧から1つ選ぶ欄。
    選択欄(選択欄型<M>),
    /// 色の編集。
    色選択(色選択型<M>),
    /// 押されると応答を発する文字のリンク。
    リンク(リンク型<M>),
    /// 押されると応答を発する画像。
    押せる画像(押せる画像型<M>),
    /// 画像の上の矩形の枠をドラッグで動かし大きさを変える部品。
    範囲枠付き画像(範囲枠付き画像型<M>),
    /// 下地の上に置いた複数の矩形の枠を、選び、ドラッグで動かし大きさを変える部品（枠の鍵の型は変換時に閉包へ閉じ込める）。
    複数の範囲枠(型を消した入力型<M>),
    /// 値の全体の範囲の上の区間と位置を1本の帯で見せ、ドラッグで動かす部品。
    区間の帯(区間の帯型<M>),
    /// 時間の軸の下に積んだ行に時間の塊を並べ、塊と位置の線をドラッグで動かす部品（塊の鍵の型は変換時に閉包へ閉じ込める）。
    時間の行の並び(型を消した入力型<M>),
}

