/// 入力の部品とは、操作されると応答を発する部品の区別のことである。
pub enum 入力の部品<M> {
    /// 押されると応答を発するボタン。
    ボタン(ボタン型<M>),
    /// 真偽を切り替えるチェックボックス。
    チェックボックス(チェックボックス型<M>),
    /// 1行の文字列の入力。
    一行テキスト入力(一行テキスト入力型<M>),
    /// 複数行の文字列の入力。
    複数行テキスト入力(複数行テキスト入力型<M>),
    /// 数のドラッグ入力（数の型は変換時に閉包へ閉じ込める）。
    数値入力(型を消した入力型<M>),
    /// 数のつまみ入力（数の型は変換時に閉包へ閉じ込める）。
    スライダー(型を消した入力型<M>),
    /// 排他的な選択肢の1つ。
    ラジオボタン(ラジオボタン型<M>),
    /// 選ばれている状態を面の色で示すボタン。
    選択ボタン(選択ボタン型<M>),
    /// 一覧から1つ選ぶ欄。
    選択欄(選択欄型<M>),
    /// 色の編集。
    色選択(色選択型<M>),
    /// 押されると応答を発する文字のリンク。
    リンク(リンク型<M>),
}

impl<M: Clone> 入力の部品<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        match self {
            Self::ボタン(中身) => 中身.描画する(ui, 発行した応答),
            Self::チェックボックス(中身) => 中身.描画する(ui, 発行した応答),
            Self::一行テキスト入力(中身) => 中身.描画する(ui, 発行した応答),
            Self::複数行テキスト入力(中身) => 中身.描画する(ui, 発行した応答),
            Self::数値入力(中身) => 中身.描画する(ui, 発行した応答),
            Self::スライダー(中身) => 中身.描画する(ui, 発行した応答),
            Self::ラジオボタン(中身) => 中身.描画する(ui, 発行した応答),
            Self::選択ボタン(中身) => 中身.描画する(ui, 発行した応答),
            Self::選択欄(中身) => 中身.描画する(ui, 発行した応答),
            Self::色選択(中身) => 中身.描画する(ui, 発行した応答),
            Self::リンク(中身) => 中身.描画する(ui, 発行した応答),
        }
    }
}

impl<M: 'static> 入力の部品<M> {
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: std::rc::Rc<dyn Fn(M) -> N>,
    ) -> 入力の部品<N> {
        use 入力の部品 as 族;
        let 変換する = &*応答を変換する;
        match self {
            Self::ボタン(中身) => 族::ボタン(中身.写す(変換する)),
            Self::チェックボックス(中身) => {
                族::チェックボックス(中身.写す(応答を変換する))
            }
            Self::一行テキスト入力(中身) => {
                族::一行テキスト入力(中身.写す(応答を変換する))
            }
            Self::複数行テキスト入力(中身) => {
                族::複数行テキスト入力(中身.写す(応答を変換する))
            }
            Self::数値入力(中身) => 族::数値入力(中身.写す(応答を変換する)),
            Self::スライダー(中身) => 族::スライダー(中身.写す(応答を変換する)),
            Self::ラジオボタン(中身) => 族::ラジオボタン(中身.写す(変換する)),
            Self::選択ボタン(中身) => 族::選択ボタン(中身.写す(変換する)),
            Self::選択欄(中身) => 族::選択欄(中身.写す(変換する)),
            Self::色選択(中身) => 族::色選択(中身.写す(応答を変換する)),
            Self::リンク(中身) => 族::リンク(中身.写す(変換する)),
        }
    }
}

