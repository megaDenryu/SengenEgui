//! 範囲枠のドラッグの読み取り。egui の反応から、掴んだ部分と開始点からの累積の移動量を読み取る。
//! 掴んだ部分と開始点はドラッグの間フレームをまたいで保つ必要があるため、入力の部品が共有する手順（`pointer_drag`）で
//! egui の一時記憶に置く。

use super::operation::{範囲枠の掴んだ部分, 範囲枠の操作};
use crate::measure::{縦横の割合の差, 論理画素};
use crate::tree::input::pointer_drag::{
    ドラッグの段階, 今のポインタの座標, 掴んでいる間の記憶の置き場,
};

/// 掴んでいる間の記憶とは、ドラッグを始めたときに決まり、放すまで変わらない値の組のことである。
#[derive(Clone, Copy)]
struct 掴んでいる間の記憶 {
    掴んだ部分: 範囲枠の掴んだ部分,
    開始位置: egui::Pos2,
}

/// 範囲枠のドラッグとは、1フレームの反応と、画面上の画像と枠の矩形の組のことである。
pub(super) struct 範囲枠のドラッグ<'反応> {
    pub(super) 反応: &'反応 egui::Response,
    pub(super) 画像の矩形: egui::Rect,
    pub(super) 枠の矩形: egui::Rect,
    pub(super) つまみの当たりの半径: 論理画素,
}

impl 範囲枠のドラッグ<'_> {
    /// このフレームで発する操作を順に返す。枠にもつまみにも当たらない位置で始めたドラッグは無視する。
    pub(super) fn 操作を読み取る(&self, ui: &egui::Ui) -> Vec<範囲枠の操作> {
        let 置き場 = self.記憶の置き場();
        let mut 操作一覧 = Vec::new();
        let 掴み始め = 置き場
            .ドラッグを始めた回なら押した座標を返す(ui, self.反応)
            .and_then(|開始位置| self.掴み始めを判定する(開始位置));
        if let Some(記憶) = 掴み始め {
            置き場.置く(ui, 記憶);
            操作一覧.push(範囲枠の操作::掴み始めた {
                掴んだ部分: 記憶.掴んだ部分,
            });
        }
        let Some(記憶) = 置き場.読む(ui) else {
            return 操作一覧;
        };
        let 現在位置 = 今のポインタの座標(ui).unwrap_or(記憶.開始位置);
        let 掴んだ部分 = 記憶.掴んだ部分;
        let 開始点からの移動量 = 縦横の割合の差::画面の移動量から作る(
            現在位置 - 記憶.開始位置,
            self.画像の矩形.size(),
        );
        match ドラッグの段階::反応から読む(self.反応) {
            ドラッグの段階::続けている => {
                操作一覧.push(範囲枠の操作::動かしている {
                    掴んだ部分,
                    開始点からの移動量,
                })
            }
            ドラッグの段階::放した => {
                置き場.捨てる(ui);
                操作一覧.push(範囲枠の操作::放した {
                    掴んだ部分,
                    開始点からの移動量,
                });
            }
            ドラッグの段階::放したと判定できずに終わった => {
                置き場.捨てる(ui)
            }
        }
        操作一覧
    }

    /// ポインタを押した位置から掴んだ部分を判定する。
    fn 掴み始めを判定する(
        &self,
        開始位置: egui::Pos2,
    ) -> Option<掴んでいる間の記憶> {
        let 掴んだ部分 = 範囲枠の掴んだ部分::位置から判定する(
            self.枠の矩形,
            開始位置,
            self.つまみの当たりの半径,
        )?;
        Some(掴んでいる間の記憶 {
            掴んだ部分,
            開始位置,
        })
    }

    /// カーソルの形を、掴んでいる間は掴んだ部分に、それ以外はポインタが乗っている部分に合わせる。
    /// 掴んでいる間に掴んだ部分を優先するのは、利用する側の規則で枠が止まりポインタが隅から外れても
    /// 形が変わらないようにするためである。
    pub(super) fn カーソルを変える(&self, ui: &egui::Ui) {
        let 掴んでいる部分 = self.記憶の置き場().読む(ui).map(|記憶| 記憶.掴んだ部分);
        let 乗っている部分 = self.反応.hover_pos().and_then(|位置| {
            範囲枠の掴んだ部分::位置から判定する(
                self.枠の矩形,
                位置,
                self.つまみの当たりの半径,
            )
        });
        if let Some(部分) = 掴んでいる部分.or(乗っている部分) {
            ui.ctx().set_cursor_icon(部分.カーソルの形());
        }
    }

    fn 記憶の置き場(
        &self,
    ) -> 掴んでいる間の記憶の置き場<掴んでいる間の記憶> {
        掴んでいる間の記憶の置き場::反応から作る(
            self.反応,
            "範囲枠の掴んでいる間の記憶",
        )
    }
}
