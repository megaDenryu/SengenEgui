//! 範囲枠のドラッグの読み取り。egui の反応から、掴んだ部分と開始点からの累積の移動量を読み取る。
//! 掴んだ部分と開始点はドラッグの間フレームをまたいで保つ必要があるため、egui の一時記憶に置く。
//! ノード木は毎フレーム捨てるため木の側には置けない。egui 自身もドラッグ中の部品を識別子で
//! 覚えているので、同じ反応の識別子から作った鍵に置く。

use super::operation::{範囲枠の掴んだ部分, 範囲枠の操作};
use crate::measure::{縦横の割合の差, 論理画素};

/// 掴んでいる間の記憶とは、ドラッグを始めたときに決まり、放すまで変わらない値の組のことである。
#[derive(Clone, Copy)]
struct 掴んでいる間の記憶 {
    掴んだ部分: 範囲枠の掴んだ部分,
    開始位置: egui::Pos2,
}

/// 範囲枠のドラッグとは、1フレームの反応と、画面上の画像と枠の矩形の組のことである。
pub(super) struct 範囲枠のドラッグ<'反応> {
    pub(super) 反応: &'反応 egui::Response,
    pub(super) 画像の矩形: egui::Rect,
    pub(super) 枠の矩形: egui::Rect,
    pub(super) つまみの当たりの半径: 論理画素,
}

impl 範囲枠のドラッグ<'_> {
    /// このフレームで発する操作を順に返す。枠にもつまみにも当たらない位置で始めたドラッグは無視する。
    pub(super) fn 操作を読み取る(&self, ui: &egui::Ui) -> Vec<範囲枠の操作> {
        let 鍵 = self.記憶の鍵();
        let mut 操作一覧 = Vec::new();
        if self.反応.drag_started() {
            ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(鍵));
            if let Some(記憶) = self.掴み始めを判定する(ui) {
                ui.data_mut(|記憶域| 記憶域.insert_temp(鍵, 記憶));
                操作一覧.push(範囲枠の操作::掴み始めた {
                    掴んだ部分: 記憶.掴んだ部分,
                });
            }
        }
        let Some(記憶) = ui.data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶>(鍵))
        else {
            return 操作一覧;
        };
        let 現在位置 = ui
            .input(|入力| 入力.pointer.latest_pos())
            .unwrap_or(記憶.開始位置);
        let 掴んだ部分 = 記憶.掴んだ部分;
        let 開始点からの移動量 = 縦横の割合の差::画面の移動量から作る(
            現在位置 - 記憶.開始位置,
            self.画像の矩形.size(),
        );
        if self.反応.dragged() && !self.反応.drag_stopped() {
            操作一覧.push(範囲枠の操作::動かしている {
                掴んだ部分,
                開始点からの移動量,
            });
            return 操作一覧;
        }
        ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(鍵));
        if self.反応.drag_stopped() {
            操作一覧.push(範囲枠の操作::放した {
                掴んだ部分,
                開始点からの移動量,
            });
        }
        操作一覧
    }

    /// ポインタを押した位置から掴んだ部分を判定する。egui はポインタが少し動いてから
    /// ドラッグの開始とするため、開始点には現在位置でなく押した位置を使う。
    fn 掴み始めを判定する(&self, ui: &egui::Ui) -> Option<掴んでいる間の記憶> {
        let 開始位置 = ui
            .input(|入力| 入力.pointer.press_origin())
            .or(self.反応.interact_pointer_pos())?;
        let 掴んだ部分 = 範囲枠の掴んだ部分::位置から判定する(
            self.枠の矩形,
            開始位置,
            self.つまみの当たりの半径,
        )?;
        Some(掴んでいる間の記憶 {
            掴んだ部分,
            開始位置,
        })
    }

    /// カーソルの形を、掴んでいる間は掴んだ部分に、それ以外はポインタが乗っている部分に合わせる。
    /// 掴んでいる間に掴んだ部分を優先するのは、利用する側の規則で枠が止まりポインタが隅から外れても
    /// 形が変わらないようにするためである。
    pub(super) fn カーソルを変える(&self, ui: &egui::Ui) {
        let 掴んでいる部分 = ui
            .data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶>(self.記憶の鍵()))
            .map(|記憶| 記憶.掴んだ部分);
        let 乗っている部分 = self.反応.hover_pos().and_then(|位置| {
            範囲枠の掴んだ部分::位置から判定する(
                self.枠の矩形,
                位置,
                self.つまみの当たりの半径,
            )
        });
        if let Some(部分) = 掴んでいる部分.or(乗っている部分) {
            ui.ctx().set_cursor_icon(部分.カーソルの形());
        }
    }

    fn 記憶の鍵(&self) -> egui::Id {
        self.反応.id.with("範囲枠の掴んでいる間の記憶")
    }
}
