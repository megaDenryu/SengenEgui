//! 範囲枠の操作の語彙。どの部分を掴んだかと、ドラッグの開始・継続・終了を区別する。
//! 枠の新しい値は部品の中で計算しない。利用する側が掴み始めたときの枠を覚えておき、
//! 開始点からの移動量から毎回計算する（最小の大きさ・画像の内側へ収める等の規則は利用する側のドメインが持つ）。

use crate::measure::{縦横の割合の差, 論理画素};

/// 範囲枠の掴んだ部分とは、ドラッグを始めた位置が枠のどこに当たったかの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 範囲枠の掴んだ部分 {
    /// 枠の内側。ドラッグで枠を動かす。
    内側,
    /// 左上の隅のつまみ。
    左上の隅,
    /// 右上の隅のつまみ。
    右上の隅,
    /// 左下の隅のつまみ。
    左下の隅,
    /// 右下の隅のつまみ。
    右下の隅,
}

/// 範囲枠の操作とは、範囲枠付き画像のドラッグの段階ごとに発する出来事の区別のことである。
/// 移動量は、ドラッグを始めた点からの累積を、画像の幅と高さを1とした割合の差で表す。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 範囲枠の操作 {
    /// ドラッグを始めた。利用する側はこの時点の枠を覚える。
    掴み始めた {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
    },
    /// ドラッグを続けている。同じフレームで掴み始めたの直後にも発する。
    動かしている {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
        /// 開始点からの累積の移動量。
        開始点からの移動量: 縦横の割合の差,
    },
    /// ドラッグを終えた。
    放した {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
        /// 開始点からの累積の移動量。
        開始点からの移動量: 縦横の割合の差,
    },
}

impl 範囲枠の掴んだ部分 {
    /// 画面上の位置が枠のどの部分に当たるかを判定する。隅のつまみを内側より優先する。
    /// 枠にもつまみにも当たらなければ None を返す。
    pub(super) fn 位置から判定する(
        枠の矩形: egui::Rect,
        位置: egui::Pos2,
        つまみの当たりの半径: 論理画素,
    ) -> Option<Self> {
        let 隅の一覧 = [
            (Self::左上の隅, 枠の矩形.left_top()),
            (Self::右上の隅, 枠の矩形.right_top()),
            (Self::左下の隅, 枠の矩形.left_bottom()),
            (Self::右下の隅, 枠の矩形.right_bottom()),
        ];
        let 半径 = つまみの当たりの半径.eguiへ渡す値();
        隅の一覧
            .into_iter()
            .find(|(_, 隅)| 隅.distance(位置) <= 半径)
            .map(|(部分, _)| 部分)
            .or_else(|| 枠の矩形.contains(位置).then_some(Self::内側))
    }

    /// この部分の上にポインタがあるときに出すカーソルの形。
    pub(super) fn カーソルの形(self) -> egui::CursorIcon {
        match self {
            Self::内側 => egui::CursorIcon::Move,
            Self::左上の隅 | Self::右下の隅 => egui::CursorIcon::ResizeNwSe,
            Self::右上の隅 | Self::左下の隅 => egui::CursorIcon::ResizeNeSw,
        }
    }
}
