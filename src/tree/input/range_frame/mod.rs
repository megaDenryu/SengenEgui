//! 範囲枠付き画像。テクスチャの上に矩形の枠を重ねて描き、枠の内側のドラッグで移動を、
//! 4隅のつまみのドラッグで大きさの変更を受け付ける。枠の位置は画像に対する割合で受け取る。
//!
//! 部品は枠の新しい値を計算しない。発するのは「どの部分を掴んだか」と「開始点からの累積の移動量」
//! だけであり、新しい枠の計算（最小の大きさ・画像の内側へ収める等）は利用する側のドメインが持つ。
//! 部品に規則を持たせると、利用する側ごとに違う規則を部品の設定項目として並べることになるためである。

mod drag;
mod operation;
mod paint;

use std::rc::Rc;

pub use operation::{範囲枠の掴んだ部分, 範囲枠の操作};

use crate::measure::{割合で表した矩形, 画素, 縦横の論理画素, 論理画素};
use crate::style::スタイル;
use drag::範囲枠のドラッグ;
use paint::範囲枠の描き方;

/// 隅のつまみに当たったとみなす距離。描くつまみより少し広く取り、細かい位置合わせを要らなくする。
/// 部品は画像の周りにこの距離の余白を確保する。枠が画像の端にあるときも、隅の外側半分を掴めるようにするためである。
const つまみの当たりの半径: 論理画素 = 画素(8.0);

/// 範囲枠付き画像が、隅のつまみを掴めるよう画像の周りの上下左右に確保する余白。
/// 部品が占める大きさは、描く画像の大きさ（表示寸法へ縦横比を保って収めた大きさ）の幅と高さに、
/// それぞれこの余白の2倍を足した大きさになる。
pub const 範囲枠付き画像の周りの余白: 論理画素 = つまみの当たりの半径;

/// 範囲枠付き画像型とは、画像の上の矩形の枠をドラッグで動かし大きさを変える部品の記述のことである。
pub struct 範囲枠付き画像型<M> {
    テクスチャ: egui::TextureHandle,
    表示寸法: 縦横の論理画素,
    枠: 割合で表した矩形,
    操作から応答を作る: Box<dyn Fn(範囲枠の操作) -> M>,
    装飾値: スタイル,
}

impl<M> 範囲枠付き画像型<M> {
    pub(crate) fn 新規(
        テクスチャ: egui::TextureHandle,
        表示寸法: 縦横の論理画素,
        枠: 割合で表した矩形,
        操作から応答を作る: Box<dyn Fn(範囲枠の操作) -> M>,
    ) -> Self {
        Self {
            テクスチャ,
            表示寸法,
            枠,
            操作から応答を作る,
            装飾値: スタイル::無指定,
        }
    }

    /// 装飾を適用する。使う項目は枠線色（枠線とつまみの色）と枠線太さだけである。
    /// 指定しなければ、色はテーマの選択の縁の色、太さは2論理画素になる。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }

    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 部品 = egui::Image::from_texture(&self.テクスチャ)
            .fit_to_exact_size(self.表示寸法.eguiへ渡す値());
        let 大きさ = 部品.calc_size(ui.available_size(), Some(self.テクスチャ.size_vec2()));
        let 余白 = egui::Vec2::splat(範囲枠付き画像の周りの余白.eguiへ渡す値());
        let (確保した矩形, 反応) = ui.allocate_exact_size(大きさ + 余白 * 2.0, egui::Sense::drag());
        let 画像の矩形 = 確保した矩形.shrink2(余白);
        部品.paint_at(ui, 画像の矩形);
        let 枠の矩形 = self.枠.画面の矩形へ写す(画像の矩形);
        範囲枠の描き方::装飾と見た目から作る(self.装飾値, ui.visuals()).描く(
            ui.painter(),
            画像の矩形,
            枠の矩形,
        );
        let ドラッグ = 範囲枠のドラッグ {
            反応: &反応,
            画像の矩形,
            枠の矩形,
            つまみの当たりの半径,
        };
        ドラッグ.カーソルを変える(ui);
        let 操作一覧 = ドラッグ.操作を読み取る(ui);
        発行した応答.extend(操作一覧.into_iter().map(&self.操作から応答を作る));
        反応
    }
}

impl<M: 'static> 範囲枠付き画像型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 範囲枠付き画像型<N> {
        let 元の作る = self.操作から応答を作る;
        範囲枠付き画像型 {
            テクスチャ: self.テクスチャ,
            表示寸法: self.表示寸法,
            枠: self.枠,
            操作から応答を作る: Box::new(move |操作| {
                応答を変換する(元の作る(操作))
            }),
            装飾値: self.装飾値,
        }
    }
}
