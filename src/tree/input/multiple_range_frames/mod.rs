/// 複数の範囲枠が、隅のつまみを掴めるよう基準の矩形の周りの上下左右に確保する余白（8論理画素）。
/// 部品が占める大きさは、指定した寸法の幅と高さに、それぞれこの余白の2倍を足した大きさになる。
pub const 複数の範囲枠の周りの余白: 論理画素 = つまみの当たりの半径;

/// 置いた範囲枠とは、基準の矩形に対する枠の矩形と、選んでいるかと、その枠の操作から応答を作る関数の組のことである。
struct 置いた範囲枠<M> {
    矩形: 割合で表した矩形,
    選び: 枠の選び,
    操作から応答を作る: Box<dyn Fn(複数の範囲枠の操作) -> M>,
}

/// 複数の範囲枠型とは、下地の上に置いた複数の矩形の枠を、選び、ドラッグで動かし大きさを変える部品の記述のことである。
pub struct 複数の範囲枠型<M> {
    寸法: 縦横の論理画素,
    下地: Box<ノード<M>>,
    枠一覧: Vec<置いた範囲枠<M>>,
    縦横比の指定: 縦横比を保つ指定,
    装飾値: スタイル,
}

impl<M> 複数の範囲枠型<M> {
    pub(crate) fn 新規(寸法: 縦横の論理画素, 下地: ノード<M>) -> Self {
        Self {
            寸法,
            下地: Box::new(下地),
            枠一覧: Vec::new(),
            縦横比の指定: 縦横比を保つ指定::保たない,
            装飾値: スタイル::無指定,
        }
    }

    /// 選んでいない枠を、基準の矩形に対する割合で表した矩形へ置く。後に置いた枠ほど手前にあり、内側が重なった場所では先に掴まれる。
    /// この枠の操作は、この枠の `操作から応答を作る` だけへ渡る。
    pub fn 枠を置く(
        self,
        矩形: 割合で表した矩形,
        操作から応答を作る: impl Fn(複数の範囲枠の操作) -> M + 'static,
    ) -> Self {
        self.置く(矩形, 枠の選び::選んでいない, Box::new(操作から応答を作る))
    }

    /// 選んでいる枠を置く。選んでいる枠は太い枠線と4隅のつまみで描き、つまみは全部の枠の内側より先に掴まれる。
    /// 選んでいる枠を押しても `選んだ` は発しない。置く順と手前の扱いは `枠を置く` と同じである。
    pub fn 選んだ枠を置く(
        self,
        矩形: 割合で表した矩形,
        操作から応答を作る: impl Fn(複数の範囲枠の操作) -> M + 'static,
    ) -> Self {
        self.置く(矩形, 枠の選び::選んでいる, Box::new(操作から応答を作る))
    }

    fn 置く(
        mut self,
        矩形: 割合で表した矩形,
        選び: 枠の選び,
        操作から応答を作る: Box<dyn Fn(複数の範囲枠の操作) -> M>,
    ) -> Self {
        self.枠一覧.push(置いた範囲枠 {
            矩形,
            選び,
            操作から応答を作る,
        });
        self
    }

    /// 隅のつまみのドラッグで、縦横比を保つと発する。指定の修飾キー（`修飾キー::SHIFT` 等）を押している間は保たないと発する。
    /// `修飾キー::NONE` を渡すと、どの修飾キーを押していても保つと発する。指定しなければ常に保たないと発する。
    pub fn 縦横比を保つ(
        mut self, 保たない間に押す修飾キー: egui::Modifiers
    ) -> Self {
        self.縦横比の指定 =
            縦横比を保つ指定::修飾キーを押している間だけ保たない(
                保たない間に押す修飾キー,
            );
        self
    }

    /// 装飾を適用する。使う項目は枠線色（枠線とつまみの色）と枠線太さ（選んでいる枠の線の太さ）だけである。
    /// 指定しなければ、色はテーマの選択の縁の色、太さは2論理画素になる。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }
}
