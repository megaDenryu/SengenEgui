//! 複数の範囲枠。下地を描いた矩形（基準の矩形）の上に、基準の矩形に対する割合で表した枠を複数置き、押した枠を選び、
//! 枠の内側のドラッグで移動を、選んでいる枠の4隅のつまみのドラッグで大きさの変更を受け付ける。
//! 範囲枠付き画像を、1枚の画像と1つの枠から、任意の下地と複数の枠へ広げた部品であり、操作の段階と移動量の表し方を揃える。
//!
//! 部品は枠の新しい値も選びも状態へ書かない。発するのは、どの枠を選んだか・掴んだ部分・開始点からの累積の移動量・
//! 縦横比の扱いだけであり、新しい枠の計算（縦横比を保つ・最小の大きさ・基準の矩形の内側へ収める等）は利用する側が持つ。
//! 部品は余白を含む全体で押下とドラッグを受け取るため、下地の中の部品は押せない。描画と操作の読み取りの順は `draw` に、応答型の写像は `map` に書く。

