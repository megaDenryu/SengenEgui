//! 複数の範囲枠。下地を描いた矩形（基準の矩形）の上に、基準の矩形に対する割合で表した枠を複数置き、押した枠を選び、
//! 枠の内側のドラッグで移動を、選んでいる枠の4隅のつまみのドラッグで大きさの変更を受け付ける。
//! 範囲枠付き画像を、1枚の画像と1つの枠から、任意の下地と複数の枠へ広げた部品であり、操作の段階と移動量の表し方を揃える。
//!
//! 部品は枠の新しい値も選択状態も状態へ書かない。発するのは、どの枠を選んだか・掴んだ部分・開始点からの累積の移動量・
//! 縦横比の扱いだけであり、新しい枠の計算（縦横比を保つ・最小の大きさ・基準の矩形の内側へ収める等）は利用する側が持つ。
//! 枠は利用する側の鍵で見分ける。ドラッグの間も鍵で枠を探すため、利用する側が毎フレーム置く枠の並びを変えても、
//! 掴んだ枠へ操作が届く。部品は余白を含む全体で押下とドラッグを受け取るため、下地の中の部品は押せない。
//! 描画と操作の読み取りの順は `draw` に書く。ノードの列挙は型引数を応答しか持てないため、ノードへ変換する時点で
//! 鍵の型を閉包へ閉じ込める（数値入力と同じ `型を消した入力型`）。応答型の写像はその型が行う。

mod cursor;
mod drag;
mod draw;
mod hit;
mod hold;
mod operation;
mod paint;

pub use operation::{縦横比の扱い, 複数の範囲枠の操作};

use super::range_frame::つまみの当たりの半径;
use crate::measure::{割合で表した矩形, 縦横の論理画素, 論理画素};
use crate::style::スタイル;
use crate::tree::ノード;
use hit::枠の選択状態;
use operation::縦横比の扱いの決め方;

/// 複数の範囲枠が、隅のつまみを掴めるよう基準の矩形の周りの上下左右に確保する余白（8論理画素）。
/// 部品が占める大きさは、指定した寸法の幅と高さに、それぞれこの余白の2倍を足した大きさになる。
pub const 複数の範囲枠の周りの余白: 論理画素 = つまみの当たりの半径;

/// 複数の範囲枠の鍵とは、利用する側が置いた枠を見分けるための値の型が満たす条件のことである。
/// 掴んでいる間の記憶を egui の一時記憶へ置くため、複製でき、スレッドをまたいで渡せる必要がある。
pub trait 複数の範囲枠の鍵: Eq + Clone + Send + Sync + 'static {}

impl<型: Eq + Clone + Send + Sync + 'static> 複数の範囲枠の鍵 for 型 {}

/// 置いた範囲枠とは、枠を見分ける鍵と、基準の矩形に対する枠の矩形と、選択状態の組のことである。
struct 置いた範囲枠<鍵> {
    鍵: 鍵,
    矩形: 割合で表した矩形,
    選択状態: 枠の選択状態,
}

/// 複数の範囲枠型とは、下地の上に置いた複数の矩形の枠を、選んで、ドラッグで動かし大きさを変える部品の記述のことである。
/// 型引数の鍵は、利用する側が枠を見分ける値の型である。
pub struct 複数の範囲枠型<M, 鍵> {
    寸法: 縦横の論理画素,
    下地: ノード<M>,
    枠一覧: Vec<置いた範囲枠<鍵>>,
    操作から応答を作る: Box<dyn Fn(鍵, 複数の範囲枠の操作) -> M>,
    何も無い所を押したときの応答: Option<M>,
    縦横比の扱いの決め方: 縦横比の扱いの決め方,
    装飾値: スタイル,
}

impl<M, 鍵: 複数の範囲枠の鍵> 複数の範囲枠型<M, 鍵> {
    pub(crate) fn 新規(
        寸法: 縦横の論理画素,
        下地: ノード<M>,
        操作から応答を作る: Box<dyn Fn(鍵, 複数の範囲枠の操作) -> M>,
    ) -> Self {
        Self {
            寸法,
            下地,
            枠一覧: Vec::new(),
            操作から応答を作る,
            何も無い所を押したときの応答: None,
            縦横比の扱いの決め方: 縦横比の扱いの決め方::常に保たない,
            装飾値: スタイル::無指定,
        }
    }

    /// 選んでいない枠を、鍵と、基準の矩形に対する割合で表した矩形で置く。後に置いた枠ほど手前にある。
    /// 鍵は同じ部品の中で重ねない（重ねると、鍵で探したときに先に置いた枠が見つかる）。
    pub fn 枠を置く(self, 鍵: 鍵, 矩形: 割合で表した矩形) -> Self {
        self.枠を選択状態で置く(鍵, 矩形, 枠の選択状態::選んでいない)
    }

    /// 選んでいる枠を置く。選んでいる枠は太い枠線と4隅のつまみで描き、つまみと内側は選んでいない枠の内側より先に掴まれる。
    /// 選んでいる枠を押しても `選んだ` は発しない。鍵と置く順の扱いは `枠を置く` と同じである。
    pub fn 選んでいる枠を置く(self, 鍵: 鍵, 矩形: 割合で表した矩形) -> Self {
        self.枠を選択状態で置く(鍵, 矩形, 枠の選択状態::選んでいる)
    }

    fn 枠を選択状態で置く(
        mut self,
        鍵: 鍵,
        矩形: 割合で表した矩形,
        選択状態: 枠の選択状態,
    ) -> Self {
        self.枠一覧.push(置いた範囲枠 {
            鍵, 矩形, 選択状態
        });
        self
    }

    /// 部品の中で、どの枠にもつまみにも当たらない所を押したら、この応答を発する。指定しなければ何も発しない。
    pub fn 何も無い所を押したら発する(mut self, 応答: M) -> Self {
        self.何も無い所を押したときの応答 = Some(応答);
        self
    }

    /// 隅のつまみのドラッグで、縦横比を保つと発する。指定の修飾キー（`修飾キー::SHIFT` 等）を押している間は保たないと発する。
    /// `修飾キー::NONE` を渡すと、どの修飾キーを押していても保つと発する。指定しなければ常に保たないと発する。
    pub fn 縦横比を保つ(
        mut self, 保たない間に押す修飾キー: egui::Modifiers
    ) -> Self {
        self.縦横比の扱いの決め方 =
            縦横比の扱いの決め方::修飾キーを押している間だけ保たない(
                保たない間に押す修飾キー,
            );
        self
    }

    /// 装飾を適用する。使う項目は枠線色（枠線とつまみの色）と枠線太さ（選んでいる枠の線の太さ）だけである。
    /// 指定しなければ、色はテーマの選択の縁の色、太さは2論理画素になる。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }
}
