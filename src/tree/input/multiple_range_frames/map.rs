//! 複数の範囲枠の応答型の写像。下地のノードと、枠ごとの操作から応答を作る関数の両方を、親の応答型へ写す。
//! 描画（draw.rs）と写像を分けるのは、入力の族の描画（mod.rs）と写像（map.rs）を分けたのと同じ理由による。

use std::rc::Rc;

use super::{置いた範囲枠, 複数の範囲枠型};

impl<M: 'static> 複数の範囲枠型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。下地と、枠ごとの応答を作る関数の両方を写す。
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 複数の範囲枠型<N> {
        let 枠一覧 = self
            .枠一覧
            .into_iter()
            .map(|枠| -> 置いた範囲枠<N> {
                let 変換する = Rc::clone(&応答を変換する);
                let 元の作る = 枠.操作から応答を作る;
                置いた範囲枠 {
                    矩形: 枠.矩形,
                    選択状態: 枠.選択状態,
                    操作から応答を作る: Box::new(move |操作| 変換する(元の作る(操作))),
                }
            })
            .collect();
        複数の範囲枠型 {
            寸法: self.寸法,
            下地: Box::new(self.下地.rcで写す(応答を変換する)),
            枠一覧,
            縦横比の扱いの決め方: self.縦横比の扱いの決め方,
            装飾値: self.装飾値,
        }
    }
}
