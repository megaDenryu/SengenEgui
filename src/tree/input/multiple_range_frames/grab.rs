//! 複数の範囲枠の掴み始め。押した座標から掴む枠と部分を判定し、掴み始めのフレームに発する出来事と、放すまで保つ
//! 掴んでいる間の記憶を決める。選んでいない枠なら、選んだを掴み始めたより先に発する。どの枠にもつまみにも当たらなければ、
//! 何も無い所を押したことだけを発して記憶を作らない。

use super::drag::{
    複数の範囲枠で読み取った出来事, 複数の範囲枠のドラッグの読み取り手
};
use super::hold::掴んでいる間の記憶;
use super::operation::複数の範囲枠の操作;
use super::複数の範囲枠の鍵;

impl<鍵: 複数の範囲枠の鍵> 複数の範囲枠のドラッグの読み取り手<'_, 鍵> {
    // 押した座標で掴み始め、このフレームの出来事と記憶を返す。
    pub(super) fn 押した座標から掴み始める(
        &self,
        開始位置: egui::Pos2,
    ) -> (
        Vec<複数の範囲枠で読み取った出来事<鍵>>,
        Option<掴んでいる間の記憶<鍵>>,
    ) {
        let 掴み始めの記憶 = self
            .枠の並び
            .掴む枠と部分を判定する(開始位置, self.つまみの当たりの半径)
            .map(|(鍵, 掴んだ部分)| 掴んでいる間の記憶 {
                鍵: 鍵.clone(),
                掴んだ部分,
                開始位置,
            });
        match 掴み始めの記憶 {
            Some(記憶) => (self.掴み始めの出来事一覧(&記憶), Some(記憶)),
            None => (
                vec![複数の範囲枠で読み取った出来事::何も無い所を押した],
                None,
            ),
        }
    }

    // 掴み始めたフレームの出来事。選んでいない枠なら、選んだを掴み始めたより先に発する。
    fn 掴み始めの出来事一覧(
        &self,
        記憶: &掴んでいる間の記憶<鍵>,
    ) -> Vec<複数の範囲枠で読み取った出来事<鍵>> {
        let 枠の操作 = |操作| {
            複数の範囲枠で読み取った出来事::枠の操作(記憶.鍵.clone(), 操作)
        };
        let 選んだ = self
            .枠の並び
            .選んでいない枠か(&記憶.鍵)
            .then(|| 枠の操作(複数の範囲枠の操作::選んだ));
        選んだ
            .into_iter()
            .chain([枠の操作(記憶.掴み始めた操作())])
            .collect()
    }
}
