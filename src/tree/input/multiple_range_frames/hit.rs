//! 画面上の枠の並びと、押した位置からどの枠のどの部分を掴むかの判定。
//! 掴む順は次のとおりである。1. 選んでいる枠の隅のつまみ（手前の枠から） 2. 枠の内側（手前の枠から）。
//! 隅のつまみは選んでいる枠にだけ描くため、選んでいる枠にだけ当たる。つまみは全部の枠より上に描くため、
//! 手前の枠の内側と重なっていてもつまみを先に掴む。後に置いた枠ほど手前であり、内側が重なった場所では手前の枠を掴む。

use crate::measure::論理画素;
use crate::tree::input::範囲枠の掴んだ部分;

/// 枠の番号とは、置いた枠を置いた順に0から数えた番号のことである。番号が大きい枠ほど手前にある。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct 枠の番号(usize);

impl 枠の番号 {
    /// 置いた枠の並びの中の位置。
    pub(super) const fn 並びの位置(self) -> usize {
        self.0
    }
}

/// 枠の選びとは、置いた枠が選んでいる枠かの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum 枠の選び {
    選んでいる,
    選んでいない,
}

/// 画面上の枠とは、置いた枠の画面上の矩形と選びの組のことである。
#[derive(Clone, Copy)]
pub(super) struct 画面上の枠 {
    pub(super) 矩形: egui::Rect,
    pub(super) 選び: 枠の選び,
}

/// 画面上の枠の並びとは、置いた順（奥から手前）に並べた画面上の枠のことである。
pub(super) struct 画面上の枠の並び {
    一覧: Vec<画面上の枠>,
}

impl 画面上の枠の並び {
    pub(super) fn 置いた順の一覧から作る(一覧: Vec<画面上の枠>) -> Self {
        Self { 一覧 }
    }

    /// 置いた順（奥から手前）の画面上の枠。描くときに使う。
    pub(super) fn 奥から順に(&self) -> impl Iterator<Item = &画面上の枠> {
        self.一覧.iter()
    }

    /// 番号の枠を返す。並びに無い番号なら None を返す。
    pub(super) fn 番号の枠(&self, 番号: 枠の番号) -> Option<画面上の枠> {
        self.一覧.get(番号.並びの位置()).copied()
    }

    /// 押した位置から、掴む枠の番号と掴んだ部分を判定する。どの枠にもつまみにも当たらなければ None を返す。
    pub(super) fn 掴む所を判定する(
        &self,
        位置: egui::Pos2,
        つまみの当たりの半径: 論理画素,
    ) -> Option<(枠の番号, 範囲枠の掴んだ部分)> {
        let 手前から順に = || self.一覧.iter().enumerate().rev();
        let 選んでいる枠の隅 = 手前から順に()
            .filter(|(_, 枠)| 枠.選び == 枠の選び::選んでいる)
            .find_map(|(位置の番号, 枠)| {
                範囲枠の掴んだ部分::隅のつまみから判定する(
                    枠.矩形,
                    位置,
                    つまみの当たりの半径,
                )
                .map(|部分| (枠の番号(位置の番号), 部分))
            });
        選んでいる枠の隅.or_else(|| {
            手前から順に()
                .find(|(_, 枠)| 枠.矩形.contains(位置))
                .map(|(位置の番号, _)| (枠の番号(位置の番号), 範囲枠の掴んだ部分::内側))
        })
    }
}
