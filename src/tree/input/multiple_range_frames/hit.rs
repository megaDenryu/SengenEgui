//! 画面上の枠の並びと、押した位置からどの枠のどの部分を掴むかの判定。
//! 掴む順は次のとおりである。1. 選んでいる枠の隅のつまみ 2. 選んでいる枠の内側 3. それ以外の枠の内側。どの段も手前の枠から調べる。
//! 隅のつまみは選んでいる枠にだけ描くため、選んでいる枠にだけ当たる。つまみは全部の枠より上に描くため、
//! 手前の枠の内側と重なっていてもつまみを先に掴む。選んでいる枠の内側を先に掴むのは、同じ大きさの枠が重なっていても、
//! 選んでいる奥の枠を動かせるようにするためである。選んでいない枠どうしが重なった場所では手前の枠を掴む。

use super::複数の範囲枠の鍵;
use crate::measure::論理画素;
use crate::tree::input::範囲枠の掴んだ部分;

/// 枠の選択状態とは、置いた枠が選んでいる枠かの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum 枠の選択状態 {
    選んでいる,
    選んでいない,
}

/// 画面上の枠とは、置いた枠の鍵と、画面上の矩形と、選択状態の組のことである。
pub(super) struct 画面上の枠<'置いた枠, 鍵> {
    pub(super) 鍵: &'置いた枠 鍵,
    pub(super) 矩形: egui::Rect,
    pub(super) 選択状態: 枠の選択状態,
}

/// 画面上の枠の並びとは、置いた順（奥から手前）に並べた画面上の枠のことである。
pub(super) struct 画面上の枠の並び<'置いた枠, 鍵> {
    一覧: Vec<画面上の枠<'置いた枠, 鍵>>,
}

impl<'置いた枠, 鍵: 複数の範囲枠の鍵> 画面上の枠の並び<'置いた枠, 鍵> {
    pub(super) fn 置いた順の一覧から作る(
        一覧: Vec<画面上の枠<'置いた枠, 鍵>>
    ) -> Self {
        Self { 一覧 }
    }

    /// 置いた順（奥から手前）の画面上の枠。描くときに使う。
    pub(super) fn 奥から手前の順に枠を巡る(
        &self,
    ) -> impl Iterator<Item = &画面上の枠<'置いた枠, 鍵>> {
        self.一覧.iter()
    }

    /// 鍵の枠を返す。並びに無い鍵なら None を返す。
    pub(super) fn 鍵の枠(
        &self, 探す鍵: &鍵
    ) -> Option<&画面上の枠<'置いた枠, 鍵>> {
        self.一覧.iter().find(|枠| 枠.鍵 == 探す鍵)
    }

    /// 鍵の枠が並びにあって、選んでいない枠か。
    pub(super) fn 選んでいない枠か(&self, 探す鍵: &鍵) -> bool {
        self.鍵の枠(探す鍵)
            .is_some_and(|枠| 枠.選択状態 == 枠の選択状態::選んでいない)
    }

    /// 押した位置から、掴む枠の鍵と掴んだ部分を判定する。どの枠にもつまみにも当たらなければ None を返す。
    pub(super) fn 掴む枠と部分を判定する(
        &self,
        位置: egui::Pos2,
        つまみの当たりの半径: 論理画素,
    ) -> Option<(&'置いた枠 鍵, 範囲枠の掴んだ部分)> {
        let 選んでいる枠を手前から = || {
            self.一覧
                .iter()
                .rev()
                .filter(|枠| 枠.選択状態 == 枠の選択状態::選んでいる)
        };
        let 隅のつまみ = 選んでいる枠を手前から().find_map(|枠| {
            範囲枠の掴んだ部分::隅のつまみから判定する(
                枠.矩形,
                位置,
                つまみの当たりの半径,
            )
            .map(|部分| (枠.鍵, 部分))
        });
        let 内側を掴む = |枠: &&画面上の枠<'置いた枠, 鍵>| 枠.矩形.contains(位置);
        隅のつまみ
            .or_else(|| {
                選んでいる枠を手前から()
                    .find(内側を掴む)
                    .map(|枠| (枠.鍵, 範囲枠の掴んだ部分::内側))
            })
            .or_else(|| {
                self.一覧
                    .iter()
                    .rev()
                    .find(内側を掴む)
                    .map(|枠| (枠.鍵, 範囲枠の掴んだ部分::内側))
            })
    }
}
