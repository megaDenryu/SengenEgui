//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴んだ枠の鍵と部分と開始点を、放すまでフレームをまたいで保つ。
//! 記憶から段階ごとの操作を作ること（開始点からの累積の移動量を、基準の矩形の幅と高さを1とした割合の差へ直す）もここに置く。

use super::operation::{
    縦横比の扱い, 縦横比の扱いの決め方, 複数の範囲枠の操作
};
use super::複数の範囲枠の鍵;
use crate::measure::縦横の割合の差;
use crate::tree::input::pointer_drag::{
    今のポインタの座標, 掴んでいる間に置く記憶
};
use crate::tree::input::範囲枠の掴んだ部分;

// 掴んでいる間の記憶とは、ドラッグを始めたときに決まり、放すまで変わらない、掴んだ枠の鍵と部分と開始点の組のことである。
#[derive(Clone)]
pub(super) struct 掴んでいる間の記憶<鍵> {
    pub(super) 鍵: 鍵,
    pub(super) 掴んだ部分: 範囲枠の掴んだ部分,
    pub(super) 開始位置: egui::Pos2,
}

// 複数の範囲枠のドラッグの今の様子とは、掴み始めた後の1フレームで、ポインタの位置と基準の矩形の大きさと縦横比の扱いの組のことである。
#[derive(Clone, Copy)]
pub(super) struct 複数の範囲枠のドラッグの今の様子 {
    pub(super) 現在位置: egui::Pos2,
    pub(super) 基準の大きさ: egui::Vec2,
    pub(super) 縦横比の扱い: 縦横比の扱い,
}

impl 複数の範囲枠のドラッグの今の様子 {
    // このフレームの入力から読む。ポインタの位置が分からないフレームは、開始点にあるとみなす。
    pub(super) fn 入力から読む(
        ui: &egui::Ui,
        開始位置: egui::Pos2,
        基準の矩形: egui::Rect,
        縦横比の扱いの決め方: 縦横比の扱いの決め方,
    ) -> Self {
        let 押している修飾キー = ui.input(|入力| 入力.modifiers);
        Self {
            現在位置: 今のポインタの座標(ui).unwrap_or(開始位置),
            基準の大きさ: 基準の矩形.size(),
            縦横比の扱い: 縦横比の扱いの決め方.扱いを決める(押している修飾キー),
        }
    }
}

impl<鍵: 複数の範囲枠の鍵> 掴んでいる間に置く記憶 for 掴んでいる間の記憶<鍵> {
    const 記憶の名前: &'static str = "複数の範囲枠の掴んでいる間の記憶";
}

impl<鍵> 掴んでいる間の記憶<鍵> {
    pub(super) fn 掴み始めた操作(&self) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::掴み始めた {
            掴んだ部分: self.掴んだ部分,
        }
    }

    pub(super) fn 動かしている操作(
        &self,
        様子: 複数の範囲枠のドラッグの今の様子,
    ) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::動かしている {
            掴んだ部分: self.掴んだ部分,
            開始点からの移動量: self.開始点からの移動量(様子),
            縦横比の扱い: 様子.縦横比の扱い,
        }
    }

    pub(super) fn 放した操作(
        &self,
        様子: 複数の範囲枠のドラッグの今の様子,
    ) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::放した {
            掴んだ部分: self.掴んだ部分,
            開始点からの移動量: self.開始点からの移動量(様子),
            縦横比の扱い: 様子.縦横比の扱い,
        }
    }

    fn 開始点からの移動量(
        &self,
        様子: 複数の範囲枠のドラッグの今の様子,
    ) -> 縦横の割合の差 {
        縦横の割合の差::画面の移動量から作る(
            様子.現在位置 - self.開始位置,
            様子.基準の大きさ,
        )
    }
}
