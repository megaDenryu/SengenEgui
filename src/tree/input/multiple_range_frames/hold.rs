//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴んだ枠と部分と開始点を、放すまでフレームをまたいで保つ。
//! 記憶から段階ごとの操作を作ること（開始点からの累積の移動量を、基準の矩形の幅と高さを1とした割合の差へ直す）もここに置く。

use super::hit::枠の番号;
use super::operation::{縦横比の扱い, 複数の範囲枠の操作};
use crate::measure::縦横の割合の差;
use crate::tree::input::範囲枠の掴んだ部分;

/// 掴んでいる間の記憶とは、ドラッグを始めたときに決まり、放すまで変わらない、掴んだ枠と部分と開始点の組のことである。
#[derive(Clone, Copy)]
pub(super) struct 掴んでいる間の記憶 {
    pub(super) 枠: 枠の番号,
    pub(super) 掴んだ部分: 範囲枠の掴んだ部分,
    pub(super) 開始位置: egui::Pos2,
}

/// ドラッグの今の様子とは、掴み始めた後の1フレームで、ポインタの位置と基準の矩形の大きさと縦横比の扱いの組のことである。
#[derive(Clone, Copy)]
pub(super) struct ドラッグの今の様子 {
    pub(super) 現在位置: egui::Pos2,
    pub(super) 基準の大きさ: egui::Vec2,
    pub(super) 縦横比の扱い: 縦横比の扱い,
}

impl 掴んでいる間の記憶 {
    pub(super) fn 掴み始めた操作(self) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::掴み始めた {
            掴んだ部分: self.掴んだ部分,
        }
    }

    pub(super) fn 動かしている操作(
        self,
        様子: ドラッグの今の様子,
    ) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::動かしている {
            掴んだ部分: self.掴んだ部分,
            開始点からの移動量: self.開始点からの移動量(様子),
            縦横比の扱い: 様子.縦横比の扱い,
        }
    }

    pub(super) fn 放した操作(
        self, 様子: ドラッグの今の様子
    ) -> 複数の範囲枠の操作 {
        複数の範囲枠の操作::放した {
            掴んだ部分: self.掴んだ部分,
            開始点からの移動量: self.開始点からの移動量(様子),
            縦横比の扱い: 様子.縦横比の扱い,
        }
    }

    fn 開始点からの移動量(
        self, 様子: ドラッグの今の様子
    ) -> 縦横の割合の差 {
        縦横の割合の差::画面の移動量から作る(
            様子.現在位置 - self.開始位置,
            様子.基準の大きさ,
        )
    }
}
