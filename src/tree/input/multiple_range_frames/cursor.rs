//! 複数の範囲枠のカーソルの形。掴んでいる間は掴んだ部分の形に、それ以外はポインタが乗っている部分の形にして、
//! 押す前に何を掴むかを見せる。掴んでいる間に掴んだ部分を優先するのは、利用する側の規則で枠が止まり、
//! ポインタが隅から外れても形が変わらないようにするためである（範囲枠付き画像と同じ）。

use super::drag::複数の範囲枠のドラッグの読み取り手;
use super::hold::掴んでいる間の記憶;
use super::複数の範囲枠の鍵;

impl<鍵: 複数の範囲枠の鍵> 複数の範囲枠のドラッグの読み取り手<'_, 鍵> {
    /// カーソルの形を、掴んでいる間は掴んだ部分に、それ以外はポインタが乗っている部分に合わせる。
    pub(super) fn カーソルを変える(&self, ui: &egui::Ui) {
        let 掴んでいる部分 = ui
            .data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶<鍵>>(self.記憶の識別子()))
            .map(|記憶| 記憶.掴んだ部分);
        let 乗っている部分 = self.反応.hover_pos().and_then(|位置| {
            self.枠の並び
                .掴む枠と部分を判定する(位置, self.つまみの当たりの半径)
                .map(|(_, 部分)| 部分)
        });
        if let Some(部分) = 掴んでいる部分.or(乗っている部分) {
            ui.ctx().set_cursor_icon(部分.カーソルの形());
        }
    }
}
