//! 複数の範囲枠の操作の語彙。枠を選んだことと、ドラッグの開始・継続・終了を区別する。どの枠の操作かは、
//! 枠を置くときに渡した「操作から応答を作る関数」がどれかで表す（その枠の関数だけが呼ばれる）。
//! 枠の新しい値は部品の中で計算しない。範囲枠付き画像と同じく、利用する側が掴み始めたときの枠を覚えておき、
//! 開始点からの移動量から毎回計算する（縦横比を保つ・最小の大きさ・基準の矩形の内側へ収める等の規則は利用する側が持つ）。

use crate::measure::縦横の割合の差;
use crate::tree::input::範囲枠の掴んだ部分;

/// 縦横比の扱いとは、隅のつまみで大きさを変えるときに、利用する側が枠の縦横比を保つべきかの区別のことである。
/// 部品は縦横比を保つ指定と押している修飾キーから決めて発するだけで、保った大きさは利用する側が計算する。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 縦横比の扱い {
    /// 縦横比を保って大きさを変える。
    保つ,
    /// 縦横比を保たずに大きさを変える。
    保たない,
}

/// 複数の範囲枠の操作とは、複数の範囲枠の1つの枠について、選ぶこととドラッグの段階ごとに発する出来事の区別のことである。
/// 移動量は、ドラッグを始めた点からの累積を、基準の矩形の幅と高さを1とした割合の差で表す。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 複数の範囲枠の操作 {
    /// 選んでいない枠を押した。同じフレームで、続けて掴み始めたを発する。
    選んだ,
    /// ドラッグを始めた。利用する側はこの時点の枠を覚える。
    掴み始めた {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
    },
    /// ドラッグを続けている。同じフレームで掴み始めたの直後にも発する。
    動かしている {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
        /// 開始点からの累積の移動量。
        開始点からの移動量: 縦横の割合の差,
        /// このフレームでの縦横比の扱い。
        縦横比: 縦横比の扱い,
    },
    /// ドラッグを終えた。
    放した {
        /// 掴んだ部分。
        掴んだ部分: 範囲枠の掴んだ部分,
        /// 開始点からの累積の移動量。
        開始点からの移動量: 縦横の割合の差,
        /// 放したフレームでの縦横比の扱い。
        縦横比: 縦横比の扱い,
    },
}

/// 縦横比を保つ指定とは、部品が発する縦横比の扱いをどう決めるかの区別のことである。
#[derive(Clone, Copy)]
pub(super) enum 縦横比を保つ指定 {
    保たない,
    修飾キーを押している間だけ保たない(egui::Modifiers),
}

impl 縦横比を保つ指定 {
    /// 今押している修飾キーから、このフレームで発する縦横比の扱いを決める。
    /// 修飾キーの指定が空なら、どの修飾キーを押していても保つ。
    pub(super) fn 扱いを決める(
        self,
        押している修飾キー: egui::Modifiers,
    ) -> 縦横比の扱い {
        match self {
            Self::保たない => 縦横比の扱い::保たない,
            Self::修飾キーを押している間だけ保たない(外す修飾キー) => {
                if !外す修飾キー.is_none() && 押している修飾キー.contains(外す修飾キー)
                {
                    縦横比の扱い::保たない
                } else {
                    縦横比の扱い::保つ
                }
            }
        }
    }
}
