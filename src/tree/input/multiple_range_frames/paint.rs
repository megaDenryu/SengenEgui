//! 複数の範囲枠の描き方。選んでいない枠は細い枠線だけを、選んでいる枠は太い枠線と4隅のつまみを描く。
//! 範囲枠付き画像と違い、枠の外側を暗くしない。複数の枠が重なり合うため、外側という領域が1つに決まらないからである。
//! 選んでいる枠は全部の枠を描いた後に描き、つまみが手前の枠の線に隠れないようにする（掴む順と一致させる）。
//! 色は、装飾の枠線色があればそれを、無ければテーマの選択の縁の色を使う。

use super::hit::{枠の選択状態, 画面上の枠の並び};
use super::複数の範囲枠の鍵;
use crate::measure::{画素, 論理画素};
use crate::style::スタイル;
use crate::tree::input::range_frame::paint::{
    四隅のつまみを描く, 既定の枠線の太さ
};

const 選んでいない枠線の太さ: 論理画素 = 画素(1.0);

/// 複数の範囲枠の描き方とは、選んでいる枠と選んでいない枠の線と、つまみの色の組のことである。
pub(super) struct 複数の範囲枠の描き方 {
    選んでいる枠線: egui::Stroke,
    選んでいない枠線: egui::Stroke,
    つまみの色: egui::Color32,
}

impl 複数の範囲枠の描き方 {
    /// 装飾の指定を優先し、指定の無い項目をテーマの見た目から埋めて描き方を作る。
    /// 枠線太さは選んでいる枠の線の太さであり、選んでいない枠の線は1論理画素で描く。
    pub(super) fn 装飾と見た目から作る(
        装飾: スタイル, 見た目: &egui::Visuals
    ) -> Self {
        let 色 = 装飾.枠線色.unwrap_or(見た目.selection.stroke.color);
        let 太さ = 装飾.枠線太さ.unwrap_or(既定の枠線の太さ);
        Self {
            選んでいる枠線: egui::Stroke::new(太さ.eguiへ渡す値(), 色),
            選んでいない枠線: egui::Stroke::new(選んでいない枠線の太さ.eguiへ渡す値(), 色),
            つまみの色: 色,
        }
    }

    /// 選んでいない枠を奥から順に描き、その上に選んでいる枠を奥から順に描く。
    pub(super) fn 描く<鍵: 複数の範囲枠の鍵>(
        &self,
        描き手: &egui::Painter,
        枠の並び: &画面上の枠の並び<'_, 鍵>,
    ) {
        for 選択状態 in [枠の選択状態::選んでいない, 枠の選択状態::選んでいる]
        {
            for 枠 in 枠の並び
                .奥から手前の順に枠を巡る()
                .filter(|枠| 枠.選択状態 == 選択状態)
            {
                self.一つの枠を描く(描き手, 枠.矩形, 選択状態);
            }
        }
    }

    fn 一つの枠を描く(
        &self,
        描き手: &egui::Painter,
        矩形: egui::Rect,
        選択状態: 枠の選択状態,
    ) {
        match 選択状態 {
            枠の選択状態::選んでいない => {
                描き手.rect_stroke(矩形, 0.0, self.選んでいない枠線, egui::StrokeKind::Middle);
            }
            枠の選択状態::選んでいる => {
                描き手.rect_stroke(矩形, 0.0, self.選んでいる枠線, egui::StrokeKind::Middle);
                四隅のつまみを描く(描き手, 矩形, self.つまみの色);
            }
        }
    }
}
