//! 複数の範囲枠のドラッグの読み取り。egui の反応から、掴んだ枠の鍵と部分と、開始点からの累積の移動量を読み取る。
//! 掴んでいる間の記憶はドラッグの間フレームをまたいで保つ必要があるため、範囲枠付き画像と同じく、
//! 入力の部品が共有する手順（`pointer_drag`）で egui の一時記憶に置く。
//! 枠は鍵で覚えるため、ドラッグの途中で置く順が変わっても同じ枠へ操作が届く。掴んだ鍵の枠が置かれなくなったら、
//! 掴んだ枠が無くなったを発してドラッグを終える。カーソルの形の合わせ方は `cursor` に書く。

use super::hit::画面上の枠の並び;
use super::hold::{ドラッグの今の様子, 掴んでいる間の記憶};
use super::operation::{縦横比の扱いの決め方, 複数の範囲枠の操作};
use super::複数の範囲枠の鍵;
use crate::measure::論理画素;
use crate::tree::input::pointer_drag::{
    ドラッグの段階, 掴んでいる間の記憶の置き場
};

/// 読み取った出来事とは、1フレームのドラッグの読み取りが見つけた、枠の操作と、何も無い所を押したことの区別のことである。
pub(super) enum 読み取った出来事<鍵> {
    枠の操作(鍵, 複数の範囲枠の操作),
    何も無い所を押した,
}

/// 複数の範囲枠のドラッグの読み取り手とは、1フレームの反応と、画面上の基準の矩形と枠の並びの組のことである。
pub(super) struct 複数の範囲枠のドラッグの読み取り手<'描画, 鍵> {
    pub(super) 反応: &'描画 egui::Response,
    pub(super) 基準の矩形: egui::Rect,
    pub(super) 枠の並び: &'描画 画面上の枠の並び<'描画, 鍵>,
    pub(super) 縦横比の扱いの決め方: 縦横比の扱いの決め方,
    pub(super) つまみの当たりの半径: 論理画素,
}

impl<鍵: 複数の範囲枠の鍵> 複数の範囲枠のドラッグの読み取り手<'_, 鍵> {
    /// このフレームで見つけた出来事を順に返す。
    pub(super) fn 出来事を読み取る(
        &self,
        ui: &egui::Ui,
    ) -> Vec<読み取った出来事<鍵>> {
        let 置き場 = self.記憶の置き場();
        let mut 出来事一覧 = Vec::new();
        if let Some(開始位置) =
            置き場.ドラッグを始めた回なら押した座標を返す(ui, self.反応)
        {
            let (掴み始めの出来事一覧, 記憶) = self.押した座標から掴み始める(開始位置);
            出来事一覧.extend(掴み始めの出来事一覧);
            if let Some(記憶) = 記憶 {
                置き場.置く(ui, 記憶);
            }
        }
        let Some(記憶) = 置き場.読む(ui) else {
            return 出来事一覧;
        };
        出来事一覧.extend(self.掴んだ後のフレームを読む(ui, &置き場, 記憶));
        出来事一覧
    }

    // 掴み始めた後の1フレームを読み、発する出来事を返す。ドラッグを終えたら記憶を捨てる。
    fn 掴んだ後のフレームを読む(
        &self,
        ui: &egui::Ui,
        置き場: &掴んでいる間の記憶の置き場<掴んでいる間の記憶<鍵>>,
        記憶: 掴んでいる間の記憶<鍵>,
    ) -> Vec<読み取った出来事<鍵>> {
        let mut 出来事一覧 = Vec::new();
        let 枠の操作 = |操作| 読み取った出来事::枠の操作(記憶.鍵.clone(), 操作);
        if self.枠の並び.鍵の枠(&記憶.鍵).is_none() {
            置き場.捨てる(ui);
            出来事一覧.push(枠の操作(複数の範囲枠の操作::掴んだ枠が無くなった));
            return 出来事一覧;
        }
        let 様子 = ドラッグの今の様子::入力から読む(
            ui,
            記憶.開始位置,
            self.基準の矩形,
            self.縦横比の扱いの決め方,
        );
        match ドラッグの段階::反応から読む(self.反応) {
            ドラッグの段階::続けている => {
                出来事一覧.push(枠の操作(記憶.動かしている操作(様子)));
            }
            ドラッグの段階::放した => {
                置き場.捨てる(ui);
                出来事一覧.push(枠の操作(記憶.放した操作(様子)));
            }
            ドラッグの段階::放したと判定できずに終わった => {
                置き場.捨てる(ui)
            }
        }
        出来事一覧
    }

    pub(super) fn 記憶の置き場(
        &self,
    ) -> 掴んでいる間の記憶の置き場<掴んでいる間の記憶<鍵>> {
        掴んでいる間の記憶の置き場::反応から作る(
            self.反応,
            "複数の範囲枠の掴んでいる間の記憶",
        )
    }
}
