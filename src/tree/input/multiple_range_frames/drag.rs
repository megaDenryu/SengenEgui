//! 複数の範囲枠のドラッグの読み取り。egui の反応から、掴んだ枠の鍵と部分と、開始点からの累積の移動量を読み取る。
//! 掴んでいる間の記憶はドラッグの間フレームをまたいで保つ必要があるため、範囲枠付き画像と同じく、
//! 反応の識別子から作った識別子で egui の一時記憶に置く（ノード木は毎フレーム捨てるため木の側には置けない）。
//! 枠は鍵で覚えるため、ドラッグの途中で置く順が変わっても同じ枠へ操作が届く。掴んだ鍵の枠が置かれなくなったら、
//! 掴んだ枠が無くなったを発してドラッグを終える。カーソルの形の合わせ方は `cursor` に書く。

use super::hit::画面上の枠の並び;
use super::hold::{ドラッグの今の様子, 掴んでいる間の記憶};
use super::operation::{縦横比の扱いの決め方, 複数の範囲枠の操作};
use super::複数の範囲枠の鍵;
use crate::measure::論理画素;

/// 枠を動かすボタン。右ボタンと中ボタンは右クリックメニュー等の別の操作に使われるため、ドラッグとして扱わない。
const 主ボタン: egui::PointerButton = egui::PointerButton::Primary;

/// 読み取った出来事とは、1フレームのドラッグの読み取りが見つけた、枠の操作と、何も無い所を押したことの区別のことである。
pub(super) enum 読み取った出来事<鍵> {
    枠の操作(鍵, 複数の範囲枠の操作),
    何も無い所を押した,
}

/// 複数の範囲枠のドラッグの読み取り手とは、1フレームの反応と、画面上の基準の矩形と枠の並びの組のことである。
pub(super) struct 複数の範囲枠のドラッグの読み取り手<'描画, 鍵> {
    pub(super) 反応: &'描画 egui::Response,
    pub(super) 基準の矩形: egui::Rect,
    pub(super) 枠の並び: &'描画 画面上の枠の並び<'描画, 鍵>,
    pub(super) 縦横比の扱いの決め方: 縦横比の扱いの決め方,
    pub(super) つまみの当たりの半径: 論理画素,
}

impl<鍵: 複数の範囲枠の鍵> 複数の範囲枠のドラッグの読み取り手<'_, 鍵> {
    /// このフレームで見つけた出来事を順に返す。
    pub(super) fn 出来事を読み取る(
        &self,
        ui: &egui::Ui,
    ) -> Vec<読み取った出来事<鍵>> {
        let 識別子 = self.記憶の識別子();
        let mut 出来事一覧 = Vec::new();
        if self.反応.drag_started_by(主ボタン) {
            self.記憶を捨てる(ui);
            match self.掴み始めを判定する(ui) {
                Some(記憶) => {
                    出来事一覧.extend(self.掴み始めの出来事一覧(&記憶));
                    ui.data_mut(|記憶域| 記憶域.insert_temp(識別子, 記憶));
                }
                None => 出来事一覧.push(読み取った出来事::何も無い所を押した),
            }
        }
        let Some(記憶) =
            ui.data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶<鍵>>(識別子))
        else {
            return 出来事一覧;
        };
        let 枠の操作 = |操作| 読み取った出来事::枠の操作(記憶.鍵.clone(), 操作);
        if self.枠の並び.鍵の枠(&記憶.鍵).is_none() {
            self.記憶を捨てる(ui);
            出来事一覧.push(枠の操作(複数の範囲枠の操作::掴んだ枠が無くなった));
            return 出来事一覧;
        }
        let 様子 = ドラッグの今の様子::入力から読む(
            ui,
            記憶.開始位置,
            self.基準の矩形,
            self.縦横比の扱いの決め方,
        );
        if self.反応.dragged_by(主ボタン) && !self.反応.drag_stopped_by(主ボタン) {
            出来事一覧.push(枠の操作(記憶.動かしている操作(様子)));
            return 出来事一覧;
        }
        self.記憶を捨てる(ui);
        if self.反応.drag_stopped_by(主ボタン) {
            出来事一覧.push(枠の操作(記憶.放した操作(様子)));
        }
        出来事一覧
    }

    /// ポインタを押した位置から掴んだ枠と部分を判定する。egui はポインタが少し動いてから
    /// ドラッグの開始とすることがあるため、開始点には現在位置でなく押した位置を使う。
    fn 掴み始めを判定する(
        &self,
        ui: &egui::Ui,
    ) -> Option<掴んでいる間の記憶<鍵>> {
        let 開始位置 = ui
            .input(|入力| 入力.pointer.press_origin())
            .or(self.反応.interact_pointer_pos())?;
        let (鍵, 掴んだ部分) = self
            .枠の並び
            .掴む枠と部分を判定する(開始位置, self.つまみの当たりの半径)?;
        Some(掴んでいる間の記憶 {
            鍵: 鍵.clone(),
            掴んだ部分,
            開始位置,
        })
    }

    /// 掴み始めたフレームの出来事。選んでいない枠なら、選んだを掴み始めたより先に発する。
    fn 掴み始めの出来事一覧(
        &self,
        記憶: &掴んでいる間の記憶<鍵>,
    ) -> Vec<読み取った出来事<鍵>> {
        let 枠の操作 = |操作| 読み取った出来事::枠の操作(記憶.鍵.clone(), 操作);
        let 選んだ = self
            .枠の並び
            .選んでいない枠か(&記憶.鍵)
            .then(|| 枠の操作(複数の範囲枠の操作::選んだ));
        選んだ
            .into_iter()
            .chain([枠の操作(記憶.掴み始めた操作())])
            .collect()
    }

    fn 記憶を捨てる(&self, ui: &egui::Ui) {
        let 識別子 = self.記憶の識別子();
        ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶<鍵>>(識別子));
    }

    pub(super) fn 記憶の識別子(&self) -> egui::Id {
        self.反応.id.with("複数の範囲枠の掴んでいる間の記憶")
    }
}
