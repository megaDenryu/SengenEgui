//! 複数の範囲枠のドラッグの読み取り。egui の反応から、掴んだ枠と部分と、開始点からの累積の移動量を読み取る。
//! 掴んでいる間の記憶はドラッグの間フレームをまたいで保つ必要があるため、範囲枠付き画像と同じく、
//! 反応の識別子から作った識別子で egui の一時記憶に置く（ノード木は毎フレーム捨てるため木の側には置けない）。
//! 枠は置いた順の番号で覚えるため、ドラッグの間は枠を置く順を変えない前提である。ドラッグの途中で番号の枠が
//! 無くなったら、操作を発さずにドラッグを終える（その枠の応答を作る関数がもう無いため）。

use super::hit::{枠の番号, 枠の選択状態, 画面上の枠の並び};
use super::hold::{ドラッグの今の様子, 掴んでいる間の記憶};
use super::operation::{縦横比の扱いの決め方, 複数の範囲枠の操作};
use crate::measure::論理画素;

/// 枠を動かすボタン。右ボタンと中ボタンは右クリックメニュー等の別の操作に使われるため、ドラッグとして扱わない。
const 主ボタン: egui::PointerButton = egui::PointerButton::Primary;

/// 複数の範囲枠のドラッグとは、1フレームの反応と、画面上の基準の矩形と枠の並びの組のことである。
pub(super) struct 複数の範囲枠のドラッグの読み取り手<'描画> {
    pub(super) 反応: &'描画 egui::Response,
    pub(super) 基準の矩形: egui::Rect,
    pub(super) 枠の並び: &'描画 画面上の枠の並び,
    pub(super) 縦横比の扱いの決め方: 縦横比の扱いの決め方,
    pub(super) つまみの当たりの半径: 論理画素,
}

impl 複数の範囲枠のドラッグの読み取り手<'_> {
    /// このフレームで発する操作を、操作した枠の番号と組にして順に返す。どの枠にも当たらない位置で始めたドラッグは無視する。
    pub(super) fn 操作を読み取る(
        &self,
        ui: &egui::Ui,
    ) -> Vec<(枠の番号, 複数の範囲枠の操作)> {
        let 識別子 = self.記憶の識別子();
        let mut 操作一覧 = Vec::new();
        if self.反応.drag_started_by(主ボタン) {
            ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(識別子));
            if let Some(記憶) = self.掴み始めを判定する(ui) {
                ui.data_mut(|記憶域| 記憶域.insert_temp(識別子, 記憶));
                if self.選んでいない枠か(記憶.枠) {
                    操作一覧.push((記憶.枠, 複数の範囲枠の操作::選んだ));
                }
                操作一覧.push((記憶.枠, 記憶.掴み始めた操作()));
            }
        }
        let Some(記憶) = ui.data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶>(識別子))
        else {
            return 操作一覧;
        };
        let 枠がある = self.枠の並び.番号の枠(記憶.枠).is_some();
        let 様子 = self.今の様子(ui, 記憶);
        if 枠がある && self.反応.dragged_by(主ボタン) && !self.反応.drag_stopped_by(主ボタン)
        {
            操作一覧.push((記憶.枠, 記憶.動かしている操作(様子)));
            return 操作一覧;
        }
        ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(識別子));
        if 枠がある && self.反応.drag_stopped_by(主ボタン) {
            操作一覧.push((記憶.枠, 記憶.放した操作(様子)));
        }
        操作一覧
    }

    /// ポインタを押した位置から掴んだ枠と部分を判定する。egui はポインタが少し動いてから
    /// ドラッグの開始とすることがあるため、開始点には現在位置でなく押した位置を使う。
    fn 掴み始めを判定する(&self, ui: &egui::Ui) -> Option<掴んでいる間の記憶> {
        let 開始位置 = ui
            .input(|入力| 入力.pointer.press_origin())
            .or(self.反応.interact_pointer_pos())?;
        let (枠, 掴んだ部分) = self
            .枠の並び
            .掴む枠と部分を判定する(開始位置, self.つまみの当たりの半径)?;
        Some(掴んでいる間の記憶 {
            枠,
            掴んだ部分,
            開始位置,
        })
    }

    fn 選んでいない枠か(&self, 番号: 枠の番号) -> bool {
        self.枠の並び
            .番号の枠(番号)
            .is_some_and(|枠| 枠.選択状態 == 枠の選択状態::選んでいない)
    }

    /// ポインタの位置が分からないフレームは、開始点にあるとみなす。
    fn 今の様子(
        &self, ui: &egui::Ui, 記憶: 掴んでいる間の記憶
    ) -> ドラッグの今の様子 {
        let (現在位置, 押している修飾キー) =
            ui.input(|入力| (入力.pointer.latest_pos(), 入力.modifiers));
        ドラッグの今の様子 {
            現在位置: 現在位置.unwrap_or(記憶.開始位置),
            基準の大きさ: self.基準の矩形.size(),
            縦横比の扱い: self.縦横比の扱いの決め方.扱いを決める(押している修飾キー),
        }
    }

    /// カーソルの形を、掴んでいる間は掴んだ部分に、それ以外はポインタが乗っている部分に合わせる。
    pub(super) fn カーソルを変える(&self, ui: &egui::Ui) {
        let 掴んでいる部分 = ui
            .data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶>(self.記憶の識別子()))
            .map(|記憶| 記憶.掴んだ部分);
        let 乗っている部分 = self.反応.hover_pos().and_then(|位置| {
            self.枠の並び
                .掴む枠と部分を判定する(位置, self.つまみの当たりの半径)
                .map(|(_, 部分)| 部分)
        });
        if let Some(部分) = 掴んでいる部分.or(乗っている部分) {
            ui.ctx().set_cursor_icon(部分.カーソルの形());
        }
    }

    fn 記憶の識別子(&self) -> egui::Id {
        self.反応.id.with("複数の範囲枠の掴んでいる間の記憶")
    }
}
