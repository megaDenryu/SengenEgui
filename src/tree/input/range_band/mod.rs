//! 区間の帯。値の全体の範囲を1本の帯に写し、その中の区間（開始から終了まで）を塗り、開始と終了のつまみと、
//! 省略できる位置の印を描く。開始・終了のつまみのドラッグで端を、区間の内側のドラッグで長さを保った区間ごとを、
//! 位置の印のドラッグと区間の外を押すことで位置を動かす。位置を渡していない帯で区間の外を押すと `区間の外` を掴んだと発する。どれを掴むかの優先は `hit` に、描画と操作の読み取りの順は `draw` に書く。
//!
//! 部品は新しい区間や位置を状態へ書かない。発するのは「何を掴んだか」と「その値」だけであり、値の丸め・区間の
//! 最小の長さ・開始が終了を超えない規則は利用する側のドメインが持つ。範囲枠付き画像と同じ考え方である。

mod drag;
mod draw;
mod hit;
mod hold;
mod layout;
mod operation;
mod paint;

use std::rc::Rc;

pub use operation::{区間の帯の掴んだもの, 区間の帯の操作};

use crate::measure::{帯の値, 帯の全体の範囲, 論理画素};
use crate::style::スタイル;
use hit::今の区間と位置;

/// 帯の幅とは、区間の帯が横に占める幅をどう決めるかの区別のことである。
#[derive(Clone, Copy)]
enum 帯の幅 {
    使える幅いっぱい,
    指定(論理画素),
}

/// 区間の帯型とは、値の全体の範囲の上の区間と位置を1本の帯で見せ、ドラッグで動かす部品の記述のことである。
pub struct 区間の帯型<M> {
    全体: 帯の全体の範囲,
    今の値: 今の区間と位置,
    幅: 帯の幅,
    操作から応答を作る: Box<dyn Fn(区間の帯の操作) -> M>,
    装飾値: スタイル,
}

impl<M> 区間の帯型<M> {
    pub(crate) fn 新規(
        全体: 帯の全体の範囲,
        開始: 帯の値,
        終了: 帯の値,
        操作から応答を作る: Box<dyn Fn(区間の帯の操作) -> M>,
    ) -> Self {
        Self {
            全体,
            今の値: 今の区間と位置 {
                開始,
                終了,
                位置: None,
            },
            幅: 帯の幅::使える幅いっぱい,
            操作から応答を作る,
            装飾値: スタイル::無指定,
        }
    }

    /// 位置の印の値（再生位置など）を渡す。渡さなければ位置の印を描かず、区間の外を押すと `区間の外` を掴む。
    pub fn 位置(mut self, 位置: 帯の値) -> Self {
        self.今の値.位置 = Some(位置);
        self
    }

    /// 帯の幅を指定する。指定しなければ使える幅いっぱいに広げる。
    pub fn 幅(mut self, 幅: 論理画素) -> Self {
        self.幅 = 帯の幅::指定(幅);
        self
    }

    /// 装飾を適用する。使う項目は背景色（帯の地）・枠線色（開始と終了のつまみ）・文字色（位置の印）だけである。
    /// 指定しなければ、帯の地はテーマの窪んだ面の色、つまみと位置の印はテーマの強い文字の色になる。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }
}

impl<M: 'static> 区間の帯型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 区間の帯型<N> {
        let 元の作る = self.操作から応答を作る;
        区間の帯型 {
            全体: self.全体,
            今の値: self.今の値,
            幅: self.幅,
            操作から応答を作る: Box::new(move |操作| {
                応答を変換する(元の作る(操作))
            }),
            装飾値: self.装飾値,
        }
    }
}
