//! 区間の帯の配置。部品が確保した矩形を、位置の印の頭を描く上の段と、全体・区間・つまみを描く帯の段に分け、
//! 値と横の位置を相互に写す。値は帯の段の左端を全体の始め、右端を全体の終わりとして写す。
//! 帯の段は確保した矩形の左右に `左右の余白` を空けた内側である。横の位置は画面の左端からの論理画素で表す。

use crate::measure::{
    帯の値, 帯の値の差, 帯の全体の範囲, 画素, 範囲との位置関係, 論理画素
};

/// 位置の印の頭（下向きの三角）を描く上の段の高さ。
pub(super) const 頭の段の高さ: 論理画素 = 画素(10.0);
/// 全体と区間を塗り、つまみを描く帯の段の高さ。
pub(super) const 帯の段の高さ: 論理画素 = 画素(18.0);
/// 確保した矩形の左右の内側に空ける幅。帯の端にあるつまみも、その外側の半分を掴めるようにする。
const 左右の余白: 論理画素 = 画素(8.0);

/// 区間の帯の配置とは、1フレームの上の段と帯の段の矩形と、帯が表す全体の範囲の組のことである。
pub(super) struct 区間の帯の配置 {
    pub(super) 頭の段: egui::Rect,
    pub(super) 帯の段: egui::Rect,
    pub(super) 全体: 帯の全体の範囲,
}

impl 区間の帯の配置 {
    /// 確保した矩形の左右に余白を空け、上から頭の段と帯の段に分ける。
    pub(super) fn 確保した矩形を分ける(
        確保した矩形: egui::Rect,
        全体: 帯の全体の範囲,
    ) -> Self {
        let 矩形 = 確保した矩形.shrink2(egui::vec2(左右の余白.eguiへ渡す値(), 0.0));
        let 境目 = 矩形.top() + 頭の段の高さ.eguiへ渡す値();
        Self {
            頭の段: egui::Rect::from_min_max(矩形.min, egui::pos2(矩形.right(), 境目)),
            帯の段: egui::Rect::from_min_max(egui::pos2(矩形.left(), 境目), 矩形.max),
            全体,
        }
    }

    /// 値を描く横の位置。全体の範囲の外の値は帯の端に描く。
    pub(super) fn 値の横の位置(&self, 値: 帯の値) -> 論理画素 {
        let 割合 = self.全体.割合へ写す(値);
        論理画素::生成する(割合.二つの値の間を取る(self.帯の段.left(), self.帯の段.right()))
    }

    /// 横の移動量が表す値の差。
    pub(super) fn 横の移動量の値の差(&self, 移動量: 論理画素) -> 帯の値の差 {
        let 幅 = f64::from(self.帯の段.width());
        let 比 = if 幅 > 0.0 {
            移動量.倍精度の小数にする() / 幅
        } else {
            0.0
        };
        self.全体.長さ() * 比
    }

    /// 横の位置が指す値。帯の外の位置は全体の範囲の端の値にする。
    pub(super) fn 横の位置の値(&self, 横の位置: 論理画素) -> 帯の値 {
        let 始めからの差 = self.横の移動量の値の差(横の位置 - self.左端());
        self.全体.内側へ収める(self.全体.始め() + 始めからの差)
    }

    /// 帯の段の左端の横の位置。
    pub(super) fn 左端(&self) -> 論理画素 {
        論理画素::生成する(self.帯の段.left())
    }

    /// 範囲の外の値を表す、帯の端から外を指す三角の頂点。範囲の内側の値なら None を返す。
    /// 三角は端の位置から外へ長さの半分、内へ長さの半分を占め、縦の範囲の全体を底辺にする。
    pub(super) fn 外を指す三角(
        端の横: f32,
        向き: 範囲との位置関係,
        縦の範囲: egui::Rangef,
        長さ: 論理画素,
    ) -> Option<Vec<egui::Pos2>> {
        let 半分 = 長さ.eguiへ渡す値() / 2.0;
        let 外へ = match 向き {
            範囲との位置関係::内側 => return None,
            範囲との位置関係::始めより前 => -半分,
            範囲との位置関係::終わりより後 => 半分,
        };
        Some(vec![
            egui::pos2(端の横 + 外へ, 縦の範囲.center()),
            egui::pos2(端の横 - 外へ, 縦の範囲.min),
            egui::pos2(端の横 - 外へ, 縦の範囲.max),
        ])
    }
}
