//! 区間の帯の配置。部品が確保した矩形を、位置の印の頭を描く上の領域と、全体・区間・つまみを描く帯の領域に分ける。
//! 値と横の位置を相互に求める規則は、時間の行の並びと共有する `帯の横の目盛り` が持つ。

use crate::measure::{帯の全体の範囲, 画素, 範囲との位置関係, 論理画素};
use crate::tree::input::band_scale::帯の横の目盛り;

pub(super) const 位置の印の頭の領域の高さ: 論理画素 = 画素(10.0); // 位置の印の頭（下向きの三角）を描く上の領域の高さ。
pub(super) const 帯の領域の高さ: 論理画素 = 画素(18.0); // 全体と区間を塗り、つまみを描く帯の領域の高さ。

// 区間の帯の配置とは、1フレームの上の領域と帯の領域の矩形と、帯の領域に刻んだ横の目盛りの組のことである。
pub(super) struct 区間の帯の配置 {
    pub(super) 位置の印の頭の領域: egui::Rect,
    pub(super) 帯の領域: egui::Rect,
    pub(super) 目盛り: 帯の横の目盛り,
}

impl 区間の帯の配置 {
    // 確保した矩形の左右に余白を空けた内側に目盛りを刻み、上から位置の印の頭の領域と帯の領域に分ける。
    pub(super) fn 確保した矩形を分ける(
        確保した矩形: egui::Rect,
        全体: 帯の全体の範囲,
    ) -> Self {
        let 目盛り =
            帯の横の目盛り::確保した矩形の内側に刻む(確保した矩形, 全体);
        let 境目 = 確保した矩形.top() + 位置の印の頭の領域の高さ.eguiへ渡す値();
        Self {
            位置の印の頭の領域: egui::Rect::from_x_y_ranges(
                目盛り.横の範囲(),
                確保した矩形.top()..=境目,
            ),
            帯の領域: egui::Rect::from_x_y_ranges(
                目盛り.横の範囲(),
                境目..=確保した矩形.bottom(),
            ),
            目盛り,
        }
    }

    // 範囲の外の値を表す、帯の端から外を指す三角の頂点。範囲の内側の値なら None を返す。
    // 三角は端の位置から外へ長さの半分、内へ長さの半分を占め、縦の範囲の全体を底辺にする。
    pub(super) fn 外を指す三角(
        端の横: f32,
        向き: 範囲との位置関係,
        縦の範囲: egui::Rangef,
        長さ: 論理画素,
    ) -> Option<Vec<egui::Pos2>> {
        let 半分 = 長さ.eguiへ渡す値() / 2.0;
        let 外へ = match 向き {
            範囲との位置関係::内側 => return None,
            範囲との位置関係::始めより前 => -半分,
            範囲との位置関係::終わりより後 => 半分,
        };
        Some(vec![
            egui::pos2(端の横 + 外へ, 縦の範囲.center()),
            egui::pos2(端の横 - 外へ, 縦の範囲.min),
            egui::pos2(端の横 - 外へ, 縦の範囲.max),
        ])
    }
}
