//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴み始めと、横に動かす値のドラッグの記憶を、フレームをまたいで保つ。
//! 値の動かし方（押した位置からの移動量を掴み始めの値に足し、`帯の全体の範囲` の規則で収める）もここに置く。
//! 横の位置の扱いと、値が変わったフレームだけ発する規則は、時間の行の並びと共有する `横に動かす値の記憶` が持つ。

use super::hit::掴み始め;
use super::区間の帯の掴んだもの;
use crate::measure::{帯の値, 論理画素};
use crate::tree::input::band_scale::帯の横の目盛り;
use crate::tree::input::horizontal_drag::横に動かす値の記憶;

/// 掴んでいる間の記憶とは、押したときに決まる掴み始めと、横に動かす値のドラッグの記憶の組のことである。
#[derive(Clone, Copy)]
pub(super) struct 掴んでいる間の記憶 {
    pub(super) 掴み始め: 掴み始め,
    pub(super) 横のドラッグ: 横に動かす値の記憶,
}

impl 掴んでいる間の記憶 {
    /// 掴み始めと押した位置から作る。
    pub(super) fn 押した座標から作る(
        掴み始め: 掴み始め, 押した座標: egui::Pos2
    ) -> Self {
        Self {
            掴み始め,
            横のドラッグ: 横に動かす値の記憶::押した横の位置から作る(
                論理画素::生成する(押した座標.x),
                掴み始め.値,
            ),
        }
    }

    /// 押した横の位置から今の横の位置まで動かした分だけ、掴んだものの値を動かす。
    /// 収め方は `帯の全体の範囲` の規則（範囲の外の値はそれより外へ動かない）による。
    pub(super) fn 動かした後の値を求める(
        self,
        目盛り: 帯の横の目盛り,
        押した横の位置: 論理画素,
        今の横の位置: 論理画素,
    ) -> 帯の値 {
        let 差 = 目盛り.横の移動量から値の差を求める(今の横の位置 - 押した横の位置);
        let 始め = self.掴み始め;
        let 全体 = 目盛り.全体();
        match 始め.掴んだもの {
            区間の帯の掴んだもの::区間の内側 => 全体
                .区間を動かす前より外へ出さずに開始を収める(
                    始め.値 + 差,
                    始め.値,
                    始め.区間の長さ,
                ),
            区間の帯の掴んだもの::開始のつまみ
            | 区間の帯の掴んだもの::終了のつまみ
            | 区間の帯の掴んだもの::位置の印
            | 区間の帯の掴んだもの::区間の外 => {
                全体.動かす前より外へ出さずに収める(始め.値 + 差, 始め.値)
            }
        }
    }
}
