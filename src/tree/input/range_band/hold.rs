//! 掴んでいる間の記憶。ドラッグを始めたときに決まる値と、ドラッグの間に更新する値を、フレームをまたいで保つ。
//! 値の動かし方（押した位置からの移動量を掴み始めの値に足し、`帯の全体の範囲` の規則で収める）もここに置く。

use super::hit::掴み始め;
use super::layout::区間の帯の配置;
use super::区間の帯の掴んだもの;
use crate::measure::{帯の値, 論理画素};

/// 掴んでいる間の記憶とは、押したときに決まる掴み始めと押した横の位置と、最後に分かった横の位置と、最後に発した値の組のことである。
#[derive(Clone, Copy)]
pub(super) struct 掴んでいる間の記憶 {
    pub(super) 掴み始め: 掴み始め,
    押した横の位置: 論理画素,
    pub(super) 最後に分かった横の位置: 論理画素,
    pub(super) 最後に発した値: 帯の値,
}

impl 掴んでいる間の記憶 {
    /// 掴み始めと押した位置から作る。最後に分かった位置は押した位置、最後に発した値は掴み始めの値から始める。
    pub(super) fn 押した位置から作る(
        掴み始め: 掴み始め, 押した位置: egui::Pos2
    ) -> Self {
        let 押した横の位置 = 論理画素::生成する(押した位置.x);
        Self {
            掴み始め,
            押した横の位置,
            最後に分かった横の位置: 押した横の位置,
            最後に発した値: 掴み始め.値,
        }
    }

    /// 押した横の位置から最後に分かった横の位置まで動かした分だけ、掴んだものの値を動かす。
    /// 収め方は `帯の全体の範囲` の規則（範囲の外の値はそれより外へ動かない）による。
    pub(super) fn 最後に分かった横の位置での値(
        &self,
        配置: &区間の帯の配置,
    ) -> 帯の値 {
        let 差 =
            配置.横の移動量の値の差(self.最後に分かった横の位置 - self.押した横の位置);
        let 始め = self.掴み始め;
        let 全体 = 配置.全体;
        match 始め.掴んだもの {
            区間の帯の掴んだもの::区間の内側 => 全体
                .区間を動かす前より外へ出さずに開始を収める(
                    始め.値 + 差,
                    始め.値,
                    始め.区間の長さ,
                ),
            区間の帯の掴んだもの::開始のつまみ
            | 区間の帯の掴んだもの::終了のつまみ
            | 区間の帯の掴んだもの::位置の印 => {
                全体.動かす前より外へ出さずに収める(始め.値 + 差, 始め.値)
            }
        }
    }
}
