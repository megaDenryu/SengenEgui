//! 掴んでいる間の記憶。ドラッグを始めたときに決まる掴み始めと、掴み始めた回の横の目盛りと、横に動かす値のドラッグの記憶を、
//! フレームをまたいで保つ。値の動かし方（押した位置からの移動量を掴み始めの値に足し、`帯の全体の範囲` の規則で収める）も
//! ここに置く。横の位置を運ぶ規則と、値が変わったフレームだけ発する規則は、時間の行の並びと共有する `横に動かす値の記憶` が持つ。
//!
//! 移動量を値の差へ直すのは、掴み始めた回の目盛りである（時間の行の並びの塊と同じ規則）。区間の帯の値はどれも掴み始めの
//! 値に押した位置からの移動量を足して求めるため、ドラッグの間に利用する側が全体の範囲を変えても、同じ移動量が同じ差を表す。
//! 収める先の全体の範囲は今のフレームのものを使う。動かした値は、今の画面に見えている範囲へ収めるのが正しいためである。

use super::hit::掴み始め;
use super::区間の帯の掴んだもの;
use crate::measure::{帯の値, 帯の全体の範囲, 論理画素};
use crate::tree::input::band_scale::帯の横の目盛り;
use crate::tree::input::horizontal_drag::横に動かす値の記憶;
use crate::tree::input::pointer_drag::掴んでいる間に置く記憶;

// 掴んでいる間の記憶とは、押したときに決まる掴み始めと、掴み始めた回の横の目盛りと、横に動かす値のドラッグの記憶の組のことである。
#[derive(Clone, Copy)]
pub(super) struct 掴んでいる間の記憶 {
    pub(super) 掴み始め: 掴み始め,
    掴み始めた回の目盛り: 帯の横の目盛り,
    pub(super) 横のドラッグ: 横に動かす値の記憶,
}

impl 掴んでいる間に置く記憶 for 掴んでいる間の記憶 {
    const 記憶の名前: &'static str = "区間の帯の掴んでいる間の記憶";
}

impl 掴んでいる間の記憶 {
    // 掴み始めと、押した座標と、その回の目盛りから作る。
    pub(super) fn 押した座標から作る(
        掴み始め: 掴み始め,
        押した座標: egui::Pos2,
        目盛り: 帯の横の目盛り,
    ) -> Self {
        Self {
            掴み始め,
            掴み始めた回の目盛り: 目盛り,
            横のドラッグ: 横に動かす値の記憶::押した横の位置から作る(
                論理画素::生成する(押した座標.x),
                掴み始め.値,
            ),
        }
    }

    // 横に動かす値のドラッグの記憶だけを替えた記憶。掴み始めと掴み始めた回の目盛りは放すまで変えない。
    pub(super) fn 横のドラッグを替える(
        self, 横のドラッグ: 横に動かす値の記憶
    ) -> Self {
        Self {
            横のドラッグ,
            ..self
        }
    }

    // 押した横の位置から最後に分かった横の位置まで動かした分だけ、掴んだものの値を動かし、今の全体の範囲へ収める。
    // 収め方は `帯の全体の範囲` の規則（範囲の外の値はそれより外へ動かない）による。
    pub(super) fn 動かした後の値を求める(
        self, 今の全体: 帯の全体の範囲
    ) -> 帯の値 {
        let 移動量 =
            self.横のドラッグ.最後に分かった横の位置() - self.横のドラッグ.押した横の位置();
        let 差 = self
            .掴み始めた回の目盛り
            .横の移動量から値の差を求める(移動量);
        let 始め = self.掴み始め;
        match 始め.掴んだもの {
            区間の帯の掴んだもの::区間の内側 => 今の全体
                .区間を動かす前より外へ出さずに開始を収める(
                    始め.値 + 差,
                    始め.値,
                    始め.区間の長さ,
                ),
            区間の帯の掴んだもの::開始のつまみ
            | 区間の帯の掴んだもの::終了のつまみ
            | 区間の帯の掴んだもの::位置の印
            | 区間の帯の掴んだもの::区間の外 => {
                今の全体.動かす前より外へ出さずに収める(始め.値 + 差, 始め.値)
            }
        }
    }
}
