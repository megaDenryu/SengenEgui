//! 区間の帯の操作の語彙。何を掴んだかと、ドラッグの開始・継続・終了を区別し、その時点の値を値の単位で運ぶ。
//! 値の丸め・区間の最小の長さ・開始が終了を超えない規則は部品の中で扱わず、利用する側のドメインが持つ。
//! 部品が保証するのは、掴んだだけでは値を変えないことと、動かした値を全体の範囲と掴み始めの値を合わせた範囲へ収める
//! こと（範囲の外にある値はそれより外へ動かない）だけである。規則の詳細は `帯の全体の範囲` の説明にある。

use crate::measure::帯の値;

/// 区間の帯の掴んだものとは、ドラッグを始めた位置が帯のどれに当たったかの区別のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 区間の帯の掴んだもの {
    /// 区間の開始のつまみ。値は新しい開始である。
    開始のつまみ,
    /// 区間の終了のつまみ。値は新しい終了である。
    終了のつまみ,
    /// 区間の内側。長さを保って区間ごと動かす。値は新しい開始であり、新しい終了は値に今の区間の長さを足したものである。
    区間の内側,
    /// 位置の印。印を掴んだときと、位置を渡している帯で区間の外を押したときに掴む。値は新しい位置である。
    位置の印,
    /// 位置を渡していない帯で、つまみにも区間の内側にも当たらない所（区間の外と上の段）を押したときに掴む。
    /// 値は押した位置の値で始まり、動かすとポインタの横の位置の値を運ぶ（位置の印と同じ動き方）。部品は何も書き換えない
    /// ため、押したことだけを知りたい利用する側は、掴み始めたか放したを見て値を捨ててよい。
    区間の外,
}

/// 区間の帯の操作とは、区間の帯のドラッグの段階ごとに発する出来事の区別のことである。
/// 同じドラッグの中では掴んだものは変わらない。値は全体の範囲と掴み始めの値を合わせた範囲に収めてある。
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum 区間の帯の操作 {
    /// 押した。区間の外を押したときは、値が押した位置の値になる。それ以外は掴んだものの今の値である。
    掴み始めた {
        /// 掴んだもの。
        掴んだもの: 区間の帯の掴んだもの,
        /// 掴んだものの値。
        値: 帯の値,
    },
    /// 押したまま動かし、値が変わった。値が変わらないフレームでは発しない。
    動かしている {
        /// 掴んだもの。
        掴んだもの: 区間の帯の掴んだもの,
        /// 掴んだものの新しい値。
        値: 帯の値,
    },
    /// 放した。値が変わっていなくても必ず発する。重い処理はここで行う。
    放した {
        /// 掴んだもの。
        掴んだもの: 区間の帯の掴んだもの,
        /// 掴んだものの最後の値。
        値: 帯の値,
    },
}

impl 区間の帯の掴んだもの {
    /// これを掴めるところにポインタがあるときに出すカーソルの形。区間の内側は区間ごと動かすため掴む形、区間の外は
    /// 押すことに意味があるため指差す形、それ以外は横に動かす形である。
    pub(super) fn カーソルの形(self) -> egui::CursorIcon {
        match self {
            Self::区間の内側 => egui::CursorIcon::Grab,
            Self::区間の外 => egui::CursorIcon::PointingHand,
            Self::開始のつまみ | Self::終了のつまみ | Self::位置の印 => {
                egui::CursorIcon::ResizeHorizontal
            }
        }
    }
}
