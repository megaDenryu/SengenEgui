//! 区間の帯の当たりの判定。押した位置から何を掴んだかを、次の優先の順で決める。
//!
//! 1. 位置の印: 上の段で、印の横の位置から `位置の印の当たりの半幅` 以内
//! 2. 開始と終了のつまみ: 上下の段の全体で、つまみの横の位置から `つまみの当たりの半幅` 以内。両方に当たれば近い方、
//!    同じ距離なら押した位置が開始のつまみより左のとき開始、それ以外は終了（開始と終了が重なったとき右へ広げられるようにする）
//! 3. 区間の内側: 帯の段で、開始のつまみと終了のつまみの間。開始が終了を超えているときは区間が無いので当たらない
//! 4. それ以外（区間の外、上の段の印の無い所）: 位置の印を押した位置へ移して掴む。位置を渡していなければ何も掴まない
//!
//! 位置の印の当たりを上の段に限るのは、区間を動かすと位置の印が開始のつまみに重なる使い方で、帯の段のつまみを掴めるようにするためである。
//! 全体の範囲の外にある値のつまみと印は帯の端に描くので、端で掴める。掴んだ後の値の動き方は `帯の全体の範囲` の収める規則による。

use super::layout::区間の帯の配置;
use crate::measure::{帯の値, 帯の値の差, 画素, 論理画素};
use crate::tree::input::range_band::区間の帯の掴んだもの;

/// つまみに当たったとみなす横の距離。描くつまみの半分の幅（3論理画素）より広く取り、細かい位置合わせを要らなくする。
const つまみの当たりの半幅: 論理画素 = 画素(8.0);
/// 位置の印の頭に当たったとみなす横の距離。描く三角の半分の幅（5論理画素）より少し広い。
const 位置の印の当たりの半幅: 論理画素 = 画素(7.0);

/// 今の区間と位置とは、このフレームに利用する側から受け取った区間の開始・終了と位置の組のことである。
/// 描くのにも当たりの判定にも使う。
#[derive(Clone, Copy)]
pub(super) struct 今の区間と位置 {
    pub(super) 開始: 帯の値,
    pub(super) 終了: 帯の値,
    pub(super) 位置: Option<帯の値>,
}

/// 掴み始めとは、何を掴んだかと、掴んだものの動かす前の値と、掴んだときの区間の長さの組のことである。
#[derive(Clone, Copy)]
pub(super) struct 掴み始め {
    pub(super) 掴んだもの: 区間の帯の掴んだもの,
    pub(super) 値: 帯の値,
    pub(super) 区間の長さ: 帯の値の差,
}

impl 今の区間と位置 {
    /// 押した位置から掴み始めを決める。何も掴まなければ None を返す。
    pub(super) fn 掴み始めを判定する(
        self,
        配置: &区間の帯の配置,
        押した位置: egui::Pos2,
    ) -> Option<掴み始め> {
        let 掴む = |掴んだもの, 値| 掴み始め {
            掴んだもの,
            値,
            区間の長さ: self.終了 - self.開始,
        };
        let 横 = 論理画素::生成する(押した位置.x);
        let 距離 = |値| (配置.値の横の位置(値) - 横).絶対値();
        if let Some(位置) = self.位置
            && 配置.頭の段.y_range().contains(押した位置.y)
            && 距離(位置) <= 位置の印の当たりの半幅
        {
            return Some(掴む(区間の帯の掴んだもの::位置の印, 位置));
        }
        if let Some((掴んだもの, 値)) = self.当たったつまみ(配置, 横) {
            return Some(掴む(掴んだもの, 値));
        }
        let 区間の横の範囲 = 配置.値の横の位置(self.開始)..=配置.値の横の位置(self.終了);
        if 配置.帯の段.y_range().contains(押した位置.y) && 区間の横の範囲.contains(&横)
        {
            return Some(掴む(区間の帯の掴んだもの::区間の内側, self.開始));
        }
        self.位置
            .map(|_| 掴む(区間の帯の掴んだもの::位置の印, 配置.横の位置の値(横)))
    }

    fn 当たったつまみ(
        self,
        配置: &区間の帯の配置,
        横: 論理画素,
    ) -> Option<(区間の帯の掴んだもの, 帯の値)> {
        let 開始の横 = 配置.値の横の位置(self.開始);
        let 開始の距離 = (開始の横 - 横).絶対値();
        let 終了の距離 = (配置.値の横の位置(self.終了) - 横).絶対値();
        let 半幅 = つまみの当たりの半幅;
        let 開始 = (区間の帯の掴んだもの::開始のつまみ, self.開始);
        let 終了 = (区間の帯の掴んだもの::終了のつまみ, self.終了);
        match (開始の距離 <= 半幅, 終了の距離 <= 半幅) {
            (true, true) if 開始の距離 < 終了の距離 => Some(開始),
            (true, true) if 開始の距離 == 終了の距離 && 横 < 開始の横 => Some(開始),
            (true, true) => Some(終了),
            (true, false) => Some(開始),
            (false, true) => Some(終了),
            (false, false) => None,
        }
    }
}
