//! 区間の帯のドラッグの読み取り。egui の反応から、掴んだものとその値をドラッグの段階ごとに読み取る。
//! 掴み始めと最後に発した値はドラッグの間フレームをまたいで保つ必要があるため、範囲枠付き画像と同じく
//! egui の一時記憶に、反応の識別子から作った鍵で置く。ノード木は毎フレーム捨てるため木の側には置けない。
//!
//! 値は、掴み始めの値に、押した位置からの横の移動量が表す値の差を足して求める。掴んだだけでは値を変えない
//! （掴み始めたと、動かさずに放したは今の値をそのまま発する）。つまみの中心から離れた所を掴んでも押した位置へ飛ばない。
//! 区間の外を押したときだけは、押した位置の値から始める。
//! ポインタの位置が分からないフレーム（ポインタが窓の外へ出た等）は、最後に分かった位置を使う。egui がドラッグを
//! 終えたら、放したと判定できたフレームでなくても、最後に分かった位置の値で放したを発する。

use super::hit::{今の区間と位置, 掴み始め};
use super::layout::区間の帯の配置;
use super::{区間の帯の掴んだもの, 区間の帯の操作};
use crate::measure::{帯の値, 論理画素};

/// 帯を動かすボタン。右ボタンと中ボタンは右クリックメニュー等の別の操作に使われるため、ドラッグとして扱わない。
const 主ボタン: egui::PointerButton = egui::PointerButton::Primary;

/// 掴んでいる間の記憶とは、押したときに決まる掴み始めと押した横の位置と、最後に分かった横の位置と、最後に発した値の組のことである。
#[derive(Clone, Copy)]
struct 掴んでいる間の記憶 {
    掴み始め: 掴み始め,
    押した横の位置: 論理画素,
    最後に分かった横の位置: 論理画素,
    最後に発した値: 帯の値,
}

/// 区間の帯のドラッグとは、1フレームの反応と、帯の配置と、このフレームの区間と位置の組のことである。
pub(super) struct 区間の帯のドラッグ<'反応> {
    pub(super) 反応: &'反応 egui::Response,
    pub(super) 配置: 区間の帯の配置,
    pub(super) 今の値: 今の区間と位置,
}

impl 区間の帯のドラッグ<'_> {
    /// このフレームで発する操作を順に返す。何も掴まない位置で始めたドラッグは無視する。
    pub(super) fn 操作を読み取る(&self, ui: &egui::Ui) -> Vec<区間の帯の操作> {
        let 鍵 = self.反応.id.with("区間の帯の掴んでいる間の記憶");
        let mut 操作一覧 = Vec::new();
        if self.反応.drag_started_by(主ボタン) {
            ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(鍵));
            if let Some(記憶) = self.押した位置から掴む(ui) {
                ui.data_mut(|記憶域| 記憶域.insert_temp(鍵, 記憶));
                let 掴んだもの = 記憶.掴み始め.掴んだもの;
                let 値 = 記憶.最後に発した値;
                操作一覧.push(区間の帯の操作::掴み始めた {
                    掴んだもの, 値
                });
            }
        }
        let Some(mut 記憶) = ui.data(|記憶域| 記憶域.get_temp::<掴んでいる間の記憶>(鍵))
        else {
            return 操作一覧;
        };
        if let Some(位置) = ui.input(|入力| 入力.pointer.latest_pos()) {
            記憶.最後に分かった横の位置 = 論理画素::生成する(位置.x);
        }
        let 値 = 記憶.最後に分かった横の位置での値(&self.配置);
        let 掴んだもの = 記憶.掴み始め.掴んだもの;
        if self.反応.dragged_by(主ボタン) && !self.反応.drag_stopped_by(主ボタン) {
            if 値 != 記憶.最後に発した値 {
                操作一覧.push(区間の帯の操作::動かしている {
                    掴んだもの, 値
                });
                記憶.最後に発した値 = 値;
            }
            ui.data_mut(|記憶域| 記憶域.insert_temp(鍵, 記憶));
            return 操作一覧;
        }
        ui.data_mut(|記憶域| 記憶域.remove::<掴んでいる間の記憶>(鍵));
        操作一覧.push(区間の帯の操作::放した {
            掴んだもの, 値
        });
        操作一覧
    }

    /// ポインタを押した位置から掴み始めを判定し、記憶を作る。
    fn 押した位置から掴む(&self, ui: &egui::Ui) -> Option<掴んでいる間の記憶> {
        let 押した位置 = ui
            .input(|入力| 入力.pointer.press_origin())
            .or(self.反応.interact_pointer_pos())?;
        let 掴み始め = self.今の値.掴み始めを判定する(&self.配置, 押した位置)?;
        let 押した横の位置 = 論理画素::生成する(押した位置.x);
        Some(掴んでいる間の記憶 {
            掴み始め,
            押した横の位置,
            最後に分かった横の位置: 押した横の位置,
            最後に発した値: 掴み始め.値,
        })
    }
}

impl 掴んでいる間の記憶 {
    /// 押した横の位置から最後に分かった横の位置まで動かした分だけ、掴んだものの値を動かす。
    /// 収め方は `帯の全体の範囲` の規則（範囲の外の値はそれより外へ動かない）による。
    fn 最後に分かった横の位置での値(
        &self, 配置: &区間の帯の配置
    ) -> 帯の値 {
        let 差 =
            配置.横の移動量の値の差(self.最後に分かった横の位置 - self.押した横の位置);
        let 始め = self.掴み始め;
        let 全体 = 配置.全体;
        match 始め.掴んだもの {
            区間の帯の掴んだもの::区間の内側 => 全体
                .区間を動かす前より外へ出さずに開始を収める(
                    始め.値 + 差,
                    始め.値,
                    始め.区間の長さ,
                ),
            区間の帯の掴んだもの::開始のつまみ
            | 区間の帯の掴んだもの::終了のつまみ
            | 区間の帯の掴んだもの::位置の印 => {
                全体.動かす前より外へ出さずに収める(始め.値 + 差, 始め.値)
            }
        }
    }
}
