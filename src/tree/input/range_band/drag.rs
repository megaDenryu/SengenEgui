//! 区間の帯のドラッグの読み取り。egui の反応から、掴んだものとその値をドラッグの段階ごとに読み取る。
//! 掴み始めと最後に発した値はドラッグの間フレームをまたいで保つ必要があるため、範囲枠付き画像と同じく
//! 入力の部品が共有する手順（`pointer_drag`）で egui の一時記憶に置く。
//!
//! 値は、掴み始めの値に、押した位置からの横の移動量が表す値の差（掴み始めた回の目盛りで求める）を足して求める。掴んだだけでは値を変えない
//! （掴み始めたと、動かさずに放したは今の値をそのまま発する）。つまみの中心から離れた所を掴んでも押した位置へ飛ばない。
//! 区間の外を押したときだけは、押した位置の値から始める（位置の印を移すときも、`区間の外` を掴むときも同じ）。
//! ポインタの位置が分からないフレーム（ポインタがウィンドウの外へ出た等）は、最後に分かった位置を使う。egui がドラッグを
//! 終えたら、放したと判定できたフレームでなくても、最後に分かった位置の値で放したを発する。

use super::hit::今の区間と位置;
use super::hold::掴んでいる間の記憶;
use super::layout::区間の帯の配置;
use super::区間の帯の操作;
use crate::measure::論理画素;
use crate::tree::input::horizontal_drag::横に動かす値の1フレーム;
use crate::tree::input::pointer_drag::{
    ドラッグの段階, 今のポインタの座標, 掴んでいる間の記憶の置き場,
};

// 区間の帯のドラッグとは、1フレームの反応と、帯の配置と、このフレームの区間と位置の組のことである。
pub(super) struct 区間の帯のドラッグ<'反応> {
    pub(super) 反応: &'反応 egui::Response,
    pub(super) 配置: 区間の帯の配置,
    pub(super) 今の値: 今の区間と位置,
}

impl 区間の帯のドラッグ<'_> {
    // このフレームで発する操作を順に返す。押した位置が分からないまま始まったドラッグは無視する。
    pub(super) fn 操作を読み取る(&self, ui: &egui::Ui) -> Vec<区間の帯の操作> {
        let 置き場 = 掴んでいる間の記憶の置き場::<掴んでいる間の記憶>::反応から作る(self.反応);
        let mut 操作一覧 = Vec::new();
        if let Some(押した座標) = 置き場.ドラッグを始めた回なら前の記憶を捨てて押した座標を返す(
            ui,
            self.反応,
        ) {
            let 掴み始め = self.今の値.掴み始めを判定する(&self.配置, 押した座標);
            let 記憶 = 掴んでいる間の記憶::押した座標から作る(
                掴み始め,
                押した座標,
                self.配置.目盛り,
            );
            置き場.置く(ui, 記憶);
            操作一覧.push(区間の帯の操作::掴み始めた {
                掴んだもの: 掴み始め.掴んだもの,
                値: 掴み始め.値,
            });
        }
        let Some(記憶) = 置き場.読む(ui) else {
            return 操作一覧;
        };
        操作一覧.extend(self.掴んだ後のフレームを読む(ui, &置き場, 記憶));
        操作一覧
    }

    // 掴み始めた後の1フレームを読み、発する操作を返す。ドラッグを続けるなら次の記憶を置き、終えたら記憶を捨てる。
    fn 掴んだ後のフレームを読む(
        &self,
        ui: &egui::Ui,
        置き場: &掴んでいる間の記憶の置き場<掴んでいる間の記憶>,
        記憶: 掴んでいる間の記憶,
    ) -> Option<区間の帯の操作> {
        let 掴んだもの = 記憶.掴み始め.掴んだもの;
        let ポインタの横の位置 =
            今のポインタの座標(ui).map(|座標| 論理画素::生成する(座標.x));
        let 覚えた記憶 = 記憶.横のドラッグを替える(
            記憶
                .横のドラッグ
                .ポインタの横の位置を覚える(ポインタの横の位置),
        );
        let 値 = 覚えた記憶.動かした後の値を求める(self.配置.目盛り.全体());
        match 覚えた記憶.横のドラッグ.求めた値でこのフレームを決める(
            値,
            ドラッグの段階::反応から読む(self.反応),
        ) {
            横に動かす値の1フレーム::続ける {
                動かした値,
                次の記憶,
            } => {
                置き場.置く(ui, 覚えた記憶.横のドラッグを替える(次の記憶));
                動かした値.map(|値| 区間の帯の操作::動かしている {
                    掴んだもの, 値
                })
            }
            横に動かす値の1フレーム::終える { 放した値 } => {
                置き場.捨てる(ui);
                Some(区間の帯の操作::放した {
                    掴んだもの,
                    値: 放した値,
                })
            }
        }
    }
}
