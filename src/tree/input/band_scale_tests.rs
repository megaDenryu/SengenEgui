//! 帯の横の目盛りが、確保した矩形が左右の余白を合わせたより狭いとき、幅0の目盛りになることを確かめる。

use super::band_scale::帯の横の目盛り;
use crate::measure::{帯の値, 帯の値の差, 帯の全体の範囲, 画素};

fn 零から百() -> 帯の全体の範囲 {
    match 帯の全体の範囲::生成する(
        帯の値::倍精度の小数から生成する(0.0),
        帯の値::倍精度の小数から生成する(100.0),
    ) {
        Ok(全体) => 全体,
        Err(不正) => panic!("0〜100 は正しい全体の範囲である（到達したらバグ）: {不正}"),
    }
}

#[test]
fn 余白より狭い矩形では幅0の目盛りになり移動量は値の差を生まない() {
    let 幅10の矩形 = egui::Rect::from_min_size(egui::Pos2::ZERO, egui::vec2(10.0, 20.0));
    let 目盛り =
        帯の横の目盛り::確保した矩形の内側に刻む(幅10の矩形, 零から百());
    assert_eq!(目盛り.横の範囲().span(), 0.0);
    assert_eq!(
        目盛り.横の移動量から値の差を求める(画素(5.0)),
        帯の値の差::倍精度の小数から生成する(0.0)
    );
}

#[test]
fn 余白より広い矩形では余白を除いた幅の目盛りになる() {
    let 幅216の矩形 = egui::Rect::from_min_size(egui::Pos2::ZERO, egui::vec2(216.0, 20.0));
    let 目盛り =
        帯の横の目盛り::確保した矩形の内側に刻む(幅216の矩形, 零から百());
    assert_eq!(目盛り.横の範囲(), egui::Rangef::new(8.0, 208.0));
}
