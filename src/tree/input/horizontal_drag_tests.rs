//! 横に動かす値の記憶の分岐を確かめる。ポインタの位置が分からないフレームは最後に分かった位置を使うことと、
//! egui がドラッグを放したと判定できずに終えたときも放したとすること。この2つは egui の入力の合成では作りにくいため、
//! 記憶のメソッドを直に呼んで確かめる。

use super::horizontal_drag::{横に動かす値の1フレーム, 横に動かす値の記憶};
use super::pointer_drag::ドラッグの段階;
use crate::measure::{帯の値, 画素};

fn 値(数: f64) -> 帯の値 {
    帯の値::倍精度の小数から生成する(数)
}

#[test]
fn ポインタの位置が分からないフレームは最後に分かった位置を使う() {
    let 記憶 = 横に動かす値の記憶::押した横の位置から作る(画素(10.0), 値(0.0))
        .ポインタの横の位置を覚える(Some(画素(30.0)))
        .ポインタの横の位置を覚える(None);
    assert_eq!(記憶.最後に分かった横の位置(), 画素(30.0));
    assert_eq!(記憶.押した横の位置(), 画素(10.0));
}

#[test]
fn 放したと判定できずに終わったときも放したとする() {
    let 記憶 = 横に動かす値の記憶::押した横の位置から作る(画素(10.0), 値(0.0));
    assert_eq!(
        記憶.求めた値でこのフレームを決める(
            値(5.0),
            ドラッグの段階::放したと判定できずに終わった
        ),
        横に動かす値の1フレーム::終える {
            放した値: 値(5.0)
        }
    );
}

#[test]
fn 続けているフレームは値が変わったときだけ動かした値を出す() {
    let 記憶 = 横に動かす値の記憶::押した横の位置から作る(画素(10.0), 値(0.0));
    let 変わらない =
        記憶.求めた値でこのフレームを決める(値(0.0), ドラッグの段階::続けている);
    assert!(matches!(
        変わらない,
        横に動かす値の1フレーム::続ける {
            動かした値: None,
            ..
        }
    ));
    let 変わった =
        記憶.求めた値でこのフレームを決める(値(2.0), ドラッグの段階::続けている);
    assert!(matches!(
        変わった,
        横に動かす値の1フレーム::続ける { 動かした値: Some(動かした), .. } if 動かした == 値(2.0)
    ));
}

#[test]
fn 続けた次のフレームで同じ値なら動かした値は無い() {
    let 記憶 = 横に動かす値の記憶::押した横の位置から作る(画素(10.0), 値(0.0));
    let 横に動かす値の1フレーム::続ける { 次の記憶, .. } =
        記憶.求めた値でこのフレームを決める(値(2.0), ドラッグの段階::続けている)
    else {
        panic!("続けている段階では続ける（到達したらバグ）");
    };
    let 次のフレーム =
        次の記憶.求めた値でこのフレームを決める(値(2.0), ドラッグの段階::続けている);
    assert!(matches!(
        次のフレーム,
        横に動かす値の1フレーム::続ける {
            動かした値: None,
            ..
        }
    ));
}
