//! 横に動かす値のドラッグ。区間の帯のつまみ・区間・位置の印と、時間の行の並びの位置の線が共に使う、横の位置から1つの
//! 帯の値を求めて運ぶドラッグの規則である。ポインタの位置が分からないフレームは最後に分かった位置を使い、値が変わった
//! フレームだけ動かしているを発する。egui がドラッグを終えたら、放したと判定できたフレームでなくても、最後に分かった位置の
//! 値で放したを発する。横の位置から値をどう求めるか（押した所からの移動量で掴み始めの値を動かすか、ポインタの位置の値を
//! そのまま使うか）は部品ごとに違うため、呼び出す側が求め方を渡す。

use super::pointer_drag::ドラッグの段階;
use crate::measure::{帯の値, 論理画素};

// 横に動かす値の記憶とは、押した横の位置と、最後に分かった横の位置と、最後に発した値の組のことである。
#[derive(Clone, Copy, Debug)]
pub(in crate::tree::input) struct 横に動かす値の記憶 {
    押した横の位置: 論理画素,
    最後に分かった横の位置: 論理画素,
    最後に発した値: 帯の値,
}

// 横に動かす値の出来事とは、掴み始めた後の1フレームで発する、動かしている値と放した値の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq)]
pub(in crate::tree::input) enum 横に動かす値の出来事 {
    動かしている(帯の値),
    放した(帯の値),
}

// 横に動かす値の1フレームの結果とは、このフレームで発する出来事と、次のフレームへ持ち越す記憶の組のことである。
pub(in crate::tree::input) struct 横に動かす値の1フレームの結果 {
    pub(in crate::tree::input) 出来事: Option<横に動かす値の出来事>,
    pub(in crate::tree::input) 次の記憶: Option<横に動かす値の記憶>,
}

impl 横に動かす値の記憶 {
    // 押した横の位置と掴み始めの値から作る。最後に分かった位置は押した位置、最後に発した値は掴み始めの値から始める。
    pub(in crate::tree::input) fn 押した横の位置から作る(
        押した横の位置: 論理画素,
        掴み始めの値: 帯の値,
    ) -> Self {
        Self {
            押した横の位置,
            最後に分かった横の位置: 押した横の位置,
            最後に発した値: 掴み始めの値,
        }
    }

    // 掴み始めた後の1フレームを読む。値を求める関数は、押した横の位置と今の横の位置から値を求める。
    pub(in crate::tree::input) fn 掴んだ後のフレームを読む(
        self,
        ポインタの横の位置: Option<論理画素>,
        段階: ドラッグの段階,
        値を求める: impl FnOnce(論理画素, 論理画素) -> 帯の値,
    ) -> 横に動かす値の1フレームの結果 {
        let 横の位置 = ポインタの横の位置.unwrap_or(self.最後に分かった横の位置);
        let 値 = 値を求める(self.押した横の位置, 横の位置);
        if 段階 != ドラッグの段階::続けている {
            return 横に動かす値の1フレームの結果 {
                出来事: Some(横に動かす値の出来事::放した(値)),
                次の記憶: None,
            };
        }
        横に動かす値の1フレームの結果 {
            出来事: (値 != self.最後に発した値)
                .then_some(横に動かす値の出来事::動かしている(値)),
            次の記憶: Some(Self {
                最後に分かった横の位置: 横の位置,
                最後に発した値: 値,
                ..self
            }),
        }
    }
}
