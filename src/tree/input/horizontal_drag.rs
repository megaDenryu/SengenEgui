//! 横に動かす値のドラッグ。区間の帯のつまみ・区間・位置の印と、時間の行の並びの位置の線が共に使う、横の位置から1つの
//! 帯の値を求めて運ぶドラッグの規則である。記憶は押した横の位置と最後に分かった横の位置と最後に発した値を運ぶだけであり、
//! 横の位置から値をどう求めるか（押した所からの移動量で掴み始めの値を動かすか、ポインタの位置の値をそのまま使うか）は
//! 部品ごとに違うため、呼び出す側が記憶の横の位置を読んで求める。1フレームの手順は次の2つのメソッドに分かれる。
//! 1. `ポインタの横の位置を覚える`: ポインタの位置が分からないフレームは、最後に分かった位置をそのまま使う
//! 2. `求めた値でこのフレームを決める`: 値が変わったフレームだけ動かした値を出す。egui がドラッグを終えたら、放したと
//!    判定できたフレームでなくても、その値で放したとする

use super::pointer_drag::ドラッグの段階;
use crate::measure::{帯の値, 論理画素};

// 横に動かす値の記憶とは、押した横の位置と、最後に分かった横の位置と、最後に発した値の組のことである。
#[derive(Clone, Copy, Debug, PartialEq)]
pub(in crate::tree::input) struct 横に動かす値の記憶 {
    押した横の位置: 論理画素,
    最後に分かった横の位置: 論理画素,
    最後に発した値: 帯の値,
}

// 横に動かす値の1フレームとは、掴み始めた後の1フレームで、ドラッグを続けるか（値が変わったなら動かした値と、次の記憶を
// 持つ）、終えるか（放した値を持つ）の区別のことである。
#[derive(Clone, Copy, Debug, PartialEq)]
pub(in crate::tree::input) enum 横に動かす値の1フレーム {
    続ける {
        動かした値: Option<帯の値>,
        次の記憶: 横に動かす値の記憶,
    },
    終える {
        放した値: 帯の値,
    },
}

impl 横に動かす値の記憶 {
    // 押した横の位置と掴み始めの値から作る。最後に分かった位置は押した位置、最後に発した値は掴み始めの値から始める。
    pub(in crate::tree::input) fn 押した横の位置から作る(
        押した横の位置: 論理画素,
        掴み始めの値: 帯の値,
    ) -> Self {
        Self {
            押した横の位置,
            最後に分かった横の位置: 押した横の位置,
            最後に発した値: 掴み始めの値,
        }
    }

    // このフレームのポインタの横の位置を覚えた記憶。位置が分からないフレームは、最後に分かった位置のままにする。
    pub(in crate::tree::input) fn ポインタの横の位置を覚える(
        self,
        ポインタの横の位置: Option<論理画素>,
    ) -> Self {
        Self {
            最後に分かった横の位置: ポインタの横の位置
                .unwrap_or(self.最後に分かった横の位置),
            ..self
        }
    }

    pub(in crate::tree::input) fn 押した横の位置(self) -> 論理画素 {
        self.押した横の位置
    }

    pub(in crate::tree::input) fn 最後に分かった横の位置(self) -> 論理画素 {
        self.最後に分かった横の位置
    }

    // 呼び出す側が横の位置から求めた値で、このフレームを続けるか終えるかを決める。
    pub(in crate::tree::input) fn 求めた値でこのフレームを決める(
        self,
        値: 帯の値,
        段階: ドラッグの段階,
    ) -> 横に動かす値の1フレーム {
        match 段階 {
            ドラッグの段階::続けている => {
                横に動かす値の1フレーム::続ける {
                    動かした値: (値 != self.最後に発した値).then_some(値),
                    次の記憶: Self {
                        最後に発した値: 値,
                        ..self
                    },
                }
            }
            ドラッグの段階::放した | ドラッグの段階::放したと判定できずに終わった => {
                横に動かす値の1フレーム::終える { 放した値: 値 }
            }
        }
    }
}
