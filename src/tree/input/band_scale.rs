//! 帯の横の目盛り。区間の帯と時間の行の並びが共に使う、帯の全体の範囲の値と画面の横の位置を相互に求める規則である。
//! 部品が確保した矩形の左右に `帯の左右の余白` を空けた内側の左端を全体の始め、右端を全体の終わりとする。
//! 余白を空けるのは、全体の端にあるつまみや位置の印の頭が部品の外へはみ出さず、端でも掴めるようにするためである。

use crate::measure::{
    帯の値, 帯の値の差, 帯の全体の範囲, 画素, 論理画素, 負でない論理画素
};

const 帯の左右の余白: 論理画素 = 画素(8.0);

// 帯の横の目盛りとは、目盛りを刻む横の範囲（左端と0以上の幅）と、その範囲が表す全体の範囲の組のことである。
// ドラッグの間に覚えておけるよう値で持つ（複製しても同じ規則になる）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub(in crate::tree::input) struct 帯の横の目盛り {
    左端: 論理画素,
    幅: 負でない論理画素,
    全体: 帯の全体の範囲,
}

impl 帯の横の目盛り {
    // 確保した矩形の左右に余白を空けた内側へ目盛りを刻む。矩形が左右の余白を合わせたより狭いときは幅0の目盛りにする
    // （どの値も左端の位置に描き、横の移動量は値の差を生まない）。
    pub(in crate::tree::input) fn 確保した矩形の内側に刻む(
        確保した矩形: egui::Rect,
        全体: 帯の全体の範囲,
    ) -> Self {
        let 確保した幅 = 論理画素::生成する(確保した矩形.width());
        Self {
            左端: 論理画素::生成する(確保した矩形.left()) + 帯の左右の余白,
            幅: 負でない論理画素::負なら0にして生成する(
                確保した幅 - 帯の左右の余白 - 帯の左右の余白,
            ),
            全体,
        }
    }

    pub(in crate::tree::input) fn 全体(self) -> 帯の全体の範囲 {
        self.全体
    }

    // 目盛りを刻んだ横の範囲。部品の中の矩形を組み立てる egui の境界でだけ使う。
    pub(in crate::tree::input) fn 横の範囲(self) -> egui::Rangef {
        let 左端 = self.左端.eguiへ渡す値();
        egui::Rangef::new(左端, 左端 + self.幅.論理画素にする().eguiへ渡す値())
    }

    // 値を描く横の位置。全体の範囲の外の値は端の位置にする。
    pub(in crate::tree::input) fn 値から横の位置を求める(
        self,
        値: 帯の値,
    ) -> 論理画素 {
        let 範囲 = self.横の範囲();
        論理画素::生成する(
            self.全体
                .割合へ写す(値)
                .二つの値の間を取る(範囲.min, 範囲.max),
        )
    }

    // 値を描く横の位置を、全体の範囲の外の値も端へ収めずに求める。全体からはみ出す塊を描くときに使う。
    pub(in crate::tree::input) fn 値から範囲へ収めずに横の位置を求める(
        self,
        値: 帯の値,
    ) -> 論理画素 {
        self.左端
            + self
                .幅
                .論理画素にする()
                .比を掛ける(self.全体.始めからの比(値))
    }

    // 横の位置が指す値。全体の範囲の外の位置は全体の端の値にする。
    pub(in crate::tree::input) fn 横の位置から値を求める(
        self,
        横の位置: 論理画素,
    ) -> 帯の値 {
        let 始めからの差 = self.横の移動量から値の差を求める(横の位置 - self.左端);
        self.全体.内側へ収める(self.全体.始め() + 始めからの差)
    }

    // 横の移動量が表す値の差。幅0の目盛りでは比が決まらないため差を0とする（幅の無い帯の上では値を区別できない）。
    pub(in crate::tree::input) fn 横の移動量から値の差を求める(
        self,
        移動量: 論理画素,
    ) -> 帯の値の差 {
        移動量.に対する比(self.幅.論理画素にする()).map_or(
            帯の値の差::倍精度の小数から生成する(0.0),
            |比| self.全体.長さ().比を掛ける(比),
        )
    }
}
