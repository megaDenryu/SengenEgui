//! 確定時のみ発行の入力欄が編集中の下書きを置く場所。egui の一時記憶に、本文と一緒に
//! 「元の値」「最後に描画したフレーム」「そのときフォーカスを持っていたか」を置く。
//! 直前のフレームに描画されていなかった下書き（入力欄が木から消えていた）と、元の値が外から
//! 変わった下書きは古いものとして捨てる。フォーカスの有無を覚えるのは、同じフレームの後の部品
//! （キー操作等）がフォーカスを手放させたとき、次のフレームでその喪失を自分で検出するためである
//! （egui の `lost_focus` は同じフレーム内の喪失しか報告しない）。

/// 下書きとは、編集中の本文と、それを作った元の値と、最後に描画した状況の組のことである。
#[derive(Clone)]
struct 下書き {
    本文: String,
    元の値: String,
    最後に描画したフレーム: u64,
    フォーカスを持っていた: bool,
}

/// 取り出した下書きとは、この描画で編集の続きにする本文と、前回フォーカスを持っていたかの組のことである。
pub(super) struct 取り出した下書き {
    pub(super) 本文: String,
    pub(super) フォーカスを持っていた: bool,
}

/// 下書きの置き場とは、識別子で決まる egui の一時記憶の中の1つの場所のことである。
pub(super) struct 下書きの置き場 {
    鍵: egui::Id,
}

impl 下書きの置き場 {
    pub(super) fn 新規(ui: &egui::Ui, 識別子: &str) -> Self {
        Self {
            鍵: ui.make_persistent_id(識別子),
        }
    }

    /// 生きている下書きを取り出す。無い、または古いなら現在の値から始める。
    pub(super) fn 取り出す(
        &self, ui: &egui::Ui, 現在の値: &str
    ) -> 取り出した下書き {
        let 現在のフレーム = ui.ctx().cumulative_frame_nr();
        ui.data(|記憶| 記憶.get_temp::<下書き>(self.鍵))
            .filter(|下書き| 下書き.最後に描画したフレーム + 1 >= 現在のフレーム)
            .filter(|下書き| 下書き.元の値 == 現在の値)
            .map_or_else(
                || 取り出した下書き {
                    本文: 現在の値.to_string(),
                    フォーカスを持っていた: false,
                },
                |下書き| 取り出した下書き {
                    本文: 下書き.本文,
                    フォーカスを持っていた: 下書き.フォーカスを持っていた,
                },
            )
    }

    /// 下書きを保存する。描画するたびに呼び、最後に描画したフレームとフォーカスの有無を更新する。
    pub(super) fn 保存する(
        &self,
        ui: &egui::Ui,
        本文: String,
        元の値: String,
        フォーカスを持っている: bool,
    ) {
        let 下書き = 下書き {
            本文,
            元の値,
            最後に描画したフレーム: ui.ctx().cumulative_frame_nr(),
            フォーカスを持っていた: フォーカスを持っている,
        };
        ui.data_mut(|記憶| 記憶.insert_temp(self.鍵, 下書き));
    }

    pub(super) fn 捨てる(&self, ui: &egui::Ui) {
        ui.data_mut(|記憶| 記憶.remove::<下書き>(self.鍵));
    }
}
