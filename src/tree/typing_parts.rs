//! 文字を打つ部品の集まり。一行・複数行のテキスト入力と数値入力は、描いたフレームごとに自分の識別子と、フォーカスを持っていたかを知らせる。
//! キー操作はこの集まりを見て、フォーカスを持つ部品が文字を打つ部品かを判定する(`文字を打っている間か`)。
//! キー操作は画面の木の最初に描かれ、そのフレームの文字を打つ部品はまだ知らせていないため、前のフレームとこのフレームの集まりを合わせて使う。
//! 2フレームより前に描いた部品は集まりから消えるため、描かれなくなった入力欄と識別子が重なる別の部品を、文字を打つ部品とみなさない。

use std::collections::HashSet;

/// 1フレームに描いた文字を打つ部品の識別子と、その中にフォーカスを持つ部品があったかの組。
#[derive(Clone, Default)]
struct 一フレームの部品 {
    識別子: HashSet<egui::Id>,
    フォーカスを持つ部品があったか: bool,
}

/// 文字を打つ部品の集まりとは、このフレームと前のフレームに描いた文字を打つ部品の組と、このフレームの番号のことである。
#[derive(Clone, Default)]
pub(crate) struct 文字を打つ部品の集まり {
    フレームの番号: u64,
    このフレーム: 一フレームの部品,
    前のフレーム: 一フレームの部品,
}

impl 文字を打つ部品の集まり {
    /// egui の一時記憶に置く識別子。
    fn 置き場() -> egui::Id {
        egui::Id::new("SengenEgui の文字を打つ部品の集まり")
    }

    /// フレームが進んでいれば、このフレームの集まりを前のフレームへ移す。2フレーム以上進んでいれば、前のフレームは空にする。
    fn フレームを合わせる(&mut self, 今の番号: u64) {
        if self.フレームの番号 == 今の番号 {
            return;
        }
        let このフレーム = std::mem::take(&mut self.このフレーム);
        self.前のフレーム = if self.フレームの番号 + 1 == 今の番号 {
            このフレーム
        } else {
            一フレームの部品::default()
        };
        self.フレームの番号 = 今の番号;
    }

    /// 文字を打つ部品が、描いたフレームで自分の識別子とフォーカスを持っているかを知らせる。
    pub(crate) fn 知らせる(eguiの本体: &egui::Context, 反応: &egui::Response) {
        let 番号 = eguiの本体.cumulative_pass_nr();
        // 注意: フォーカスは一時記憶を書く閉包の外で読む。閉包の中で egui の本体を読むと、同じ錠を二重に取って止まる。
        let フォーカスを持つか = 反応.has_focus();
        eguiの本体.data_mut(|記憶| {
            let 集まり = 記憶.get_temp_mut_or_default::<Self>(Self::置き場());
            集まり.フレームを合わせる(番号);
            集まり.このフレーム.識別子.insert(反応.id);
            集まり.このフレーム.フォーカスを持つ部品があったか |= フォーカスを持つか;
        });
    }

    /// 利用者が文字を打っている間か。フォーカスを持つ部品が、前のフレームかこのフレームに描いた文字を打つ部品なら真である。
    /// 前のフレームに文字を打つ部品がフォーカスを持っていたときも真にする。egui はフレームの始めに Escape で入力欄のフォーカスを外すため、
    /// その Escape を入力欄の編集をやめる操作として入力欄に任せ、キー操作が消費しないようにするためである。
    pub(crate) fn 文字を打っている間か(eguiの本体: &egui::Context) -> bool {
        let 番号 = eguiの本体.cumulative_pass_nr();
        let フォーカス = eguiの本体.memory(|記憶| 記憶.focused());
        eguiの本体.data_mut(|記憶| {
            let 集まり = 記憶.get_temp_mut_or_default::<Self>(Self::置き場());
            集まり.フレームを合わせる(番号);
            集まり.前のフレーム.フォーカスを持つ部品があったか
                || フォーカス.is_some_and(|識別子| {
                    集まり.前のフレーム.識別子.contains(&識別子)
                        || 集まり.このフレーム.識別子.contains(&識別子)
                })
        })
    }
}
