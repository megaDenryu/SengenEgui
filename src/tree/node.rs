//! ノードの直和型と描画。族ごとの列挙を枝に持ち、描画と写像は族へ委譲する。

use crate::measure::論理画素;
use crate::tree::{
    attach::付け足し, container::容器, display::表示の部品, input::入力の部品,
    invisible::見えない部品,
};

/// ノードとは、1フレーム分のUI構造の記述のことである。
/// 型引数 M は操作が発する応答（利用側で定義するメッセージ型）を表す。
pub enum ノード<M> {
    /// 応答を発しない表示の部品。
    表示(表示の部品),
    /// 操作されると応答を発する入力の部品。
    入力(入力の部品<M>),
    /// 子を並べる容器。
    容器(容器<M>),
    /// 1つの子に説明や右クリックメニュー等を付け足したもの。
    付け足し(Box<付け足し<M>>),
    /// 画面に何も描かず、入力の事象だけを見張る部品。
    見えない(見えない部品<M>),
    /// 並びの向きに空ける余白。
    余白(論理画素),
    /// 並びの向きに直交する区切り線。
    区切り線,
    /// 何も描画しないノード。`if` 式の「無い側」に使う。
    無し,
}

impl<M: Clone> ノード<M> {
    /// 木を描画し、操作が発した応答を引数の `発行した応答` へ積む。
    /// 描画した範囲の反応を返す。末端の部品は部品の反応、容器は枠や領域の反応である。
    pub fn 描画する(
        &self, ui: &mut egui::Ui, 発行した応答: &mut Vec<M>
    ) -> egui::Response {
        match self {
            Self::表示(中身) => 中身.描画する(ui),
            Self::入力(中身) => 中身.描画する(ui, 発行した応答),
            Self::容器(中身) => 中身.描画する(ui, 発行した応答),
            Self::付け足し(中身) => 中身.描画する(ui, 発行した応答),
            Self::見えない(中身) => 中身.描画する(ui, 発行した応答),
            Self::余白(量) => {
                ui.add_space(量.eguiへ渡す値());
                ui.response()
            }
            Self::区切り線 => ui.separator(),
            Self::無し => ui.response(),
        }
    }

    /// 描画して、発した応答の一覧を返す。アプリの毎フレーム処理の入口。
    pub fn 描画して集める(&self, ui: &mut egui::Ui) -> Vec<M> {
        let mut 発行した応答 = Vec::new();
        self.描画する(ui, &mut 発行した応答);
        発行した応答
    }
}
