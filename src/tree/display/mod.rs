//! 表示の族。応答を発しない部品のまとまりであり、応答型 M を持たない。

mod external_link;
mod image;
mod image_source;
mod notice;
mod progress_bar;
mod spinner;
mod text;

pub use external_link::外部リンク型;
pub use image::画像型;
pub use image_source::画像の出所;
pub use notice::{一定時間で消える通知型, 通知の回};
pub use progress_bar::進捗バー型;
pub use spinner::読み込み中表示型;
pub use text::文字表示型;

/// 表示の部品とは、応答を発しない部品の区別のことである。
pub enum 表示の部品 {
    /// 文字列の表示。
    文字表示(文字表示型),
    /// 割合を横棒で示す表示。
    進捗バー(進捗バー型),
    /// 処理中であることを回転で示す表示。
    読み込み中表示(読み込み中表示型),
    /// ブラウザで行き先を開くリンク。
    外部リンク(外部リンク型),
    /// 画像の表示。
    画像(画像型),
    /// 他の部品の上へ重ねて出し、一定時間で消える通知。
    一定時間で消える通知(一定時間で消える通知型),
}

impl 表示の部品 {
    pub(crate) fn 描画する(&self, ui: &mut egui::Ui) -> egui::Response {
        match self {
            Self::文字表示(中身) => 中身.描画する(ui),
            Self::進捗バー(中身) => 中身.描画する(ui),
            Self::読み込み中表示(中身) => 中身.描画する(ui),
            Self::外部リンク(中身) => 中身.描画する(ui),
            Self::画像(中身) => 中身.描画する(ui),
            Self::一定時間で消える通知(中身) => 中身.描画する(ui),
        }
    }
}

ノードへ変換する!(表示, 表示の部品::文字表示, 文字表示型);
ノードへ変換する!(表示, 表示の部品::進捗バー, 進捗バー型);
ノードへ変換する!(表示, 表示の部品::読み込み中表示, 読み込み中表示型);
ノードへ変換する!(表示, 表示の部品::外部リンク, 外部リンク型);
ノードへ変換する!(表示, 表示の部品::画像, 画像型);
ノードへ変換する!(
    表示,
    表示の部品::一定時間で消える通知,
    一定時間で消える通知型
);
