//! 容器の族の応答型の写像。各容器の `写す` へ委譲して、部品ローカルの応答型を親の応答型へ埋め込む。
//! 入力の族と同じく、枝の多い族なので描画（mod.rs）と写像を分けて置く。

use std::rc::Rc;

use super::容器;

impl<M: 'static> 容器<M> {
    pub(crate) fn 写す<N: 'static>(self, 応答を変換する: Rc<dyn Fn(M) -> N>) -> 容器<N> {
        match self {
            Self::積み(中身) => 容器::積み(中身.写す(応答を変換する)),
            Self::スクロール(中身) => 容器::スクロール(中身.写す(応答を変換する)),
            Self::仮想列(中身) => 容器::仮想列(中身.写す(応答を変換する)),
            Self::折り畳み見出し(中身) => {
                容器::折り畳み見出し(中身.写す(応答を変換する))
            }
            Self::格子(中身) => 容器::格子(中身.写す(応答を変換する)),
            Self::ウィンドウ(中身) => 容器::ウィンドウ(中身.写す(応答を変換する)),
            Self::パネル(中身) => 容器::パネル(中身.写す(応答を変換する)),
            Self::タブ列(中身) => 容器::タブ列(中身.写す(応答を変換する)),
            Self::メニューバー(中身) => {
                容器::メニューバー(中身.写す(応答を変換する))
            }
            Self::メニュー(中身) => 容器::メニュー(中身.写す(応答を変換する)),
            Self::モーダル(中身) => 容器::モーダル(中身.写す(応答を変換する)),
            Self::使える大きさから組む(中身) => {
                容器::使える大きさから組む(中身.写す(応答を変換する))
            }
            Self::重ね(中身) => 容器::重ね(中身.写す(応答を変換する)),
            Self::大きさを決めた領域(中身) => {
                容器::大きさを決めた領域(中身.写す(応答を変換する))
            }
        }
    }
}
