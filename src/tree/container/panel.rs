//! パネル。親の領域の上下左右の縁に固定した区画と、残りを埋める中央の区画。
//!
//! 注意: egui は縁のパネルを先に描いて残りの領域を決めるため、中央パネルは同じ親の中で
//! 上下左右のパネルより後に置く。先に置くと中央が領域を全部取り、縁のパネルが重なる。
//! 縁のパネルの幅・高さは egui が識別子ごとに内部保持し、既定の値は最初のフレームだけに効く。範囲は毎フレーム効く（`panel_size` 参照）。
//! 装飾の枠系の項目は、egui のパネルの既定の枠（テーマの地の色と既定の内余白）へ上書きする。指定の無い項目は既定のまま残る。

use std::rc::Rc;

use crate::measure::論理画素;
use crate::style::スタイル;
use crate::tree::container::panel_side::{パネルの位置, 縁の種類};
use crate::tree::container::panel_size::パネルの大きさの指定;
use crate::tree::{ノード, 子を順に描画する};

/// パネル型とは、親の領域を縁と中央に区切る容器の記述のことである。
pub struct パネル型<M> {
    識別子: String,
    位置: パネルの位置,
    大きさの指定: パネルの大きさの指定,
    装飾値: スタイル,
    子一覧: Vec<ノード<M>>,
}

impl<M> パネル型<M> {
    pub(crate) fn 新規(
        識別子: String, 位置: パネルの位置, 子一覧: Vec<ノード<M>>
    ) -> Self {
        Self {
            識別子,
            位置,
            大きさの指定: パネルの大きさの指定::default(),
            装飾値: スタイル::無指定,
            子一覧,
        }
    }

    /// 左右のパネルで、最初に表示したときの幅を指定する。上下と中央では効かない。
    pub fn 既定の幅(mut self, 幅: 論理画素) -> Self {
        self.大きさの指定 = self.大きさの指定.最初の寸法を決める(幅);
        self
    }

    /// 左右のパネルで、幅が取れる範囲（最小と最大）を指定する。縁のドラッグで変えられる幅も、最初の幅もこの範囲へ収まる。
    /// 最大が最小より小さいときは最小を優先する。幅は装飾の内余白を含む。上下と中央では効かない。
    pub fn 幅の範囲(mut self, 最小: 論理画素, 最大: 論理画素) -> Self {
        self.大きさの指定 = self.大きさの指定.範囲を決める(最小, 最大);
        self
    }

    /// 上下のパネルで、最初に表示したときの高さを指定する。左右と中央では効かない。
    pub fn 既定の高さ(mut self, 高さ: 論理画素) -> Self {
        self.大きさの指定 = self.大きさの指定.最初の寸法を決める(高さ);
        self
    }

    /// 上下のパネルで、高さが取れる範囲（最小と最大）を指定する。縁のドラッグで変えられる高さも、最初の高さもこの範囲へ収まる。
    /// 最大が最小より小さいときは最小を優先する。高さは装飾の内余白を含む。左右と中央では効かない。
    pub fn 高さの範囲(mut self, 最小: 論理画素, 最大: 論理画素) -> Self {
        self.大きさの指定 = self.大きさの指定.範囲を決める(最小, 最大);
        self
    }

    /// 縁のドラッグで大きさを変えられるかを指定する。既定は変えられない。
    pub fn 大きさを変えられる(mut self, 変えられる: bool) -> Self {
        self.大きさの指定 = self.大きさの指定.変えられるかを決める(変えられる);
        self
    }

    /// 装飾を適用する。使う項目は枠系（背景色・内余白・外余白・角丸・枠線色・枠線太さ）であり、
    /// 背景色はパネルの地の全体を塗る。指定しない項目はテーマの地の色と egui の既定の余白のまま残る。
    pub fn 装飾(mut self, 指定: スタイル) -> Self {
        self.装飾値 = 指定;
        self
    }
}

impl<M: Clone> パネル型<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 中身を描く =
            |内側: &mut egui::Ui| 子を順に描画する(&self.子一覧, 内側, 発行した応答);
        let 種類 = self.位置.縁の種類へ変換する();
        let 枠 = self.装飾値.枠の指定を重ねる(種類.既定の枠(ui.style()));
        match 種類 {
            縁の種類::左右(側) => {
                self.大きさの指定
                    .左右のパネルを作る(側, egui::Id::new(&self.識別子))
                    .frame(枠)
                    .show_inside(ui, 中身を描く)
                    .response
            }
            縁の種類::上下(側) => {
                self.大きさの指定
                    .上下のパネルを作る(側, egui::Id::new(&self.識別子))
                    .frame(枠)
                    .show_inside(ui, 中身を描く)
                    .response
            }
            縁の種類::中央 => {
                egui::CentralPanel::default()
                    .frame(枠)
                    .show_inside(ui, 中身を描く)
                    .response
            }
        }
    }
}

impl<M: 'static> パネル型<M> {
    pub(crate) fn 写す<N: 'static>(
        self, 応答を変換する: Rc<dyn Fn(M) -> N>
    ) -> パネル型<N> {
        パネル型 {
            識別子: self.識別子,
            位置: self.位置,
            大きさの指定: self.大きさの指定,
            装飾値: self.装飾値,
            子一覧: crate::tree::map::子一覧を写す(self.子一覧, &応答を変換する),
        }
    }
}
