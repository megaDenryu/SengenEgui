//! ポインタが止まると隠す組の出し入れの記憶と、前の回の記憶とその回のポインタの様子から次の記憶を決める規則。
//!
//! 動いたと数えるのは、ポインタが下地の上で、最後に動いたと数えた位置から `動いたと数える距離` 以上離れたときと、
//! 下地の上で押したときである。同じ位置への移動の知らせ（窓の再描画などで届くことがある）や、手の震えほどの
//! わずかな移動では出さない。動いたと数えた位置はポインタが下地の外へ出ると忘れ、戻ってきたら動いたと数える。

use std::time::Duration;

use crate::measure::{画素, 論理画素};
use crate::tree::container::overlay_idle_pointer::{ポインタの様子, 入力の時刻};

/// ポインタが最後に動いたと数えた位置からこの距離以上離れたら、動いたと数える。
const 動いたと数える距離: 論理画素 = 画素(3.0);

/// 出し入れの状態とは、組の子を出しているか隠しているかの区別のことである。
#[derive(Clone, Copy, Debug)]
enum 出し入れの状態 {
    出している {
        数え始めた時刻: 入力の時刻,
    },
    隠している,
}

/// 出し入れの記憶とは、組がある回に決めた出し入れと、次の回に「動いたか」「外へ出たか」を判定するための値の組のことである。
#[derive(Clone, Copy, Debug)]
pub(super) struct 出し入れの記憶 {
    状態: 出し入れの状態,
    動いたと数えた位置: Option<egui::Pos2>,
    下地の上だったか: bool,
}

/// 出し入れの条件とは、次の記憶を決めるために指定から渡す値の組のことである。
pub(super) struct 出し入れの条件 {
    pub(super) 隠すまでの時間: Duration,
    pub(super) 出したままにするか: bool,
}

impl 出し入れの記憶 {
    /// 前の回の記憶とその回の様子から、次の記憶を決める。前の回の記憶が無ければ、その回から数え始める。
    /// 数え直す理由が無く、ポインタが下地の上から外へ出た回は、時間を待たずに隠す。
    pub(super) fn 次を決める(
        前の回: Option<Self>,
        様子: &ポインタの様子,
        条件: &出し入れの条件,
    ) -> Self {
        let 前の位置 = 前の回.and_then(|記憶| 記憶.動いたと数えた位置);
        let 動いたか = 様子.下地の上か && 位置が離れたか(様子.位置, 前の位置);
        let 数え直すか = 前の回.is_none()
            || 動いたか
            || 様子.下地の上で押したか
            || 様子.子の上で押し始めて押し続けているか
            || 様子.指定のキーを押しているか
            || 条件.出したままにするか;
        let 外へ出たか = 前の回.is_some_and(|記憶| 記憶.下地の上だったか) && !様子.下地の上か;
        let 状態 = if 数え直すか {
            出し入れの状態::出している {
                数え始めた時刻: 様子.今,
            }
        } else if 外へ出たか {
            出し入れの状態::隠している
        } else {
            前の回.map_or(出し入れの状態::隠している, |記憶| {
                記憶.時間が経ったら隠す(様子.今, 条件.隠すまでの時間)
            })
        };
        let 動いたと数えた位置 = match (様子.下地の上か, 動いたか || 前の回.is_none())
        {
            (false, _) => None,
            (true, true) => 様子.位置,
            (true, false) => 前の位置,
        };
        Self {
            状態,
            動いたと数えた位置,
            下地の上だったか: 様子.下地の上か,
        }
    }

    /// 子を出しているか。
    pub(super) fn 出すか(&self) -> bool {
        matches!(self.状態, 出し入れの状態::出している { .. })
    }

    /// 出している間は、隠すまでに残っている時間を返す。
    pub(super) fn 隠すまでの残り(
        &self,
        今: 入力の時刻,
        隠すまでの時間: Duration,
    ) -> Option<Duration> {
        match self.状態 {
            出し入れの状態::出している {
                数え始めた時刻
            } => Some(隠すまでの時間.saturating_sub(今.前の時刻から経った時間(数え始めた時刻))),
            出し入れの状態::隠している => None,
        }
    }

    fn 時間が経ったら隠す(
        self,
        今: 入力の時刻,
        隠すまでの時間: Duration,
    ) -> 出し入れの状態 {
        match self.隠すまでの残り(今, 隠すまでの時間) {
            Some(残り) if !残り.is_zero() => self.状態,
            _ => 出し入れの状態::隠している,
        }
    }
}

/// 今の位置が、最後に動いたと数えた位置から `動いたと数える距離` 以上離れたか。数えた位置が無ければ離れたとみなす。
fn 位置が離れたか(
    今の位置: Option<egui::Pos2>, 数えた位置: Option<egui::Pos2>
) -> bool {
    match (今の位置, 数えた位置) {
        (Some(今の位置), Some(数えた位置)) => {
            今の位置.distance(数えた位置) >= 動いたと数える距離.eguiへ渡す値()
        }
        (Some(_), None) => true,
        (None, _) => false,
    }
}
