//! 重ねる容器。下地の子を描いてから、その矩形の上へ別の子を重ねて描く。映像の上のボタンや、
//! 半透明の覆いの上の案内のように、同じ場所に部品を重ねたいときに使う。
//!
//! 重ねる子の並びと鍵は `overlay_children` が、子を寄せ先へ描く手順は `overlay_place` が持つ。重ねる子は、識別子ごとに最初に出した1回だけ
//! 大きさを測るため見えず、押せない（描き直しを求めるため、人の目には1フレームである）。2回目以降は出した回から見えて押せる。
//! egui は後に登録した部品を上として押下とドラッグを配るため、重ねる子は下地より優先して押される。

use std::rc::Rc;

use crate::measure::{画素, 論理画素};
use crate::style::スタイル;
use crate::tree::container::overlay_children::重ねる子の一覧;
use crate::tree::container::overlay_idle::ポインタが止まると隠す指定;
use crate::tree::container::overlay_place::重ねる置き方;
use crate::tree::container::overlay_position::重ねる位置;
use crate::tree::ノード;

const 既定の端からの間隔: 論理画素 = 画素(8.0);
/// 覆いの背景色を指定しなかったときの色。egui のモーダルの既定の覆いと同じ色である。
const 既定の覆う色: egui::Color32 = egui::Color32::from_black_alpha(100);

/// 重ね型とは、下地の子と、その上へ重ねる子の一覧の記述のことである。
pub struct 重ね型<M> {
    識別子: String,
    下地: Box<ノード<M>>,
    重ねる子一覧: 重ねる子の一覧<M>,
    端からの間隔: 論理画素,
}

impl<M> 重ね型<M> {
    pub(crate) fn 新規(識別子: String, 下地: ノード<M>) -> Self {
        Self {
            識別子,
            下地: Box::new(下地),
            重ねる子一覧: 重ねる子の一覧::空(),
            端からの間隔: 既定の端からの間隔,
        }
    }

    /// 下地の端から間隔を空けた範囲の中の、指定の位置へ子を寄せて重ねる。書いた順に上へ重なる。
    pub fn 上に置く(mut self, 位置: 重ねる位置, 子: impl Into<ノード<M>>) -> Self {
        self.重ねる子一覧
            .足す(重ねる置き方::寄せて置く(位置), 子.into());
        self
    }

    /// 下地の上にマウスがある間だけ、`上に置く` と同じ位置へ子を重ねる。マウスが重ねた子の上にあるときも、
    /// 子は下地の範囲の中にあるため出たままである。子が見えない間は、子の中のボタンも押せない。
    /// 初めて出す回は大きさを測るため見えない（人の目には1フレームである）。
    pub fn マウスを乗せている間だけ上に置く(
        mut self,
        位置: 重ねる位置,
        子: impl Into<ノード<M>>,
    ) -> Self {
        let 置き方 = 重ねる置き方::マウスを乗せている間だけ寄せて置く(位置);
        self.重ねる子一覧.足す(置き方, 子.into());
        self
    }

    /// 下地の上でポインタが動いてから、指定の時間だけ `上に置く` と同じ位置へ子を重ねる。子の上にポインタがある間と、
    /// 子の上で押し始めたボタンを押し続けている間は隠さない。出し入れの規則は `ポインタが止まると隠す指定` の説明を参照する。
    /// 初めて出す回は大きさを測るため見えない（人の目には1フレームである）。
    pub fn ポインタが止まると隠して上に置く(
        mut self,
        位置: 重ねる位置,
        指定: ポインタが止まると隠す指定,
        子: impl Into<ノード<M>>,
    ) -> Self {
        let 置き方 =
            重ねる置き方::ポインタが止まると隠して寄せて置く(位置, 指定);
        self.重ねる子一覧.足す(置き方, 子.into());
        self
    }

    /// 下地の全体を覆いで塗り、その真ん中へ子を重ねる。覆っている間、下地は無効（淡色）で描き、
    /// ポインタでもキーボードでも操作できない。
    /// 覆いに使う装飾の項目は背景色だけである。指定しなければ egui のモーダルと同じ半透明の黒で塗る。
    pub fn 覆って中央に置く(
        mut self, 覆い: スタイル, 子: impl Into<ノード<M>>
    ) -> Self {
        let 色 = 覆い.背景色.unwrap_or(既定の覆う色);
        self.重ねる子一覧
            .足す(重ねる置き方::覆って中央に置く(色), 子.into());
        self
    }

    /// `上に置く` で寄せるときに、下地の端から空ける間隔を指定する。既定は8論理画素である。
    pub fn 端からの間隔(mut self, 間隔: 論理画素) -> Self {
        self.端からの間隔 = 間隔;
        self
    }
}

impl<M: Clone> 重ね型<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 覆っている = self.重ねる子一覧.覆っているか();
        let 下地の反応 = ui
            .add_enabled_ui(!覆っている, |内側| {
                self.下地.描画する(内側, 発行した応答)
            })
            .inner;
        self.重ねる子一覧.描く(
            ui,
            &self.識別子,
            下地の反応.rect,
            self.端からの間隔,
            発行した応答,
        );
        下地の反応
    }
}

impl<M: 'static> 重ね型<M> {
    pub(crate) fn 写す<N: 'static>(
        self, 応答を変換する: Rc<dyn Fn(M) -> N>
    ) -> 重ね型<N> {
        重ね型 {
            識別子: self.識別子,
            下地: Box::new(self.下地.rcで写す(Rc::clone(&応答を変換する))),
            重ねる子一覧: self.重ねる子一覧.写す(&応答を変換する),
            端からの間隔: self.端からの間隔,
        }
    }
}
