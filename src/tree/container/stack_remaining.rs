//! 横並びの残りの幅の配分。指定の子に、その後ろの子を置いた残りの幅を渡し、子は左から右へ置く順に描く。
//! 描く順が見えている並びと同じなので、Tab キーでフォーカスが移る順も左から右になる。
//!
//! 後ろの子の幅は、渡す子を描く前に、同じ回の中で後ろの子を見えない子の Ui へ一度描いて測る。前の回の値を使わないため、
//! どの回でも、並びが使える幅を超えて描かれることが無い(超えると、パネルがはみ出した幅を覚えて広がる)。
//! 測るために描いた回の応答は捨てる。見えない Ui は操作を受け付けない。
//! 注意: 後ろの子に、入力を取り除く見えない部品(キー操作・落とされたファイルの受け取り)や、使える幅いっぱいに広がる部品を置かない。
//! 前者は測る描画で入力を取り除いてしまい、後者は測った幅が使える幅の全部になって、渡す子の幅が0になる。

use crate::tree::ノード;

/// 測るための見えない Ui を置く位置を、画面の上へずらす量。測るために描いた部品がマウスの下に来て、
/// 本物の部品のマウスの乗り方を妨げないためである(見えない Ui の部品は押せないが、マウスが乗っていることは記録される)。
const 画面の外へずらす量: f32 = 1.0e6;

/// 子を左から右へ描き、番号の子(0から数える)には、後ろの子を置いた残りの幅を渡す。
pub(super) fn 残りの幅を渡して描く<M: Clone>(
    子一覧: &[ノード<M>],
    渡す子の番号: usize,
    ui: &mut egui::Ui,
    発行した応答: &mut Vec<M>,
) {
    for (番号, 子) in 子一覧.iter().enumerate() {
        if 番号 != 渡す子の番号 {
            子.描画する(ui, 発行した応答);
            continue;
        }
        let 後ろの子 = 子一覧.get(番号 + 1..).unwrap_or_default();
        let 大きさ = egui::vec2(
            (ui.available_size_before_wrap().x - 後ろの子の幅を測る(後ろの子, ui)).max(0.0),
            ui.spacing().interact_size.y,
        );
        let 配置 = *ui.layout();
        ui.allocate_ui_with_layout(大きさ, 配置, |内側| {
            子.描画する(内側, 発行した応答)
        });
    }
}

/// 後ろの子を、画面の外に置いた見えない子の Ui へ描いて、渡す子との間隔を含めた幅を測る。見えない Ui は親の並びの位置を進めない。
fn 後ろの子の幅を測る<M: Clone>(後ろの子: &[ノード<M>], ui: &mut egui::Ui) -> f32 {
    if 後ろの子.is_empty() {
        return 0.0;
    }
    let mut 測る = ui.new_child(
        egui::UiBuilder::new()
            .id_salt("後ろの子の幅を測る")
            .max_rect(
                ui.available_rect_before_wrap()
                    .translate(egui::vec2(0.0, -画面の外へずらす量)),
            )
            .layout(*ui.layout())
            .invisible(),
    );
    let mut 捨てる応答 = Vec::new();
    for 子 in 後ろの子 {
        子.描画する(&mut 測る, &mut 捨てる応答);
    }
    測る.min_rect().width() + ui.spacing().item_spacing.x
}
