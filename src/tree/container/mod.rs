/// 容器とは、子のノードを並べる部品の区別のことである。
pub enum 容器<M> {
    /// 縦積み・横並び・折り返す横並び。
    積み(積み型<M>),
    /// 転がせる領域。
    スクロール(スクロール型<M>),
    /// 見えている行だけを組む縦のリスト。
    仮想列(仮想列型<M>),
    /// 開閉できる見出し。
    折り畳み見出し(折り畳み見出し型<M>),
    /// 表の形の並び。
    格子(格子型<M>),
    /// 浮きウィンドウ。
    ウィンドウ(ウィンドウ型<M>),
    /// 縁または中央の区画。
    パネル(パネル型<M>),
    /// 見出しを横に並べたタブの列。
    タブ列(タブ列型<M>),
    /// メニューを横に並べる帯。
    メニューバー(メニューバー型<M>),
    /// 押すと子を吹き出しで開くメニュー。
    メニュー(メニュー型<M>),
    /// 画面を覆う区画。
    モーダル(モーダル型<M>),
    /// 使える大きさを測ってから子を組む容器。
    使える大きさから組む(使える大きさから組む型<M>),
    /// 下地の上へ子を重ねる容器。
    重ね(重ね型<M>),
    /// 指定の幅と高さをちょうど占める領域。
    大きさを決めた領域(大きさを決めた領域型<M>),
}

impl<M: Clone> 容器<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        match self {
            Self::積み(中身) => 中身.描画する(ui, 発行した応答),
            Self::スクロール(中身) => 中身.描画する(ui, 発行した応答),
            Self::仮想列(中身) => 中身.描画する(ui, 発行した応答),
            Self::折り畳み見出し(中身) => 中身.描画する(ui, 発行した応答),
            Self::格子(中身) => 中身.描画する(ui, 発行した応答),
            Self::ウィンドウ(中身) => 中身.描画する(ui, 発行した応答),
            Self::パネル(中身) => 中身.描画する(ui, 発行した応答),
            Self::タブ列(中身) => 中身.描画する(ui, 発行した応答),
            Self::メニューバー(中身) => 中身.描画する(ui, 発行した応答),
            Self::メニュー(中身) => 中身.描画する(ui, 発行した応答),
            Self::モーダル(中身) => 中身.描画する(ui, 発行した応答),
            Self::使える大きさから組む(中身) => 中身.描画する(ui, 発行した応答),
            Self::重ね(中身) => 中身.描画する(ui, 発行した応答),
            Self::大きさを決めた領域(中身) => 中身.描画する(ui, 発行した応答),
        }
    }
}

