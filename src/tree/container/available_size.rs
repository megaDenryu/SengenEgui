//! 使える大きさから組む容器。描画する時点で親が使わせる大きさを測り、その大きさから子の木を組んで描く。
//!
//! 使える大きさは描画の途中でしか分からないため、子の木は組む手続きとして受け取り、描画のたびに呼ぶ。
//! 使える大きさとは、この容器を置いた位置から親の領域の右端と下端までの幅と高さのことである。
//! 縦積みの途中に置けば、高さは前の兄弟が使った残りになる。

use std::rc::Rc;

use crate::measure::縦横の論理画素;
use crate::tree::ノード;

type 大きさから子を組む手続き<M> = Box<dyn Fn(縦横の論理画素) -> ノード<M>>;

/// 使える大きさから組む型とは、使える大きさから子の木を組む手続きの記述のことである。
pub struct 使える大きさから組む型<M> {
    子を組む: 大きさから子を組む手続き<M>,
}

impl<M> 使える大きさから組む型<M> {
    pub(crate) fn 新規(子を組む: 大きさから子を組む手続き<M>) -> Self {
        Self { 子を組む }
    }
}

impl<M: Clone> 使える大きさから組む型<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 大きさ = 縦横の論理画素::eguiの大きさから作る(ui.available_size());
        (self.子を組む)(大きさ).描画する(ui, 発行した応答)
    }
}

impl<M: 'static> 使える大きさから組む型<M> {
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 使える大きさから組む型<N> {
        let 元の子を組む = self.子を組む;
        使える大きさから組む型 {
            子を組む: Box::new(move |大きさ| {
                元の子を組む(大きさ).rcで写す(Rc::clone(&応答を変換する))
            }),
        }
    }
}
