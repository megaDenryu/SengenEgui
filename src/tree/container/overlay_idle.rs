//! ポインタが止まると隠す置き方の出し入れの規則。重ねる子を、下地の上でポインタが動いてから一定時間だけ出す。
//! 動画の再生画面の操作の欄のように、見ている間は隠し、マウスを動かせば出てくる部品に使う。
//!
//! 動画サイトの再生画面に揃え、子を出すのはポインタが下地の上で実際に動いたとき（同じ位置への移動の知らせは数えない）と、
//! 下地の上で押したときと、指定のキーを押している間である。ポインタが子の上にあっても、止まれば時間が経って隠す。
//! 子の上で押し始めたボタンを押し続けている間（つまみのドラッグ等）だけは隠さない。ポインタが下地の外へ出たら、すぐ隠す。
//! 記憶は組ごとに egui の一時記憶に置く（`overlay_idle_group`）。動いたかの判定と次の記憶の規則は `overlay_idle_memory` が持つ。

use std::time::Duration;

use crate::tree::container::overlay_idle_group::ポインタが止まると隠す組;
use crate::tree::container::overlay_idle_memory::{出し入れの条件, 出し入れの記憶};
use crate::tree::container::overlay_idle_pointer::{ポインタの様子, 重ねた子の矩形};

/// ポインタが止まると隠す指定とは、重ねる子を、下地の上でポインタが動いてから一定時間だけ出すときの条件のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ポインタが止まると隠す指定 {
    隠すまでの時間: Duration,
    出したままにするか: bool,
    隠している間はカーソルも隠すか: bool,
    出すキー一覧: &'static [egui::Key],
    組: Option<ポインタが止まると隠す組>,
}

impl ポインタが止まると隠す指定 {
    /// ポインタが最後に動いてから `隠すまでの時間` が経ったら子を隠す指定を作る。カーソルは隠さず、キーでは出さず、組にもしない。
    pub fn 作成する(隠すまでの時間: Duration) -> Self {
        Self {
            隠すまでの時間,
            出したままにするか: false,
            隠している間はカーソルも隠すか: false,
            出すキー一覧: &[],
            組: None,
        }
    }

    /// 条件が真の間は、ポインタが止まっていても子を出したままにする。偽に戻すと、最後に真だった回から数え始める。
    /// 利用する側の状態で決める条件（読み込み中は出したままにする等）に使う。
    pub fn 出したままにする(mut self, 条件: bool) -> Self {
        self.出したままにするか = 条件;
        self
    }

    /// 子を隠している間、ポインタが下地の上にあればマウスのカーソルも隠す。
    pub fn 隠している間はカーソルも隠す(mut self) -> Self {
        self.隠している間はカーソルも隠すか = true;
        self
    }

    /// 一覧のキーを押している間は、ポインタが動いたときと同じく子を出し、放してから数え始める。
    /// キーの押下の出来事を別の部品が消費していても効く。
    pub fn キーを押している間は出す(
        mut self, キー一覧: &'static [egui::Key]
    ) -> Self {
        self.出すキー一覧 = キー一覧;
        self
    }

    /// 同じ組を指定した子と一緒に出し入れする。規則は `ポインタが止まると隠す組` の説明を参照する。
    pub fn 組にする(mut self, 組: ポインタが止まると隠す組) -> Self {
        self.組 = Some(組);
        self
    }

    /// 今回子を出すかを決めて組の記憶を更新する。子の矩形は前の回に測った大きさで寄せた矩形である。
    pub(super) fn 出すかを決める(
        self,
        ui: &egui::Ui,
        識別子: egui::Id,
        下地の矩形: egui::Rect,
        子の矩形: egui::Rect,
    ) -> bool {
        let 組 = self
            .組
            .unwrap_or_else(|| ポインタが止まると隠す組::子1つだけの組(識別子));
        let 矩形 = 重ねた子の矩形 {
            下地: 下地の矩形,
            子: 子の矩形,
        };
        組.出すかを決める(ui, self, 矩形)
    }

    /// 組の全ての子の矩形と前の回の記憶から、組の次の記憶を決める。出している間は隠す時刻に描き直しを予約し、
    /// 隠している間は指定があり、ポインタが組のいずれかの下地の上にあればカーソルを隠す。
    pub(super) fn 決める(
        self,
        ui: &egui::Ui,
        矩形一覧: &[重ねた子の矩形],
        前の回: Option<出し入れの記憶>,
    ) -> 出し入れの記憶 {
        let 様子 = ポインタの様子::読む(ui, 矩形一覧, self.出すキー一覧);
        let 条件 = 出し入れの条件 {
            隠すまでの時間: self.隠すまでの時間,
            出したままにするか: self.出したままにするか,
        };
        let 記憶 = 出し入れの記憶::次を決める(前の回, &様子, &条件);
        match 記憶.隠すまでの残り(様子.今, self.隠すまでの時間) {
            Some(残り) if !self.出したままにするか => {
                ui.ctx().request_repaint_after(残り)
            }
            Some(_) => {}
            None if self.隠している間はカーソルも隠すか && 様子.下地の上か => {
                ui.ctx().set_cursor_icon(egui::CursorIcon::None);
            }
            None => {}
        }
        記憶
    }
}
