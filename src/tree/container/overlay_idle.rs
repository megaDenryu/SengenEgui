//! ポインタが止まると隠す置き方の出し入れの規則。重ねる子を、下地の上でポインタが動いてから一定時間だけ出す。
//! 動画の再生画面の操作の欄のように、見ている間は隠し、マウスを動かせば出てくる部品に使う。
//!
//! 最後にポインタが動いた時刻は、組ごとに egui の一時記憶に置く（`overlay_idle_group`）。子の上にポインタがある間と、
//! 子の上で押し始めたボタンを押し続けている間（つまみのドラッグ等）は、動いたものとして数え続け、隠さない。
//! 前の回に描いていなかった子（初めて出す回や、木から外した後に戻した回）は、出した回から数え始める。

use std::time::Duration;

use crate::tree::container::overlay_idle_group::ポインタが止まると隠す組;
use crate::tree::container::overlay_idle_pointer::{ポインタの様子, 重ねた子の矩形};

/// ポインタが止まると隠す指定とは、重ねる子を、下地の上でポインタが動いてから一定時間だけ出すときの条件のことである。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ポインタが止まると隠す指定 {
    隠すまでの時間: Duration,
    出したままにするか: bool,
    隠している間はカーソルも隠すか: bool,
    組: Option<ポインタが止まると隠す組>,
}

/// 出し入れの決定とは、組がある回に決めた、最後にポインタが動いた時刻と子を出すかの組のことである。
pub(super) struct 出し入れの決定 {
    pub(super) 最後に動いた時刻: f64,
    pub(super) 出すか: bool,
}

impl ポインタが止まると隠す指定 {
    /// ポインタが最後に動いてから `隠すまでの時間` が経ったら子を隠す指定を作る。カーソルは隠さず、組にもしない。
    pub fn 作成する(隠すまでの時間: Duration) -> Self {
        Self {
            隠すまでの時間,
            出したままにするか: false,
            隠している間はカーソルも隠すか: false,
            組: None,
        }
    }

    /// 条件が真の間は、ポインタが止まっていても子を出したままにする。偽に戻すと、最後に真だった回から数え始める。
    /// 一時停止している間は操作の欄を出したままにする、のように利用する側の状態で決める条件に使う。
    pub fn 出したままにする(mut self, 条件: bool) -> Self {
        self.出したままにするか = 条件;
        self
    }

    /// 子を隠している間、ポインタが下地の上にあればマウスのカーソルも隠す。
    pub fn 隠している間はカーソルも隠す(mut self) -> Self {
        self.隠している間はカーソルも隠すか = true;
        self
    }

    /// 同じ組を指定した子と一緒に出し入れする。規則は `ポインタが止まると隠す組` の説明を参照する。
    pub fn 組にする(mut self, 組: ポインタが止まると隠す組) -> Self {
        self.組 = Some(組);
        self
    }

    /// 今回子を出すかを決めて組の記憶を更新する。子の矩形は前の回に測った大きさで寄せた矩形である。
    pub(super) fn 出すかを決める(
        self,
        ui: &egui::Ui,
        鍵: egui::Id,
        下地の矩形: egui::Rect,
        子の矩形: egui::Rect,
    ) -> bool {
        let 組 = self
            .組
            .unwrap_or_else(|| ポインタが止まると隠す組::子1つだけの組(鍵));
        let 矩形 = 重ねた子の矩形 {
            下地: 下地の矩形,
            子: 子の矩形,
        };
        組.出すかを決める(ui, self, 矩形)
    }

    /// 組の全ての子の矩形と前の回の時刻から、組を今回出すかを決める。出している間は隠す時刻に描き直しを予約し、
    /// 隠している間は指定があり、ポインタが組のいずれかの下地の上にあればカーソルを隠す。
    pub(super) fn 決める(
        self,
        ui: &egui::Ui,
        矩形一覧: &[重ねた子の矩形],
        前の回に動いた時刻: Option<f64>,
    ) -> 出し入れの決定 {
        let 様子 = ポインタの様子::読む(ui, 矩形一覧);
        let 数え直すか = self.出したままにするか || 様子.止めずに数え直すか();
        let 最後に動いた時刻 = match 前の回に動いた時刻 {
            Some(時刻) if !数え直すか => 時刻,
            _ => 様子.今,
        };
        let 残りの秒 = self.隠すまでの時間.as_secs_f64() - (様子.今 - 最後に動いた時刻);
        let 出すか = 残りの秒 > 0.0;
        if 出すか && !self.出したままにするか {
            ui.ctx()
                .request_repaint_after(Duration::from_secs_f64(残りの秒));
        }
        if !出すか && self.隠している間はカーソルも隠すか && 様子.下地の上か
        {
            ui.ctx().set_cursor_icon(egui::CursorIcon::None);
        }
        出し入れの決定 {
            最後に動いた時刻,
            出すか,
        }
    }
}
