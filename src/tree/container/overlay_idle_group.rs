//! ポインタが止まると隠す子の組。組にした子は、出し入れの記憶（`overlay_idle_memory`）を1つ共有し、一緒に出し入れする。
//!
//! 組の記憶は egui の一時記憶に置く。子は描く順に1つずつ出し入れを決めるため、組の中でその回に最初に来た子が
//! 組の全ての子の分を決め、後から来た子はその決定に従う。最初に来た子はまだ描いていない子の矩形を知らないため、
//! 前の回に組の子が足した矩形と自分の矩形の和で「下地の上か」「子の上で押し始めたか」を判定する。
//! 組を指定しない子は、その子1つだけの組として同じ規則で数える。

use crate::tree::container::overlay_idle::ポインタが止まると隠す指定;
use crate::tree::container::overlay_idle_memory::出し入れの記憶;
use crate::tree::container::overlay_idle_pointer::重ねた子の矩形;

/// ポインタが止まると隠す組とは、ポインタが止まると隠す子のうち、一緒に出し入れする子のまとまりのことである。
///
/// 同じ組の子は、出し入れの記憶を1つ共有し、「下地の上か」「子の上で押し始めたか」を組の全ての子の和で判定し、
/// 出す・隠す・カーソルを隠すを一緒に行う。別の重ねるの子とも組にできるため、重ねるを入れ子にして
/// 外側と内側に置いた子を一緒に出し入れできる。組の出し入れは、その回に組の中で最初に描く子の指定で決めるため、
/// 同じ組の子には同じ指定を渡す。
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct ポインタが止まると隠す組 {
    記憶の鍵: egui::Id,
}

impl ポインタが止まると隠す組 {
    /// 組の名から組を作る。同じ名から作った組を指定した子が、同じ組に入る。
    pub fn 作成する(組の名: &str) -> Self {
        Self {
            記憶の鍵: egui::Id::new(("ポインタが止まると隠す組", 組の名)),
        }
    }

    /// 組を指定しない子の、その子1つだけの組。
    pub(super) fn 子1つだけの組(子の鍵: egui::Id) -> Self {
        Self {
            記憶の鍵: 子の鍵.with("ポインタが止まると隠す組"),
        }
    }

    /// 今回この組の子を出すかを返し、組の記憶へ子の矩形を足す。
    pub(super) fn 出すかを決める(
        self,
        ui: &egui::Ui,
        指定: ポインタが止まると隠す指定,
        矩形: 重ねた子の矩形,
    ) -> bool {
        let 今の回 = ui.ctx().cumulative_pass_nr();
        let 記憶 = ui.data(|記憶域| 記憶域.get_temp::<組の記憶>(self.記憶の鍵));
        let 新しい記憶 = match 記憶 {
            Some(mut 記憶) if 記憶.決めた回 == 今の回 => {
                記憶.矩形一覧.push(矩形);
                記憶
            }
            前の記憶 => {
                組の記憶::回の最初の子で決める(前の記憶, 今の回, ui, 指定, 矩形)
            }
        };
        let 出すか = 新しい記憶.出し入れ.出すか();
        ui.data_mut(|記憶域| 記憶域.insert_temp(self.記憶の鍵, 新しい記憶));
        出すか
    }
}

/// 組の記憶とは、組がある回に決めた出し入れと、その回に組の子が足した矩形の記録のことである。
#[derive(Clone)]
struct 組の記憶 {
    出し入れ: 出し入れの記憶,
    決めた回: u64,
    矩形一覧: Vec<重ねた子の矩形>,
}

impl 組の記憶 {
    /// その回に組の中で最初に来た子が、前の回の記憶と自分の矩形から組の出し入れを決める。
    /// 前の回に組の子を1つも描いていなければ、前の記憶を捨てて今回から数え始める。
    fn 回の最初の子で決める(
        前の記憶: Option<Self>,
        今の回: u64,
        ui: &egui::Ui,
        指定: ポインタが止まると隠す指定,
        矩形: 重ねた子の矩形,
    ) -> Self {
        let 前の回の記憶 = 前の記憶.filter(|記憶| 記憶.決めた回.saturating_add(1) >= 今の回);
        let (前の回の出し入れ, mut 判定する矩形一覧) = match 前の回の記憶 {
            Some(記憶) => (Some(記憶.出し入れ), 記憶.矩形一覧),
            None => (None, Vec::new()),
        };
        判定する矩形一覧.push(矩形);
        Self {
            出し入れ: 指定.決める(ui, &判定する矩形一覧, 前の回の出し入れ),
            決めた回: 今の回,
            矩形一覧: vec![矩形],
        }
    }
}
