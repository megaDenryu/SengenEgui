//! 落とされたファイルの受け取り。画面に何も描かず、OS のファイルがウィンドウの上へドラッグで運ばれて放されたら、
//! そのパスから作った応答を発する。ウィンドウのどこへ落としても受け取る。ファイルごとに1つの応答を発するか、
//! 1回に落とされたファイルをまとめて1つの応答を発するかは、受け取り方が決める。
//!
//! 受け取ったファイルは egui の入力から取り除く。木の中で先に描画した受け取りだけが受け取り、同じファイルを二度発さない。
//! 注意: パスを持たないファイル（ブラウザの中で動かしたときに落とされたファイル）は受け取らず、入力に残す。
//! この部品は OS のファイルのパスを扱う利用のためにあり、中身のバイト列を受け取る口を持たないためである。

use std::path::PathBuf;
use std::rc::Rc;

/// 落とされたファイルの受け取り方とは、落とされたファイルのパスから応答をどの単位で作るかの区別のことである。
enum 受け取り方<M> {
    ファイルごと(Box<dyn Fn(PathBuf) -> M>),
    まとめて(Box<dyn Fn(Vec<PathBuf>) -> M>),
}

/// 落とされたファイルの受け取り型とは、落とされたファイルのパスから応答を作る手続きの記述のことである。
pub struct 落とされたファイルの受け取り型<M> {
    受け取り方: 受け取り方<M>,
}

impl<M> 落とされたファイルの受け取り型<M> {
    pub(crate) fn ファイルごとに受け取る(
        パスから応答を作る: Box<dyn Fn(PathBuf) -> M>,
    ) -> Self {
        Self {
            受け取り方: 受け取り方::ファイルごと(パスから応答を作る),
        }
    }

    pub(crate) fn まとめて受け取る(
        パスの一覧から応答を作る: Box<dyn Fn(Vec<PathBuf>) -> M>,
    ) -> Self {
        Self {
            受け取り方: 受け取り方::まとめて(パスの一覧から応答を作る),
        }
    }

    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let パス一覧 = ui.input_mut(|入力| {
            パスを持つファイルを取り出す(&mut 入力.raw.dropped_files)
        });
        if パス一覧.is_empty() {
            return ui.response();
        }
        match &self.受け取り方 {
            受け取り方::ファイルごと(作る) => {
                発行した応答.extend(パス一覧.into_iter().map(作る))
            }
            受け取り方::まとめて(作る) => 発行した応答.push(作る(パス一覧)),
        }
        ui.response()
    }
}

impl<M: 'static> 落とされたファイルの受け取り型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 落とされたファイルの受け取り型<N> {
        let 写した受け取り方: 受け取り方<N> = match self.受け取り方 {
            受け取り方::ファイルごと(元の作る) => {
                受け取り方::ファイルごと(Box::new(move |パス| {
                    応答を変換する(元の作る(パス))
                }))
            }
            受け取り方::まとめて(元の作る) => {
                受け取り方::まとめて(Box::new(move |一覧| 応答を変換する(元の作る(一覧))))
            }
        };
        落とされたファイルの受け取り型 {
            受け取り方: 写した受け取り方,
        }
    }
}

/// 落とされたファイルの一覧から、パスを持つものを取り除いてそのパスを返す。パスを持たないものは一覧に残す。
fn パスを持つファイルを取り出す(一覧: &mut Vec<egui::DroppedFile>) -> Vec<PathBuf> {
    let mut パス一覧 = Vec::new();
    一覧.retain_mut(|ファイル| match ファイル.path.take() {
        Some(パス) => {
            パス一覧.push(パス);
            false
        }
        None => true,
    });
    パス一覧
}
