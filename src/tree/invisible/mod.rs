//! 見えない部品の族。画面に何も描かず、そのフレームの入力の事象を見張って応答を発するか、
//! 描き直しの時機だけを egui へ伝える部品のまとまりである。

mod dropped_file;
mod repaint;
mod shortcut;

use std::rc::Rc;

pub use dropped_file::落とされたファイルの受け取り型;
pub use repaint::描き直しの予約型;
pub use shortcut::{キーの組, キー操作型};

/// 見えない部品とは、何も描かずに入力を見張る、または描き直しを予約する部品の区別のことである。
pub enum 見えない部品<M> {
    /// キーの組が押されたら応答を発する。
    キー操作(キー操作型<M>),
    /// OS のファイルが窓へ落とされたら、パスから作った応答を発する。
    落とされたファイルの受け取り(落とされたファイルの受け取り型<M>),
    /// 指定の時間が経ったらもう一度描画させる。応答は発しない。
    描き直しの予約(描き直しの予約型),
}

impl<M: Clone> 見えない部品<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        match self {
            Self::キー操作(中身) => 中身.描画する(ui, 発行した応答),
            Self::落とされたファイルの受け取り(中身) => {
                中身.描画する(ui, 発行した応答)
            }
            Self::描き直しの予約(中身) => 中身.描画する(ui),
        }
    }
}

impl<M: 'static> 見えない部品<M> {
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 見えない部品<N> {
        match self {
            Self::キー操作(中身) => {
                見えない部品::キー操作(中身.写す(&*応答を変換する))
            }
            Self::落とされたファイルの受け取り(中身) => {
                見えない部品::落とされたファイルの受け取り(
                    中身.写す(応答を変換する),
                )
            }
            Self::描き直しの予約(中身) => 見えない部品::描き直しの予約(中身),
        }
    }
}

ノードへ変換する!(見えない, 見えない部品::キー操作, キー操作型<M>);
ノードへ変換する!(
    見えない,
    見えない部品::落とされたファイルの受け取り,
    落とされたファイルの受け取り型<M>
);
ノードへ変換する!(見えない, 見えない部品::描き直しの予約, 描き直しの予約型);
