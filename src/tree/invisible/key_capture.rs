//! キーの組の受け取り。画面に何も描かず、そのフレームに押されたキーの組を1つ受け取り、組から作った応答を発する。
//! キーの割り当てを利用者が変える画面で、「変更」を押した後に押されたキーを受け取るために置く。振る舞いは次のとおり。
//!
//! - 受け取るのは押下(押し続けによる繰り返しを除く)の最初の1つだけであり、その押下の事象を消費する。木の中で後に描画する部品
//!   (フォーカスを持つボタン・モーダルの Escape で閉じる処理)はその押下を見ない
//! - 押していた修飾キーを組に含める。Ctrl と Command(macOS)は `修飾キー::COMMAND` にそろえる(`キーの組::生成する` がそろえる)
//! - どのキーにも特別な意味を持たせない(Escape も1つの組として受け取る)。取りやめ等の意味は利用する側が組を見て決める
//! - 文字を打つ部品にフォーカスがあっても受け取る。受け取る間だけ木へ置くことを前提にするためである
//! - 木の中でこの部品より先に描画された部品が事象を消費していれば、その押下は見えない

use std::rc::Rc;

use super::key_combo::キーの組;

/// キーの組の受け取り型とは、押されたキーの組から応答を作る手続きの記述のことである。
pub struct キーの組の受け取り型<M> {
    組から応答を作る: Box<dyn Fn(キーの組) -> M>,
}

impl<M> キーの組の受け取り型<M> {
    pub(crate) fn 新規(組から応答を作る: Box<dyn Fn(キーの組) -> M>) -> Self {
        Self {
            組から応答を作る
        }
    }

    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        if let Some(組) = ui.input_mut(|入力| 最初の押下を取り出す(&mut 入力.events))
        {
            発行した応答.push((self.組から応答を作る)(組));
        }
        ui.response()
    }
}

impl<M: 'static> キーの組の受け取り型<M> {
    /// 応答型を別の型へ写す。ノードの `写す` から呼ばれる。
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> キーの組の受け取り型<N> {
        let 元の作る = self.組から応答を作る;
        キーの組の受け取り型::新規(Box::new(move |組| 応答を変換する(元の作る(組))))
    }
}

/// 事象の列から、繰り返しでない最初の押下を取り除いて、その組を返す。
fn 最初の押下を取り出す(事象の列: &mut Vec<egui::Event>) -> Option<キーの組> {
    let (位置, 組) = 事象の列
        .iter()
        .enumerate()
        .find_map(|(位置, 事象)| match 事象 {
            egui::Event::Key {
                key,
                modifiers,
                pressed: true,
                repeat: false,
                ..
            } => Some((位置, キーの組::生成する(*modifiers, *key))),
            _ => None,
        })?;
    事象の列.remove(位置);
    Some(組)
}
