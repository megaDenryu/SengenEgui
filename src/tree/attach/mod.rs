//! 付け足しの族。1つの子のノードを包み、子の描画した範囲の反応に機能を足す部品のまとまりである。
//! 子の操作を横取りしないことを設計の条件にする（右クリックメニューの説明を参照）。

mod context_menu;
mod drag_source;
mod drop_zone;
mod tooltip;

use std::rc::Rc;

pub use context_menu::右クリックメニュー型;
pub use drag_source::ドラッグ元型;
pub use drop_zone::落とし先型;
pub use tooltip::説明型;

use crate::tree::ノード;

/// 付け足しとは、1つの子に足す機能の区別のことである。
pub enum 付け足し<M> {
    /// 子の上に留まると出る説明の吹き出し。
    説明(説明型<M>),
    /// 子を右クリックすると開くメニュー。
    右クリックメニュー(右クリックメニュー型<M>),
    /// 子をドラッグで運び出せる元。
    ドラッグ元(ドラッグ元型<M>),
    /// 運ばれた値を受け取る先。
    落とし先(落とし先型<M>),
}

impl<M: Clone> 付け足し<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        match self {
            Self::説明(中身) => 中身.描画する(ui, 発行した応答),
            Self::右クリックメニュー(中身) => 中身.描画する(ui, 発行した応答),
            Self::ドラッグ元(中身) => 中身.描画する(ui, 発行した応答),
            Self::落とし先(中身) => 中身.描画する(ui, 発行した応答),
        }
    }
}

impl<M: 'static> 付け足し<M> {
    pub(crate) fn 写す<N: 'static>(self, 変換: Rc<dyn Fn(M) -> N>) -> 付け足し<N> {
        match self {
            Self::説明(中身) => 付け足し::説明(中身.写す(変換)),
            Self::右クリックメニュー(中身) => {
                付け足し::右クリックメニュー(中身.写す(変換))
            }
            Self::ドラッグ元(中身) => 付け足し::ドラッグ元(中身.写す(変換)),
            Self::落とし先(中身) => 付け足し::落とし先(中身.写す(変換)),
        }
    }
}

impl<M> From<付け足し<M>> for ノード<M> {
    fn from(値: 付け足し<M>) -> Self {
        Self::付け足し(Box::new(値))
    }
}

/// 付け足せるとは、ノードへ変換できるものに説明や右クリックメニューを付ける口のことである。
/// 部品の型・容器の型・ノードのどれに対しても同じ書き方で付けられる。
pub trait 付け足せる<M>: Into<ノード<M>> + Sized {
    /// 子の上にポインタが留まったときに出す説明の文を付ける。
    fn 説明(self, 文: impl Into<String>) -> ノード<M> {
        付け足し::説明(説明型::新規(self.into(), 文.into())).into()
    }

    /// 子を右クリックしたときに開くメニューの子一覧を付ける。
    fn 右クリックメニュー(self, 子一覧: Vec<ノード<M>>) -> ノード<M> {
        付け足し::右クリックメニュー(右クリックメニュー型::新規(self.into(), 子一覧)).into()
    }
}

impl<M, T: Into<ノード<M>>> 付け足せる<M> for T {}
