//! 右クリックメニュー。子を右クリックすると子一覧を吹き出しで開く。
//!
//! 注意: 右クリックの判定を子の上に重ねると、子のボタン等の左クリックを横取りする。
//! そのため判定は子を包む Ui 自身に持たせる（`UiBuilder::sense`。Ui の判定は中の部品より
//! 後ろに置かれ、部品が受け取らなかった押下だけを拾う）。子が自分で押下を受け取る部品
//! （ボタン等）のときは子自身の反応の右クリックも拾えるよう、2つの反応を合わせて判定する。
//! メニューの中の部品が応答を発行したら、そのフレームでメニューを閉じる。

use std::rc::Rc;

use crate::tree::{ノード, 子を順に描画する};

/// 右クリックメニュー型とは、子と、右クリックで開くメニューの子一覧の組の記述のことである。
pub struct 右クリックメニュー型<M> {
    子: ノード<M>,
    メニューの子一覧: Vec<ノード<M>>,
}

impl<M> 右クリックメニュー型<M> {
    pub(crate) fn 新規(子: ノード<M>, メニューの子一覧: Vec<ノード<M>>) -> Self {
        Self {
            子,
            メニューの子一覧,
        }
    }
}

impl<M: Clone> 右クリックメニュー型<M> {
    pub(crate) fn 描画する(
        &self,
        ui: &mut egui::Ui,
        発行した応答: &mut Vec<M>,
    ) -> egui::Response {
        let 包み = ui.scope_builder(egui::UiBuilder::new().sense(egui::Sense::click()), |内側| {
            self.子.描画する(内側, 発行した応答)
        });
        let 合わせた反応 = 包み.response.union(包み.inner);
        合わせた反応.context_menu(|内側| {
            let 開く前の件数 = 発行した応答.len();
            子を順に描画する(&self.メニューの子一覧, 内側, 発行した応答);
            if 発行した応答.len() > 開く前の件数 {
                内側.close();
            }
        });
        合わせた反応
    }
}

impl<M: 'static> 右クリックメニュー型<M> {
    pub(crate) fn 写す<N: 'static>(
        self,
        応答を変換する: Rc<dyn Fn(M) -> N>,
    ) -> 右クリックメニュー型<N> {
        右クリックメニュー型 {
            子: self.子.rcで写す(Rc::clone(&応答を変換する)),
            メニューの子一覧: crate::tree::map::子一覧を写す(
                self.メニューの子一覧,
                &応答を変換する,
            ),
        }
    }
}
