//! ノードの中核。ノードは「描画コマンドを発行する永続オブジェクト」であり、値を持たない。
//! 値は利用側の状態に置き、クロージャで描画のたびに取りに行く（lib.rs 方針2）。

/// ノードとは、毎フレーム呼ばれる `描画する` で egui の描画呼び出しを再生するUI要素のことである。
pub trait ノード {
    fn 描画する(&mut self, ui: &mut egui::Ui);
}

/// ノード箱とは、種類の異なるノードを同じ子スロットへ入れるための箱のことである。
pub type ノード箱 = Box<dyn ノード>;

impl ノード for ノード箱 {
    fn 描画する(&mut self, ui: &mut egui::Ui) {
        self.as_mut().描画する(ui);
    }
}

/// ノードを箱へ包む。`子!` マクロが各子要素に対して呼ぶ。
pub fn 箱(節: impl ノード + 'static) -> ノード箱 {
    Box::new(節)
}

/// 空ノードとは、何も描画しないノードのことである。構築時に決まる条件分岐
/// （`if 条件 { 箱(節) } else { 箱(無し()) }`）で「無い側」を表すために使う。
/// 実行中に変わる条件には条件ノードを使う。
pub struct 空ノード;

impl ノード for 空ノード {
    fn 描画する(&mut self, _ui: &mut egui::Ui) {}
}
